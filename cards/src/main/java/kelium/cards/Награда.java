package kelium.cards;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * НАГРАДА КАРТЫ, ОБЪЯВЛЕННАЯ В КОДЕ.
 *
 * <p>Прежде награда лежала числами в YAML, и код карты её не видел вовсе. Отсюда
 * шли расхождения, которых никто не замечал: в коде порог два здания, на карте
 * напечатано три; в каталоге награда контейнером, в правилах контейнеров в
 * наградах нет. Теперь награда — часть карты, как и её условие, и печатный
 * каталог выгружается отсюда, а не сверяется с этим руками.
 *
 * <p>ПРАВИЛО ДИЗАЙНЕРА 17.08.2026, которое здесь и проверяется: не больше ДВУХ
 * видов добра в базовой награде, не больше ДВУХ в усиленной, не больше ТРЁХ
 * разных видов на карте суммарно; контейнеров в наградах заданий нет вовсе.
 * Нарушение — ошибка сборки каталога, а не замечание в ревью.
 */
public record Награда(int монеты, int боеприпасы, int обломки, int келемий,
                      int картыЗаданий, int картыАрсенала, int картыСВитрины,
                      String модуль) {

    /** Пустая награда — у карты этой ступени награды нет. */
    public static Награда нет() {
        return new Награда(0, 0, 0, 0, 0, 0, 0, null);
    }

    public static Награда монеты(int n) {
        return нет().иМонеты(n);
    }

    public static Награда боеприпасы(int n) {
        return нет().иБоеприпасы(n);
    }

    public static Награда обломки(int n) {
        return нет().иОбломки(n);
    }

    public static Награда картыЗаданий(int n) {
        return нет().иКартыЗаданий(n);
    }

    public static Награда картаАрсенала() {
        return нет().иКартыАрсенала(1);
    }

    /** Карта арсенала НА ВЫБОР из открытых на витрине — см. {@link #иКартуСВитрины}. */
    public static Награда картаСВитрины() {
        return нет().иКартуСВитрины();
    }

    /** Жетон модуля: {@code attack} — атаки, {@code assembly} — сборки. */
    public static Награда модуль(String какой) {
        return new Награда(0, 0, 0, 0, 0, 0, 0, какой);
    }

    public Награда иМонеты(int n) {
        return new Награда(n, боеприпасы, обломки, келемий, картыЗаданий, картыАрсенала, картыСВитрины, модуль);
    }

    public Награда иБоеприпасы(int n) {
        return new Награда(монеты, n, обломки, келемий, картыЗаданий, картыАрсенала, картыСВитрины, модуль);
    }

    public Награда иОбломки(int n) {
        return new Награда(монеты, боеприпасы, n, келемий, картыЗаданий, картыАрсенала, картыСВитрины, модуль);
    }

    public Награда иКелемий(int n) {
        return new Награда(монеты, боеприпасы, обломки, n, картыЗаданий, картыАрсенала, картыСВитрины, модуль);
    }

    public Награда иКартыЗаданий(int n) {
        return new Награда(монеты, боеприпасы, обломки, келемий, n, картыАрсенала, картыСВитрины, модуль);
    }

    public Награда иКартыАрсенала(int n) {
        return new Награда(монеты, боеприпасы, обломки, келемий, картыЗаданий, n, картыСВитрины, модуль);
    }

    /**
     * КАРТА АРСЕНАЛА С ВИТРИНЫ — выбор одной из двух ОТКРЫТЫХ карт.
     *
     * <p>Дороже обычной карты арсенала именно этим: не слепая тяга, а выбор,
     * поэтому такая награда ставится на самые трудные условия (решение дизайнера
     * 21.08.2026).
     */
    public Награда иКартуСВитрины() {
        return new Награда(монеты, боеприпасы, обломки, келемий, картыЗаданий,
            картыАрсенала, 1, модуль);
    }

    public Награда иМодуль(String какой) {
        return new Награда(монеты, боеприпасы, обломки, келемий, картыЗаданий, картыАрсенала, картыСВитрины, какой);
    }

    /** Сколько РАЗНЫХ видов добра в этой награде — по правилу дизайнера. */
    public int видов() {
        int n = 0;
        for (int v : new int[] {монеты, боеприпасы, обломки, келемий, картыЗаданий,
                картыАрсенала, картыСВитрины}) {
            if (v > 0) {
                n++;
            }
        }
        return модуль == null ? n : n + 1;
    }

    public boolean пусто() {
        return видов() == 0;
    }

    /**
     * Выгрузка в запись каталога. Ключи — те же, которыми награду выдаёт движок,
     * поэтому выгруженный каталог читается без единой правки в движке.
     */
    public Map<String, Object> выгрузить() {
        Map<String, Object> out = new LinkedHashMap<>();
        положить(out, "coin", монеты);
        положить(out, "ammo", боеприпасы);
        положить(out, "debris", обломки);
        положить(out, "kelium", келемий);
        положить(out, "objective_card", картыЗаданий);
        положить(out, "arsenal", картыАрсенала);
        положить(out, "arsenal_from_display", картыСВитрины);
        if (модуль != null) {
            out.put("module", модуль);
        }
        return out;
    }

    private static void положить(Map<String, Object> m, String ключ, int n) {
        if (n > 0) {
            m.put(ключ, n);
        }
    }

    /** Печатная строка награды — для карты, справочника и правил. */
    public String печатно() {
        StringBuilder sb = new StringBuilder();
        добавить(sb, монеты, "монета", "монеты", "монет");
        добавить(sb, боеприпасы, "боеприпас", "боеприпаса", "боеприпасов");
        добавить(sb, обломки, "обломок", "обломка", "обломков");
        добавить(sb, келемий, "келемий", "келемия", "келемия");
        добавить(sb, картыЗаданий, "карта задания", "карты задания", "карт задания");
        добавить(sb, картыАрсенала, "карта арсенала", "карты арсенала", "карт арсенала");
        if (картыСВитрины > 0) {
            если(sb);
            // Название говорит ровно то, чем эта награда отличается: не «карта
            // арсенала», а ВЫБОР из открытых. Иначе на карте не видно, за что
            // именно платят дороже.
            sb.append("карта арсенала на выбор из открытых");
        }
        if (модуль != null) {
            если(sb);
            sb.append("жетон модуля ").append("attack".equals(модуль) ? "атаки" : "сборки");
        }
        return sb.isEmpty() ? "нет награды" : sb.toString();
    }

    private static void добавить(StringBuilder sb, int n, String один, String мало, String много) {
        if (n <= 0) {
            return;
        }
        если(sb);
        sb.append(n).append(' ').append(n == 1 ? один : n < 5 ? мало : много);
    }

    private static void если(StringBuilder sb) {
        if (!sb.isEmpty()) {
            sb.append(" и ");
        }
    }
}
