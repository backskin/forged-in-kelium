package kelium.cards;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * НАГРАДА КАРТЫ, ОБЪЯВЛЕННАЯ В КОДЕ.
 *
 * <p>Прежде награда лежала числами в YAML, и код карты её не видел вовсе. Отсюда
 * шли расхождения, которых никто не замечал: в коде порог два здания, на карте
 * напечатано три; в каталоге награда контейнером, в правилах контейнеров в
 * наградах нет. Теперь награда — часть карты, как и её условие, и печатный
 * каталог выгружается отсюда, а не сверяется с этим руками.
 *
 * <p>ПРАВИЛО ДИЗАЙНЕРА 17.08.2026, которое здесь и проверяется: не больше ДВУХ
 * видов добра в базовой награде, не больше ДВУХ в усиленной, не больше ТРЁХ
 * разных видов на карте суммарно; контейнеров в наградах заданий нет вовсе.
 * Нарушение — ошибка сборки каталога, а не замечание в ревью.
 */
public record Награда(int монеты, int боеприпасы, int трофеи, int келемий,
                      int картыЗаданий, int картыАрсенала, int картыСВитрины,
                      String модуль, String действие, boolean позолота,
                      int спецДействий) {

    /**
     * НАГРАДА-ДЕЙСТВИЕ (ревизия дизайнера 18.09.2026): «не ресурсы давать
     * заданием, а именно действия — которые ты не успел отыграть». Выполнил
     * задание — играешь полноценное действие прямо сейчас, сверх своих приказов.
     *
     * @param имя действие движка: build, assembly, mining, movement, combat,
     *            market, science
     */
    public static Награда действием(String имя) {
        return new Награда(0, 0, 0, 0, 0, 0, 0, null, имя, false, 0);
    }

    /**
     * НАГРАДА — ВЫБОР ОДНОГО ИЗ ДВУХ ДЕЙСТВИЙ (решение дизайнера 22.09.2026).
     *
     * <p>Основная награда каждого задания — не одно действие, а выбор одного из
     * двух РАЗНЫХ действий из разных приказов. Выбор кодируется в строке через
     * «{@code |}» ({@code "combat|energy_swap"}): движок при выдаче разбивает её
     * и спрашивает игрока, а record и все его конструкторы не меняются — это
     * по-прежнему одно поле «действие».
     */
    public static Награда выбор(String первое, String второе) {
        return действием(первое + "|" + второе);
    }

    /** ПОЗОЛОЧЕНИЕ МОДУЛЯ — восьмая награда ревизии: прогресс, а не ресурс. */
    public static Награда позолотой() {
        return new Награда(0, 0, 0, 0, 0, 0, 0, null, null, true, 0);
    }

    /**
     * ДВА СПЕЦ-ДЕЙСТВИЯ В ЭТОТ ХОД (решение дизайнера 19.09.2026, заменяет
     * позолоту в наградах заданий).
     *
     * <p>Почему позолота ушла. Замер 19.09: позолота выпадала 2.36 раза за
     * партию, игралась в 69% случаев и была самой слабой наградой — она ничего
     * не меняет в этот ход, только чуть улучшает жетон на будущее. Дизайнер
     * словами: «действия по золоту — это хуйня».
     *
     * <p>Спец-действие, наоборот, — самый дефицитный ресурс хода: его ровно
     * ОДНО, и через него проходят и выполнение заданий, и карты арсенала.
     * Замер это показал прямо: за ход выполняется максимум одно задание,
     * ходов с двумя не бывает вовсе. Награда «ещё два спец-действия» снимает
     * именно это горлышко и делает возможными цепочки, которых в игре не было.
     */
    public static Награда спецДействиями(int сколько) {
        return new Награда(0, 0, 0, 0, 0, 0, 0, null, null, false, сколько);
    }

    /** Пустая награда — у карты этой ступени награды нет. */
    public static Награда нет() {
        return new Награда(0, 0, 0, 0, 0, 0, 0, null, null, false, 0);
    }

    public static Награда монеты(int n) {
        return нет().иМонеты(n);
    }

    public static Награда боеприпасы(int n) {
        return нет().иБоеприпасы(n);
    }

    /** Келемий — им платят на Рынке, а с правилом-джокером ещё и в бою и науке. */
    public static Награда келемий(int n) {
        return нет().иКелемий(n);
    }

    public static Награда трофеи(int n) {
        return нет().иТрофеи(n);
    }

    public static Награда картыЗаданий(int n) {
        return нет().иКартыЗаданий(n);
    }

    public static Награда картаАрсенала() {
        return нет().иКартыАрсенала(1);
    }

    /** Карта арсенала НА ВЫБОР из открытых на витрине — см. {@link #иКартуСВитрины}. */
    public static Награда картаСВитрины() {
        return нет().иКартуСВитрины();
    }

    /** Жетон модуля: {@code attack} — атаки, {@code assembly} — сборки. */
    public static Награда модуль(String какой) {
        return new Награда(0, 0, 0, 0, 0, 0, 0, какой, null, false, 0);
    }

    public Награда иМонеты(int n) {
        return new Награда(n, боеприпасы, трофеи, келемий, картыЗаданий, картыАрсенала, картыСВитрины, модуль, действие, позолота, спецДействий);
    }

    public Награда иБоеприпасы(int n) {
        return new Награда(монеты, n, трофеи, келемий, картыЗаданий, картыАрсенала, картыСВитрины, модуль, действие, позолота, спецДействий);
    }

    public Награда иТрофеи(int n) {
        return new Награда(монеты, боеприпасы, n, келемий, картыЗаданий, картыАрсенала, картыСВитрины, модуль, действие, позолота, спецДействий);
    }

    public Награда иКелемий(int n) {
        return new Награда(монеты, боеприпасы, трофеи, n, картыЗаданий, картыАрсенала, картыСВитрины, модуль, действие, позолота, спецДействий);
    }

    public Награда иКартыЗаданий(int n) {
        return new Награда(монеты, боеприпасы, трофеи, келемий, n, картыАрсенала, картыСВитрины, модуль, действие, позолота, спецДействий);
    }

    public Награда иКартыАрсенала(int n) {
        return new Награда(монеты, боеприпасы, трофеи, келемий, картыЗаданий, n, картыСВитрины, модуль, действие, позолота, спецДействий);
    }

    /**
     * КАРТА АРСЕНАЛА С ВИТРИНЫ — выбор одной из двух ОТКРЫТЫХ карт.
     *
     * <p>Дороже обычной карты арсенала именно этим: не слепая тяга, а выбор,
     * поэтому такая награда ставится на самые трудные условия (решение дизайнера
     * 21.08.2026).
     */
    public Награда иКартуСВитрины() {
        return new Награда(монеты, боеприпасы, трофеи, келемий, картыЗаданий,
            картыАрсенала, 1, модуль, действие, позолота, спецДействий);
    }

    public Награда иМодуль(String какой) {
        return new Награда(монеты, боеприпасы, трофеи, келемий, картыЗаданий,
            картыАрсенала, картыСВитрины, какой, действие, позолота, спецДействий);
    }

    /**
     * ДОБАВИТЬ СПЕЦ-ДЕЙСТВИЕ К НАГРАДЕ (решение дизайнера 22.09.2026): усиленная
     * награда даёт ресурс/жетон И спец-действие — чтобы завести цепочку
     * (выполнить ещё карту, поставить арсенал). Спец-действие не считается
     * отдельным «видом» в {@link #видов()}: это не добро, а право хода.
     */
    public Награда иСпец(int сколько) {
        return new Награда(монеты, боеприпасы, трофеи, келемий, картыЗаданий,
            картыАрсенала, картыСВитрины, модуль, действие, позолота, спецДействий + сколько);
    }

    /** Сколько РАЗНЫХ видов добра в этой награде — по правилу дизайнера. */
    public int видов() {
        int n = 0;
        for (int v : new int[] {монеты, боеприпасы, трофеи, келемий, картыЗаданий,
                картыАрсенала, картыСВитрины}) {
            if (v > 0) {
                n++;
            }
        }
        if (модуль != null) {
            n++;
        }
        // ДЕЙСТВИЕ И ПОЗОЛОТА — тоже виды награды (ревизия 18.09.2026). Без них
        // награда-действие считалась ПУСТОЙ, запись base_reward не выгружалась
        // вовсе, и карта уходила в игру без награды: сторож каталога поймал это
        // на o03 сразу же.
        if (действие != null) {
            n++;
        }
        if (позолота) {
            n++;
        }
        if (спецДействий > 0) {
            n++;
        }
        return n;
    }

    public boolean пусто() {
        return видов() == 0;
    }

    /**
     * Выгрузка в запись каталога. Ключи — те же, которыми награду выдаёт движок,
     * поэтому выгруженный каталог читается без единой правки в движке.
     */
    public Map<String, Object> выгрузить() {
        Map<String, Object> out = new LinkedHashMap<>();
        положить(out, "coin", монеты);
        положить(out, "ammo", боеприпасы);
        положить(out, "trophy", трофеи);
        положить(out, "kelium", келемий);
        положить(out, "objective_card", картыЗаданий);
        положить(out, "arsenal", картыАрсенала);
        положить(out, "arsenal_from_display", картыСВитрины);
        if (модуль != null) {
            out.put("module", модуль);
        }
        if (действие != null) {
            out.put("action", действие);
        }
        if (позолота) {
            out.put("gild", 1);
        }
        if (спецДействий > 0) {
            out.put("spec_actions", спецДействий);
        }
        return out;
    }

    private static void положить(Map<String, Object> m, String ключ, int n) {
        if (n > 0) {
            m.put(ключ, n);
        }
    }

    /** Печатная строка награды — для карты, справочника и правил. */
    public String печатно() {
        StringBuilder sb = new StringBuilder();
        добавить(sb, монеты, "монета", "монеты", "монет");
        добавить(sb, боеприпасы, "боеприпас", "боеприпаса", "боеприпасов");
        добавить(sb, трофеи, "трофей", "трофея", "трофеев");
        добавить(sb, келемий, "келемий", "келемия", "келемия");
        добавить(sb, картыЗаданий, "карта задания", "карты задания", "карт задания");
        добавить(sb, картыАрсенала, "карта арсенала", "карты арсенала", "карт арсенала");
        if (картыСВитрины > 0) {
            если(sb);
            // Название говорит ровно то, чем эта награда отличается: не «карта
            // арсенала», а ВЫБОР из открытых. Иначе на карте не видно, за что
            // именно платят дороже.
            sb.append("карта арсенала на выбор из открытых");
        }
        if (модуль != null) {
            если(sb);
            sb.append("жетон модуля ").append("attack".equals(модуль) ? "атаки" : "сборки");
        }
        return sb.isEmpty() ? "нет награды" : sb.toString();
    }

    private static void добавить(StringBuilder sb, int n, String один, String мало, String много) {
        if (n <= 0) {
            return;
        }
        если(sb);
        sb.append(n).append(' ').append(n == 1 ? один : n < 5 ? мало : много);
    }

    private static void если(StringBuilder sb) {
        if (!sb.isEmpty()) {
            sb.append(" и ");
        }
    }
}
