package kelium.cards.objectives;

import java.util.LinkedHashMap;
import java.util.Map;

import kelium.cards.Награда;

/**
 * ЩЕДРОСТЬ КАТАЛОГА ЗАДАНИЙ — во сколько раз награда карты больше авторской.
 *
 * <p>ЗАЧЕМ ЭТО ЕСТЬ. Замеры всех составов ботов упирались в одно и то же: карту
 * задания ЖГУТ чаще, чем выполняют. Причина не в ботах и не в условиях, а в
 * арифметике. Верх карты — бесплатное действие, то есть половина приказа, и он
 * доступен всегда; низ требует расстановки на поле и платит три-четыре монеты.
 * Пока верх дороже низа, выполнять задания невыгодно, и никакая настройка весов
 * этого не переставит.
 *
 * <p>ЧТО ЗДЕСЬ НАСТРАИВАЕТСЯ. Один множитель на весь каталог: во сколько раз
 * жирнее авторские числа. Множитель — единственный, потому что искать надо
 * ПОРОГ («при какой щедрости задания начинают выполнять»), а не сорок отдельных
 * цен: сорок цен подгоняются под замер по одной и подгоняются бесконечно.
 *
 * <p>ЧТО МАСШТАБИРУЕТСЯ. Только СЧЁТНОЕ добро: монеты, боеприпасы, трофеи,
 * келемий и карты заданий. Жетон модуля и карта арсенала — не число, а предмет:
 * «два модуля» на карте не напечатать, и ячеек под арсенал у игрока всё равно
 * три. НАЧАЛЬНЫЕ задания не масштабируются вовсе — это обучающие карты первого
 * раунда с фиксированной наградой «трофей и карта задания», и жирность им ни к
 * чему.
 *
 * <p>ЩЕДРОСТЬ ПРИВЯЗАНА К ВЕРСИИ НАБОРА, а не к дате сборки. Наборы
 * неизменяемы: партии и замеры на 1.14.0 обязаны воспроизводиться в точности,
 * поэтому у старых версий множитель равен единице, и код ведёт себя так, будто
 * этого класса нет. Новая версия каталога — новая строка в таблице ниже.
 *
 * <p>ДЛЯ ЗАМЕРОВ множитель переопределяется настройкой запуска
 * {@code -Dkelium.objectives.scale=1.6}. Она нужна ровно затем, чтобы искать
 * порог, не выпуская по версии каталога на каждую пробу, и, как всякая настройка
 * запуска, не переживает перезапуск и не может тихо испортить будущие прогоны.
 */
public final class Щедрость {

    private Щедрость() {
    }

    /** Версия набора заданий → во сколько раз её награды жирнее авторских. */
    private static final Map<String, Double> ПО_ВЕРСИЯМ = new LinkedHashMap<>();

    static {
        // Авторские числа — всё, что было до 08.09.2026.
        ПО_ВЕРСИЯМ.put("1.14.0", 1.0);
        // 1.15.0 (08.09.2026): найдено замером — при этой щедрости задания
        // выполняют примерно так же часто, как жгут. Как искали и что вышло —
        // reports/balance/щедрость-заданий.md.
        ПО_ВЕРСИЯМ.put("1.15.0", 2.0);
        // 1.16.0 (09.09.2026): колода собрана по таблице дизайнера, где числа
        // наград выверены между собой (средняя цена карты 3.5). Щедрость
        // остаётся прежней: её искали замером, и менять её заодно с составом
        // колоды нельзя — иначе не понять, что подействовало.
        ПО_ВЕРСИЯМ.put("1.16.0", 2.0);
    }

    /** Версия набора → сколько ТРОФЕЕВ обязательно лежит в базовой награде. */
    private static final Map<String, Integer> ТРОФЕЙ_ПО_ВЕРСИЯМ = new LinkedHashMap<>();

    static {
        ТРОФЕЙ_ПО_ВЕРСИЯМ.put("1.14.0", 0);
        ТРОФЕЙ_ПО_ВЕРСИЯМ.put("1.15.0", 1);
        ТРОФЕЙ_ПО_ВЕРСИЯМ.put("1.16.0", 1);
    }

    /**
     * ЧИСЛО ИЗ НАСТРОЙКИ ЗАПУСКА или {@code null}, если настройки нет.
     *
     * <p>Именно {@code null}, а не ноль: ноль — законное значение («никакой
     * щедрости»), и отличать «не задано» от «задано нулём» приходится, иначе
     * настройкой нельзя ВЫКЛЮЧИТЬ то, что включено версией набора. На этом уже
     * спотыкался сторож: он выставлял множитель 1 и ждал авторских чисел, а
     * трофей продолжал приходить из таблицы версий.
     */
    private static Double число(String ключ) {
        String s = System.getProperty(ключ, "");
        if (s.isBlank()) {
            return null;
        }
        try {
            return Double.parseDouble(s.trim().replace(',', '.'));
        } catch (NumberFormatException notANumber) {
            return null;
        }
    }

    /**
     * СКОЛЬКО ТРОФЕЕВ ОБЯЗАНО БЫТЬ В БАЗОВОЙ НАГРАДЕ — вторая ручка, и она про
     * ВАЛЮТУ, а не про размер.
     *
     * <p>ЗАЧЕМ ОНА НУЖНА ОТДЕЛЬНО ОТ МНОЖИТЕЛЯ. Свод 1.35.0 обнулил очки за
     * монеты, келемий, войска и здания: базовых источников очков осталось шесть,
     * и ни один из них не покупается монетой напрямую. А базовые награды заданий
     * — это как раз монеты и боеприпасы, то есть чистый темп. Верх карты (утиль)
     * — тоже темп, только даром и без условия. Поэтому сколько монету ни
     * умножай, выполнение остаётся разменом темпа на темп, и замер это показал:
     * девятикратная награда подняла долю выполнений всего на двенадцать пунктов
     * и упёрлась.
     *
     * <p>Трофей — единственная награда, которая обменивается на очки напрямую
     * (шаг трека науки). Один трофей в базовой награде делает выполнение
     * качественно другим предложением, а не «чуть больше того же самого».
     *
     * <p>Настройка запуска для поиска: {@code -Dkelium.objectives.trophy=1}.
     */
    public static int трофеевВБазе() {
        Double изЗапуска = число("kelium.objectives.trophy");
        if (изЗапуска != null) {
            return (int) Math.max(0, Math.round(изЗапуска));
        }
        String версия = kelium.engine.cards.CardRegistry.activeVersion("objectives");
        return версия == null ? 0 : ТРОФЕЙ_ПО_ВЕРСИЯМ.getOrDefault(версия, 0);
    }

    /** Действующий множитель: настройка запуска, иначе таблица версий, иначе 1. */
    public static double множитель() {
        Double изЗапуска = число("kelium.objectives.scale");
        if (изЗапуска != null) {
            return изЗапуска <= 0 ? 1.0 : изЗапуска;
        }
        String версия = kelium.engine.cards.CardRegistry.activeVersion("objectives");
        return версия == null ? 1.0 : ПО_ВЕРСИЯМ.getOrDefault(версия, 1.0);
    }

    /** Множитель этой версии набора по таблице (для отчётов и сторожей). */
    public static double множительВерсии(String версия) {
        return версия == null ? 1.0 : ПО_ВЕРСИЯМ.getOrDefault(версия, 1.0);
    }

    /**
     * Награда, увеличенная в {@link #множитель()} раз.
     *
     * <p>Округление обычное, к ближайшему целому, но добро не исчезает: то, что
     * на карте напечатано, при любом множителе остаётся хотя бы единицей —
     * иначе карта обещала бы монету и не давала ничего.
     */
    public static Награда жирнее(Награда н) {
        double k = множитель();
        return жирнее(н, k);
    }

    /** То же с явным множителем — для выгрузки и сторожей. */
    public static Награда жирнее(Награда н, double k) {
        if (н == null || k == 1.0) {
            return н;
        }
        return new Награда(
            больше(н.монеты(), k), больше(н.боеприпасы(), k), больше(н.трофеи(), k),
            больше(н.келемий(), k), больше(н.картыЗаданий(), k),
            н.картыАрсенала(), н.картыСВитрины(), н.модуль());
    }

    /**
     * БАЗОВАЯ НАГРАДА С ОБЯЗАТЕЛЬНЫМ ТРОФЕЕМ — уже жирная, теперь ещё и очковая.
     *
     * <p>ПРАВИЛО ДИЗАЙНЕРА «не больше двух видов добра в одной награде»
     * соблюдается, и это диктует, как именно трофей встаёт:
     * <ul>
     *   <li>трофеи в награде уже есть — просто прибавляются;</li>
     *   <li>вид один (только монеты или только боеприпасы) — трофей становится
     *       вторым видом;</li>
     *   <li>видов уже два — самый дешёвый (боеприпасы, иначе монеты) УХОДИТ, а
     *       на его место встаёт трофей: иначе на карте оказалось бы три вида.</li>
     * </ul>
     */
    public static Награда сТрофеем(Награда н, int трофеев) {
        if (н == null || трофеев <= 0 || н.пусто()) {
            return н;
        }
        if (н.трофеи() > 0) {
            return н.иТрофеи(н.трофеи() + трофеев);
        }
        int видов = н.выгрузить().size();
        if (видов <= 1) {
            return н.иТрофеи(трофеев);
        }
        if (н.боеприпасы() > 0) {
            return н.иБоеприпасы(0).иТрофеи(трофеев);
        }
        if (н.монеты() > 0) {
            return н.иМонеты(0).иТрофеи(трофеев);
        }
        return н.иТрофеи(трофеев);
    }

    /** Базовая награда карты в том виде, в каком её издаёт действующая версия. */
    public static Награда базоваяВВерсии(Награда н) {
        return сТрофеем(жирнее(н), трофеевВБазе());
    }

    private static int больше(int n, double k) {
        if (n <= 0) {
            return n;
        }
        return Math.max(1, (int) Math.round(n * k));
    }

    /**
     * ПЕЧАТНЫЙ ТЕКСТ КАРТЫ СЛЕДУЕТ ЗА НАГРАДОЙ.
     *
     * <p>Текст карты РАССКАЗЫВАЕТ про награду словами («— награда 3 боеприпаса»),
     * и если поднять числа молча, карта начнёт обещать одно, а выдавать другое.
     * Поэтому здесь та же подстановка, которой печатается награда
     * ({@link Награда#печатно()}): старая формулировка заменяется новой ровно
     * там, где стоит.
     *
     * <p>Подставляется ПЕРВОЕ вхождение базовой награды, затем первое вхождение
     * усиленной ПОСЛЕ него: у карт вида «награда 2 монеты и 3 боеприпаса… условие
     * усилено: 3 боеприпаса» иначе можно было бы попасть в середину базовой
     * формулировки.
     */
    public static String текстПодНаграду(String описание, Награда база, Награда сверх) {
        if (описание == null || (множитель() == 1.0 && трофеевВБазе() == 0)) {
            return описание;
        }
        String out = описание;
        int после = 0;
        if (база != null && !база.пусто()) {
            Правка п = подставить(out, база, базоваяВВерсии(база), после);
            out = п.текст();
            после = п.конец();
        }
        if (сверх != null && !сверх.пусто()) {
            out = подставить(out, сверх, жирнее(сверх), после).текст();
        }
        return out;
    }

    /** Итог подстановки: новый текст и место, дальше которого искать следующую. */
    private record Правка(String текст, int конец) {
    }

    /**
     * ПОДСТАВИТЬ НОВЫЕ ЧИСЛА В ПЕЧАТНЫЙ ТЕКСТ — сперва целой формулировкой,
     * потом по составляющим.
     *
     * <p>Почему двумя способами. Большинство карт пишут награду ровно так, как
     * её печатает {@link Награда#печатно()}, и тогда достаточно заменить всю
     * формулировку разом. Но текст писали руками, и часть карт называет то же
     * самое в своём порядке («жетон модуля атаки и 2 трофея») или без единицы
     * («карта задания» вместо «1 карта задания»). Переписывать авторскую прозу
     * ради удобства подстановки — плохой обмен: тогда правится то, что дизайнер
     * писал, а не то, что считает машина. Поэтому второй проход идёт ПО ВИДАМ
     * добра и находит каждое число там, где оно стоит.
     */
    private static Правка подставить(String текст, Награда было, Награда стало, int от) {
        String целиком = было.печатно();
        int i = текст.indexOf(целиком, от);
        if (i >= 0) {
            String новое = стало.печатно();
            if (целиком.equals(новое)) {
                return new Правка(текст, i + целиком.length());
            }
            return new Правка(текст.substring(0, i) + новое
                + текст.substring(i + целиком.length()), i + новое.length());
        }
        String out = текст;
        int конец = от;
        boolean трофейВстал = стало.трофеи() == было.трофеи();
        for (Вид в : Вид.values()) {
            int n0 = в.сколько(было);
            int n1 = в.сколько(стало);
            if (n0 == 0 || n0 == n1) {
                continue;
            }
            // Вид ушёл целиком — на его место встаёт трофей (так работает
            // обязательный трофей в базовой награде: он вытесняет самое дешёвое).
            String чем = n1 > 0 ? в.штука(n1)
                : (!трофейВстал ? Вид.ТРОФЕИ.штука(стало.трофеи()) : "");
            if (chemПусто(чем)) {
                continue;
            }
            int j = найти(out, в, n0, конец);
            if (j < 0) {
                continue;
            }
            String что = нашлось(out, в, n0, j);
            out = out.substring(0, j) + чем + out.substring(j + что.length());
            конец = Math.max(конец, j + чем.length());
            if (n1 == 0) {
                трофейВстал = true;
            }
        }
        // Трофей ДОБАВИЛСЯ там, где его не было и где ничего не вытеснялось:
        // приписываем его к формулировке после самого дорогого вида, который
        // на карте уже назван.
        if (!трофейВстал && стало.трофеи() > было.трофеи()) {
            for (Вид в : Вид.values()) {
                int n1 = в.сколько(стало);
                if (в == Вид.ТРОФЕИ || n1 == 0) {
                    continue;
                }
                int j = out.indexOf(в.штука(n1), от);
                if (j < 0) {
                    continue;
                }
                int end = j + в.штука(n1).length();
                out = out.substring(0, end) + " и " + Вид.ТРОФЕИ.штука(стало.трофеи())
                    + out.substring(end);
                конец = Math.max(конец, end);
                break;
            }
        }
        return new Правка(out, конец);
    }

    private static boolean chemПусто(String s) {
        return s == null || s.isEmpty();
    }

    /** Где в тексте стоит это добро в количестве {@code n}; −1 — не нашлось. */
    private static int найти(String текст, Вид в, int n, int от) {
        int i = текст.indexOf(в.штука(n), от);
        if (i >= 0) {
            return i;
        }
        // Единицу на карте часто не пишут: «карта задания», «келемий».
        return n == 1 ? текст.indexOf(в.безЕдиницы(), от) : -1;
    }

    private static String нашлось(String текст, Вид в, int n, int j) {
        String сЧислом = в.штука(n);
        return текст.startsWith(сЧислом, j) ? сЧислом : в.безЕдиницы();
    }

    /**
     * ВИДЫ СЧЁТНОГО ДОБРА и то, как каждый печатается по отдельности.
     *
     * <p>Печатная форма берётся у самой {@link Награда}: она уже умеет склонять
     * («1 монета», «2 монеты», «5 монет»), и второй такой таблицы в проекте быть
     * не должно.
     */
    private enum Вид {
        МОНЕТЫ, БОЕПРИПАСЫ, ТРОФЕИ, КЕЛЕМИЙ, КАРТЫ_ЗАДАНИЙ;

        int сколько(Награда н) {
            return switch (this) {
                case МОНЕТЫ -> н.монеты();
                case БОЕПРИПАСЫ -> н.боеприпасы();
                case ТРОФЕИ -> н.трофеи();
                case КЕЛЕМИЙ -> н.келемий();
                case КАРТЫ_ЗАДАНИЙ -> н.картыЗаданий();
            };
        }

        /** Печатная форма только этого вида в количестве {@code n}. */
        String штука(int n) {
            if (n <= 0) {
                return "";
            }
            return switch (this) {
                case МОНЕТЫ -> Награда.монеты(n).печатно();
                case БОЕПРИПАСЫ -> Награда.боеприпасы(n).печатно();
                case ТРОФЕИ -> Награда.трофеи(n).печатно();
                case КЕЛЕМИЙ -> Награда.нет().иКелемий(n).печатно();
                case КАРТЫ_ЗАДАНИЙ -> Награда.картыЗаданий(n).печатно();
            };
        }

        /** То же в единственном числе, но без ведущей единицы — как пишут на картах. */
        String безЕдиницы() {
            String с = штука(1);
            return с.startsWith("1 ") ? с.substring(2) : с;
        }
    }
}
