/**
 * ЗАДАНИЯ НА НЕПРЕРЫВНОЕ СОСЕДСТВО — восемь карт (заказ дизайнера 19.08.2026).
 *
 * <p>ЗАЧЕМ ОНИ. Пункт 6 заказа от 13.08.2026 требовал заменить самые
 * невыполняемые задания на задания «на фигуры из жетонов». Замер 19.08.2026
 * подтвердил нужду с другой стороны: карт-фигур в колоде было ТРИ на 52, и две
 * из них (o50 «Линия фронта», o54 «Заслон») не выполнялись НИ РАЗУ за 300
 * партий. То есть подвид заданий существовал формально.
 *
 * <p>ГЛАВНЫЙ УРОК, ВЛОЖЕННЫЙ В ЭТИ ВОСЕМЬ. Фигура дорога: чтобы связать два
 * гекса, нужны жетоны на каждом гексе пути, а жетоны нужны ещё и для войны и
 * для стройки. Поэтому БАЗОВОЕ требование здесь всегда короткое — два соседних
 * гекса подходящего вида уже закрывают карту, — а вся трудность вынесена в
 * УСИЛЕНИЕ (длина, состав участников, запрет вышек). Прежние две карты ровно на
 * этом и умерли: у них и базовое требование просило длинную цепь.
 *
 * <p>ПРЯМЫЕ ЛИНИИ СЮДА НЕ ВОШЛИ. Распознаватель прямых полос из половин гексов
 * написан и покрыт тестом ({@code Shapes.longestStraightBand}), но дизайнер
 * отложил такие задания 19.08.2026: правило слишком трудно объяснить за столом.
 */
public final class ЗаданияСоседства {

    private ЗаданияСоседства() {
    }

    /** Общий предок: все восемь — состояния, все считаются одним распознавателем. */
    private abstract static class Соседство extends ЗаданиеВКоде {
        Соседство(String id) {
            super(id);
        }

        /** Параметры базового требования для {@link Shapes#chainConnects}. */
        protected abstract Map<String, Object> базовое();

        /** Параметры усиленного требования. */
        protected abstract Map<String, Object> усиленное();

        @Override
        public boolean satisfied(CardContext ctx) {
            return Shapes.chainConnects(ctx.state(), ctx.seat(), базовое());
        }

        @Override
        public boolean satisfiedEnhanced(CardContext ctx) {
            return Shapes.chainConnects(ctx.state(), ctx.seat(), усиленное());
        }

        /**
         * БЛИЗОСТЬ — по размеру самой большой связной группы против того, сколько
         * гексов нужно фигуре.
         *
         * <p>Точнее посчитать нельзя дёшево: «сколько осталось до фигуры» — это
         * задача о путях, и решать её на каждом выборе бота слишком дорого. Зато
         * размер группы честно отражает главное препятствие: фигура не собирается
         * потому, что жетоны стоят вразброс. Потолок — половина шкалы: своя
         * группа нужного размера ещё не значит, что она накрыла нужные гексы.
         */
        @Override
        public double progress(CardContext ctx) {
            if (satisfied(ctx)) {
                return 1.0;
            }
            int need = базовое().get("min_hexes") instanceof Number n
                ? n.intValue()
                : (базовое().get("anchor_count") instanceof Number a ? a.intValue() : 2);
            int have = Shapes.largestConnectedHexes(ctx.state(), ctx.seat());
            return готовность(доля(have, Math.max(2, need)));
        }

        /**
         * ЧЕГО НЕ ХВАТАЕТ — общий текст на всю семью.
         *
         * <p>Точнее сказать нельзя честно: «докуда именно тянуть цепь» — это
         * задача о путях, и ответ зависит от того, какую пару опор игрок выберет.
         * Поэтому подсказка называет ПРЕПЯТСТВИЕ, а не готовый маршрут: жетоны
         * стоят вразброс, и фигура не собирается именно из-за этого.
         */
        @Override
        public String needed(CardContext ctx) {
            if (satisfied(ctx)) {
                return "";
            }
            int have = Shapes.largestConnectedHexes(ctx.state(), ctx.seat());
            return "свести жетоны в одну непрерывную цепь (сейчас самая большая — "
                + have + " гекс" + (have == 1 ? "" : have < 5 ? "а" : "ов") + ")";
        }

        @Override
        protected String действие() {
            return "movement";   // фигуру собирают Движением
        }
    }

    // ==================================================================
    //  1. ПЕРИМЕТР — от края поля до края (существующая o55)
    // ==================================================================

    // ==================================================================
    //  2. ПРОРЫВ — от своего здания до чужого
    // ==================================================================

    // ==================================================================
    //  3. ДОРОГА МЕЖДУ ДВОРАМИ — через стартовые зарождения
    // ==================================================================

    // ==================================================================
    //  4. ЖИВАЯ ЦЕПЬ — только войсками
    // ==================================================================

    // ==================================================================
    //  5. ПРОМЫШЛЕННАЯ СВЯЗКА — только зданиями
    // ==================================================================

    // ==================================================================
    //  6. КЛИН — до чужого здания, но по земле
    // ==================================================================

    // ==================================================================
    //  7. ШИРОКИЙ ФРОНТ — три края разом
    // ==================================================================

    // ==================================================================
    //  8. ОБХОД — вокруг зарождения, длиной
    // ==================================================================
}
