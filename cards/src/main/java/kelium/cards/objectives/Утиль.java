    private final String метка;
    private final String эффект;
    private final Map<String, Object> параметры;

    /** Даровое действие: эффект один и тот же, разнится только само действие. */
    Утиль(String метка, String действие) {
        this(метка, "free_action", Map.of("action", действие));
    }

    Утиль(String метка, String эффект, Map<String, Object> параметры) {
        this.метка = метка;
        this.эффект = эффект;
        this.параметры = параметры;
    }

    /** Что напечатано на карте. */
    public String метка() {
        return метка;
    }

    /**
     * ЗАПИСЬ ВЕРХА ДЛЯ КАТАЛОГА — метка, идентификатор эффекта и параметры.
     *
     * <p>Эффект здесь НЕ для исполнения: играет верх метод {@link #сыграть}.
     * Он для того, чтобы верх можно было прочитать, не разбирая русскую строку,
     * — оценкой бота, справочником и сводом.
     */
    public Map<String, Object> запись() {
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("label", метка);
        out.put("effect", эффект);
        if (!параметры.isEmpty()) {
            // КЛЮЧИ ПО АЛФАВИТУ: Map.of не держит порядка, и без сортировки
            // каждая выгрузка каталога перетасовывала параметры заново.
            out.put("params", new LinkedHashMap<>(new java.util.TreeMap<>(параметры)));
        }
        return out;
    }

    /** Реакция ли это — верх, который играется только в чужой ход. */
    public boolean реакция() {
        return "reaction".equals(эффект);
    }

    /**
     * Сыграть верх. Даровое действие — общий случай, остальные переопределяют.
     *
     * <p>РЕАКЦИЯ ЗДЕСЬ НЕ ИГРАЕТСЯ НИКОГДА. Её окно открывает бой, и вне окна
     * ответить нечем: сжечь карту «в свой ход просто так» значило бы отдать её
     * даром. Поэтому здесь честный отказ, а не молчаливое ничего.
     */
    public boolean сыграть(CardContext ctx) {
        if (реакция()) {
            return false;
        }
        ctx.freeAction(String.valueOf(параметры.get("action")));
        return true;
    }

    /**
     * ВКЛЮЧЁН ЛИ УРЕЗАННЫЙ УТИЛЬ (свод {@code objectives.util_limited}).
     *
     * <p>Правило-вариант: полные действия в утиле сжимаются до одного жетона.
     * Проверяется гипотеза, что карты сжигают потому, что утиль не слабее
     * награды, а условия не требует.
     */
    static boolean урезанный(CardContext ctx) {
        return Boolean.TRUE.equals(kelium.dataio.Ctx.rules(ctx.state())
            .get("objectives.util_limited", Boolean.FALSE));
    }

    /** Найти утиль по печатной метке — для чтения старых наборов и таблиц. */
    public static Утиль поМетке(String метка) {
        for (Утиль у : values()) {
            if (у.метка.equals(метка)) {
                return у;
            }
        }
        return null;
    }
