package kelium.cards.objectives;

import kelium.cards.Награда;

/**
 * ЛИЦО КАРТЫ ЗАДАНИЯ — всё, что на карте напечатано, объявленное в коде.
 *
 * <p>ЗАЧЕМ ЭТО ЕСТЬ. Раньше карта была разорвана: условие проверял код, а имя,
 * порог, награда и текст лежали в YAML. Разойтись они могли молча — и расходились:
 * в коде порог два здания, на карте напечатано три; в пачке карт стоит имя
 * «Основа», в каталоге «Подъём». Заметить это было нечем, потому что никто и
 * ничто не сравнивало два источника.
 *
 * <p>ТЕПЕРЬ ИСТОЧНИК ОДИН — КЛАСС КАРТЫ. Каталог не читается, а ВЫГРУЖАЕТСЯ из
 * классов: то, что печатается на карте, показывает визуализатор и раздаёт движок,
 * берётся из одного и того же места. Разойтись стало нечему.
 *
 * @param имя        печатное название карты
 * @param вид        обычная карта или начальная
 * @param природа    что проверяет условие: расстановку, событие хода или плату
 * @param условие    печатный текст обычного требования
 * @param усиление   печатный текст усиленного требования; {@code null}, если его нет
 * @param награда    награда за обычное требование
 * @param сверх      добавка за усиленное требование
 * @param верх       одноразовый эффект: карту сжигают вместо выполнения.
 *                   Объявлен ОДИН раз — перечислением {@link Утиль}, которое
 *                   держит и печатную метку, и то, что верх делает. Раньше
 *                   здесь стояла голая строка, а поведение — отдельным методом
 *                   {@code burn} в каждой карте: разойтись этой паре было
 *                   нечему помешать. {@code null}, если сжигать нечем
 * @param описание   литературный текст карты целиком — для справочника и правил
 */
public record Лицо(String имя, Вид вид, Природа природа,
                   String условие, String усиление,
                   Награда награда, Награда сверх,
                   Утиль верх, String описание) {

    /** Обычная карта колоды или начальная (только первый раунд, без усиления). */
    public enum Вид { ОБЫЧНАЯ, НАЧАЛЬНАЯ }

    /**
     * ЧТО ПРОВЕРЯЕТ УСЛОВИЕ. Различие не косметическое: от него зависит и текст
     * карты, и то, можно ли доказать выполнение за столом.
     */
    public enum Природа {
        /** Расстановка на столе прямо сейчас. Текст: «имей…». */
        СОСТОЯНИЕ,
        /** Событие ЭТОГО хода — доказать задним числом нечем. Текст: «в этот ход…». */
        ПРОИСШЕСТВИЕ,
        /** Плата в момент розыгрыша: сдай, верни, отдай. */
        ЖЕРТВА
    }

    /**
     * ПРОВЕРКА ФОРМЫ КАРТЫ — правила дизайнера, нарушение которых должно быть
     * ошибкой сборки, а не замечанием в ревью через полгода.
     *
     * @return жалоба человеческой строкой или {@code null}, если карта в порядке
     */
    public String жалоба() {
        if (имя == null || имя.isBlank()) {
            return "у карты нет печатного имени";
        }
        if (условие == null || условие.isBlank()) {
            return "у карты нет печатного текста условия";
        }
        if (природа == Природа.ПРОИСШЕСТВИЕ && !условие.contains("В ЭТОТ ХОД")) {
            return "требование-происшествие обязано начинаться с «В ЭТОТ ХОД»: "
                + "без этой приписки карта читается как «когда-нибудь сделал», "
                + "а записи матча у игроков нет";
        }
        if (природа == Природа.СОСТОЯНИЕ && условие.contains("В ЭТОТ ХОД")) {
            return "требование-состояние не может говорить «В ЭТОТ ХОД»: "
                + "карта обещала бы событие, а проверяла расстановку";
        }
        if (вид == Вид.НАЧАЛЬНАЯ && усиление != null) {
            return "у начальных заданий нет усиления ни у одного";
        }
        if (вид == Вид.НАЧАЛЬНАЯ && !сверх.пусто()) {
            return "у начального задания не может быть добавки за усиление";
        }
        // ДВА ВИДА — ЭТО ПРЕДЕЛ ДЛЯ КАРТЫ С УСИЛЕНИЕМ. У карты БЕЗ усиления
        // награда одна и выдаётся целиком (решение дизайнера 09.09.2026: в его
        // таблице у восьми карт из сорока в колонке усиления тире, а обе
        // колонки награды — одна и та же награда). Там законны три вида: то,
        // что у других карт разложено на базовую и усиленную, здесь стоит
        // рядом.
        if (награда.видов() > (усиление == null ? 3 : 2)) {
            return "в базовой награде больше "
                + (усиление == null ? "трёх" : "двух") + " видов добра: "
                + награда.печатно();
        }
        if (сверх.видов() > 2) {
            return "в усиленной награде больше двух видов добра: " + сверх.печатно();
        }
        if (всегоВидов() > 3) {
            return "на карте больше трёх разных видов награды суммарно: "
                + награда.печатно() + " плюс " + сверх.печатно();
        }
        if (усиление != null && усиление.equals(условие)) {
            return "усиленное требование напечатано теми же словами, что обычное";
        }
        String приказ = повелительное(условие);
        if (приказ == null && усиление != null) {
            приказ = повелительное(усиление);
        }
        if (приказ != null) {
            return "требование написано приказом («" + приказ + "»), а должно быть "
                + "ПРОВЕРКОЙ: «у тебя есть», «ты стоишь», «ты сделал», «ты сыграл», "
                + "«у тебя не осталось», «ты подвигал», «ты уничтожил в этот ход»";
        }
        return null;
    }

    /**
     * ПОВЕЛИТЕЛЬНОЕ НАКЛОНЕНИЕ В ТРЕБОВАНИИ — ошибка формы (решение дизайнера
     * 18.10.2026: «убрать императивный текст, вместо него настоящее или
     * прошедшее время проверка; никаких указательных „уничтожь, сыграй,
     * сделай“»).
     *
     * <p>Почему это сторожится кодом, а не ревью. Карта говорит игроку, ЧТО
     * проверяется в момент розыгрыша, а приказ обещает действие, которого в
     * действии приказа нет: «уничтожь добытчик» звучит как разрешение
     * уничтожить, хотя карта только смотрит, уничтожен ли он. Разницу легко
     * потерять при правке одной карты из полусотни.
     *
     * @return найденное повелительное слово или {@code null}
     */
    private static String повелительное(String текст) {
        if (текст == null) {
            return null;
        }
        for (String слово : ПРИКАЗЫ) {
            java.util.regex.Matcher m = java.util.regex.Pattern
                .compile("(?iu)(?<!\\p{L})" + слово + "(?!\\p{L})")
                .matcher(текст);
            if (m.find()) {
                return m.group();
            }
        }
        return null;
    }

    /**
     * Повелительные формы, которыми были написаны прежние карты. Список именно
     * из встречавшихся слов, а не «вообще всех глаголов»: сторож должен ловить
     * возврат к старому стилю, а не угадывать русскую морфологию.
     */
    private static final String[] ПРИКАЗЫ = {
        "имей", "имейте", "уничтожь", "построй", "сыграй", "сделай", "займи",
        "сдай", "сбрось", "верни", "найми", "дойди", "забери", "возьми",
        "воспользуйся", "произведи", "держи", "снеси", "отдай", "подвигай",
        "атакуй", "активируй", "потрать", "перенеси", "поставь", "собери",
        "стой", "выполни", "открой", "вскрой", "запитай", "пожертвуй",
    };

    private int всегоВидов() {
        java.util.Set<String> виды = new java.util.LinkedHashSet<>();
        виды.addAll(награда.выгрузить().keySet());
        виды.addAll(сверх.выгрузить().keySet());
        return виды.size();
    }
}
