package kelium.cards.objectives;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * СЕМЬ СЕМЕЙСТВ КОЛОДЫ ЗАДАНИЙ — таблица дизайнера 04–06.09.2026.
 *
 * <p>ЗАЧЕМ ОТДЕЛЬНЫМ КЛАССОМ. Семейство — это не украшение каталога, а рабочий
 * признак: дизайнер раздаёт утиль ПО СЕМЕЙСТВАМ («щиты достались Засаде»,
 * «Обеспечению этот утиль не дан ни одной картой»), и без семейства такую
 * раздачу нельзя ни показать, ни проверить. До сих пор список семейств жил
 * только в сборщике {@code tools/собрать-задания-1-17-0.py}, то есть в
 * инструменте, который не запускается на рабочей машине и которого не видит ни
 * движок, ни справочник.
 *
 * <p>ПОРЯДОК ВНУТРИ СЕМЬИ — тот же, что в сборщике: так колоду читают глазами и
 * так она выгружена в каталог.
 *
 * <p>НАЧАЛЬНЫЕ ЗАДАНИЯ семейств не имеют: это обучающие карты первого раунда,
 * и таблица дизайнера их не делит.
 */
public final class СемействаЗаданий {

    private СемействаЗаданий() {
    }

    /** Семейство → номера карт, в порядке таблицы дизайнера. */
    public static final Map<String, List<String>> ПО_СЕМЕЙСТВАМ;

    static {
        Map<String, List<String>> m = new LinkedHashMap<>();
        m.put("Выработка", List.of("o04", "o05", "o40", "o08", "o01"));
        m.put("Засада", List.of("o29", "o03", "o07", "o27", "o63"));
        m.put("Обеспечение", List.of("o33", "o36", "o34", "o64"));
        // ПОРЯДОК 1.19.0 — ПО ПЕЧАТНЫМ НОМЕРАМ КАРТ (рисунки дизайнера
        // 25.09.2026, номера 01-40): в «Развёртывании» № 19 — o12, № 20 — o15; в
        // «Экспансии» № 37 — o02, № 38 — o75.
        m.put("Развёртывание", List.of("o17", "o11", "o18", "o65", "o12", "o15", "o20"));
        m.put("Расплата", List.of("o66", "o67", "o10", "o06"));
        m.put("Устранение", List.of("o68", "o69", "o42", "o25", "o70", "o71", "o72",
            "o21", "o43", "o73"));
        m.put("Экспансия", List.of("o74", "o02", "o75", "o76", "o77"));
        ПО_СЕМЕЙСТВАМ = Map.copyOf(m);
    }

    /** Имена семейств в порядке таблицы. */
    public static final List<String> ИМЕНА = List.of("Выработка", "Засада",
        "Обеспечение", "Развёртывание", "Расплата", "Устранение", "Экспансия");

    private static final Map<String, String> ПО_КАРТАМ;

    static {
        Map<String, String> m = new LinkedHashMap<>();
        for (String семья : ИМЕНА) {
            for (String id : ПО_СЕМЕЙСТВАМ.get(семья)) {
                m.put(id, семья);
            }
        }
        ПО_КАРТАМ = Map.copyOf(m);
    }

    /** Семейство карты или {@code "—"} у начальных и у карт вне таблицы. */
    public static String семейство(String id) {
        return ПО_КАРТАМ.getOrDefault(id, "—");
    }

    /** Сколько карт в колоде разложено по семействам (для сторожей). */
    public static int карт() {
        return ПО_КАРТАМ.size();
    }
}
