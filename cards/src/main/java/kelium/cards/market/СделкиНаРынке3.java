    /**
     * Келемий встаёт в ячейку энергии своего здания и остаётся там до конца
     * партии. Копий: 1 — у кого все здания запитаны, тому предложение пустое.
     */
    private static Map<String, Object> подключение() {
        return предл("Подключение", "place_on_energy_cell", Map.of(),
            "келемий в ячейку энергии навсегда");
    }

    /**
     * Жетон первого игрока и ОДНА карта задания из руки того, у кого его
     * забрали. Копий: 1.
     *
     * <p>Вся рука (набор 2.0.0) отменена дизайнером 14.09.2026: забрать у
     * соседа все бумаги разом — не торговля, а разбой по одному человеку за
     * столом, выбранному жребием колоды. Одна карта — ровно та же мысль без
     * обиды.
     */
    private static Map<String, Object> перехватИнициативы() {
        return предл("Перехват инициативы", "grab_first_player",
            Map.of("now", true, "take_objective_cards", 1),
            "жетон первого игрока и 1 карта задания у него");
    }

    /** Добыча даром, и все добытчики считаются запитанными. Копий: 1. */
    private static Map<String, Object> наряд() {
        return предл("Наряд", "free_action",
            Map.of("action", "mining", "all_powered", true),
            "Добыча даром: все добытчики запитаны");
    }

    /** Манёвр даром и 2 боеприпаса. Копий: 1. */
    private static Map<String, Object> передислокация() {
        return предл("Передислокация", "free_action",
            Map.of("action", "movement", "ammo", 2),
            "Манёвр даром и 2 боеприпаса");
    }

    // ======================================================================
    //  ДЕСЯТЬ КАРТ
    // ======================================================================

