    private static Map<String, Object> предл(String name, String effect,
                                             Map<String, Object> params, String label) {
        return Map.of("name", name, "effect", effect, "params", params, "label", label);
    }

    /** То же, но предложение не занимает ячейку (см. {@code no_cell}). */
    private static Map<String, Object> предлБезЯчейки(String name, String effect,
                                                      Map<String, Object> params,
                                                      String label) {
        return Map.of("name", name, "effect", effect, "params", params, "label", label,
            "no_cell", true);
    }

