package kelium.cards.market;

import java.util.List;
import java.util.Map;

/**
 * ДЕСЯТЬ КАРТ РЫНКА НАБОРА 4.0.0 — ПЕЧАТЬ ДИЗАЙНЕРА 24.09.2026
 * («Общие компоненты / экспорт-колода-рынка», карты 01–10; решение 25.09.2026:
 * «пока играем с такими картами рынка, меня они устраивают»).
 *
 * <p>ИСТОЧНИК — ЛИЦО КАРТЫ. Каждая половина напечатана одной фразой и одной
 * иконкой; здесь ровно эта фраза, без добавок прежних наборов («Бой даром и
 * 2 боеприпаса», «все здания запитаны» на печати больше нет — значит, нет и
 * здесь). Номер класса = номер в углу карты.
 *
 * <p>ВОСЕМЬ ПРЕДЛОЖЕНИЙ НА ДЕСЯТЬ КАРТ: четыре ресурсных («получи») и четыре
 * действия («выполни»). Пары на картах не повторяются.
 *
 * <p>Набор 3.0.0 остаётся нетронутым: на нём сыграны записи партий, и класс
 * накрывает каталог своим номером — правка задним числом переписала бы их.
 */
public final class СделкиНаРынке4 {

    private СделкиНаРынке4() {
    }

    private static Map<String, Object> предл(String name, String effect,
                                             Map<String, Object> params, String label) {
        return Map.of("name", name, "effect", effect, "params", params, "label", label);
    }

    // ======================================================================
    //  ПОЛУЧИ
    // ======================================================================

    /** «Получи 5 монет». */
    private static Map<String, Object> монеты() {
        return предл("5 монет", "gain", Map.of("coin", 5), "Получи 5 монет");
    }

    /** «Получи 2 арсенала» — две карты арсенала вслепую, в руку (рука без предела). */
    private static Map<String, Object> арсенал() {
        return предл("2 арсенала", "gain", Map.of("arsenal", 2), "Получи 2 арсенала");
    }

    /** «Получи 3 боеприпаса». */
    private static Map<String, Object> боеприпасы() {
        return предл("3 боеприпаса", "gain", Map.of("ammo", 3), "Получи 3 боеприпаса");
    }

    /** «Посмотри 4 задания — 2 оставь себе». */
    private static Map<String, Object> задания() {
        return предл("4 задания, 2 себе", "gain",
            Map.of("objective_cards", 4, "objective_cards_keep", 2),
            "Посмотри 4 задания — 2 оставь себе");
    }

    // ======================================================================
    //  ВЫПОЛНИ
    // ======================================================================

    /**
     * «Выполни наём 2 разных войск на 1 гекс» — иконка найма «2+» со стрелкой
     * на гекс. Два жетона РАЗНЫХ родов из запаса на один гекс своей зоны
     * стройки (как десант заданий: место на печати не названо, значит, туда,
     * куда игрок вообще вправе ставить).
     */
    private static Map<String, Object> наём() {
        return предл("Наём 2 войск", "landing", Map.of("count", 2, "same_hex", true),
            "Выполни наём 2 разных войск на 1 гекс");
    }

    /** «Выполни „Манёвр“». */
    private static Map<String, Object> манёвр() {
        return предл("Манёвр", "free_action", Map.of("action", "movement"),
            "Выполни «Манёвр»");
    }

    /** «Выполни „Питание“» — смена энергии. */
    private static Map<String, Object> питание() {
        return предл("Питание", "free_action", Map.of("action", "energy_swap"),
            "Выполни «Питание»");
    }

    /** «Выполни „Бой“». */
    private static Map<String, Object> бой() {
        return предл("Бой", "free_action", Map.of("action", "combat"), "Выполни «Бой»");
    }

    // ======================================================================
    //  ДЕСЯТЬ КАРТ — левая половина · правая, как на печати
    // ======================================================================

    private static final class Карта4 extends СделкаВКоде {
        private final ЛицоСделки лицо;

        Карта4(String id, String имя, Map<String, Object> левое, Map<String, Object> правое) {
            super(id);
            this.лицо = new ЛицоСделки(имя, левое, правое, левое.get("label") + " · "
                + правое.get("label"));
        }

        @Override
        public ЛицоСделки лицо() {
            return лицо;
        }
    }

    /** Все десять карт набора по порядку номеров на печати. */
    public static List<СделкаВКоде> все() {
        return List.of(
            new Карта4("m4_01", "Рынок 01", наём(), монеты()),
            new Карта4("m4_02", "Рынок 02", монеты(), арсенал()),
            new Карта4("m4_03", "Рынок 03", арсенал(), манёвр()),
            new Карта4("m4_04", "Рынок 04", манёвр(), питание()),
            new Карта4("m4_05", "Рынок 05", питание(), боеприпасы()),
            new Карта4("m4_06", "Рынок 06", боеприпасы(), задания()),
            new Карта4("m4_07", "Рынок 07", задания(), бой()),
            new Карта4("m4_08", "Рынок 08", бой(), наём()),
            new Карта4("m4_09", "Рынок 09", монеты(), питание()),
            new Карта4("m4_10", "Рынок 10", боеприпасы(), арсенал()));
    }
}
