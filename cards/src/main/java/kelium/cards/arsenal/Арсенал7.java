    private static void карта(List<Card> out, String id, ЛицоАрсенала.Вид вид, String имя,
                              Верх верх, Низ низ, int звёзд) {
        карта(out, id, вид, имя, null, верх, низ, звёзд);
    }

    /**
     * @param печатное что напечатано в поле названия, если там не {@code имя}
     *                 (дубль названия соседней карты на печати 25.09.2026)
     */
    private static void карта(List<Card> out, String id, ЛицоАрсенала.Вид вид, String имя,
                              String печатное, Верх верх, Низ низ, int звёзд) {
        String описание = "Утиль: " + верх.текст() + ". Установка: " + низ.текст()
            + (звёзд > 0 ? " Пока установлена — " + звёзд + " победное очко." : "");
        out.add(new Карта(id, new ЛицоАрсенала(имя, вид, низ.контейнер(),
            верх.эффект(), верх.параметры(), верх.текст(),
            низ.вид(), низ.способность(), null, низ.текст(), описание, звёзд, печатное)));
    }

    private static void обычная(List<Card> out, int номер, String имя, Верх верх, Низ низ,
                                int звёзд) {
        карта(out, String.format("a7_%02d", номер), ОБЫЧНАЯ, имя, верх, низ, звёзд);
    }

