package kelium.cards.arsenal;

import java.util.Map;

/**
 * КАРТА АРСЕНАЛА, ЖИВУЩАЯ ЦЕЛИКОМ В КОДЕ.
 *
 * <p>Наследует {@link ArsenalCardBase} и получает даром всё, что уже правильно
 * работает от данных: оценку установки/утиля по самоописанию способности
 * ({@code installValue}/{@code burnValue}), сжигание верха через реестр
 * эффектов ({@code CardTop.burn}). Единственное, что здесь меняется, — ОТКУДА
 * берётся запись: не из YAML, а из {@link #лицо()} самого класса.
 *
 * <p>ПОЧЕМУ ЭТОГО ДОСТАТОЧНО, А НЕ НУЖНО ПЕРЕПИСЫВАТЬ burn()/usefulness()
 * ПО-СВОЕМУ У КАЖДОЙ КАРТЫ. У заданий предикат был МЁРТВЫМ строковым
 * диспетчером: незарегистрированный ключ молча означал «не выполнено», и три
 * карты из-за этого не работали годами. У арсенала другая история: реестр
 * эффектов и реестр способностей — уже код, уже проверены (ни одного мёртвого
 * id), и разбор награды/утиля по данным — это законная общая услуга движка,
 * тот же принцип, каким объектные карты заданий пользуются
 * {@code CardRewards.grantFromData} или {@code ctx.freeAction(...)}. Разница
 * между картами арсенала — это данные (какой эффект, какая способность), а не
 * поведение, и плодить 42 одинаковых by-hand реализации burn() значило бы
 * имитировать объектное устройство, а не строить его.
 */
public abstract class КартаАрсеналаВКоде extends ArsenalCardBase {

    protected КартаАрсеналаВКоде(String id) {
        super(id);
    }

    /** ВСЁ, ЧТО НА КАРТЕ НАПЕЧАТАНО. Объявляется каждой картой в её классе. */
    public abstract ЛицоАрсенала лицо();

    @Override
    public final boolean describesItself() {
        return true;
    }

    @Override
    public final String name() {
        return лицо().имя();
    }

    @Override
    public final String describe() {
        // Текст карты — из набора, когда он там задан: см. data().
        Object текст = запись == null ? null : запись.get("описание");
        return текст instanceof String s && !s.isBlank() ? s : лицо().описание();
    }

    /**
     * ЗАПИСЬ НАБОРА, если карта пришла из файла — нужна только для УТИЛЯ.
     *
     * @see #data()
     */
    private Map<String, Object> запись;

    @Override
    public final void bind(Map<String, Object> entry) {
        // КОПИЯ, А НЕ ССЫЛКА: сразу после bind() реестр стирает эту запись и
        // заполняет её выгрузкой карты (см. CardRegistry.bindAll). По ссылке мы
        // читали бы то, что сами же и записали, — и утиль из набора терялся бы.
        this.запись = entry == null ? null : new java.util.LinkedHashMap<>(entry);
    }

    /**
     * ВСЁ, ЧТО НА КАРТЕ, — из класса; УТИЛЬ — из набора, если тот его задаёт.
     *
     * <p>ПОЧЕМУ ВЕРХ ЖИВЁТ В ДАННЫХ, А НИЗ В КОДЕ (решение 21.08.2026). Низ — это
     * ПОВЕДЕНИЕ: способность вмешивается в точку правил, у неё есть условия и
     * самоописание, и держать её в строке данных значило бы вернуть тот самый
     * разрыв, который чинили у заданий. Верх — это ДАННЫЕ и ничего кроме:
     * идентификатор эффекта из общего реестра плюс его параметры; сам класс к
     * исполнению утиля не добавляет ни строки.
     *
     * <p>И это не удобство, а необходимость. Наборы карт НЕИЗМЕНЯЕМЫ: правка
     * утиля — это новая версия набора, а класс у обеих версий один и тот же. Если
     * бы верх жил только в классе, изменить его в новой версии было бы нельзя, не
     * изменив заодно и старую, — то есть нельзя было бы ни сравнить две редакции
     * утиля замером, ни воспроизвести прошлые партии.
     *
     * <p>Печатное описание тоже берётся из набора, когда оно там есть: текст
     * карты рассказывает и про верх, и менять его отдельно от утиля нельзя.
     */
    @Override
    public final Map<String, Object> data() {
        Map<String, Object> out = лицо().выгрузить(id());
        if (запись != null && запись.get("top") instanceof Map<?, ?> top) {
            out.put("top", top);
        }
        if (запись != null && запись.get("описание") instanceof String текст) {
            out.put("описание", текст);
        }
        return out;
    }

    @Override
    public String passiveId() {
        return лицо().пассивка();
    }
}
