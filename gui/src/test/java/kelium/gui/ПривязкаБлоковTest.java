package kelium.gui;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import org.junit.jupiter.api.Test;

import kelium.dataio.GameConfig;
import kelium.engine.BlockAssembler.Cell;
import kelium.engine.BlockAssembler.Placement;

/**
 * ПРИВЯЗКА СБОРКИ К КАРТОНКАМ — сторож на то, что метки едут вместе с блоком.
 *
 * <p>ЗАЧЕМ ОН ОБЯЗАТЕЛЕН. Ошибка здесь НЕ ВИДНА ГЛАЗОМ: если контейнер уедет на
 * соседний гекс или в соседний сектор, картинка останется совершенно
 * правдоподобной — блоки те же, меток столько же, — и брак уйдёт в печать.
 * Поэтому поворот проверяется не на вид, а счётом.
 */
class ПривязкаБлоковTest {

    private static Map<String, НаборыБлоков.Версия> наборы() {
        Map<String, НаборыБлоков.Версия> все =
            НаборыБлоков.загрузить(GameConfig.resolveDataRoot(null));
        assertTrue(!все.isEmpty(), "наборы блоков не прочитались");
        return все;
    }

    /**
     * ОСНОВНОЙ ИНВАРИАНТ ПОВОРОТА: поворот КЛЕТКИ и поворот НОМЕРА СЕКТОРА
     * обязаны означать одно и то же движение.
     *
     * <p>Проверяется прямо по векторам направлений: вектор сектора, повёрнутый
     * тем же преобразованием, что и клетка, обязан оказаться вектором того
     * сектора, который выдаёт {@code повернутьСектор}. Если эти две операции
     * разойдутся, метки поедут по кругу относительно картонки.
     */
    @Test
    void поворотКлеткиИПоворотСектораОдноИТоЖе() {
        int[][] напр = kelium.core.Field.AXIAL_DIRS;
        for (int сектор = 0; сектор < 6; сектор++) {
            Cell вектор = new Cell(напр[сектор][0], напр[сектор][1]);
            Cell повёрнутый = вектор;
            for (int шагов = 1; шагов <= 6; шагов++) {
                повёрнутый = ПривязкаБлоков.повернуть(повёрнутый);
                int ждём = ПривязкаБлоков.повернутьСектор(сектор, шагов);
                assertEquals(напр[ждём][0], повёрнутый.q(),
                    "сектор " + сектор + ", шагов " + шагов + ": q вектора разошёлся");
                assertEquals(напр[ждём][1], повёрнутый.r(),
                    "сектор " + сектор + ", шагов " + шагов + ": r вектора разошёлся");
            }
        }
    }

    /**
     * УКЛАДКА СТОРОНЫ НА ПОВЁРНУТЫЙ КУСОК: каждая метка обязана оказаться на
     * своём гексе и в своём секторе.
     *
     * <p>Проверка round-trip: берём сторону, поворачиваем её РУКАМИ на k шагов
     * (и клетки, и секторы), делаем из повёрнутых клеток кусок сборки — и
     * требуем, чтобы {@code уложить} вернула ровно то же самое.
     */
    @Test
    void сторонаЛожитсяЛюбымПоворотомБезПотериМеток() {
        for (НаборыБлоков.Версия версия : наборы().values()) {
            for (НаборыБлоков.Сторона сторона : версия.все()) {
                for (int шагов = 0; шагов < 6; шагов++) {
                    // руками поворачиваем сторону
                    Map<String, int[]> ждём = new HashMap<>();
                    List<Cell> клетки = new ArrayList<>();
                    for (НаборыБлоков.Гекс h : сторона.гексы()) {
                        Cell c = new Cell(h.q(), h.r());
                        for (int i = 0; i < шагов; i++) {
                            c = ПривязкаБлоков.повернуть(c);
                        }
                        клетки.add(c);
                        ждём.put(c.q() + ":" + c.r(), new int[]{
                            ПривязкаБлоков.повернутьСектор(h.контейнер(), шагов),
                            ПривязкаБлоков.повернутьСектор(h.энергия(), шагов)});
                    }
                    Placement место = new Placement(клетки.size(), клетки);
                    var п = ПривязкаБлоков.уложить(место, сторона);
                    assertNotNull(п, версия.id() + " " + сторона.подпись()
                        + ": сторона не легла поворотом " + шагов);
                    assertEquals(сторона.гексы().size(), п.гексы().size(),
                        "гексов в привязке не столько, сколько на стороне");
                    for (var h : п.гексы()) {
                        int[] надо = ждём.get(h.клетка().q() + ":" + h.клетка().r());
                        assertNotNull(надо, версия.id() + " " + сторона.подпись()
                            + " поворот " + шагов + ": лишний гекс "
                            + h.клетка());
                        assertEquals(надо[0], h.контейнер(),
                            версия.id() + " " + сторона.подпись() + " поворот " + шагов
                                + ", гекс " + h.клетка() + ": сектор контейнера уехал");
                        assertEquals(надо[1], h.энергия(),
                            версия.id() + " " + сторона.подпись() + " поворот " + шагов
                                + ", гекс " + h.клетка() + ": сектор энергии уехал");
                    }
                }
            }
        }
    }

    /**
     * РАЗДАЧА БЕЗ ПОВТОРОВ: один блок не может лежать на поле дважды — картонка
     * в коробке одна.
     */
    @Test
    void одинБлокНеЛожитсяДважды() {
        НаборыБлоков.Версия версия = наборы().values().iterator().next();
        // Пять малых кусков подряд: столько малых блоков и есть в коробке.
        List<Placement> куски = new ArrayList<>();
        for (int i = 0; i < 5; i++) {
            List<Cell> клетки = new ArrayList<>();
            for (НаборыБлоков.Гекс h : версия.малые().get(0).гексы()) {
                клетки.add(new Cell(h.q() + i * 4, h.r()));
            }
            куски.add(new Placement(5, клетки));
        }
        for (long зерно = 1; зерно <= 20; зерно++) {
            var привязки = ПривязкаБлоков.привязать(куски, версия, зерно);
            assertEquals(5, привязки.size(), "зерно " + зерно + ": легли не все куски");
            java.util.Set<String> блоки = new java.util.HashSet<>();
            for (var п : привязки) {
                assertTrue(блоки.add(п.сторона().блок()),
                    "зерно " + зерно + ": блок " + п.сторона().блок()
                        + " лёг на поле дважды");
            }
        }
    }

    /** Кусков больше, чем картонок в коробке, — лишние просто не привязываются. */
    @Test
    void картонокНеБольшеЧемВКоробке() {
        НаборыБлоков.Версия версия = наборы().values().iterator().next();
        List<Placement> куски = new ArrayList<>();
        for (int i = 0; i < 8; i++) {
            List<Cell> клетки = new ArrayList<>();
            for (НаборыБлоков.Гекс h : версия.малые().get(0).гексы()) {
                клетки.add(new Cell(h.q() + i * 4, h.r()));
            }
            куски.add(new Placement(5, клетки));
        }
        var привязки = ПривязкаБлоков.привязать(куски, версия, 7L);
        assertEquals(5, привязки.size(),
            "малых картонок в коробке пять — больше пяти привязок быть не может");
    }
}
