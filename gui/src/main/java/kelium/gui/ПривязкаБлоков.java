package kelium.gui;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashSet;
import java.util.List;
import java.util.Random;
import java.util.Set;

import kelium.gui.BlockAssembler.Cell;
import kelium.gui.BlockAssembler.Placement;

/**
 * ПРИВЯЗКА СБОРКИ К ФИЗИЧЕСКИМ БЛОКАМ: какой кусок сборки — какая картонка.
 *
 * <p>ЗАЧЕМ. Сборщик поля работает с ФОРМАМИ, а не с картонками: его
 * {@link Placement} знает только размер и накрытые клетки. Пока этого хватало —
 * сборка показывала контуры. Но чтобы нарисовать на блоках печатные контейнеры
 * и жёлтые ячейки, надо знать, КАКОЙ блок лёг и КАКИМ ПОВОРОТОМ: метки привязаны
 * к номерам секторов гекса, и при повороте картонки они едут вместе с ней.
 *
 * <p>ОТРАЖЕНИЯ НЕТ. Формы обоих блоков АХИРАЛЬНЫ — {@code orientations} даёт по
 * шесть различных положений, а не двенадцать (проверено), то есть перевёрнутая
 * картонка ложится тем же контуром, что и повёрнутая. Значит для совпадения
 * контура хватает поворота, а какая СТОРОНА картонки смотрит вверх — свободный
 * выбор. Он и есть то, что дизайнер перебрасывает кнопкой «случайно: только
 * блоки»: сборка остаётся, а картонки в её ячейках меняются.
 *
 * <p>КАЖДЫЙ БЛОК — ОДНА КАРТОНКА. В коробке пять малых и пять больших, и один и
 * тот же блок не может лежать на поле дважды: раздача идёт без повторов.
 */
public final class ПривязкаБлоков {

    private ПривязкаБлоков() {
    }

    /**
     * Один гекс уложенного блока — уже в координатах ПОЛЯ и с секторами,
     * повёрнутыми вместе с картонкой.
     */
    public record ГексНаПоле(Cell клетка, int контейнер, int энергия) {

        public boolean естьКонтейнер() {
            return контейнер != НаборыБлоков.ПУСТО;
        }

        public boolean естьЭнергия() {
            return энергия != НаборыБлоков.ПУСТО;
        }

        public boolean контейнерВНебе() {
            return контейнер == НаборыБлоков.НЕБО;
        }
    }

    /**
     * Уложенный блок: какая сторона картонки, каким поворотом и что на её гексах.
     *
     * @param место     кусок сборки, как его вернул сборщик
     * @param сторона   сторона картонки из выбранного набора
     * @param поворотов на сколько шагов по 60° по часовой повёрнута картонка
     * @param гексы     гексы блока в координатах поля с повёрнутыми секторами
     */
    public record Привязка(Placement место, НаборыБлоков.Сторона сторона,
                           int поворотов, List<ГексНаПоле> гексы) {
    }

    // ==================================================================
    //  ПОВОРОТ
    // ==================================================================

    /** Поворот клетки на 60° по часовой в осевых координатах. */
    static Cell повернуть(Cell c) {
        return new Cell(-c.r(), c.q() + c.r());
    }

    /**
     * Поворот НОМЕРА СЕКТОРА на 60° по часовой.
     *
     * <p>Нумерация сторон гекса ({@code Field.AXIAL_DIRS}) идёт ПРОТИВ часовой,
     * поэтому при повороте картонки по часовой номер сектора сдвигается назад.
     * Небесный сектор стороне не принадлежит и не поворачивается вовсе.
     */
    static int повернутьСектор(int сектор, int шагов) {
        if (сектор == НаборыБлоков.ПУСТО || сектор == НаборыБлоков.НЕБО) {
            return сектор;
        }
        return (сектор + 6 - шагов % 6) % 6;
    }

    private static String отпечаток(List<Cell> клетки) {
        List<Cell> s = new ArrayList<>(клетки);
        s.sort(Comparator.comparingInt(Cell::r).thenComparingInt(Cell::q));
        Cell первая = s.get(0);
        StringBuilder sb = new StringBuilder();
        for (Cell c : s) {
            sb.append(c.q() - первая.q()).append(':').append(c.r() - первая.r()).append(';');
        }
        return sb.toString();
    }

    private static Cell перваяПоПорядку(List<Cell> клетки) {
        return клетки.stream()
            .min(Comparator.comparingInt(Cell::r).thenComparingInt(Cell::q))
            .orElseThrow();
    }

    // ==================================================================
    //  ПРИВЯЗКА
    // ==================================================================

    /**
     * Разложить куски сборки по картонкам выбранного набора.
     *
     * @param куски   что вернул сборщик
     * @param версия  выбранный набор блоков
     * @param выбор   чем тасовать картонки: одно и то же зерно — одна и та же
     *                раздача, поэтому показ не «дрожит» при каждой перерисовке
     * @return привязки в том же порядке, что и куски; кусок, которому не хватило
     *         картонки, пропускается
     */
    public static List<Привязка> привязать(List<Placement> куски,
                                           НаборыБлоков.Версия версия, long выбор) {
        List<Привязка> out = new ArrayList<>();
        if (версия == null || куски == null) {
            return out;
        }
        Random rnd = new Random(выбор);
        List<НаборыБлоков.Сторона> малые = раздача(версия.малые(), rnd);
        List<НаборыБлоков.Сторона> большие = раздача(версия.большие(), rnd);
        int сМалых = 0;
        int сБольших = 0;
        for (Placement место : куски) {
            boolean малый = место.size() == 5;
            List<НаборыБлоков.Сторона> запас = малый ? малые : большие;
            int взято = малый ? сМалых : сБольших;
            if (взято >= запас.size()) {
                continue;      // картонок этого размера больше нет
            }
            НаборыБлоков.Сторона сторона = запас.get(взято);
            if (малый) {
                сМалых++;
            } else {
                сБольших++;
            }
            Привязка п = уложить(место, сторона);
            if (п != null) {
                out.add(п);
            }
        }
        return out;
    }

    /**
     * РАЗДАЧА КАРТОНОК БЕЗ ПОВТОРОВ: по одному блоку каждого номера, сторона
     * каждого выбирается случайно. Физически блок один, и лежать на поле дважды
     * он не может; какая сторона вверх — решает раздача.
     */
    private static List<НаборыБлоков.Сторона> раздача(List<НаборыБлоков.Сторона> стороны,
                                                      Random rnd) {
        java.util.Map<String, List<НаборыБлоков.Сторона>> поБлокам =
            new java.util.LinkedHashMap<>();
        for (НаборыБлоков.Сторона с : стороны) {
            поБлокам.computeIfAbsent(с.блок(), k -> new ArrayList<>()).add(с);
        }
        List<НаборыБлоков.Сторона> out = new ArrayList<>();
        for (var e : поБлокам.entrySet()) {
            List<НаборыБлоков.Сторона> свои = e.getValue();
            out.add(свои.get(rnd.nextInt(свои.size())));
        }
        java.util.Collections.shuffle(out, rnd);
        return out;
    }

    /**
     * Найти поворот, которым сторона ложится на этот кусок сборки, и перенести
     * её метки в координаты поля. {@code null} — форма не совпала (такого быть
     * не должно: сборщик работает теми же двумя формами).
     */
    static Привязка уложить(Placement место, НаборыБлоков.Сторона сторона) {
        List<Cell> цель = место.cells();
        String отпЦели = отпечаток(цель);
        Cell перваяЦели = перваяПоПорядку(цель);

        List<Cell> свои = new ArrayList<>();
        for (НаборыБлоков.Гекс h : сторона.гексы()) {
            свои.add(new Cell(h.q(), h.r()));
        }
        for (int шагов = 0; шагов < 6; шагов++) {
            List<Cell> текущие = new ArrayList<>(свои);
            for (int i = 0; i < шагов; i++) {
                текущие.replaceAll(ПривязкаБлоков::повернуть);
            }
            if (!отпечаток(текущие).equals(отпЦели)) {
                continue;
            }
            // Совпало: сдвигаем повёрнутую форму так, чтобы её первая по порядку
            // клетка встала на первую по порядку клетку куска.
            Cell перваяСвоей = перваяПоПорядку(текущие);
            int dq = перваяЦели.q() - перваяСвоей.q();
            int dr = перваяЦели.r() - перваяСвоей.r();
            List<ГексНаПоле> гексы = new ArrayList<>();
            Set<String> проверка = new HashSet<>();
            for (int i = 0; i < сторона.гексы().size(); i++) {
                Cell c = текущие.get(i);
                НаборыБлоков.Гекс h = сторона.гексы().get(i);
                Cell наПоле = new Cell(c.q() + dq, c.r() + dr);
                проверка.add(наПоле.q() + ":" + наПоле.r());
                гексы.add(new ГексНаПоле(наПоле,
                    повернутьСектор(h.контейнер(), шагов),
                    повернутьСектор(h.энергия(), шагов)));
            }
            // Сторож: клетки блока обязаны совпасть с клетками куска ТОЧНО, а не
            // только формой. Иначе метки уедут на соседний гекс, и это будет не
            // видно глазом — картинка останется правдоподобной.
            for (Cell c : цель) {
                if (!проверка.contains(c.q() + ":" + c.r())) {
                    return null;
                }
            }
            return new Привязка(место, сторона, шагов, гексы);
        }
        return null;
    }
}
