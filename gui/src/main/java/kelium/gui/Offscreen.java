package kelium.gui;

import java.awt.Window;

/**
 * БЕЗЗВУЧНЫЙ РЕЖИМ ОКНА — для прогонщиков и тестов интерфейса.
 *
 * <p>Окно собирается целиком и живёт как обычно, но НЕ показывается на экране:
 * снимок с него берут рисованием слоёной панели в картинку, а не съёмкой
 * настоящего экрана. Иначе прогон отнимает у человека и экран, и клавиатуру —
 * а прогон партии это сотни точек решения подряд.
 *
 * <p>Включается системным свойством {@code -Dkelium.gui.offscreen=true}.
 */
public final class Offscreen {

    private Offscreen() {
    }

    /** Включён ли беззвучный режим. */
    public static boolean on() {
        return Boolean.getBoolean("kelium.gui.offscreen");
    }

    /**
     * Показать окно — или оставить невидимым в беззвучном режиме. Размер и
     * раскладка нужны и невидимому окну (иначе рисовать нечего), поэтому
     * {@code pack}/{@code setSize} должны быть сделаны ДО этого вызова, а здесь
     * добирается только раскладка потомков.
     */
    public static void show(Window w) {
        if (on()) {
            // Окно всё же показывается — иначе Swing не разложит потомков и
            // рисовать будет нечего, — но ДАЛЕКО ЗА ПРЕДЕЛАМИ любого монитора
            // и без права брать фокус: ни закрыть собой чужое окно, ни
            // перехватить клавиатуру оно не может.
            w.setFocusableWindowState(false);
            w.setAutoRequestFocus(false);
            w.setLocation(-32000, -32000);
            w.setVisible(true);
            w.setLocation(-32000, -32000);
            return;
        }
        w.setVisible(true);
    }
}
