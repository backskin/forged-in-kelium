package kelium.gui;

import java.awt.Color;

/**
 * ExportPaint — КРАСКИ ЭКСПОРТА, не зависящие от темы интерфейса.
 *
 * <p>Экспорт уходит в печать и в работу с макетами, и там тёмной темы не бывает
 * никогда. Полотно конструктора при этом рисует себя цветами {@code Theme}: в
 * тёмной теме заливка гекса, обводка и подписи темнеют вместе с интерфейсом — и
 * ровно эти же методы зовёт выгрузка картинки. Из-за этого выгруженный PNG
 * получался тёмным, если пользователь работал в тёмной теме.
 *
 * <p>Здесь заведён один флаг на процесс: пока он поднят, полотно берёт краски
 * отсюда, а не из темы. Флаг поднимается ровно на время отрисовки картинки и
 * опускается в {@code finally} — на экран он не влияет.
 *
 * <p>Флаг статический, а не поле холста, потому что в отрисовке участвуют ДВА
 * разных холста (полотно раскладки и вид сборки из блоков), и оба обязаны
 * переключиться разом. Экспорт идёт в потоке отрисовки Swing, то есть
 * последовательно, — гонки здесь быть не может.
 */
public final class ExportPaint {

    private ExportPaint() {
    }

    private static boolean active;

    /** Идёт ли сейчас отрисовка в файл (а не на экран). */
    public static boolean active() {
        return active;
    }

    /**
     * Выполнить отрисовку в режиме экспорта. Флаг снимается всегда, даже если
     * отрисовка бросит исключение, — иначе интерфейс навсегда остался бы в
     * печатных красках.
     */
    public static void with(Runnable draw) {
        boolean was = active;
        active = true;
        try {
            draw.run();
        } finally {
            active = was;
        }
    }

    /** То же для отрисовки, возвращающей картинку. */
    public static <T> T with(java.util.function.Supplier<T> draw) {
        boolean was = active;
        active = true;
        try {
            return draw.get();
        } finally {
            active = was;
        }
    }

    // ======================================================================
    //  ПАЛИТРА
    // ======================================================================

    /** Бумага страницы — то, на чём лежит вся картинка целиком. */
    public static final Color PAGE = new Color(0xFFFFFF);

    /**
     * ФОН ПОД САМИМ ПОЛЕМ — чуть темнее бумаги (просьба дизайнера 17.08.2026).
     * Нужен, чтобы кадр с полем читался как отдельный объект на листе, а белые
     * гексы не сливались с полями страницы.
     */
    public static final Color FIELD_BG = new Color(0xF0EEE8);

    /** Заливка обычного гекса в экспорте — всегда белая, без цвета блока. */
    public static final Color HEX_FILL = new Color(0xFFFFFF);

    /** Обводка гекса — тёмная серо-коричневая, как просил дизайнер. */
    public static final Color HEX_EDGE = new Color(0x3E3A33);

    /** Заливка запретного гекса. */
    public static final Color FORBIDDEN_FILL = new Color(0x3A3A3A);

    /** Подписи координат и прочая мелочь. */
    public static final Color LABEL = new Color(0x8A857A);

    /** Тонкая гексовая сетка вне поля. */
    public static final Color GRID = new Color(0x3E3A33);
}
