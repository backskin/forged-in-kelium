package kelium.gui;

import java.util.Random;

/**
 * ЛИДЕРЫ НАЦИЙ ЗА СТОЛОМ (дизайнер 28–29.09.2026: боты — не типы «Каратель ·
 * новичок» и не просто «Имя Фамилия», а тематические персонажи-лидеры).
 *
 * <p>Нация — по цвету места, как в книге мира: синие живут у Венеры на корабле,
 * красные — на Марсе, жёлтые — на спутнике Юпитера, зелёные — земляне.
 * Звание — по укладу нации (корабль — флотские звания, марсианские колонии —
 * комендатура, шахты спутника — смотрители, Земля — старые земные титулы),
 * имя — в звучании этой нации.
 *
 * <p>Лидер выводится из сида партии и места: сохранённая партия, её разбор и
 * журнал показывают тех же людей.
 */
public final class BotNames {

    private BotNames() {
    }

    /** Цвет места: 0 синие, 1 красные, 2 зелёные, 3 жёлтые (FieldGeometry.SEAT_STROKE). */
    private static final String[][] ЗВАНИЯ = {
        {"Капитан", "Навигатор", "Старпом"},              // синие — корабль у Венеры
        {"Комендант", "Маршал", "Трибун"},                // красные — Марс
        {"Воевода", "Атаман", "Староста"},                // зелёные — Земля
        {"Смотритель", "Инженер", "Управляющий"},         // жёлтые — спутник Юпитера
    };

    private static final String[][] ИМЕНА = {
        {"Лиара", "Эол", "Мирра", "Севин", "Ория", "Велан", "Ильса", "Таэль"},
        {"Торм", "Рагна", "Кард", "Вольх", "Стрега", "Хасс", "Брана", "Дрег"},
        {"Всеслав", "Мирон", "Добрава", "Ратибор", "Любава", "Гордей", "Милава", "Бронислав"},
        {"Кельв", "Исса", "Нордан", "Тарнис", "Ильм", "Альва", "Скарин", "Юна"},
    };

    /** Лидер на месте {@code seat} цвета {@code color} в партии с сидом {@code seed}. */
    public static String of(long seed, int seat, int color) {
        int c = Math.floorMod(color, 4);
        Random rnd = new Random(seed * 0x9E3779B97F4A7C15L + seat * 7919L + c);
        return ЗВАНИЯ[c][rnd.nextInt(ЗВАНИЯ[c].length)] + " "
            + ИМЕНА[c][rnd.nextInt(ИМЕНА[c].length)];
    }
}
