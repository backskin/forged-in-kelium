    /** Что из текстур реально лежит на месте — это факт, а не обещание. */
    private String texturesFound() {
        Path dir = dataRoot.resolve("textures");
        if (!Files.isDirectory(dir)) {
            return "<p style='color:" + Html.DIM + "'>Каталог текстур не найден.</p>";
        }
        List<String[]> rows = new ArrayList<>();
        for (String sub : List.of("token", "field")) {
            Path p = dir.resolve(sub);
            long files = 0;
            long masks = 0;
            if (Files.isDirectory(p)) {
                try (var s = Files.list(p)) {
                    List<Path> all = s.toList();
                    for (Path f : all) {
                        String n = f.getFileName().toString().toLowerCase();
                        if (n.endsWith(".zones.png")) {
                            masks++;
                        } else if (n.endsWith(".png")) {
                            files++;
                        }
                    }
                } catch (java.io.IOException e) {
                    // ниже покажем нули — каталог есть, прочитать не удалось
                }
            }
            rows.add(new String[]{sub.equals("token") ? "жетоны" : "поле",
                files + " картинок, " + masks + " масок зон"});
        }
        return "<div style='color:" + Html.DIM + ";margin-top:10px'>Что лежит сейчас"
            + "</div>" + Html.table(rows);
    }

    static String esc(String s) {
        if (s == null) {
            return "";
        }
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }

    // ==================== мелкий сборщик html ====================

    /** Сборщик статьи: заголовки, абзацы, списки, таблицы «подпись → значение». */
    static final class Html {

        static final String DIM = "#8a8a8a";

        private final StringBuilder sb = new StringBuilder();

        void h(String title) {
            sb.append("<div style='font-size:115%;font-weight:bold;margin:14px 0 4px 0'>")
                .append(title).append("</div>");
        }

        void p(String text) {
            sb.append("<p style='line-height:1.45;margin:6px 0'>").append(text)
                .append("</p>");
        }

        void raw(String html) {
            sb.append(html);
        }

        void ul(String... items) {
            sb.append("<ul style='margin:6px 0 6px 18px'>");
            for (String i : items) {
                sb.append("<li style='margin:3px 0'>").append(i).append("</li>");
            }
            sb.append("</ul>");
        }

        void note(String text) {
            sb.append("<p style='color:").append(DIM).append(";margin:10px 0'>")
                .append(text).append("</p>");
        }

        void table2(String caption, List<String[]> rows) {
            sb.append("<div style='color:").append(DIM).append(";margin-top:10px'>")
                .append(caption).append("</div>").append(table(rows));
        }

        static String table(List<String[]> rows) {
            StringBuilder t = new StringBuilder("<table cellspacing='0' cellpadding='4'>");
            for (String[] r : rows) {
                t.append("<tr><td valign='top'>").append(r[0])
                    .append("</td><td valign='top'>")
                    .append(r.length > 1 ? r[1] : "").append("</td></tr>");
            }
            return t.append("</table>").toString();
        }

        String done() {
            return sb.toString();
        }
    }

