    private String statTable(String title, Map<String, Object> src, List<String> fields) {
        if (src == null || src.isEmpty()) {
            return "";
        }
        List<String[]> rows = new ArrayList<>();
        for (Map.Entry<String, Object> e : src.entrySet()) {
            Map<String, Object> m = asMap(e.getValue());
            if (m == null) {
                continue;
            }
            StringBuilder v = new StringBuilder();
            for (String f : fields) {
                if (!m.containsKey(f)) {
                    continue;
                }
                if (v.length() > 0) {
                    v.append(" · ");
                }
                v.append(esc(statName(f))).append(' ')
                    .append(esc(RuleWords.value(m.get(f))));
            }
            rows.add(new String[]{esc(tokenName(e.getKey())), v.toString()});
        }
        return "<div style='color:" + Html.DIM + ";margin-top:10px'>" + esc(title)
            + "</div>" + Html.table(rows);
    }

    private String levelTable(String title, Object list, List<String> fields) {
        if (!(list instanceof List<?> l) || l.isEmpty()) {
            return "";
        }
        List<String[]> rows = new ArrayList<>();
        for (Object o : l) {
            Map<String, Object> m = asMap(o);
            if (m == null) {
                continue;
            }
            StringBuilder v = new StringBuilder();
            for (String f : fields) {
                if (!m.containsKey(f)) {
                    continue;
                }
                if (v.length() > 0) {
                    v.append(" · ");
                }
                v.append(esc(statName(f))).append(' ')
                    .append(esc(RuleWords.value(m.get(f))));
            }
            rows.add(new String[]{"уровень " + esc(RuleWords.value(m.get("level"))),
                v.toString()});
        }
        return "<div style='color:" + Html.DIM + ";margin-top:10px'>" + esc(title)
            + "</div>" + Html.table(rows);
    }

    /** Подпись характеристики жетона. Неизвестная — «не описано», не ключ. */
    private static String statName(String f) {
        return switch (f) {
            case "hp" -> "прочность";
            case "count" -> "жетонов в запасе";
            case "trophy" -> "трофеев на обороте (трофейная сторона)";
            case "energy_slots" -> "ячеек энергии";
            case "energy_gives" -> "даёт энергии";
            case "yield_kelium" -> "добывает келемия";
            case "cost" -> "цена";
            case "level" -> "уровень";
            default -> "не описано";
        };
    }

    /** Имя жетона по его коду в данных: сперва род войск, потом здание. */
    private static String tokenName(String key) {
        try {
            return Names.unit(key);
        } catch (RuntimeException ignored) {
            // не род войск — пробуем здание
        }
        try {
            return Names.building(key);
        } catch (RuntimeException ignored) {
            return "не описано";
        }
    }

    /** Сколько жетонов выдано игроку — числа из набора планшетов. */
    private List<String[]> tokenCounts() {
        List<String[]> out = new ArrayList<>();
        Map<String, Object> t = tokens();
        if (t == null) {
            out.add(new String[]{"нет данных", ""});
            return out;
        }
        Map<String, Object> units = asMap(t.get("units"));
        if (units != null) {
            for (Map.Entry<String, Object> e : units.entrySet()) {
                Map<String, Object> m = asMap(e.getValue());
                if (m != null && m.get("count") != null) {
                    out.add(new String[]{esc(Names.unit(e.getKey())),
                        esc(RuleWords.value(m.get("count"))) + " жетонов"});
                }
            }
        }
        if (t.get("unit_tokens_per_color") != null) {
            out.add(new String[]{"войск всего на игрока",
                esc(RuleWords.value(t.get("unit_tokens_per_color")))});
        }
        if (t.get("building_tokens_per_color") != null) {
            out.add(new String[]{"жетонов зданий на игрока",
                esc(RuleWords.value(t.get("building_tokens_per_color")))});
        }
        Map<String, Object> mods = asMap(t.get("modules"));
        if (mods != null) {
            for (Map.Entry<String, Object> e : mods.entrySet()) {
                String k = e.getKey();
                String what = k.startsWith("red") ? "красных модулей на игрока"
                    : k.startsWith("blue") ? "синих модулей на игрока" : "не описано";
                out.add(new String[]{what, esc(RuleWords.value(e.getValue()))});
            }
        }
        if (out.isEmpty()) {
            out.add(new String[]{"нет данных", ""});
        }
        return out;
    }

