    /** Значение правила словами; нет данных — говорим честно. */
    public String num(String path) {
        if (ruleset == null) {
            return "нет данных";
        }
        Object v = ruleset.get(path, MISSING);
        return v == MISSING ? "нет данных" : RuleWords.value(v);
    }

    private static final Object MISSING = new Object();

    /** Строки таблицы «подпись правила → значение» для перечня путей. */
    List<String[]> rows(String... paths) {
        List<String[]> out = new ArrayList<>();
        for (String p : paths) {
            out.add(new String[]{esc(RuleWords.rule(p)), esc(num(p))});
        }
        return out;
    }

    /**
     * Обмены из правил. Каждый обмен записан отображением: опознавательное имя и
     * условия («отдать столько — получить столько»). На экран идут только слова:
     * имя обмена и его условия переводит {@link Names#effect}.
     */
    private List<String[]> exchanges(String path) {
        List<String[]> out = new ArrayList<>();
        Object v = ruleset == null ? null : ruleset.get(path, null);
        List<?> list = v instanceof List<?> l ? l : List.of();
        for (Object o : list) {
            if (!(o instanceof Map<?, ?> m)) {
                out.add(new String[]{esc(RuleWords.value(o)), ""});
                continue;
            }
            Object id = m.get("id");
            String left = id == null ? "не описано"
                : Names.effect(String.valueOf(id), "");
            List<String> terms = new ArrayList<>();
            for (Map.Entry<?, ?> e : m.entrySet()) {
                String key = String.valueOf(e.getKey());
                if ("id".equals(key)) {
                    continue;
                }
                // Ключ effect несёт имя эффекта в значении, а не в ключе.
                terms.add("effect".equals(key)
                    ? Names.effect(String.valueOf(e.getValue()), "")
                    : Names.effect(key, RuleWords.value(e.getValue())));
            }
            out.add(new String[]{esc(left), esc(String.join(" · ", terms))});
        }
        if (out.isEmpty()) {
            out.add(new String[]{"нет данных", ""});
        }
        return out;
    }

