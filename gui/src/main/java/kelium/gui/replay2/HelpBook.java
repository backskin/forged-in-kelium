    private String rulesDiff(String older, String newer) {
        Html h = new Html();
        Ruleset a;
        Ruleset b;
        try {
            a = Ruleset.loadById(older, dataRoot.resolve("rulesets"));
            b = Ruleset.loadById(newer, dataRoot.resolve("rulesets"));
        } catch (RuntimeException e) {
            h.note("Один из файлов правил не читается — сравнить не получилось.");
            return h.done();
        }
        h.p("Версия <b>" + newer + "</b> против <b>" + older + "</b>.");
        Object based = b.get("meta.based_on", null);
        Object descr = b.get("meta.description", null);
        // ЗАПИСКА АВТОРА ВЕРСИИ — приведена ДОСЛОВНО, как написана в файле правил.
        // Это не текст приложения, а цитата: пересказывать её своими словами нельзя,
        // иначе справочник начнёт спорить с решением, которое там записано. Потому
        // здесь и допустимы внутренние имена — они часть цитаты.
        Object note = based != null ? based : descr;
        if (note != null) {
            h.note("Записка автора версии, дословно:");
            h.p("<i>" + esc(String.valueOf(note).trim()) + "</i>");
        }
        List<RulesetDiff.Row> rows = RulesetDiff.compare(a.raw, b.raw);
        if (rows.isEmpty()) {
            h.note("По данным версии не отличаются ничем, кроме описания.");
            return h.done();
        }
        h.h("Изменено");
        h.raw(diffTable(rows, RulesetDiff.Kind.CHANGED));
        h.h("Добавлено");
        h.raw(diffTable(rows, RulesetDiff.Kind.ADDED));
        h.h("Убрано");
        h.raw(diffTable(rows, RulesetDiff.Kind.REMOVED));
        return h.done();
    }

    private String diffTable(List<RulesetDiff.Row> rows, RulesetDiff.Kind kind) {
        List<String[]> out = new ArrayList<>();
        for (RulesetDiff.Row r : rows) {
            if (r.kind() != kind) {
                continue;
            }
            String what = RuleWords.rule(r.path());
            String group = RuleWords.group(r.path().split("\\.")[0]);
            String left = esc(what) + " <span style='color:" + Html.DIM + "'>· " + esc(group)
                + "</span>";
            String right = switch (kind) {
                case CHANGED -> esc(RuleWords.value(r.before())) + " → <b>"
                    + esc(RuleWords.value(r.after())) + "</b>";
                case ADDED -> "<b>" + esc(RuleWords.value(r.after())) + "</b>";
                case REMOVED -> esc(RuleWords.value(r.before()));
            };
            out.add(new String[]{left, right});
        }
        if (out.isEmpty()) {
            return "<p style='color:" + Html.DIM + "'>ничего</p>";
        }
        return Html.table(out);
    }

