    private static String onTable(HelpBook book) {
        HelpBook.Html h = new HelpBook.Html();
        h.p("Состав набора — по тем карточным модулям, которые подключила эта версия "
            + "правил. Полный каталог карт с разворотами — в ветке «Каталог всех карт».");
        List<String[]> rows = new ArrayList<>();
        for (String type : List.of("orders", "objectives", "arsenal", "super_arsenal",
                "super_objectives", "containers", "market")) {
            String count = "нет данных";
            if (book.content() != null) {
                try {
                    count = book.content().get(type).size() + " карт, набор "
                        + book.content().get(type).version;
                } catch (RuntimeException e) {
                    count = "нет данных";
                }
            }
            rows.add(new String[]{RuleWords.contentType(type), count});
        }
        h.table2("Колоды", rows);
        h.h("Поле");
        h.p("Поле собирается из двусторонних картонных блоков: малые на пять гексов, "
            + "большие на шесть. На каждом гексе <b>напечатан контейнер</b>, поэтому "
            + "раскладка блоков задаёт всю географию находок. Раскладка — это тоже данные: "
            + "их версия подключается правилами вместе с колодами.");
        h.h("Жетоны игрока");
        h.raw(book.tokenStatsTables());
        return h.done();
    }

