    /** Число из правил, если оно там есть; иначе — запасное. */
    private static int numberOr(HelpBook book, String path, int fallback) {
        try {
            return Integer.parseInt(book.num(path).trim());
        } catch (NumberFormatException e) {
            return fallback;
        }
    }
