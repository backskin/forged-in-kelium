package kelium.gui.net;

import javax.swing.JPanel;

import kelium.gui.HotSeatWindow;

/**
 * ДОСТУП К СОДЕРЖИМОМУ ЛОББИ ДЛЯ ПРОГОНЩИКА СНИМКОВ.
 *
 * <p>Окно лобби ({@link ОкноЛобби}) само себя не показывает, пока его не
 * попросят, — а прогонщик снимков обязан не показывать окон вовсе. Этот
 * мостик отдаёт ему готовую панель: лежит рядом с лобби, потому что внутрь
 * его пакета никого другого пускать незачем.
 */
public final class ЛоббиДляСнимка {

    private ЛоббиДляСнимка() {
    }

    /** Лобби хозяина на свободном порту (порт 0 — любой свободный). */
    public static JPanel хозяин(HotSeatWindow.Options настройки, int моёМесто) {
        return ОкноЛобби.собратьХозяина(настройки, моёМесто, 0).содержимоеДляСнимка();
    }

    /** Экран «подключиться к столу» с полем адреса. */
    public static JPanel адрес() {
        return ОкноЛобби.собратьАдрес().содержимоеДляСнимка();
    }
}
