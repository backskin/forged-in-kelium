    /** Подложка по умолчанию, % (как на печати): у заданий 15, у рынка 65, у супер-заданий 60. */
    static int plateDefault(String id) {
        return switch (id) {
            case "слева", "справа" -> 65;
            case "условие_2" -> 60;
            default -> 15;
        };
    }

    static String ru(String id) {
        if (id.startsWith("свой_")) {
            return "Свой элемент " + id.substring(5);
        }
        return RU.getOrDefault(id, id);
    }
