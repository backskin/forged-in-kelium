package kelium;

import java.util.ArrayList;
import java.util.List;
import java.util.Random;

import kelium.core.Agent;
import kelium.core.GameState;
import kelium.dataio.GameConfig;
import kelium.engine.GameEngine;
import kelium.engine.Scoring;
import kelium.engine.Setup;

/**
 * РАВНОВЕСИЕ ПО НЭШУ: выгодно ли ОДНОМУ начать войну за мирным столом.
 *
 * <p>Вопрос дизайнера 06.09.2026. Страх такой: война невыгодна не потому, что
 * плохо считается, а потому, что она РАВНОВЕСНО невыгодна. Игрок видит, что
 * начав драку, он вызовет ответную, потеряет здания и просядет по экономике —
 * и не начинает. Если так, «все мирные» — равновесие по Нэшу, и никакая
 * подкрутка наград войны его не сломает, пока не сломано само равновесие.
 *
 * <p>ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Равновесие — это про ОДНОСТОРОННЕЕ отклонение:
 * набор стратегий равновесен, если никому не выгодно поменять свою, пока
 * остальные не меняют своих. Поэтому меряются четыре стола:
 *
 * <pre>
 *   МИР×4          все Зодчие          — базовая выплата мирного
 *   МИР, один воюет  один Каратель      — выплата ОТКЛОНИВШЕГОСЯ в войну
 *   ВОЙНА×4        все Каратели         — базовая выплата воюющего
 *   ВОЙНА, один мирный один Зодчий      — выплата ОТКЛОНИВШЕГОСЯ в мир
 * </pre>
 *
 * «Все мирные» равновесно, если отклонение в войну НЕ поднимает выплату.
 * «Все воюют» равновесно, если отклонение в мир НЕ поднимает выплату.
 * Возможно и то, и другое сразу (две равновесные точки), и ни одного.
 *
 * <p>МЕСТО ОТКЛОНЯЮЩЕГОСЯ РОТИРУЕТСЯ по сиду: очерёдность и стартовый гекс
 * влияют на исход, и сажать отклоняющегося всегда на место 0 значило бы мерить
 * место, а не стратегию. Сид и раскладка в паре «база / отклонение» одни и те
 * же — сравниваются одинаковые поля.
 *
 * <p>ОГОВОРКА, БЕЗ КОТОРОЙ ЧИСЛА ЧИТАТЬ НЕЛЬЗЯ: веса ботов не переякорены после
 * того, как монеты, трофеи, здания и войска перестали давать очки (бэклог E23).
 * Каратель воюет по старой шкале ценностей, то есть возможно воюет ХУЖЕ, чем
 * стоило бы. Поэтому «война не окупается» здесь — верхняя граница вывода: если
 * даже так она окупается, вопрос закрыт; если не окупается, надо переобучить и
 * померить снова.
 */
public final class РавновесиеВойны {

    private РавновесиеВойны() {
    }

    /** Итог одного стола глазами ОДНОГО места. */
    private record Итог(double очки, double победа, double уничтожил, double потерял) { }

    private static Итог партия(long seed, int игроков, String[] характеры, int место) {
        GameState s = Setup.buildGame(
            GameConfig.buildCached(GameConfig.DEFAULT_RULESET, игроков, seed, null, null));
        List<Agent> боты = new ArrayList<>();
        for (int seat = 0; seat < игроков; seat++) {
            боты.add(kelium.agents.Bots.create(характеры[seat], seat,
                new Random(seed * 31 + seat), игроков));
        }
        new GameEngine(s, боты, ev -> { }).run();

        int мои = Scoring.scorePlayer(s, место).getOrDefault("total", 0);
        int лучшийЧужой = 0;
        for (int seat = 0; seat < игроков; seat++) {
            if (seat == место) {
                continue;
            }
            лучшийЧужой = Math.max(лучшийЧужой,
                Scoring.scorePlayer(s, seat).getOrDefault("total", 0));
        }
        // Уничтожил — жетоны на моём месте уничтоженных; потерял — мои жетоны,
        // лежащие у чужих. Обе величины про ход войны, а не про счёт.
        int уничтожил = s.player(место).destroyedTokens.size();
        int потерял = 0;
        for (int seat = 0; seat < игроков; seat++) {
            if (seat == место) {
                continue;
            }
            for (kelium.core.Token t : s.player(seat).destroyedTokens) {
                if (t.owner() == место) {
                    потерял++;
                }
            }
        }
        return new Итог(мои, мои > лучшийЧужой ? 1 : 0, уничтожил, потерял);
    }

    private static void строка(String имя, List<Итог> и) {
        double о = и.stream().mapToDouble(Итог::очки).average().orElse(0);
        double п = и.stream().mapToDouble(Итог::победа).average().orElse(0);
        double у = и.stream().mapToDouble(Итог::уничтожил).average().orElse(0);
        double пт = и.stream().mapToDouble(Итог::потерял).average().orElse(0);
        System.out.printf("  %-34s очки %5.2f | побед %4.0f%% | уничтожил %.2f | потерял %.2f%n",
            имя, о, 100 * п, у, пт);
    }

    public static void main(String[] args) {
        int партий = args.length > 0 ? Integer.parseInt(args[0]) : 60;
        int игроков = args.length > 1 ? Integer.parseInt(args[1]) : 4;
        String МИР = "builder";
        String ВОЙНА = "punisher";

        List<Итог> мирВМиру = new ArrayList<>();
        List<Итог> войнаВМиру = new ArrayList<>();
        List<Итог> войнаВВойне = new ArrayList<>();
        List<Итог> мирВВойне = new ArrayList<>();

        for (int i = 0; i < партий; i++) {
            long seed = 9000L + i;
            int место = i % игроков;           // ротация места отклоняющегося

            String[] всеМирные = new String[игроков];
            String[] всеВоюют = new String[игроков];
            java.util.Arrays.fill(всеМирные, МИР);
            java.util.Arrays.fill(всеВоюют, ВОЙНА);

            String[] одинВоюет = всеМирные.clone();
            одинВоюет[место] = ВОЙНА;
            String[] одинМирный = всеВоюют.clone();
            одинМирный[место] = МИР;

            мирВМиру.add(партия(seed, игроков, всеМирные, место));
            войнаВМиру.add(партия(seed, игроков, одинВоюет, место));
            войнаВВойне.add(партия(seed, игроков, всеВоюют, место));
            мирВВойне.add(партия(seed, игроков, одинМирный, место));
        }

        System.out.printf("свод %s, игроков %d, партий на сценарий %d%n%n",
            GameConfig.DEFAULT_RULESET, игроков, партий);

        System.out.println("СТОЛ МИРНЫЙ (остальные — Зодчие):");
        строка("мирный (база)", мирВМиру);
        строка("ОТКЛОНИЛСЯ В ВОЙНУ", войнаВМиру);
        double дельтаВойны = войнаВМиру.stream().mapToDouble(Итог::победа).average().orElse(0)
            - мирВМиру.stream().mapToDouble(Итог::победа).average().orElse(0);
        System.out.printf("  -> отклонение в войну меняет шанс победы на %+.0f п.п.%n%n",
            100 * дельтаВойны);

        System.out.println("СТОЛ ВОЮЮЩИЙ (остальные — Каратели):");
        строка("воюющий (база)", войнаВВойне);
        строка("ОТКЛОНИЛСЯ В МИР", мирВВойне);
        double дельтаМира = мирВВойне.stream().mapToDouble(Итог::победа).average().orElse(0)
            - войнаВВойне.stream().mapToDouble(Итог::победа).average().orElse(0);
        System.out.printf("  -> отклонение в мир меняет шанс победы на %+.0f п.п.%n%n",
            100 * дельтаМира);

        System.out.println("ВЕРДИКТ:");
        System.out.printf("  «все мирные»  %s равновесие по Нэшу (отклонение в войну %+.0f п.п.)%n",
            дельтаВойны <= 0 ? "ЕСТЬ" : "НЕ", 100 * дельтаВойны);
        System.out.printf("  «все воюют»   %s равновесие по Нэшу (отклонение в мир %+.0f п.п.)%n",
            дельтаМира <= 0 ? "ЕСТЬ" : "НЕ", 100 * дельтаМира);
    }
}
