    /** Порядок столбцов награды — тот же, что у курса. */
    private static List<String> видыНаград(List<Map<String, Object>> карты) {
        java.util.Set<String> есть = new java.util.LinkedHashSet<>();
        for (Map<String, Object> c : карты) {
            есть.addAll(ключиНаграды(c.get("base_reward")));
            есть.addAll(ключиНаграды(c.get("special_reward")));
        }
        List<String> out = new ArrayList<>();
        for (String ключ : КУРС.keySet()) {
            if (есть.remove(ключ)) {
                out.add(ключ);
            }
        }
        out.addAll(есть);        // вид, которого нет в курсе, всё равно покажем
        return out;
    }

    private static List<String> ключиНаграды(Object узел) {
        List<String> out = new ArrayList<>();
        if (узел instanceof Map<?, ?> m) {
            for (Object k : m.keySet()) {
                out.add(текст(k));
            }
        }
        return out;
    }

    /**
     * ЧИСЛО ЭТОГО ВИДА В НАГРАДЕ. Модуль — не число, а предмет: в данных он
     * записан цветом ({@code module: attack}), поэтому считается штукой, а в
     * ячейку идёт «атаки» или «сборки», чтобы цвет не потерялся.
     */
    private static void добавитьНаграду(List<Object> строка, Object узел, List<String> виды) {
        Map<?, ?> m = узел instanceof Map<?, ?> x ? x : Map.of();
        for (String вид : виды) {
            Object значение = m.get(вид);
            if (значение == null) {
                строка.add("");
            } else if ("module".equals(вид)) {
                строка.add("attack".equals(текст(значение)) ? "атаки" : "сборки");
            } else if (значение instanceof Number n) {
                строка.add(n.intValue());
            } else {
                строка.add(текст(значение));
            }
        }
    }

    /** Оценка награды по курсу. Пустая награда — ноль, а не пустая ячейка. */
    private static double оценка(Object узел) {
        if (!(узел instanceof Map<?, ?> m)) {
            return 0.0;
        }
        double сумма = 0.0;
        for (Map.Entry<?, ?> e : m.entrySet()) {
            String вид = текст(e.getKey());
            double цена = КУРС.getOrDefault(вид, 0.0);
            int сколько = e.getValue() instanceof Number n ? n.intValue() : 1;
            сумма += цена * сколько;
        }
        return Math.round(сумма * 100.0) / 100.0;
    }

