        б.строка("СИНИЕ", "прочность авиации", 1, 2, "+2");
        б.строка("СИНИЕ", "цель авиации", "техника", "здания и вышки", "+1");
        б.строка("СИНИЕ", "ячейки энергии казармы", 1, 2, "−3");
        б.строка("СИНИЕ", "скорость авиации", 3, 2, "−1");
        б.строка("СИНИЕ", "цель техники", "здания и вышки", "авиация", "−2");
        б.строка("СИНИЕ", "ИТОГО", "", "", 0);
        б.строка("");
        б.строка("КРАСНЫЕ", "ячейки энергии завода", 2, 1, "+3");
        б.строка("КРАСНЫЕ", "цена завода", 2, 1, "+1");
        б.строка("КРАСНЫЕ", "ячейки энергии казармы", 1, 2, "−3");
