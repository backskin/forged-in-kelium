package kelium.agents;

import kelium.core.GameState;

/**
 * ОЦЕНКА ПОЗИЦИИ ОТНОСИТЕЛЬНО СОПЕРНИКОВ (заказ дизайнера 27.09.2026).
 *
 * <p>«Цель игры не набирать победные очки. Это игра с другими участниками».
 * Прежняя оценка ({@link PositionValue}) мерила только МОЮ позицию, а соперник
 * входил в неё поправкой — разницей очков с лучшим из них, с весом 0,35. Для
 * такой оценки ход «+1 мне, +3 соседу» был выгодным, и бот сносил своё ЦУ,
 * отдавая соседу жетон на три очка.
 *
 * <p>Здесь из моей оценки вычитается сила соперников, увиденная так, как её
 * видит игрок за столом ({@link PositionValue#publicValue} — руки только числом
 * карт — плюс открытые угрозы {@link Угрозы}: свободная ступень науки по
 * карману, вершины, войска у чужого ЦУ, порог военной победы). Вес ЛИДЕРА —
 * соперника, который ближе всех к победе, — больше единицы: своё очко, взятое
 * ценой очка лидеру, хуже нуля, а очко, отнятое у лидера, дороже своего.
 * Остальные соперники весят меньше: удар по отстающему — подарок лидеру.
 */
public final class Относительно {

    private Относительно() {
    }

    /** Вес лидера по умолчанию: больше единицы — отнять у лидера дороже, чем взять себе. */
    public static final double ВЕС_ЛИДЕРА = 1.5;
    /** Вес прочих соперников (втроём и вчетвером). */
    public static final double ВЕС_ПРОЧИХ = 0.25;

    /**
     * Веса соперников на это решение. Лидер определяется по позиции ДО хода и
     * держится на всё решение: иначе бот «побеждал» бы лидера тем, что делал
     * лидером другого.
     */
    public static double[] веса(GameState s, int seat, Genome g) {
        int n = s.numPlayers();
        double[] w = new double[n];
        // ВДВОЁМ соперник один, и игра — чистая разница: его очко стоит ровно
        // моего. Перевес веса лидера нужен там, где есть кого стравить.
        double wl = n <= 2 ? 1.0 : g == null ? ВЕС_ЛИДЕРА : g.get("pl.rel_leader", ВЕС_ЛИДЕРА);
        double wo = n <= 2 ? wl : (g == null ? ВЕС_ПРОЧИХ : g.get("pl.rel_other", ВЕС_ПРОЧИХ));
        if (n <= 2) {
            for (int r = 0; r < n; r++) {
                if (r != seat) {
                    w[r] = wl;
                }
            }
            return w;
        }
        // ВЕС РАСТЁТ С ОТРЫВОМ (07.10.2026). Прежде лидер получал полный вес,
        // даже опережая второго на полочка, — и стоило лидерству смениться от
        // одного очка, весь стол поворачивался к другому. Люди так не играют:
        // против того, кто едва впереди, никто не объединяется, а против
        // ушедшего далеко — все. Отсюда шкала: превосходство соперника над
        // средним по остальным соперникам (в очках видимой силы) переводится в
        // долю от лёгкого веса к весу лидера; полный вес — при отрыве ОТРЫВ_ПОЛНЫЙ.
        double[] сил = new double[n];
        Genome нейтр = Bots.genome("balanced", n);
        for (int r = 0; r < n; r++) {
            if (r != seat) {
                сил[r] = сила(s, r, нейтр);
            }
        }
        for (int r = 0; r < n; r++) {
            if (r == seat) {
                continue;
            }
            double прочие = 0;
            int k = 0;
            for (int q = 0; q < n; q++) {
                if (q != seat && q != r) {
                    прочие += сил[q];
                    k++;
                }
            }
            double отрыв = k == 0 ? 0 : сил[r] - прочие / k;
            double доля = Math.max(0, Math.min(1, отрыв / ОТРЫВ_ПОЛНЫЙ));
            w[r] = wo + (wl - wo) * доля;
        }
        return w;
    }

    /**
     * ДОЛЯ ОТРЫВА каждого соперника (0…1): насколько он видимо сильнее среднего
     * по остальным соперникам, в долях {@link #ОТРЫВ_ПОЛНЫЙ}. Общая мерка для
     * веса в оценке и для выбора цели: против кого собирается стол.
     */
    public static double[] долиОтрыва(GameState s, int seat) {
        int n = s.numPlayers();
        double[] out = new double[n];
        double[] сил = new double[n];
        Genome нейтр = Bots.genome("balanced", n);
        for (int r = 0; r < n; r++) {
            if (r != seat) {
                сил[r] = сила(s, r, нейтр);
            }
        }
        for (int r = 0; r < n; r++) {
            if (r == seat) {
                continue;
            }
            double прочие = 0;
            int k = 0;
            for (int q = 0; q < n; q++) {
                if (q != seat && q != r) {
                    прочие += сил[q];
                    k++;
                }
            }
            double отрыв = k == 0 ? 0 : сил[r] - прочие / k;
            out[r] = Math.max(0, Math.min(1, отрыв / ОТРЫВ_ПОЛНЫЙ));
        }
        return out;
    }

    /** Отрыв в очках видимой силы, при котором соперник весит как полный лидер. */
    public static final double ОТРЫВ_ПОЛНЫЙ = 6.0;

    /** Сила соперника в очках — только по открытому. */
    public static double сила(GameState s, int r, Genome нейтральный) {
        Угрозы.Соперник с = Угрозы.соперник(s, r);
        return PositionValue.publicValue(s, r, нейтральный) + (с.сила() - с.очки());
    }

    /** Моя позиция минус взвешенная сила соперников. */
    public static double оценка(GameState после, int seat, Genome g, Intents in, double[] w,
                                Genome нейтральный) {
        double v = PositionValue.value(после, seat, g, in);
        for (int r = 0; r < w.length && r < после.numPlayers(); r++) {
            if (r != seat && w[r] > 0) {
                v -= w[r] * сила(после, r, нейтральный);
            }
        }
        return v;
    }
}
