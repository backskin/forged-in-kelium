package kelium.agents;

import java.util.List;
import java.util.Map;
import java.util.Random;

import kelium.core.Agent;
import kelium.core.Choice;
import kelium.core.GameState;

/**
 * БОТ, КОТОРЫЙ ОШИБАЕТСЯ — обёртка над любым другим ботом.
 *
 * <p>ЗАЧЕМ. Уровень сложности должен быть ЛЕСТНИЦЕЙ: чем выше, тем сильнее. Сама
 * по себе разница «формула против просчёта» такой лестницы не даёт — замер на 40
 * партиях показал, что просчёт вперёд играет в пределах шума от простой формулы,
 * а жадная эвристика без генома иногда обыгрывает обученного бота. То есть
 * «новичок» получался не слабее «любителя», и уровень сложности ничего не значил.
 *
 * <p>ЧТО ДЕЛАЕТ. С заданной вероятностью подменяет выбор бота случайным из тех же
 * предложенных вариантов. Это и есть ошибка новичка в чистом виде: он видит те же
 * возможности и хочет того же — просто иногда выбирает не то. Ходы остаются
 * ЗАКОННЫМИ (выбор идёт из того же списка), поэтому странных ходов вроде «сходил
 * в пустоту» не появляется.
 *
 * <p>ПОЧЕМУ НЕ УЧИТЬ СЛАБОГО БОТА ПОДДАВАТЬСЯ. Бот, обученный проигрывать,
 * играет НЕ ХУЖЕ, а ИНАЧЕ: он гонится за другой целью, и со стороны это выглядит
 * не как слабость, а как бессмыслица. Про такие ходы дизайнер и сказал «страдают
 * хуйней». Ошибающийся бот хочет ровно того же, что сильный.
 *
 * <p>ПАС НЕ ПОДМЕНЯЕТСЯ. Отказ от действия — единственный вариант, случайная
 * подмена которого превращает партию в стояние: новичок, который каждый третий
 * раз пасует, не слабый, а неиграющий. Ошибка новичка — выбрать не то, а не
 * бросить ход.
 */
public final class NoisyAgent extends Agent {

    private final Agent под;
    private final double доляОшибок;
    private final Random rng;

    /**
     * @param под         кто на самом деле думает
     * @param доляОшибок  доля решений, которые будут заменены случайным (0..1)
     */
    public NoisyAgent(Agent под, double доляОшибок, Random rng) {
        super(под.seat, "новичок·" + под.name);
        this.под = под;
        this.доляОшибок = Math.max(0, Math.min(1, доляОшибок));
        this.rng = rng;
    }

    @Override
    public Choice choose(GameState state, List<Choice> options, Map<String, Object> context) {
        Choice умный = под.choose(state, options, context);
        if (options == null || options.size() < 2 || rng.nextDouble() >= доляОшибок) {
            return умный;
        }
        // Случайный вариант из ТЕХ ЖЕ предложенных — кроме паса (см. javadoc).
        java.util.List<Choice> годные = new java.util.ArrayList<>();
        for (Choice c : options) {
            if (c != null && c.payload() != null) {
                годные.add(c);
            }
        }
        if (годные.isEmpty()) {
            return умный;
        }
        return годные.get(rng.nextInt(годные.size()));
    }

    @Override
    public String toString() {
        return "ошибается(" + Math.round(доляОшибок * 100) + "%) " + под;
    }
}
