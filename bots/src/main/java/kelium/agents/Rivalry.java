package kelium.agents;

import java.util.ArrayList;
import java.util.List;

import kelium.core.BuildingToken;
import kelium.core.GameState;
import kelium.core.Token;
import kelium.core.UnitToken;
import kelium.engine.Scoring;

/**
 * СОПЕРНИЧЕСТВО — взгляд бота на партию как на МНОГОПОЛЬЗОВАТЕЛЬСКУЮ ИГРУ, а не
 * как на набор личных показателей.
 *
 * <p>Заказ дизайнера 15.08.2026, и он попадает в самую суть. До этого класса бот
 * решал задачу «набрать побольше»: соперники входили в его картину мира одним
 * числом — очками лидера. Отсюда всё наблюдаемое поведение: он копил
 * боеприпасы, потому что копить безопасно; не лез в размен, потому что размен
 * виден как убыток; заканчивал партию добычей, потому что добыча даёт очки
 * предсказуемо. Ни одно из этих решений не было бы принято игроком, который
 * понимает, что за столом сидят живые соперники, играющие ПРОТИВ него.
 *
 * <p>Что здесь заведено — четыре понятия из теории игр, каждое считаемое:
 *
 * <ol>
 *   <li><b>Относительная победа.</b> Ценность положения — не мои очки, а разрыв
 *       с ЛУЧШИМ из остальных. Отнять у лидера очко ровно так же ценно, как
 *       заработать своё, и это не метафора, а равенство в формуле
 *       {@link #relativeScore}. Игрок, набравший 20 при лидере с 25, проиграл;
 *       игрок, набравший 12 при лидере с 10, выиграл.</li>
 *   <li><b>Угроза.</b> Соперник опасен не тем, сколько у него очков, а тем,
 *       насколько быстро он их набирает И насколько он дотягивается до меня
 *       оружием ({@link #threat}). Эти две опасности разные, и путать их нельзя:
 *       мирный лидер отнимает победу, военный сосед отнимает жетоны.</li>
 *   <li><b>Кому вредить.</b> Урон отстающему — подарок лидеру: я трачу своё
 *       действие, а разрыв с тем, кто меня обгоняет, не меняется. Поэтому
 *       ценность вреда взвешивается угрозой жертвы ({@link #damageValue}). Это
 *       и есть «стравливать соперников»: бей того, кто ведёт, — остальным это
 *       выгодно, и они присоединятся сами, без всякого сговора.</li>
 *   <li><b>Своя заметность.</b> Кто впереди, того и бьют. Идущий первым в
 *       середине партии платит за это чужой агрессией, и ранний отрыв может
 *       стоить дороже, чем даёт ({@link #exposure}). Отсюда осмысленная игра
 *       вторым номером — «пусть лидером побудет кто-то другой».</li>
 * </ol>
 *
 * <p>ЧЕГО ЗДЕСЬ НАРОЧНО НЕТ. Договора между ботами. Коалиция в такой игре не
 * заключается, а СКЛАДЫВАЕТСЯ: если каждый бьёт лидера просто потому, что это
 * ему выгодно, коалиция против лидера возникает сама, без переговоров и без
 * общего кода. Так честнее и так же ведут себя живые игроки за столом.
 *
 * <p>Класс СЧИТАЕТ, но не решает. Все числа умножаются на веса генома, то есть
 * проходят отбор: насколько сильно бить лидера и насколько бояться заметности —
 * решает обучение, а не я.
 */
public final class Rivalry {

    private final GameState state;
    private final int seat;
    private final int players;
    private final int[] vp;
    private final double[] reachAtMe;
    private final double[] threat;

    /** Оценка положения для места {@code seat} в партии {@code s}. */
    public Rivalry(GameState s, int seat) {
        this.state = s;
        this.seat = seat;
        this.players = s.numPlayers();
        this.vp = new int[players];
        this.reachAtMe = new double[players];
        this.threat = new double[players];
        for (int i = 0; i < players; i++) {
            vp[i] = Scoring.scorePlayer(s, i).getOrDefault("total", 0);
        }
        computeReach();
        computeThreat();
    }

    // ==================================================================
    //  Кто где стоит
    // ==================================================================

    /** Очки места. */
    public int vpOf(int st) {
        return vp[st];
    }

    /** Мои очки. */
    public int myVp() {
        return vp[seat];
    }

    /** Место сильнейшего СОПЕРНИКА (не меня). При двух игроках — просто второй. */
    public int leader() {
        int best = -1;
        for (int i = 0; i < players; i++) {
            if (i != seat && (best < 0 || vp[i] > vp[best])) {
                best = i;
            }
        }
        return best;
    }

    /** Веду ли я по очкам (строго больше всех остальных). */
    public boolean iAmLeading() {
        int l = leader();
        return l < 0 || vp[seat] > vp[l];
    }

    /**
     * ОТНОСИТЕЛЬНЫЙ СЧЁТ — мои очки минус очки лучшего соперника.
     *
     * <p>Единственная величина, которая на самом деле решает партию. Именно её и
     * надо максимизировать: положительная — я выигрываю, отрицательная — нет,
     * и абсолютное число очков при этом не значит ничего.
     */
    public int relativeScore() {
        int l = leader();
        return l < 0 ? vp[seat] : vp[seat] - vp[l];
    }

    // ==================================================================
    //  Кто чем опасен
    // ==================================================================

    /**
     * Насколько соперник опасен ДЛЯ МЕНЯ: от 0.0 (безобиден) до примерно 1.5.
     *
     * <p>Складывается из двух разных опасностей. Первая — очковая: он рядом со
     * мной или впереди, значит отнимает победу. Вторая — военная: его войска
     * дотягиваются до моих жетонов, значит отнимает жетоны. Мирный лидер и
     * агрессивный сосед опасны по-разному, и лечатся они тоже по-разному.
     */
    public double threat(int st) {
        return st < 0 || st >= players ? 0.0 : threat[st];
    }

    /** Сколько чужих стволов дотягивается до моих жетонов прямо сейчас. */
    public double reachAtMe(int st) {
        return st < 0 || st >= players ? 0.0 : reachAtMe[st];
    }

    /**
     * СКОЛЬКО СТОИТ НАВРЕДИТЬ ИМЕННО ЭТОМУ игроку — множитель к ценности удара.
     *
     * <p>Около 1.4 для того, кто ведёт и достаёт меня; около 0.3 для безобидного
     * отстающего. Смысл прямой: **урон отстающему — подарок лидеру.** Я трачу
     * своё действие, свои боеприпасы и подставляюсь под ответ, а разрыв с тем,
     * кто меня обгоняет, не меняется ни на очко.
     *
     * <p>Отсюда же само собой выходит «стравливание»: если каждый за столом
     * считает так же, все бьют лидера, и коалиция против него складывается без
     * всякого сговора.
     */
    public double damageValue(int victim) {
        if (victim < 0 || victim == seat) {
            return 0.0;
        }
        return 0.3 + 0.8 * threat(victim);
    }

    /**
     * НАСКОЛЬКО Я САМ МИШЕНЬ — от 0.0 до примерно 1.5.
     *
     * <p>Кто впереди, того и бьют: за столом на четверых лидера бьют трое.
     * Поэтому ранний отрыв может стоить дороже, чем даёт, и игра вторым номером
     * — не трусость, а расчёт. Величина складывается из того, насколько я
     * впереди, и того, сколько чужих стволов до меня дотягивается.
     */
    public double exposure() {
        int l = leader();
        double ahead = l < 0 ? 0.0 : Math.max(0, vp[seat] - vp[l]) / 8.0;
        double aimed = 0.0;
        for (int i = 0; i < players; i++) {
            if (i != seat) {
                aimed += reachAtMe[i];
            }
        }
        return Math.min(1.5, ahead + Math.min(1.0, aimed / 4.0));
    }

    /**
     * СКОЛЬКО РАУНДОВ ОСТАЛОСЬ — грубо, по числу карт рынка.
     *
     * <p>Нужно затем, что цена всего меняется к концу: отнять у соперника
     * добытчик в третьем раунде — это минус пять раундов его добычи, а в
     * последнем — почти ничего. Раньше бот этой разницы не видел вовсе.
     */
    public int roundsLeft() {
        // Предел раундов задаётся ЧИСЛОМ ПЕЧАТНЫХ КАРТ РЫНКА — так же, как его
        // считает движок (GameEngine.lastRoundByMarket). Брать оттуда же, а не
        // держать свою константу: иначе появится ещё один источник одного и того
        // же правила, а их и так уже было три.
        int cap = 8;
        try {
            cap = kelium.dataio.Ctx.cfg(state).content.get("market").entries.size();
        } catch (RuntimeException e) {
            // данных рынка нет (собранная вручную сцена в тесте) — печатные восемь
        }
        return Math.max(0, cap - state.round);
    }

    /**
     * ЦЕНА УНИЧТОЖЕНИЯ ЧУЖОГО ЖЕТОНА С УЧЁТОМ ОСТАВШЕЙСЯ ПАРТИИ.
     *
     * <p>Главная поправка, которой боту не хватало. Уничтожение — это не разовый
     * трофей, а изъятие у противника ВСЕГО, что этот жетон принёс бы до конца
     * партии: добытчик перестаёт добывать, здание перестаёт собирать, войско
     * перестаёт бить и занимать место. Оценщик видел только трофей, поэтому
     * размен всегда выглядел убытком — и бот копил боеприпасы вместо стрельбы.
     *
     * @return множитель к базовой ценности цели
     */
    public double lostFutureValue(Token target) {
        int left = roundsLeft();
        if (left <= 0) {
            return 0.2;                      // в последнем раунде важен только счёт
        }
        double perRound;
        if (target instanceof BuildingToken b) {
            perRound = switch (b.type) {
                case MINER -> 1.0;           // прямая добыча каждый раунд
                case POWER_PLANT -> 0.8;     // энергия — это чужие действия
                case COMMAND_CENTER -> 1.2;  // и энергия, и вышки, и сама партия
                default -> 0.6;              // военные здания: чужие войска
            };
        } else {
            perRound = 0.5;                  // войско: удары, занятое место, угроза
        }
        // Насыщение: восемь оставшихся раундов не вдвое ценнее четырёх — до конца
        // партии успевает сказаться далеко не всё.
        return 0.4 + perRound * Math.min(4.0, left) / 2.0;
    }

    // ==================================================================
    //  Внутреннее
    // ==================================================================

    private void computeReach() {
        List<String> myHexes = new ArrayList<>();
        for (Token t : state.player(seat).unitsOnField()) {
            myHexes.add(t.hexId());
        }
        for (Token t : state.player(seat).buildingsOnField()) {
            myHexes.add(t.hexId());
        }
        if (myHexes.isEmpty()) {
            return;
        }
        for (int st = 0; st < players; st++) {
            if (st == seat) {
                continue;
            }
            for (UnitToken u : state.player(st).unitsOnField()) {
                if (!u.alive() || u.hexId == null) {
                    continue;
                }
                // Грубая мера досягаемости: сосед или тот же гекс. Точная
                // проходимость здесь не нужна — это оценка опасности, а не
                // проверка правил, и считается она на каждом ходу.
                for (String mine : myHexes) {
                    if (mine.equals(u.hexId)
                            || state.field.neighbors(u.hexId).contains(mine)) {
                        reachAtMe[st] += 1.0;
                        break;
                    }
                }
            }
        }
    }

    private void computeThreat() {
        int maxVp = 1;
        for (int i = 0; i < players; i++) {
            maxVp = Math.max(maxVp, vp[i]);
        }
        for (int st = 0; st < players; st++) {
            if (st == seat) {
                continue;
            }
            // ОЧКОВАЯ опасность: доля от лучшего результата за столом. Тот, кто
            // идёт вровень с лидером, опасен почти как лидер — обгонит на ходу.
            double byScore = vp[st] / (double) maxVp;
            // ВОЕННАЯ опасность: сколько его стволов смотрит на мои жетоны.
            double byArms = Math.min(1.0, reachAtMe[st] / 3.0);
            threat[st] = Math.min(1.5, 0.7 * byScore + 0.8 * byArms);
        }
    }
}
