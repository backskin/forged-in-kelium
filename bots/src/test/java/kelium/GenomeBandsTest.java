package kelium;

import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.Random;

import org.junit.jupiter.api.Test;

import kelium.agents.Bots;
import kelium.agents.Genome;

/**
 * КОРИДОР ВЕСОВ И ЗАЩИТА ХАРАКТЕРА — сторож против того, что уже случилось.
 *
 * <p>Мутация двигала вес шумом масштаба {@code rate * |вес|} и держала только пол
 * в нуле. Такой шаг растёт вместе с весом: ушедший вверх разгоняется, ушедший в
 * нуль там и остаётся. За несколько обучений это дало на линиях 3–4 игроков
 * {@code combat.kill_value} 554.51 при печатной шестёрке, {@code action.assembly}
 * около нуля почти у всех при печатных 6.5 — а Сборка единственный способ сделать
 * войско, — и агрессию 0.35 у ЯСТРЕБА против 1.68 у ГОЛУБЯ.
 *
 * <p>Тест проверяет три вещи, каждая из которых тогда не проверялась ничем:
 * мутация не выносит вес за коридор, характер остаётся на своей стороне, и
 * приоритеты действий не разъезжаются настолько, чтобы Рынок обогнал Сборку.
 */
class GenomeBandsTest {

    /** Сколько раз подряд мутировать: разгон весов был именно накопительным. */
    private static final int ПОКОЛЕНИЙ = 400;

    private static Genome погонять(String профиль, long зерно) {
        Genome g = Genome.defaults().withProfile(профиль);
        Random rng = new Random(зерно);
        for (int i = 0; i < ПОКОЛЕНИЙ; i++) {
            g = g.mutate(rng, 0.25);
        }
        return g;
    }

    /**
     * НИ ОДИН ВЕС НЕ УХОДИТ ДАЛЕКО ОТ ПЕЧАТНОГО. Порог здесь нарочно щедрый — 20
     * раз: тест ловит не настройку коридора, а его отсутствие. 554 против 6 — это
     * 92 раза.
     */
    @Test
    void весаНеРазгоняются() {
        Genome base = Genome.defaults();
        for (String профиль : Bots.CHARACTERS) {
            Genome g = погонять(профиль, 777L);
            for (String ключ : Genome.TUNABLE_KEYS) {
                double печатное = base.get(ключ, 0.0);
                if (печатное <= 0.0) {
                    continue;       // признаки позиции: печатного значения нет
                }
                double стало = g.get(ключ, печатное);
                assertTrue(стало <= печатное * 20.0,
                    профиль + ": вес " + ключ + " разогнался до " + стало
                    + " при печатном " + печатное);
                assertTrue(стало >= печатное / 20.0,
                    профиль + ": вес " + ключ + " просел до " + стало
                    + " при печатном " + печатное);
            }
        }
    }

    /**
     * ЯСТРЕБ ОСТАЁТСЯ АГРЕССИВНЕЕ ГОЛУБЯ, сколько бы ни мутировали. Именно это и
     * сломалось: характеры не просто стёрлись, а поменялись местами, и ни одно
     * место в коде не могло этого заметить.
     */
    @Test
    void характерыНеМеняютсяМестами() {
        for (long зерно : new long[]{1L, 42L, 999L, 20250817L}) {
            Genome ястреб = погонять("hawk", зерно);
            Genome голубь = погонять("dove", зерно);
            assertTrue(ястреб.get("aggression", 0) > голубь.get("aggression", 0),
                "зерно " + зерно + ": агрессия ястреба " + ястреб.get("aggression", 0)
                + " не больше голубиной " + голубь.get("aggression", 0));
            assertTrue(ястреб.get("action.combat", 0) > голубь.get("action.combat", 0),
                "зерно " + зерно + ": ястреб ценит Бой не выше голубя");
        }
    }

    /**
     * РЫНОК НЕ ОБГОНЯЕТ СНАРЯЖЕНИЕ. Приоритеты действий — это ПОРЯДОК, чем занять ход,
     * и разъехаться им нельзя: у обученных линий {@code action.market} доходил до
     * 24.89 при {@code action.assembly} 0.00, то есть бот весь ход менял монеты на
     * келемий и не производил войск вообще. Дизайнер это и увидел за столом.
     */
    @Test
    void рынокНеОбгоняетПроизводство() {
        for (String профиль : Bots.CHARACTERS) {
            Genome g = погонять(профиль, 31337L);
            double рынок = g.get("action.market", 0);
            assertTrue(рынок < g.get("action.assembly", 0),
                профиль + ": Рынок " + рынок + " дороже Сборки " + g.get("action.assembly", 0));
            assertTrue(рынок < g.get("action.build", 0),
                профиль + ": Рынок " + рынок + " дороже Стройки " + g.get("action.build", 0));
        }
    }

    /**
     * ПРИБОРЫ НЕ САДЯТСЯ ЗА ОБЫЧНЫЙ СТОЛ. У аксиомы и жнеца победных очков в цели
     * обучения нет вовсе, поэтому их присутствие портит замер соседей.
     */
    @Test
    void приборыОтделеныОтИгроков() {
        assertTrue(Bots.PLAYERS.size() == Bots.CHARACTERS.size() - Bots.INSTRUMENTS.size(),
            "список игроков должен быть полным списком без приборов");
        for (String i : Bots.INSTRUMENTS) {
            assertTrue(!Bots.PLAYERS.contains(i), i + " — прибор, за обычным столом ему не место");
            assertTrue(Bots.isInstrument(i), i + " не помечен прибором");
        }
        for (String p : Bots.PLAYERS) {
            assertTrue(!Bots.isInstrument(p), p + " ошибочно помечен прибором");
        }
    }
}
