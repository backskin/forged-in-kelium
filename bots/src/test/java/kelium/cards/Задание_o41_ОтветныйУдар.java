package kelium.cards;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.EnumSet;
import java.util.Set;

import org.junit.jupiter.api.Test;

import kelium.bench.CardBench;

/**
 * o41 «Ответный удар» — карта, которая НЕ МОГЛА БЫТЬ ВЫПОЛНЕНА НИКОГДА.
 *
 * <p>ЧТО БЫЛО СЛОМАНО. Ответный бой по устройству случается не в твой ход: по тебе
 * бьют, ты отбиваешься, и запись ложится в твой журнал посреди ЧУЖОГО хода. К
 * началу твоего собственного хода журнал обнулялся, а в свой ход тебя не атакуют —
 * ты атакуешь сам. Условие «в этот ход уничтожь жетон в ответном бою» поэтому не
 * могло стать истинным ни при какой игре. Замер подтверждал: ноль выполнений и
 * 584 сожжения за 150 партий.
 *
 * <p>РЕШЕНО: годится ответный бой, случившийся ПОСЛЕ НАЧАЛА ТВОЕГО ПРОШЛОГО ХОДА.
 * Факт переносится через чужие ходы и живёт ровно один твой ход.
 *
 * <p>Эти проверки бьют ровно в то место, где карта была мертва: ответная победа
 * записана как случившаяся в чужой ход — условие обязано быть выполнено.
 */
class Задание_o41_ОтветныйУдар {

    private static final String ID = "o41";
    private static final String НАБОР = "objectives";

    private static final Set<CardBench.Способ> ПОКРЫТО = EnumSet.of(
        CardBench.Способ.ВЫПОЛНИТЬ,
        CardBench.Способ.УСИЛИТЬ,
        CardBench.Способ.СЖЕЧЬ);

    @Test
    void всеСпособыПокрыты() {
        var b = CardBench.партия(4);
        var непокрыто = CardBench.способыБезПроверки(b.настройка(), НАБОР, ID, ПОКРЫТО);
        assertTrue(непокрыто.isEmpty(),
            "у карты " + ID + " есть способы разыграть её, на которые нет теста: " + непокрыто);
    }

    /** НА ПУСТОМ СТОЛЕ УСЛОВИЯ НЕТ — иначе карта давалась бы даром. */
    @Test
    void безОтветногоБояНеГотово() {
        var b = CardBench.партия(4).заданиеВРуку(0, ID);
        assertFalse(b.готово(0, ID),
            "без ответного боя условие не должно считаться выполненным");
    }

    /**
     * ГЛАВНАЯ ПРОВЕРКА: ответная победа случилась в ЧУЖОЙ ход — условие выполнено.
     *
     * <p>Именно этот случай и был невыполним: запись переносится через чужие ходы,
     * а не стирается началом твоего.
     */
    @Test
    void ответнаяПобедаВЧужойХодГодится() {
        var b = CardBench.партия(4).заданиеВРуку(0, ID);
        b.журнал().of(0).retaliationSincePrevTurn = 1;
        assertTrue(b.готово(0, ID),
            "ответный бой случается в чужой ход — карта обязана это видеть, "
            + "иначе она невыполнима вовсе");
    }

    /** УСИЛЕНИЕ: в тех же ответных боях не потеряно ни одного своего жетона. */
    @Test
    void безПотерьУсиление() {
        var b = CardBench.партия(4).заданиеВРуку(0, ID);
        b.журнал().of(0).retaliationSincePrevTurn = 1;
        assertTrue(b.усилено(0, ID), "без потерь усиленное требование обязано быть выполнено");
    }

    /** С ПОТЕРЕЙ УСИЛЕНИЯ НЕТ, а базовое условие остаётся выполненным. */
    @Test
    void сПотерейУсиленияНет() {
        var b = CardBench.партия(4).заданиеВРуку(0, ID);
        b.журнал().of(0).retaliationSincePrevTurn = 1;
        b.журнал().of(0).lostSincePrevTurn = 1;
        assertTrue(b.готово(0, ID), "базовое условие с потерей всё равно выполнено");
        assertFalse(b.усилено(0, ID), "с потерей своего жетона усиления быть не должно");
    }

    /** СЖЕЧЬ: карта уходит из руки, верх даёт два боеприпаса. */
    @Test
    void сжечь() {
        var b = CardBench.партия(4).заданиеВРуку(0, ID);
        b.игратьДо(1, 0, CardBench.сжечьЗадание(ID));
        assertTrue(b.было("objective_burn", "card", ID),
            "движок не сообщил о сжигании задания. " + b.сводка());
        assertFalse(b.состояние().player(0).objectiveHand.contains(ID),
            "сожжённое задание осталось в руке");
    }

    /**
     * ВЫПОЛНИТЬ В ПАРТИИ: движок объявляет награду в 3 боеприпаса.
     *
     * <p>ЗАПИСЬ СТАВИТСЯ УЖЕ ВНУТРИ ХОДА. Первые две редакции теста писали факт в
     * журнал до партии — и падали, потому что движок при запуске заводит журнал
     * заново. Выглядело это как неработающая карта, хотя ломался сам тест.
     */
    @Test
    void выполнитьВПартии() {
        var b = CardBench.партия(4).заданиеВРуку(0, ID)
            .фактХода(ф -> ф.retaliationSincePrevTurn = 1);
        b.игратьДо(1, 0, CardBench.выполнитьЗадание(ID));
        assertTrue(b.было("objective", "card", ID),
            "задание не выполнено, хотя условие было верно. " + b.сводка());
        assertTrue(b.наградаБазовая(ID, "ammo") > 0,
            "награда боеприпасами не выдана: " + b.награда(ID));
    }
}
