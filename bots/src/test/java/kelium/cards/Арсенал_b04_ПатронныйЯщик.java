package kelium.cards;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.EnumSet;
import java.util.Set;

import org.junit.jupiter.api.Test;

import kelium.bench.CardBench;
import kelium.core.BuildingType;
import kelium.core.Resource;

/**
 * b04 «Патронный ящик» — ВСЕМИ СПОСОБАМИ, КАКИМИ ЕЁ МОЖНО РАЗЫГРАТЬ.
 *
 * <p>Карта составная: верх сжигают ради разового бонуса, низ добавляет ячейку
 * боеприпаса и даёт СПЕЦ-действие — собрать боеприпасы с любого своего
 * запитанного военного здания, минуя обычную Сборку.
 *
 * <p>Способы: СЖЕЧЬ · УСТАНОВИТЬ · ПРИМЕНИТЬ. Каждый проверяется отдельно, и
 * отдельно проверяется, что применить нельзя там, где условия нет.
 */
class Арсенал_b04_ПатронныйЯщик {

    private static final String ID = "b04";
    private static final String НАБОР = "arsenal";

    /** Способы, покрытые тестами этого класса. */
    private static final Set<CardBench.Способ> ПОКРЫТО = EnumSet.of(
        CardBench.Способ.СЖЕЧЬ,
        CardBench.Способ.УСТАНОВИТЬ,
        CardBench.Способ.ПРИМЕНИТЬ);

    /**
     * НИ ОДИН СПОСОБ НЕ ЗАБЫТ. Проверка идёт по данным карты: появится у карты
     * новый способ — тест упадёт, пока на него не напишут проверку.
     */
    @Test
    void всеСпособыПокрыты() {
        var b = CardBench.партия(4);
        var непокрыто = CardBench.способыБезПроверки(b.настройка(), НАБОР, ID, ПОКРЫТО);
        assertTrue(непокрыто.isEmpty(),
            "у карты " + ID + " есть способы разыграть её, на которые нет теста: " + непокрыто);
    }

    /** УСТАНОВИТЬ: карта уходит из руки в установленные. */
    @Test
    void установить() {
        var b = CardBench.партия(4)
            .арсеналВРуку(0, ID)
            .монеты(0, 6)
            .игратьДо(2, 0, CardBench.установить(ID));
        assertTrue(b.состояние().player(0).arsenalInstalled.contains(ID),
            "карта не установлена. " + b.сводка());
        assertFalse(b.состояние().player(0).arsenalHand.contains(ID),
            "установленная карта осталась в руке");
        assertTrue(b.было("arsenal", "mode", "install", "card", ID),
            "движок не сообщил об установке. " + b.сводка());
    }

    /** УСТАНОВЛЕННАЯ КАРТА ДАЁТ ЯЧЕЙКУ: потолок боеприпасов выше на один. */
    @Test
    void установленнаяДаётЯчейкуБоеприпаса() {
        var без = CardBench.партия(4);
        int потолокБез = kelium.engine.Storage.ammoMax(без.состояние(), без.состояние().player(0));
        var с = CardBench.партия(4).арсеналУстановлен(0, ID);
        int потолокС = kelium.engine.Storage.ammoMax(с.состояние(), с.состояние().player(0));
        assertEquals(потолокБез + 1, потолокС,
            "установленный «Патронный ящик» не поднял потолок боеприпасов");
    }

    /** СЖЕЧЬ: карта уходит в сброс, верх срабатывает. */
    @Test
    void сжечь() {
        var b = CardBench.партия(4)
            .арсеналВРуку(0, ID)
            .монеты(0, 6)
            .игратьДо(2, 0, CardBench.сжечьАрсенал(ID));
        assertFalse(b.состояние().player(0).arsenalHand.contains(ID),
            "сожжённая карта осталась в руке. " + b.сводка());
        assertFalse(b.состояние().player(0).arsenalInstalled.contains(ID),
            "сожжённая карта оказалась установленной");
        assertTrue(b.было("arsenal", "mode", "burn", "card", ID),
            "движок не сообщил о сжигании. " + b.сводка());
    }

    /**
     * ПРИМЕНИТЬ: СПЕЦ установленной карты даёт боеприпасы с запитанной казармы.
     *
     * <p>Обстановка ставится так, чтобы других источников боеприпасов не было:
     * иначе прирост нельзя приписать карте.
     */
    @Test
    void применитьСПЕЦ() {
        var b = CardBench.партия(4)
            .арсеналУстановлен(0, ID)
            .безЭнергии(0)
            .здание(0, BuildingType.BARRACKS, 1)
            .монеты(0, 6)
            .боеприпасы(0, 0);
        assertTrue(b.доступноПрименение(0, ID),
            "СПЕЦ карты недоступен при запитанной казарме и монете: " + b.доступныеСпец(0));
        b.игратьДо(2, 0, b.применить(ID));
        assertTrue(b.предлагалосьПрименение(ID),
            "СПЕЦ карты не был предложен при запитанной казарме. "
            + b.вариантыВида("spec"));
        assertTrue(b.событий("ability_spec") > 0,
            "движок не сообщил о применении СПЕЦ карты. " + b.сводка());
    }

    /**
     * НЕ СРАБАТЫВАЕТ БЕЗ ЗАПИТАННОГО ВОЕННОГО ЗДАНИЯ. Половина смысла проверки
     * карты — в отрицательном случае: без него «работает» означает лишь «не
     * падает».
     */
    @Test
    void безЗапитанногоВоенногоЗданияНеПредлагается() {
        var b = CardBench.партия(4)
            .арсеналУстановлен(0, ID)
            .безЭнергии(0)                          // ЦУ тоже военное здание
            .здание(0, BuildingType.MINER, 0)       // не военное и без энергии
            .монеты(0, 6);
        assertFalse(b.доступноПрименение(0, ID),
            "СПЕЦ карты доступен, хотя запитанного военного здания нет: "
            + b.доступныеСпец(0));
    }

    /** НЕ СРАБАТЫВАЕТ БЕЗ МОНЕТЫ: СПЕЦ этой карты стоит монету. */
    @Test
    void безМонетыНеПредлагается() {
        var b = CardBench.партия(4)
            .арсеналУстановлен(0, ID)
            .безЭнергии(0)
            .здание(0, BuildingType.BARRACKS, 1)    // запитана, но платить нечем
            .ресурс(0, Resource.COIN, 0);
        assertFalse(b.доступноПрименение(0, ID),
            "СПЕЦ карты доступен без монеты на оплату: " + b.доступныеСпец(0));
    }
}
