# -*- coding: utf-8 -*-
"""Снимает с выгруженного PDF номера страниц, на которых начинаются части, и
кладёт их в tools/страницы.json — оттуда их берёт СОДЕРЖАНИЕ при следующей
сборке. Поле TOC для этого не годится: Word обновляет его при каждой выгрузке,
и на книге с шестью десятками разделов выгрузка не заканчивается вовсе."""
import io
import json
import pathlib
import re

import pymupdf

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
# Ключ — ровно то, чем книга названа в КНИГИ['цель'] сборщика: по нему
# СОДЕРЖАНИЕ и ищет свои номера.
КНИГИ = {
    'rules/РУЛБУК — Кристаллы Раздора.docx': 'rules/РУЛБУК — Кристаллы Раздора.md',
    'rules/СПРАВОЧНИК — Кристаллы Раздора.docx':
        'rules/СПРАВОЧНИК — Кристаллы Раздора.md',
}


def части(md):
    строки = io.open(КОРЕНЬ / md, encoding='utf-8').read().split('\n')
    # Первый заголовок первого уровня — название книги, оно на обложке.
    return [с[2:].strip() for с in строки if с.startswith('# ')][1:]


def собрать(имя, md):
    pdf = КОРЕНЬ / (имя[:-len('.docx')] + '.pdf')
    if not pdf.exists():
        return {}
    doc = pymupdf.open(pdf)
    # СРАВНИВАТЬ ТОЛЬКО С ПЕРВОЙ СТРОКОЙ ПОЛОСЫ. Названия частей стоят и в
    # СОДЕРЖАНИИ — поиск по всему тексту нашёл бы их все на одной странице.
    полосы = []
    for i in range(doc.page_count):
        строки = [с.strip() for с in doc[i].get_text().splitlines() if с.strip()]
        # Первой строкой извлекается колонцифра из подвала, второй — баннер
        # части. Колонцифра и есть искомый номер: он печатный, а не порядковый,
        # и на обложке с содержанием его нет.
        полосы.append(строки[:2])
    doc.close()
    номера = {}
    for заголовок in части(md):
        # Баннер части набран одной строкой в самом верху полосы.
        игла = re.sub(r'\s+', ' ', заголовок).strip().upper()
        for верх in полосы:
            if len(верх) < 2 or not верх[0].strip().isdigit():
                continue
            if re.sub(r'\s+', ' ', верх[1]).strip().upper() == игла:
                номера[заголовок] = int(верх[0].strip())
                break
    return номера


if __name__ == '__main__':
    итог = {имя: собрать(имя, md) for имя, md in КНИГИ.items()}
    путь = КОРЕНЬ / 'tools' / 'страницы.json'
    io.open(путь, 'w', encoding='utf-8').write(
        json.dumps(итог, ensure_ascii=False, indent=1))
    for имя, н in итог.items():
        print(имя, '—', len(н), 'частей с номерами')
