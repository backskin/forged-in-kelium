# -*- coding: utf-8 -*-
"""ПРОВЕРКА СУПЕР-ЗАДАНИЙ ПРОТИВ ТОГО, ЧТО В ИГРЕ РЕАЛЬНО ЕСТЬ.

Зачем. Карты писались по памяти, и в них оказались параметры, которых в игре
нет: «четыре своих здания первого уровня» при том, что уровни есть только у
добытчиков и энергостанций и зданий первого уровня всего два; «потолок 6» на
множителе, чей настоящий максимум 2. Ловить это глазами бесполезно — глаз
помнит то же, что и написал.

Поэтому потолки здесь НЕ ЗАПИСАНЫ, а ВЫВЕДЕНЫ из data/boards: сколько у
игрока жетонов, у каких зданий бывают уровни и по сколько их. Меняются
планшеты — меняются и потолки, без правки этого файла.

Что проверяется:
  1. потолок множителя достижим (обещанное число можно набрать);
  2. потолок не декоративен (он строго меньше максимума, иначе он не ограничение);
  3. требование возможно (не просит больше жетонов, чем у игрока есть);
  4. пара «требование + награда» не скопирована с другой карты.

Запуск: python tools/проверка-супер-заданий.py [файл.yaml]
Без аргумента берётся каталог, закреплённый в своде; с аргументом — любой
черновик, чтобы предложение проверялось той же меркой, что и действующий набор.
"""
import io
import re
import sys
from collections import defaultdict

import yaml

sys.path.insert(0, 'tools')
import версии                                    # noqa: E402


def инвентарь():
    """Что у игрока есть — из планшетов, а не из головы."""
    b = yaml.safe_load(io.open('data/boards/boards.3.0.0.yaml', encoding='utf-8'))['boards']
    tok = [x for x in b if x['id'] == 'tokens'][0]
    tech = [x for x in b if x['id'] == 'tech_tracks'][0]
    военные = [k for k in tok['buildings'] if k != 'command_center']
    добыт, станц = len(tok['miners']), len(tok['power_plants'])
    воен_всего = tok['building_tokens_per_color'] - 1 - добыт - станц
    и = {
        'родов войск': len(tok['units']),
        'войск': sum(u['count'] for u in tok['units'].values()),
        'зданий': tok['building_tokens_per_color'],
        'зданий без уровня': 1 + воен_всего,          # ЦУ + казарма/завод/авиабаза
        'добытчиков': добыт,
        'энергостанций': станц,
        'треков': len(tech['tracks']),
        'военных каждого вида': воен_всего // len(военные),
    }
    for ур in range(1, max(добыт, станц) + 1):
        и[f'зданий {ур}-го уровня'] = sum(
            1 for x in tok['miners'] + tok['power_plants'] if x['level'] == ур)
    return и


# Слова множителя -> что считается. Таблица открыта и правится глазом.
# ПОРЯДОК ЗНАЧИМ: сначала длинные и точные шаблоны, потом короткие. Иначе
# «третьего ИЛИ четвёртого уровня» съедается шаблоном «четвёртого уровня», и
# проверка считает потолок не от того максимума (поймано на себе 10.09.2026).
ЧТО_СЧИТАЕТ = [
    (r'третьего или четвёртого уровня',      'зданий 3-4 уровня'),
    (r'четвёртого уровня|четвертого уровня', 'зданий 4-го уровня'),
    (r'первого уровня',                      'зданий 1-го уровня'),
    (r'разный род войск|разных рода войск',  'родов войск'),
    (r'трек',                                'треков'),
    (r'нет уровня|без уровня',               'зданий без уровня'),
    (r'установленн\w+ карт\w* арсенала',     'карт арсенала в ячейках'),
    (r'здани',                               'зданий'),
    (r'войск',                               'войск'),
]


def чем_считает(м):
    for шаблон, имя in ЧТО_СЧИТАЕТ:
        if re.search(шаблон, м, re.I):
            return имя
    return None


def главное(текст, ключ='требован'):
    """Число из требования: «Имей четыре своих здания…» -> 4."""
    словами = {'одно': 1, 'два': 2, 'две': 2, 'три': 3, 'четыре': 4, 'пять': 5,
               'шесть': 6, 'семь': 7, 'восемь': 8, 'девять': 9, 'десять': 10}
    m = re.search(r'\b(' + '|'.join(словами) + r')\b', текст, re.I)
    if m:
        return словами[m.group(1).lower()]
    m = re.search(r'\b(\d+)\b', текст)
    return int(m.group(1)) if m else None


def main():
    и = инвентарь()
    и['карт арсенала в ячейках'] = yaml.safe_load(
        io.open(f'data/rulesets/{версии.свод_по_умолчанию()}.yaml',
                encoding='utf-8')).get('arsenal_cells', 3)
    и['зданий 3-4 уровня'] = и['зданий 3-го уровня'] + и['зданий 4-го уровня']

    if len(sys.argv) > 1:
        путь = sys.argv[1]
        карты = yaml.safe_load(io.open(путь, encoding='utf-8'))['super_objectives']
        свод, в = версии.свод_по_умолчанию(), f'черновик {путь}'
    else:
        свод, в, карты, путь = версии.каталог('super_objectives')
    print(f'свод {свод}, каталог супер-заданий {в} — {len(карты)} карт')
    print('ИНВЕНТАРЬ (выведен из data/boards):')
    for k, v in sorted(и.items()):
        print(f'   {v:3d}  {k}')
    print()

    беды = defaultdict(list)

    # 4. копии пары «требование + награда»
    пары = defaultdict(list)
    for c in карты:
        пары[(c.get('requirement', ''), c.get('reward', ''))].append(c['id'])
    for _, ids in пары.items():
        if len(ids) > 1:
            for i in ids:
                беды[i].append(f'КОПИЯ: требование и награда те же, что у {", ".join(x for x in ids if x != i)}')

    for c in карты:
        м = c.get('multiplier', '')
        за = re.search(r'(\d+)\s*ПО за', м)
        пот = re.search(r'[Пп]отолок\s+(\d+)', м)
        чем = чем_считает(м)
        if за and пот and чем and чем in и:
            максПО = int(за.group(1)) * и[чем]
            if int(пот.group(1)) > максПО:
                беды[c['id']].append(
                    f'ПОТОЛОК НЕДОСТИЖИМ: обещано {пот.group(1)} ПО, '
                    f'максимум {максПО} ({и[чем]} × {за.group(1)}, считается «{чем}»)')
            elif int(пот.group(1)) == максПО:
                беды[c['id']].append(
                    f'ПОТОЛОК ДЕКОРАТИВЕН: равен максимуму {максПО}, значит ничего не ограничивает')

        # 3. требование не просит больше, чем есть
        т = c.get('requirement', '')
        n = главное(т)
        чемт = чем_считает(т)
        if n and чемт and чемт in и and n > и[чемт]:
            беды[c['id']].append(
                f'ТРЕБОВАНИЕ НЕВЫПОЛНИМО: просит {n}, а «{чемт}» у игрока всего {и[чемт]}')

    print('=' * 78)
    порядок = [c['id'] for c in карты]
    имена = {c['id']: c['name'] for c in карты}
    for i in порядок:
        if беды[i]:
            print(f"{i} «{имена[i]}»")
            for б in беды[i]:
                print(f'    · {б}')
    целых = [i for i in порядок if not беды[i]]
    print()
    print(f'ЧИСТЫХ КАРТ: {len(целых)} из {len(карты)} — {", ".join(целых)}')
    print(f'С БЕДАМИ:    {len(карты) - len(целых)}')
    return 1 if len(целых) != len(карты) else 0


if __name__ == '__main__':
    sys.exit(main())
