# -*- coding: utf-8 -*-
"""ПОДОГНАТЬ ФОН КАРТИНОК ПОД ЦВЕТ СТРАНИЦЫ.

Конструктор рисует раскладки на своём светло-сером кадре, а страница книги
песочная. На песке такой кадр лежит серым прямоугольником с отчётливой
границей — картинка выглядит вставленной из другого документа.

Здесь ровно одна операция: пиксели ФОНА (тот цвет, что в углу кадра) меняются
на цвет страницы. Всё нарисованное — сетка, блоки, жетоны — не трогается: у
него другие цвета.

Трогаются только копии в `docs/раскладки`; выгрузки конструктора и его
собственный экспорт остаются как были.

Запуск: python tools/раскладки-под-фон.py
"""
import io
import os
import sys

from PIL import Image

ПАПКА = 'docs/раскладки'
# Тот же песочный, что стоит в tools/книжки-в-docx.py (ФОН_СТРАНИЦЫ).
ЦВЕТ_СТРАНИЦЫ = (0xF7, 0xF1, 0xE1)
# Насколько пиксель может отличаться от углового и всё ещё считаться фоном.
# Кадр залит ровно, поэтому допуск нужен только на сжатие картинки.
ДОПУСК = 6


def перекрасить(путь):
    im = Image.open(путь).convert('RGB')
    фон = im.getpixel((0, 0))
    if фон == ЦВЕТ_СТРАНИЦЫ:
        return 0
    точки = im.load()
    ш, в = im.size
    сколько = 0
    for y in range(в):
        for x in range(ш):
            c = точки[x, y]
            if (abs(c[0] - фон[0]) <= ДОПУСК and abs(c[1] - фон[1]) <= ДОПУСК
                    and abs(c[2] - фон[2]) <= ДОПУСК):
                точки[x, y] = ЦВЕТ_СТРАНИЦЫ
                сколько += 1
    im.save(путь)
    return сколько


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    if not os.path.isdir(ПАПКА):
        raise SystemExit('нет папки ' + ПАПКА)
    for имя in sorted(os.listdir(ПАПКА)):
        if not имя.lower().endswith('.png'):
            continue
        путь = os.path.join(ПАПКА, имя)
        n = перекрасить(путь)
        print('%-16s перекрашено точек фона: %d' % (имя, n))


if __name__ == '__main__':
    main()
