# -*- coding: utf-8 -*-
"""КОЛОДА ЗАДАНИЙ 1.19.0 — по печатным картам дизайнера (25.09.2026).

Эталон — рисунки дизайнера:
  Общие компоненты/экспорт-задания/награды-действия/задания-с-действи-2..41.png
      (печатные номера 01-40; файл 1 — рубашка);
  Общие компоненты/экспорт-задания-начальные/Задания начальные-2..13.png
      (печатные номера 01-12; файл 1 — рубашка).

Колода собирается ИЗ КЛАССОВ: у карты задания источник правды — её класс, а файл
набора это его выгрузка. Здесь из общей пачки отбираются сорок карт по семействам
(порядок — по печатным номерам) и двенадцать начальных (порядок — тоже по
печатным номерам: № 08 — n10, № 10 — n8).

Запуск:
  1) java kelium.ВыгрузкаЗаданий <куда.json>     — снимок классов
  2) python tools/собрать-задания-1-19-0.py <куда.json>
Пишет: data/cards/objectives.1.19.0.yaml
"""
import io
import json
import os
import sys

import yaml

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ВЕРСИЯ = '1.19.0'
ЦЕЛЬ = os.path.join(КОРЕНЬ, 'data', 'cards', 'objectives.%s.yaml' % ВЕРСИЯ)

# Семейство — печатный заголовок карты; порядок — печатные номера 01-40.
СЕМЕЙСТВА = [
    ('Выработка', ['o04', 'o05', 'o40', 'o08', 'o01']),                  # 01-05
    ('Засада', ['o29', 'o03', 'o07', 'o27', 'o63']),                      # 06-10
    ('Обеспечение', ['o33', 'o36', 'o34', 'o64']),                        # 11-14
    ('Развёртывание', ['o17', 'o11', 'o18', 'o65', 'o12', 'o15', 'o20']),  # 15-21
    ('Расплата', ['o66', 'o67', 'o10', 'o06']),                           # 22-25
    ('Устранение', ['o68', 'o69', 'o42', 'o25', 'o70', 'o71', 'o72',
                    'o21', 'o43', 'o73']),                                # 26-35
    ('Экспансия', ['o74', 'o02', 'o75', 'o76', 'o77']),                   # 36-40
]
# Начальные — по печатным номерам 01-12.
НАЧАЛЬНЫЕ = ['n1', 'n2', 'n3', 'n4', 'n5', 'n6', 'n7', 'n10', 'n9', 'n8', 'n11', 'n12']


def main():
    if len(sys.argv) < 2:
        raise SystemExit('нужен снимок классов: python %s <задания-из-кода.json>' % sys.argv[0])
    снимок = json.load(io.open(sys.argv[1], encoding='utf-8'))
    поId = {c['id']: c for c in снимок['classes']}

    карты = []
    беды = []
    for семья, ids in СЕМЕЙСТВА:
        for cid in ids:
            c = поId.get(cid)
            if c is None:
                беды.append('нет класса для %s (%s)' % (cid, семья))
                continue
            карты.append(c)
    for cid in НАЧАЛЬНЫЕ:
        c = поId.get(cid)
        if c is None:
            беды.append('нет класса начального задания %s' % cid)
            continue
        карты.append(c)
    if беды:
        raise SystemExit('колода не собрана:\n  ' + '\n  '.join(беды))

    обычных = sum(1 for c in карты if c.get('kind') == 'regular')
    начальных = sum(1 for c in карты if c.get('kind') == 'starting')
    if обычных != 40 or начальных != 12:
        raise SystemExit('обычных %d (надо 40), начальных %d (надо 12)' % (обычных, начальных))

    doc = {
        'meta': {
            'id': ВЕРСИЯ,
            'type': 'objectives',
            'выгружено': ('задания 1.19.0: ПЕЧАТНЫЕ КАРТЫ ДИЗАЙНЕРА 25.09.2026 — сорок '
                          'обычных (экспорт «награды-действия», номера 01-40) и '
                          'двенадцать начальных. Условия, усиления («дополнительно»), '
                          'обе награды и верх — с рисунка. Верх: ∞ — свободный '
                          '(реакции и перестановка модулей), ▶ — СПЕЦ-действием '
                          '(«Атакуй дважды», «2 max»).'),
        },
        'objectives': карты,
    }
    with io.open(ЦЕЛЬ, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# CONTENT: objectives  version %s\n' % ВЕРСИЯ)
        f.write('#\n')
        f.write('# ВЫГРУЗКА ИЗ КЛАССОВ (tools/собрать-задания-1-19-0.py). Источник правды —\n')
        f.write('# классы kelium.cards.objectives; этот файл читают люди и таблицы.\n')
        f.write('# Порядок — по печатным номерам карт дизайнера.\n')
        f.write('#\n')
        for семья, ids in СЕМЕЙСТВА:
            f.write('# %-16s %s\n' % (семья + ':', ' '.join(ids)))
        f.write('# %-16s %s\n' % ('Начальные:', ' '.join(НАЧАЛЬНЫЕ)))
        f.write('\n')
        yaml.safe_dump(doc, f, allow_unicode=True, sort_keys=False, width=100)
    print('записано: %s' % ЦЕЛЬ)
    print('обычных %d, начальных %d' % (обычных, начальных))


main()
