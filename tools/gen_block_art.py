# -*- coding: utf-8 -*-
"""РАСКЛАДКА ПЕЧАТНОГО АРТА МОДУЛЕЙ ПОЛЯ — перезапускать при новом экспорте.

Дизайнер отдаёт модули поля одной папкой: «Модули-поля-1.png» … «-20.png»,
сначала большие, потом малые, каждый по два раза — сторона «а» и сторона «б».
Здесь этот экспорт превращается в текстуры игры:

  * имена по данным: big-1-A.png … small-5-B.png (блок Б1 сторона A и т.д.);
  * размер под экран: печатный файл в семь мегабайт на экране не нужен;
  * якорь: где на картинке лежит гекс (0,0), какой у гекса радиус и на
    сколько шагов по 60° повёрнута печать относительно данных.

СВЕРКА, А НЕ ДОВЕРИЕ. Порядок файлов — слова дизайнера, и ошибиться в нём
легко: перепутанные стороны разложат по полю чужие контейнеры, и заметить это
на глаз почти нельзя. Поэтому каждая картинка сверяется с data/blocks: на ней
находятся жёлтые кольца энергии и коричневые ящики контейнеров, и наборы
гексов, где они стоят, обязаны совпасть с набором блоков. Не совпало — скрипт
скажет, на какой картинке, и ничего не запишет.

Запуск:  python tools/gen_block_art.py . "<папка экспорта>"
Пишет:   data/textures/block/*.png и data/textures/block/anchors.yaml
"""
import io
import math
import os
import sys

import numpy as np
import yaml
from PIL import Image
from scipy import ndimage as nd

ROOT = sys.argv[1] if len(sys.argv) > 1 else '.'
SRC = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.expanduser('~'), 'Yandex.Disk', 'Forged in Kelium',
    'Общие компоненты', 'экспорт-модули-поля')
OUT = os.path.join(ROOT, 'data', 'textures', 'block')

# ВЕРСИЯ НАБОРА, С КОТОРОЙ СНЯТ ЭТОТ ЭКСПОРТ. Дизайнер: «версия, где нет
# энергии на 1 гексе и нет контейнеров на 2 гексах из всех» — это ровно
# blocks.5.0.0 (энергия 4/5 и 5/6, контейнеры 3/5 и 4/6).
ВЕРСИЯ = '5.0.0'

# ШИРИНА ТЕКСТУРЫ. Печатный файл — 2776 пикселей на модуль; на экране модуль
# шире четырёхсот-пятисот не бывает даже при полуторном масштабе интерфейса, а
# двадцать распакованных картинок висят в памяти все сразу. Девятьсот — запас
# вдвое к самому крупному показу и около мегабайта на файл. Печатные исходники
# живут у дизайнера; надо будет качество для типографии — поднять это число и
# перегенерировать.
ШИРИНА = 900

S3 = math.sqrt(3)


def центр(q, r, size, origin=(0.0, 0.0)):
    """Экранный центр гекса: плоский верх, та же формула, что в FieldGeometry."""
    return (origin[0] + 1.5 * q * size, origin[1] + S3 * (r + q / 2.0) * size)


def повернуть(cells, n):
    """n шагов по 60° ПО ЧАСОВОЙ: (q,r) → (−r, q+r)."""
    out = list(cells)
    for _ in range(n):
        out = [(-r, q + r) for q, r in out]
    return out


def рамка_в_единицах(cells):
    xs = [центр(q, r, 1)[0] for q, r in cells]
    ys = [центр(q, r, 1)[1] for q, r in cells]
    return min(xs) - 1, min(ys) - S3 / 2, max(xs) + 1, max(ys) + S3 / 2


def рамка_картинки(alpha, thr=128):
    ys, xs = np.nonzero(alpha > thr)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


def набор(путь):
    d = yaml.safe_load(io.open(путь, encoding='utf-8'))
    out = {}
    for b in d['blocks']:
        for f, cells in b['faces'].items():
            out[(b['id'], f)] = (b['kind'],
                                 [(c['q'], c['r'], c['cell'], c['energy']) for c in cells])
    return out


def подогнать(alpha, cells):
    """Найти поворот, радиус гекса и центр гекса (0,0) на картинке.

    Экспорт вписывает модуль в холст, поэтому радиус считается по рамке: у
    ВЕРНОГО поворота масштаб по ширине и по высоте совпадает, у остальных
    расходится в разы. Догадка проверяется по самой картинке: центры гексов
    обязаны быть непрозрачными, а центры соседних (вне модуля) — прозрачными.
    """
    x0, y0, x1, y1 = рамка_картинки(alpha)
    W, H = x1 - x0, y1 - y0
    лучшее = None
    for n in range(6):
        cs = повернуть(cells, n)
        ux0, uy0, ux1, uy1 = рамка_в_единицах(cs)
        sx, sy = W / (ux1 - ux0), H / (uy1 - uy0)
        разброс = abs(sx - sy) / max(sx, sy)
        size = (sx + sy) / 2
        origin = (x0 - ux0 * size, y0 - uy0 * size)
        внутри = 0
        for q, r in cs:
            cx, cy = центр(q, r, size, origin)
            iy, ix = int(cy), int(cx)
            if 0 <= iy < alpha.shape[0] and 0 <= ix < alpha.shape[1] and alpha[iy, ix] > 200:
                внутри += 1
        кольцо = set()
        свои = set(cs)
        for q, r in cs:
            for dq, dr in ((1, 0), (1, -1), (0, -1), (-1, 0), (-1, 1), (0, 1)):
                if (q + dq, r + dr) not in свои:
                    кольцо.add((q + dq, r + dr))
        снаружи = 0
        for q, r in кольцо:
            cx, cy = центр(q, r, size, origin)
            iy, ix = int(cy), int(cx)
            if not (0 <= iy < alpha.shape[0] and 0 <= ix < alpha.shape[1]) \
                    or alpha[iy, ix] < 40:
                снаружи += 1
        оценка = (внутри == len(cs), снаружи == len(кольцо), -разброс)
        if лучшее is None or оценка > лучшее[0]:
            лучшее = (оценка, n, size, origin, внутри, len(cs), снаружи, len(кольцо))
    return лучшее


def пятна(маска, минимум):
    lab, n = nd.label(маска)
    if n == 0:
        return []
    веса = nd.sum(np.ones_like(lab), lab, range(1, n + 1))
    центры = nd.center_of_mass(маска, lab, range(1, n + 1))
    return [(c[1], c[0]) for c, w in zip(центры, веса) if w >= минимум]


# Поворот поля: гексы лежат «плашмя вверх», сторона s смотрит под этим углом
# (то же число, что FieldGeometry.TILT и edgeAngle в игре).
НАКЛОН = 30.0


def угол_стороны(s):
    return -60.0 * s + НАКЛОН


def сторона_по_углу(dx, dy):
    """На какую сторону гекса смотрит эта точка."""
    ang = math.degrees(math.atan2(dy, dx))
    лучшая, разница = -1, 999.0
    for s in range(6):
        d = abs((ang - угол_стороны(s) + 180) % 360 - 180)
        if d < разница:
            разница, лучшая = d, s
    return лучшая


def повернуть_ячейку(s, n):
    """Номер ячейки при повороте картонки на n шагов по часовой (как в игре)."""
    if s < 0 or s == 6:
        return s
    return (s + 6 - n % 6) % 6


def сверить(rgb, cells, n_rot, size, origin, cells_data):
    """Что напечатано на картинке — против того, что записано в наборе.

    Проверяются ДВЕ вещи: на тех ли гексах стоят жёлтые ячейки и ящики
    контейнеров и на тех ли СТОРОНАХ. Сторона важна не меньше: контейнер даётся
    тому, кто встал именно на его ячейку, и если печать смотрит на другую
    сторону, игрок будет видеть ящик там, где движок его не отдаёт.
    """
    a = rgb.astype(int)
    r, g, b = a[:, :, 0], a[:, :, 1], a[:, :, 2]
    жёлтый = (r > 190) & (g > 165) & (b < 150) & (r - b > 60) & (abs(r - g) < 45)
    коричневый = (r > 130) & (r < 228) & (r - g > 33) & (r - b > 72) & (g - b > 20)
    точки = [центр(q, rr, size, origin) for q, rr in повернуть(cells, n_rot)]

    def ближайший(px, py):
        return min(range(len(точки)),
                   key=lambda i: (точки[i][0] - px) ** 2 + (точки[i][1] - py) ** 2)

    было_э, было_к = {}, {}
    for px, py in пятна(жёлтый, 2500):
        i = ближайший(px, py)
        было_э[i] = сторона_по_углу(px - точки[i][0], py - точки[i][1])
    for px, py in пятна(коричневый, 2500):
        i = ближайший(px, py)
        далеко = math.hypot(px - точки[i][0], py - точки[i][1]) / size
        было_к[i] = 6 if далеко < 0.34 else сторона_по_углу(
            px - точки[i][0], py - точки[i][1])
    надо_э = {i: повернуть_ячейку(en, n_rot)
              for i, (_, _, _, en) in enumerate(cells_data) if en >= 0}
    надо_к = {i: повернуть_ячейку(co, n_rot)
              for i, (_, _, co, _) in enumerate(cells_data) if co >= 0}
    return (было_э, надо_э, было_к, надо_к)


def main():
    blocks = набор(os.path.join(ROOT, 'data', 'blocks', 'blocks.%s.yaml' % ВЕРСИЯ))
    порядок = []
    for i in range(1, 6):
        порядок += [('Б%d' % i, 'A'), ('Б%d' % i, 'B')]
    for i in range(1, 6):
        порядок += [('М%d' % i, 'A'), ('М%d' % i, 'B')]

    беды = []
    стороны = []
    готово = []
    общий = None
    for n, key in enumerate(порядок, start=1):
        путь = os.path.join(SRC, 'Модули-поля-%d.png' % n)
        if not os.path.isfile(путь):
            беды.append('нет файла %s' % путь)
            continue
        kind, cells_data = blocks[key]
        cells = [(q, r) for q, r, _, _ in cells_data]
        im = Image.open(путь).convert('RGBA')
        alpha = np.asarray(im)[:, :, 3]
        (оценка, n_rot, size, origin, внутри, всего, снаружи, кольцо) = подогнать(alpha, cells)
        if внутри != всего or снаружи != кольцо:
            беды.append('%s: сетка не села (гексов %d/%d, вне модуля %d/%d)'
                        % (os.path.basename(путь), внутри, всего, снаружи, кольцо))
            continue
        было_э, надо_э, было_к, надо_к = сверить(
            np.asarray(im.convert('RGB')), cells, n_rot, size, origin, cells_data)
        if set(было_э) != set(надо_э):
            беды.append('%s ↔ %s-%s: энергия на гексах %s, а в наборе %s'
                        % (os.path.basename(путь), key[0], key[1],
                           sorted(было_э), sorted(надо_э)))
        if set(было_к) != set(надо_к):
            беды.append('%s ↔ %s-%s: контейнеры на гексах %s, а в наборе %s'
                        % (os.path.basename(путь), key[0], key[1],
                           sorted(было_к), sorted(надо_к)))
        # СТОРОНЫ — предупреждение, а не отказ: печать ЖИВЁТ на картинке, и
        # если художник поставил ячейку не на ту сторону, чинить надо картинку
        # или набор, но раскладывать текстуры это не мешает. Молчать нельзя:
        # игрок увидит ящик там, где движок его не отдаёт.
        for i, надо in надо_э.items():
            if i in было_э and было_э[i] != надо:
                стороны.append('%s-%s гекс %d: жёлтая ячейка напечатана на стороне %d, '
                               'а в наборе %d' % (key[0], key[1], i, было_э[i], надо))
        for i, надо in надо_к.items():
            if i in было_к and было_к[i] != надо:
                стороны.append('%s-%s гекс %d: ящик напечатан на стороне %s, '
                               'а в наборе %s' % (key[0], key[1], i,
                                                  было_к[i], надо))
        готово.append((key, kind, im, n_rot, size, origin))
        # Преобразование у всех картинок экспорта одно и то же — это одна
        # выгрузка одним размером. Если вдруг разойдётся, лучше узнать сразу.
        свой = (n_rot, round(size, 1), round(origin[0], 1), round(origin[1], 1))
        if общий is None:
            общий = свой
        elif abs(свой[1] - общий[1]) > 2 or abs(свой[2] - общий[2]) > 3 \
                or abs(свой[3] - общий[3]) > 3 or свой[0] != общий[0]:
            беды.append('%s: своё преобразование %s против %s (экспорт не однородный)'
                        % (os.path.basename(путь), свой, общий))

    if беды:
        print('НИЧЕГО НЕ ЗАПИСАНО — сперва разберитесь с расхождениями:')
        for b in беды:
            print('  ' + b)
        return 1

    os.makedirs(OUT, exist_ok=True)
    k = ШИРИНА / готово[0][2].width
    for key, kind, im, n_rot, size, origin in готово:
        имя = '%s-%d-%s.png' % ('big' if kind == 'big' else 'small',
                                int(key[0][1:]), key[1])
        мал = im.resize((int(round(im.width * k)), int(round(im.height * k))),
                        Image.LANCZOS)
        мал.save(os.path.join(OUT, имя), optimize=True)
    _, _, im0, n_rot0, size0, origin0 = готово[0]
    доc = [
        '# ===========================================================================',
        '#  ЯКОРЬ ПЕЧАТНЫХ МОДУЛЕЙ ПОЛЯ — как положить картинку модуля на гексы',
        '# ===========================================================================',
        '#  Файл СГЕНЕРИРОВАН (tools/gen_block_art.py) по самому экспорту и сверен',
        '#  с data/blocks/blocks.%s.yaml: на каждой картинке найдены жёлтые' % ВЕРСИЯ,
        '#  ячейки и ящики контейнеров, и гексы, где они стоят, совпали с набором.',
        '#',
        '#  hex     — радиус гекса на картинке (пиксели картинки);',
        '#  origin  — где на картинке центр гекса (0, 0) набора;',
        '#  поворот — на сколько шагов по 60° по часовой печать повёрнута',
        '#            относительно координат набора. Чтобы положить модуль на',
        '#            поле повёрнутым на rot шагов, картинку крутят на',
        '#            (rot − поворот)·60° вокруг origin.',
        '# ===========================================================================',
        '',
        'meta:',
        '  id: 1.0.0',
        '  type: block_art',
        '  blocks: %s' % ВЕРСИЯ,
        '  сгенерировано: tools/gen_block_art.py',
        '',
        'арт:',
        '  size: [%d, %d]' % (int(round(im0.width * k)), int(round(im0.height * k))),
        '  hex: %.2f' % (size0 * k),
        '  origin: [%.2f, %.2f]' % (origin0[0] * k, origin0[1] * k),
        '  поворот: %d' % n_rot0,
    ]
    io.open(os.path.join(OUT, 'anchors.yaml'), 'w', encoding='utf-8') \
        .write('\n'.join(доc) + '\n')
    print('записано модулей: %d, папка %s' % (len(готово), OUT))
    print('сверка с набором blocks.%s: гексы сошлись' % ВЕРСИЯ)
    if стороны:
        print('')
        print('РАСХОЖДЕНИЯ ПО СТОРОНАМ (печать против набора) — %d:' % len(стороны))
        for с in стороны:
            print('  ' + с)
    else:
        print('стороны ячеек тоже сошлись, все %d' % (len(готово) * 5))
    return 0


sys.exit(main())
