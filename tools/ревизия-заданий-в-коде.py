def склеить(кусок):
    """Java-выражение из литералов, склеенных «+», — в одну строку."""
    шаблон = r'"((?:[^"\\]|\\.)*)"'
    из = re.findall(шаблон, кусок)
    return "".join(из)


def разбить_текст(текст, ширина=66):
    """Строка — обратно в Java-литералы, по словам, с отступом карты."""
    слова = текст.split(" ")
    строки_, тек = [], ""
    for сл in слова:
        if тек and len(тек) + 1 + len(сл) > ширина:
            строки_.append(тек + " ")
            тек = сл
        else:
            тек = (тек + " " + сл).strip()
    if тек:
        строки_.append(тек)
    бэкслеш = chr(92)
    куски = ['"' + с.replace(бэкслеш, бэкслеш * 2).replace('"', бэкслеш + '"') + '"'
             for с in строки_]
    перенос = chr(10) + " " * 16
    return перенос + ((перенос + "+ ").join(куски))


def чистая(s):
    return " ".join((s or "").split())


def классы():
    """id карты -> (файл, имя класса) по регистрации в ObjectivePack."""
    t = io.open(os.path.join(ПАКЕТ, "ObjectivePack.java"), encoding="utf-8").read()
    из = {}
    for имя, ид in re.findall(r"out\.add\(new\s+([\w.]+)\(\)\);\s*//\s*(o\d+)", t):
        файл, клас = имя.split(".") if "." in имя else ("ЗаданияТаблицы", имя)
        из[ид] = (файл + ".java", клас)
    return из


def тело_класса(t, клас):
    m = re.search(r"class\s+" + re.escape(клас) + r"\b", t)
    if not m:
        return None
    i = t.index("{", m.end())
    гл, j = 0, i
    while j < len(t):
        if t[j] == "{":
            гл += 1
        elif t[j] == "}":
            гл -= 1
            if гл == 0:
                return (m.start(), j + 1)
        j += 1
    return None


def разбить(аргументы):
    """Разбить список аргументов по запятым ВЕРХНЕГО уровня."""
    части, гл, кав, тек = [], 0, False, ""
    i = 0
    while i < len(аргументы):
        c = аргументы[i]
        if кав:
            тек += c
            if c == "\\":
                тек += аргументы[i + 1]
                i += 2
                continue
            if c == '"':
                кав = False
        elif c == '"':
            кав = True
            тек += c
        elif c in "([":
            гл += 1
            тек += c
        elif c in ")]":
            гл -= 1
            тек += c
        elif c == "," and гл == 0:
            части.append(тек)
            тек = ""
        else:
            тек += c
        i += 1
    части.append(тек)
    return части


def main():
    только_проверить = "--проверить" in sys.argv
    with io.open(ТАБЛИЦА, encoding="utf-8-sig", newline="") as f:
        таблица = list(csv.DictReader(f))
    семейства = {}
    for с in таблица:
        семейства.setdefault(чистая(с["Семейство"]), []).append(с)

    шапка = io.open(os.path.join(КОРЕНЬ, "data", "cards", "objectives.1.18.0.yaml"),
                    encoding="utf-8").read()
    порядок = {}
    for сем in семейства:
        m = re.search(r"^#\s*%s:\s*(.+)$" % re.escape(сем), шапка, re.M)
        порядок[сем] = m.group(1).split() if m else []

    карты = классы()
    правок, беды = 0, []
    файлы = {}
    for сем, строки in семейства.items():
        иды = порядок[сем]
        assert len(строки) == len(иды), (сем, len(строки), len(иды))
        for с, ид in zip(строки, иды):
            пара = карты.get(ид)
            if пара is None:
                беды.append("нет класса для " + ид)
                continue
            файл, клас = пара
            путь = os.path.join(ПАКЕТ, файл)
            t = файлы.get(файл) or io.open(путь, encoding="utf-8").read()
            гр = тело_класса(t, клас)
            if гр is None:
                беды.append("не нашёлся класс %s (%s)" % (клас, ид))
                continue
            начало, конец = гр
            тело = t[начало:конец]
            m = re.search(r"new Лицо\(", тело)
            if m is None:
                беды.append("%s (%s): нет лица" % (клас, ид))
                continue
            i = тело.index("(", m.end() - 1)
            гл, j = 0, i
            while j < len(тело):
                if тело[j] == "(":
                    гл += 1
                elif тело[j] == ")":
                    гл -= 1
                    if гл == 0:
                        break
                j += 1
            части = разбить(тело[i + 1:j])
            if len(части) != 9:
                беды.append("%s (%s): аргументов %d, ждали 9" % (клас, ид, len(части)))
                continue
            печатная = чистая(с["Награда: действие"])
            утиль = чистая(с["Утиль"])
            if печатная not in НАГРАДА:
                беды.append("%s: неизвестная награда «%s»" % (ид, печатная))
                continue
            if утиль not in УТИЛЬ:
                беды.append("%s: неизвестный утиль «%s»" % (ид, утиль))
                continue
            части[5] = "\n                " + НАГРАДА[печатная]
            # УСИЛЕННАЯ НАГРАДА — ТОПЛИВО ДЛЯ НАГРАДНОГО ДЕЙСТВИЯ. Пустая
            # усиленная награда не трогается: у таких карт усиления нет вовсе.
            if "Награда.нет()" not in части[6]:
                части[6] = "\n                " + ТОПЛИВО[печатная]
            части[7] = "\n                Утиль." + УТИЛЬ[утиль]
            # ОПИСАНИЕ: заменить прежнюю ресурсную награду на новую. Текст карты
            # читают за столом, и если он спорит с иконкой — спорить будут игроки.
            # Трогается ровно оборот «— награда …» до точки или до конца строки;
            # литературная часть и усиление остаются как написаны.
            # ОПИСАНИЕ СЛЕДУЕТ ЗА НАГРАДОЙ — обе её половины.
            #
            # Текст карты в исходнике разбит Java-конкатенацией на куски, и
            # править его регулярным выражением по сырому коду нельзя: оборот
            # «условие усилено: …» запросто оказывается на стыке двух литералов,
            # выражение съедает кавычки и ломает строку (так я уже испортил
            # текст o25). Поэтому куски СКЛЕИВАЮТСЯ в одну строку, правятся как
            # текст, и заново разбиваются на литералы.
            текст = склеить(части[8])
            текст = re.sub(r"— награда [^.]*\.",
                           "— награда " + СЛОВАМИ[печатная] + ".", текст, count=1)
            if "Награда.нет()" not in части[6]:
                текст = re.sub(r"услови[ея] усилено: [^.]*\.",
                               "условие усилено: "
                               + ТОПЛИВО_СЛОВАМИ[печатная] + ".", текст, count=1)
            части[8] = разбить_текст(текст)
            if "Награда.нет()" not in части[6]:
                части[8] = re.sub(r"услови[ея] усилено: [^.]*\.",
                                  "условие усилено: "
                                  + ТОПЛИВО_СЛОВАМИ[печатная] + ".",
                                  части[8], count=1)
            новое = тело[:i + 1] + ",".join(части) + тело[j:]
            if новое != тело:
                правок += 1
            файлы[файл] = t[:начало] + новое + t[конец:]

    if беды:
        print("БЕДЫ:")
        for б in беды:
            print("  *", б)
        return 1
    if только_проверить:
        print("правок потребовалось бы:", правок)
        return 0
    for файл, t in файлы.items():
        io.open(os.path.join(ПАКЕТ, файл), "w", encoding="utf-8", newline="\n").write(t)
    print("переписано карт:", правок, "в файлах:", len(файлы))
    return 0


if __name__ == "__main__":
    sys.exit(main())
