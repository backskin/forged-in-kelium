# -*- coding: utf-8 -*-
"""Собирает текст из PDF, где после каждой литеры стоит лишний глиф пробела.

Настоящая граница слова опознаётся только по горизонтальному зазору:
внутри слова он около нуля, между словами — больше единицы.
"""
import io
import pathlib
import re
import sys

import pymupdf

# Пороги найдены по гистограмме зазоров: у каждого случая своя впадина.
ЗАЗОР_ЗА_ПРОБЕЛОМ = 0.15   # между литерами вставлен лишний глиф пробела
ЗАЗОР_ЗА_ЛИТЕРОЙ = 1.35    # пара слиплась кернингом, глифа пробела нет
ПОРЧА = "�"     # этим глифом в теле текста набрана точка


def строка_из_литер(линия):
    куски = []
    прежний = None
    прежний_пробел = False
    for спан in линия["spans"]:
        for знак in спан["chars"]:
            симв = знак["c"]
            рамка = знак["bbox"]
            if симв == " ":
                прежний = рамка
                прежний_пробел = True
                continue
            if симв == "\xa0":
                if куски and куски[-1] != " ":
                    куски.append(" ")
                прежний = рамка
                прежний_пробел = True
                continue
            порог = ЗАЗОР_ЗА_ПРОБЕЛОМ if прежний_пробел else ЗАЗОР_ЗА_ЛИТЕРОЙ
            if прежний is not None and рамка[0] - прежний[2] > порог:
                if куски and куски[-1] != " ":
                    куски.append(" ")
            куски.append(симв)
            прежний = рамка
            прежний_пробел = False
    return "".join(куски)


def страница(лист):
    линии = []
    for блок in лист.get_text("rawdict")["blocks"]:
        if блок["type"] != 0:
            continue
        for линия in блок["lines"]:
            текст = строка_из_литер(линия).rstrip()
            if текст:
                линии.append(текст)
    return линии


def склеить_переносы(линии):
    итог = []
    for текст in линии:
        if итог and итог[-1].endswith("-") and текст[:1].islower():
            итог[-1] = итог[-1][:-1] + текст
        else:
            итог.append(текст)
    return итог


def чинить(текст):
    текст = текст.replace(ПОРЧА, ".")
    текст = re.sub(r"\.{3,}", " … ", текст)
    текст = re.sub(r"[ \t]{2,}", " ", текст)
    return текст


if __name__ == "__main__":
    источник = pathlib.Path(sys.argv[1])
    приёмник = pathlib.Path(sys.argv[2])
    книга = pymupdf.open(источник)
    всё = []
    for номер, лист in enumerate(книга, 1):
        линии = склеить_переносы(страница(лист))
        тело = чинить("\n".join(линии)) or "[[БЕЗ ТЕКСТОВОГО СЛОЯ]]"
        всё.append("\n===== стр. %d =====\n%s" % (номер, тело))
    io.open(приёмник, "w", encoding="utf-8", newline="").write("\n".join(всё))
    print(приёмник.name, len(книга), "стр.")
