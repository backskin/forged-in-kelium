# -*- coding: utf-8 -*-
"""СВЕРКА КОЛОДЫ ЗАДАНИЙ С ТАБЛИЦЕЙ ДИЗАЙНЕРА, СТРОКА В СТРОКУ.

Дизайнер 09.09.2026: «я только вот эти карты заданий считаю легитимными» — и
прислал таблицу сорока карт. Она лежит в
``data/cards/эталон/задания-40-таблица-дизайнера.tsv`` и является ЭТАЛОНОМ: где
данные игры с ней расходятся, неправа игра.

Сравнивается по каждой карте четыре вещи: печатное требование, усиление, базовая
награда и усиленная награда.

СВЯЗКА СТРОКИ И КАРТЫ — по семействам и порядку внутри них, а не по тексту:
колода и собиралась по этой таблице, сборщик держит семейства в её порядке,
значит N-я карта семейства и есть N-я строка того же семейства. По формулировкам
пары искать нельзя — они как раз и расходятся, это и есть предмет сверки.

Запуск:  python tools/сверка-заданий-с-таблицей.py
Возвращает 1, если есть хоть одно расхождение — годится как сторож.
"""

import io
import os
import re
import sys

import yaml

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЭТАЛОН = os.path.join(КОРЕНЬ, 'data', 'cards', 'эталон',
                      'задания-40-таблица-дизайнера.tsv')
СБОРЩИК = os.path.join(КОРЕНЬ, 'tools', 'собрать-задания-1-17-0.py')


def свод():
    """Действующий свод и версия набора заданий в нём — а не наугад."""
    путь = os.path.join(КОРЕНЬ, 'engine', 'src', 'main', 'java', 'kelium',
                        'dataio', 'GameConfig.java')
    свод_ид = re.search(r'"kelium\.ruleset",\s*"([^"]+)"',
                        io.open(путь, encoding='utf-8').read()).group(1)
    правила = io.open(os.path.join(КОРЕНЬ, 'data', 'rulesets', свод_ид + '.yaml'),
                      encoding='utf-8').read()
    версия = re.search(r'^\s*objectives:\s*([0-9.]+)', правила, re.M).group(1)
    return свод_ид, версия


def ключ(текст):
    """Текст без того, чем письмо отличается от смысла: регистр, ё, знаки."""
    t = (текст or '').lower().replace('ё', 'е')
    t = re.sub(r'[^a-zа-я0-9]+', ' ', t)
    return ' '.join(t.split())


ДОБРО = {
    'монет': 'coin', 'монета': 'coin', 'монеты': 'coin', 'мон': 'coin',
    'бпр': 'ammo', 'боеприпас': 'ammo', 'боеприпаса': 'ammo',
    'боеприпасов': 'ammo',
    'карт задания': 'objective_card', 'карты задания': 'objective_card',
    'карта задания': 'objective_card', 'карт заданий': 'objective_card',
    'трофей': 'trophy', 'трофея': 'trophy', 'трофеев': 'trophy',
    'контейнер': 'container', 'контейнера': 'container',
    'келемий': 'kelium',
}


def награда_из_таблицы(текст):
    """«2 монет, 1 БПР» → {'coin': 2, 'ammo': 1}; «АРСЕНАЛ» → {'arsenal': 1}."""
    из = {}
    текст = (текст or '').strip()
    if текст in ('', '—', '-'):
        return из
    верх = текст.upper()
    if верх == 'АРСЕНАЛ':
        return {'arsenal': 1}
    if верх == 'МОДУЛЬ АТАКИ':
        return {'module': 'attack'}
    if верх == 'МОДУЛЬ СБОРКИ':
        return {'module': 'assembly'}
    for кусок in текст.split(','):
        м = re.match(r'\s*(\d+)\s+(.+?)\s*$', кусок)
        if not м:
            continue
        сколько, слово = int(м.group(1)), м.group(2).strip().lower()
        вид = ДОБРО.get(слово, слово)
        из[вид] = из.get(вид, 0) + сколько
    return из


def печатно(d):
    if not d:
        return '—'
    return ', '.join('%s %s' % (v, k) for k, v in sorted(d.items()))


def порядок_колоды():
    """Идентификаторы карт в порядке таблицы — берутся из сборщика колоды."""
    исходник = io.open(СБОРЩИК, encoding='utf-8').read()
    начало = исходник.index('СЕМЕЙСТВА = [')
    # ЗАКРЫВАЮЩАЯ СКОБКА — ТА, ЧТО СТОИТ В НАЧАЛЕ СТРОКИ. Первая же «]» после
    # последнего семейства закрывает ВНУТРЕННИЙ список, и кусок кода тогда
    # обрывается посреди объявления.
    конец = исходник.index('\n]', начало) + 2
    среда = {}
    exec(исходник[начало:конец], среда)          # noqa: S102 — свой же файл
    ids = []
    for _, список in среда['СЕМЕЙСТВА']:
        ids.extend(список)
    return ids


def строки_таблицы():
    текст = io.open(ЭТАЛОН, encoding='utf-8').read()
    строки = текст.splitlines()[1:]
    return [с.split('\t') for с in строки if с.strip()]


def main():
    свод_ид, версия = свод()
    файл = os.path.join(КОРЕНЬ, 'data', 'cards', 'objectives.' + версия + '.yaml')
    карты = yaml.safe_load(io.open(файл, encoding='utf-8'))['objectives']
    по_ид = {c['id']: c for c in карты}
    порядок = порядок_колоды()
    таблица = строки_таблицы()

    if len(порядок) != len(таблица):
        raise SystemExit('в колоде %d карт, в таблице %d строк — сверять нечем'
                         % (len(порядок), len(таблица)))

    print('свод %s, набор заданий %s, карт %d, строк в таблице %d'
          % (свод_ид, версия, len(порядок), len(таблица)))

    расхождений = 0
    for i, стр in enumerate(таблица):
        номер, семья = стр[0], стр[1]
        требование, усиление, награда, _цена, сверх = стр[3], стр[4], стр[5], стр[6], стр[7]
        карта = по_ид.get(порядок[i])
        if карта is None:
            print('')
            print('строка №%s: карты %s в наборе нет' % (номер, порядок[i]))
            расхождений += 1
            continue

        беды = []
        наш_текст = ((карта.get('requirement') or {}).get('условие') or '').strip()
        if ключ(наш_текст) != ключ(требование):
            беды.append('ТРЕБОВАНИЕ напечатано иначе')
            беды.append('      в таблице: ' + требование.strip())
            беды.append('      на карте:  ' + наш_текст)

        наше_ус = ((карта.get('enhanced') or {}).get('условие') or '').strip()
        эт_ус = '' if усиление.strip() in ('—', '-', '') else усиление.strip()
        if bool(наше_ус) != bool(эт_ус):
            беды.append('УСИЛЕНИЕ: у нас «%s», в таблице «%s»'
                        % (наше_ус or 'нет', эт_ус or 'нет'))
        elif эт_ус and ключ(наше_ус) != ключ(эт_ус):
            беды.append('УСИЛЕНИЕ напечатано иначе')
            беды.append('      в таблице: ' + эт_ус)
            беды.append('      на карте:  ' + наше_ус)

        эт_б = награда_из_таблицы(награда)
        эт_с = награда_из_таблицы(сверх)
        наша_б = dict(карта.get('base_reward') or {})
        наша_с = dict(карта.get('special_reward') or {})
        if наша_б != эт_б:
            беды.append('НАГРАДА: у нас «%s», в таблице «%s»'
                        % (печатно(наша_б), печатно(эт_б)))
        if наша_с != эт_с:
            беды.append('УСИЛЕННАЯ НАГРАДА: у нас «%s», в таблице «%s»'
                        % (печатно(наша_с), печатно(эт_с)))

        if беды:
            расхождений += 1
            print('')
            print('№%s (%s, карта %s) %s' % (номер, семья, карта['id'], требование))
            for б in беды:
                print('   ' + б if not б.startswith('      ') else б)

    print('')
    print('строк с расхождениями: %d из %d' % (расхождений, len(таблица)))
    return 1 if расхождений else 0


if __name__ == '__main__':
    sys.exit(main())
