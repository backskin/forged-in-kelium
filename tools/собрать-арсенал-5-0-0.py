# -*- coding: utf-8 -*-
"""АРСЕНАЛ 5.0.0 — состав набора по таблицам дизайнера 02.09.2026.

Карты живут в КОДЕ (cards/arsenal/Арсенал5.java): там их названия, установки и
печатные тексты. Здесь — состав набора и стартовые карты.

ЭТОТ ФАЙЛ ДЕЛАЕТ ЗАГОТОВКУ, А НЕ ИТОГОВЫЙ НАБОР. Он перечисляет состав (32
номера плюс восемь стартовых карт из 4.2.0), после чего набор выгружается из
классов инструментом kelium.ВыгрузкаКаталога — и вот его-то результат и лежит
в data/cards. Так надо: файл набора обязан быть САМОДОСТАТОЧНЫМ. Модуля карт
нет на класспасе тестов движка, и набор из одних номеров означал бы, что там
у карт нет ни низов, ни верхов вовсе; ровно на этом упали два сторожа правила
«незапитанное здание работает только с картой Аварийное питание».

Порядок работы: правишь класс -> запускаешь этот файл (если менялся СОСТАВ) ->
выгружаешь каталог заново.

Стартовые восемь карт заказ не трогает — берутся из действующего набора 4.2.0.

Запуск: python tools/собрать-арсенал-5-0-0.py
"""
import io

import yaml

ИСТОЧНИК_СТАРТОВЫХ = 'data/cards/arsenal.4.2.0.yaml'
ЦЕЛЬ = 'data/cards/arsenal.5.0.0.yaml'

ШАПКА = """# CONTENT: arsenal  version 5.0.0
# ============================================================================
#  АРСЕНАЛ 5.0 - НАБОР ДИЗАЙНЕРА 02.09.2026 (32 обычные карты + 8 стартовых)
# ============================================================================
#  ИСТОЧНИК ПРАВДЫ - КОД: cards/src/main/java/kelium/cards/arsenal/Арсенал5.java.
#  Двадцать две установки и семнадцать утилей продиктованы двумя таблицами;
#  распределение утилей по установкам и названия карт - в том же классе, а
#  разбор «зачем такая пара» лежит в docs/АРСЕНАЛ 5.0.0 - карты целиком.xlsx.
#
#  НОМЕРА СВОИ (a5_01..a5_32), не как в 4.2.0: класс накрывает собой запись с
#  тем же номером в ЛЮБОМ наборе, и правка классов 4.2.0 переписала бы колоду,
#  на которой сыграны прежние замеры.
#
#  ВЕРХА ЗДЕСЬ НЕ ПОВТОРЕНЫ. Ключ top в записи перебивает верх из класса - это
#  нужно, чтобы переиздать утиль новой версией набора, не трогая класс. Набору
#  5.0.0 переиздавать нечего: он появился вместе с классом, и вторая копия
#  верхов разошлась бы с ним при первой же правке.
#
#  ГЛАВНОЕ ПРАВИЛО РАСКЛАДКИ: утиль не должен быть тем же инструментом, которым
#  выполняется низ, иначе карта становится автоматом - игрок жжёт верх, делая
#  ровно то, что закрыло бы установку.
"""


def main():
    старый = yaml.safe_load(io.open(ИСТОЧНИК_СТАРТОВЫХ, encoding='utf-8').read())
    стартовые = [c for c in старый['arsenal'] if c.get('kind') == 'starting']
    if len(стартовые) != 8:
        raise SystemExit(f'стартовых {len(стартовые)}, а надо 8')

    строки = [ШАПКА, 'meta:\n  id: 5.0.0\n  type: arsenal\n\narsenal:\n']
    for n in range(1, 33):
        строки.append(f'  - id: a5_{n:02d}\n    kind: regular\n')
    io.open(ЦЕЛЬ, 'w', encoding='utf-8').write(''.join(строки))

    # Стартовые дописываем как есть, целыми записями: они из другого набора и
    # своих классов не имеют, значит их данные нужны полностью.
    d = yaml.safe_load(io.open(ЦЕЛЬ, encoding='utf-8').read())
    d['arsenal'].extend(стартовые)
    io.open(ЦЕЛЬ, 'w', encoding='utf-8').write(
        ШАПКА + yaml.safe_dump(d, allow_unicode=True, sort_keys=False, width=100))
    print(f'готово: {ЦЕЛЬ}, обычных 32, стартовых {len(стартовые)}')


if __name__ == '__main__':
    main()
