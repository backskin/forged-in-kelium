# -*- coding: utf-8 -*-
"""ПРИЛОЖЕНИЯ РУЛБУКА — полные списки карт, собранные из данных.

Списки карт руками не пишутся: они выросли бы из колод и разошлись бы с ними на
первой же пересборке. Скрипт читает наборы, которые пинит ДЕЙСТВУЮЩИЙ свод, и
переписывает в рулбуке всё между метками. Правила выше меток он не трогает.

Запуск: python tools/приложения-рулбука.py
"""
import io
import os
import re

import yaml

РУЛБУК = 'rules/РУЛБУК — Кристаллы Раздора.md'
НАЧАЛО = '<!-- ПРИЛОЖЕНИЯ: собирается tools/приложения-рулбука.py, руками не править -->'
КОНЕЦ = '<!-- КОНЕЦ ПРИЛОЖЕНИЙ -->'


def свод():
    """Действующий свод — тот, что стоит в GameConfig.DEFAULT_RULESET."""
    s = io.open('engine/src/main/java/kelium/dataio/GameConfig.java',
                encoding='utf-8').read()
    m = re.search(r'kelium\.ruleset",\s*"([^"]+)"', s)
    if not m:
        raise SystemExit('не нашёл действующий свод в GameConfig')
    return m.group(1)


def набор(семья, версия):
    путь = 'data/cards/%s.%s.yaml' % (семья, версия)
    d = yaml.safe_load(io.open(путь, encoding='utf-8'))
    return d.get(семья) or []


def версии(свод_id):
    s = io.open('data/rulesets/%s.yaml' % свод_id, encoding='utf-8').read()
    блок = re.search(r'(?ms)^content_versions:\s*\n(.*?)(?=^\S|\Z)', s)
    out = {}
    for семья, в in re.findall(r'^\s{2}([a-z_]+):\s*([0-9][0-9.]*)',
                               блок.group(1), re.M):
        out[семья] = в
    return out


def кратко(текст, слов=22):
    """Первая фраза описания: приложение — список, а не пересказ карт."""
    if not текст:
        return ''
    т = ' '.join(str(текст).split())
    точка = т.find('. ')
    if 0 < точка < 200:
        т = т[:точка + 1]
    части = т.split(' ')
    if len(части) > слов:
        т = ' '.join(части[:слов]) + '…'
    return т


def строка(*ячейки):
    return '| ' + ' | '.join(str(x).replace('|', '/') for x in ячейки) + ' |'


ПРИКАЗЫ = {'development': 'Разработка', 'infrastructure': 'Инфраструктура',
           'operation': 'Операция', 'acquisitions': 'Приобретения'}
# Три формы на каждую награду: «1 монета», «3 монеты», «5 монет».
# Без них таблица приложения читается как машинный вывод: «3 боеприпасов».
НАГРАДЫ = {
    'coin': ('монета', 'монеты', 'монет'),
    'ammo': ('боеприпас', 'боеприпаса', 'боеприпасов'),
    'kelium': ('келемий', 'келемия', 'келемиев'),
    'trophy': ('трофей', 'трофея', 'трофеев'),
    'objective_card': ('карта задания', 'карты задания', 'карт задания'),
    'objective_cards': ('карта задания', 'карты задания', 'карт задания'),
    'container': ('контейнер', 'контейнера', 'контейнеров'),
    'containers': ('контейнер', 'контейнера', 'контейнеров'),
    'arsenal': ('карта арсенала', 'карты арсенала', 'карт арсенала'),
    'module': ('жетон модуля', 'жетона модуля', 'жетонов модуля'),
    'vp': ('ПО', 'ПО', 'ПО'),
}


def числом(сколько, формы):
    """Согласование с числом: 1 · 2-4 · 5+ (и 11-14 как 5+)."""
    n = abs(int(сколько))
    if n % 100 // 10 == 1:
        return формы[2]
    if n % 10 == 1:
        return формы[0]
    if n % 10 in (2, 3, 4):
        return формы[1]
    return формы[2]


def награда(узел):
    if not isinstance(узел, dict):
        return '—'
    части = []
    for k, v in узел.items():
        формы = НАГРАДЫ.get(k)
        # У награды «модуль» значение — не число, а РОД жетона: attack/assembly.
        if not isinstance(v, int):
            вид = {'attack': 'жетон модуля атаки',
                   'assembly': 'жетон модуля сборки'}.get(str(v))
            части.append(вид or '%s %s' % (v, k))
        elif формы is None:
            части.append('%s %s' % (v, k))
        else:
            части.append('%s %s' % (v, числом(v, формы)))
    return ', '.join(части) if части else '—'


def приложение_а():
    из = набор('orders', '1.0.0')
    строки = ['## Приложение А. Карты приказов', '',
              'Шестнадцать карт приказов — четыре колоды по четыре — и четыре карты',
              'БЕЗОПАСНОСТЬ. Каждый игрок играет одной колодой плюс своей БЕЗОПАСНОСТЬЮ.',
              '',
              строка('Колода', 'Верхний приказ', 'Нижний приказ', 'Манёвр'),
              '|---|---|---|---|']
    цвета = {'blue': 'Голубая', 'scarlet': 'Алая', 'green': 'Зелёная',
             'yellow': 'Жёлтая', 'security': 'БЕЗОПАСНОСТЬ'}
    for c in из:
        if c.get('joker'):
            continue
        строки.append(строка(цвета.get(c.get('deck'), c.get('deck')),
                             ПРИКАЗЫ.get(c.get('top'), '—'),
                             ПРИКАЗЫ.get(c.get('bottom'), '—'),
                             'да' if c.get('maneuver') else '—'))
    сколько = sum(1 for c in из if c.get('joker'))
    строки += ['', '**БЕЗОПАСНОСТЬ — %d карты.** Все восемь действий, играй любые два '
               'разных; нижнего приказа нет.' % сколько]
    return строки


def приложение_б(в):
    из = набор('objectives', в)
    обычные = [c for c in из if c.get('kind') != 'starting']
    начальные = [c for c in из if c.get('kind') == 'starting']
    вид = {'state': 'состояние', 'incident': 'происшествие', 'sacrifice': 'жертва'}
    строки = ['## Приложение Б. Карты заданий', '',
              'Обычных карт %d, начальных %d. НИЗ — требование и награда за него, '
              'ВЕРХ — утиль,' % (len(обычные), len(начальные)),
              'ради которого карту сжигают вместо выполнения.', '',
              строка('Карта', 'Вид', 'Требование', 'Награда', 'Усиление даёт', 'Утиль'),
              '|---|---|---|---|---|---|']
    for c in обычные:
        треб = (c.get('requirement') or {}).get('условие', '')
        строки.append(строка('**%s**' % c.get('name'),
                             вид.get(c.get('type'), c.get('type')),
                             кратко(треб, 26),
                             награда(c.get('base_reward')),
                             награда(c.get('special_reward')),
                             (c.get('top') or {}).get('label', '—')))
    строки += ['', '### Начальные задания', '',
               'Играют только в первом раунде: каждому игроку одна карта.', '',
               строка('Карта', 'Требование', 'Награда', 'Утиль'),
               '|---|---|---|---|']
    for c in начальные:
        треб = (c.get('requirement') or {}).get('условие', '')
        строки.append(строка('**%s**' % c.get('name'), кратко(треб, 22),
                             награда(c.get('base_reward')),
                             (c.get('top') or {}).get('label', '—')))
    return строки


def приложение_в(в):
    из = набор('arsenal', в)
    обычные = [c for c in из if c.get('kind') != 'starting']
    стартовые = [c for c in из if c.get('kind') == 'starting']
    строки = ['## Приложение В. Карты арсенала', '',
              'В колоде %d карт, ещё %d стартовых раздаются в подготовку. ВЕРХ — разовый '
              'утиль' % (len(обычные), len(стартовые)),
              '(карту сжигают), НИЗ — постоянный эффект (карту вскрывают в ячейке).', '',
              строка('Карта', 'Верх — утиль', 'Низ — постоянный эффект'),
              '|---|---|---|']
    for c in обычные + стартовые:
        верх = (c.get('top') or {}).get('label', '—')
        низ = (c.get('bottom') or {}).get('label', '—')
        имя = '**%s**' % c.get('name')
        if c.get('kind') == 'starting':
            имя += ' *(стартовая)*'
        строки.append(строка(имя, кратко(верх, 18), кратко(низ, 18)))
    return строки


