def main():
    id_свода = свод()
    в = версии(id_свода)
    куски = [НАЧАЛО, '',
             '# ПРИЛОЖЕНИЯ — ПОЛНЫЕ СПИСКИ КАРТ', '',
             '> Списки собраны из колод действующего свода **%s** '
             '(`tools/приложения-рулбука.py`).' % id_свода,
             '> Пересобрал колоду — пересобери приложения, и расходиться им будет нечем.',
             '']
    for часть in (приложение_а(),
                  приложение_б(в['objectives']),
                  приложение_в(в['arsenal']),
                  приложение_г(в['containers']),
                  приложение_д(в['market']),
                  приложение_е(в['super_objectives']),
                  приложение_ж(в['super_arsenal'])):
        куски += ['---', ''] + часть + ['']
    куски += [КОНЕЦ, '']

    текст = io.open(РУЛБУК, encoding='utf-8').read()
    новое = '\n'.join(куски)
    if НАЧАЛО in текст:
        i = текст.index(НАЧАЛО)
        j = текст.index(КОНЕЦ) + len(КОНЕЦ) + 1
        текст = текст[:i] + новое + текст[j:]
    else:
        текст = текст.rstrip() + '\n\n---\n\n' + новое
    io.open(РУЛБУК, 'w', encoding='utf-8', newline='').write(текст)
    print('приложения собраны по своду', id_свода)
    for семья in ('orders', 'objectives', 'arsenal', 'containers', 'market',
                  'super_objectives', 'super_arsenal'):
        версия = в.get(семья, '1.0.0')
        print('   %-18s %-8s %d карт' % (семья, версия, len(набор(семья, версия))))


if __name__ == '__main__':
    main()
