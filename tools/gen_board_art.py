# -*- coding: utf-8 -*-
"""РАСКЛАДКА ПЕЧАТНЫХ ПЛАНШЕТОВ — перезапускать при новом экспорте.

Источник: «Компоненты игрока/экспорт-планшеты» (планшеты войск и хранилища,
по одному на цвет) и «Общие компоненты/экспорт-планшеты» (научный отдел,
рынок). Игра берёт их через Textures.board(...) из data/textures/board/.

НУМЕРАЦИЯ. Планшеты игроков лежат в игре ПО НОМЕРУ ЭКСПОРТА, а не по гнезду
цвета жетонов: troop-p1/storage-p1 — красный, p2 — зелёный, p3 — синий,
p4 — жёлтый (песочный). С цветом места их связывает
PrintedBoards.ПЛАНШЕТ_ПО_ЦВЕТУ = {3, 1, 2, 4}: синее гнездо 0 берёт p3 и т. д.
Поэтому «new-N» кладётся в «-pN» без перестановки.

ЧТО ПРОЧИТАНО ПО КАРТИНКАМ (экспорт 25.09.2026, листы-коллажи):
  * планшет-войск-new-1..4: фон красный, зелёный, синий, жёлтый — тот же
    порядок, что у прежних troop-p1..p4; портрет командира у каждого свой;
  * Планшет-хранилища-new-1..4: фон в том же порядке; В ЦЕНТРЕ ТЕПЕРЬ ТРИ
    ячейки склада (гаража), было две; жетоны добытчика и станции нарисованы
    по бокам от них;
  * научный отдел: три крыла (красное, синее, зелёное) и центр — как прежде;
  * рынок: верхняя плашка «0 / 1 / 2 келемия → 1 / 3 / 7 монет» (прежняя —
    «1 / 2 → 3 / 7»), нижняя — «келемий: посмотреть 2 карты → взять».
Размеры полотен совпадают с прежними пиксель в пиксель, поэтому файлы
кладутся как есть. После раскладки — python tools/gen_anchors.py .

Запуск:  python tools/gen_board_art.py [--проверить]
"""
import os
import sys

from PIL import Image

КОРЕНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
КУДА = os.path.join(КОРЕНЬ, "data", "textures", "board")
ДИСК = os.environ.get("KELIUM_EXPORT") or r"C:\shared\Yandex.Disk\Forged in Kelium"
ИГРОКА = os.path.join(ДИСК, "Компоненты игрока", "экспорт-планшеты")
ОБЩИЕ = os.path.join(ДИСК, "Общие компоненты", "экспорт-планшеты")

РАСКЛАД = [(os.path.join(ИГРОКА, "планшет-войск-new-%d.png" % n), "troop-p%d.png" % n)
           for n in range(1, 5)]
РАСКЛАД += [(os.path.join(ИГРОКА, "Планшет-хранилища-new-%d.png" % n), "storage-p%d.png" % n)
            for n in range(1, 5)]
РАСКЛАД += [(os.path.join(ОБЩИЕ, "Планшет научный отдел.png"), "science.png"),
            (os.path.join(ОБЩИЕ, "Планшет рынка new.png"), "market.png")]


def средний_цвет(img):
    мал = img.convert("RGB").resize((32, 16))
    px = list(мал.getdata())
    return tuple(sum(p[i] for p in px) // len(px) for i in range(3))


def главная():
    проверить = "--проверить" in sys.argv
    for откуда, имя in РАСКЛАД:
        новый = Image.open(откуда)
        путь = os.path.join(КУДА, имя)
        прежний = Image.open(путь) if os.path.exists(путь) else None
        размер = "" if прежний is None or прежний.size == новый.size else \
            "  <-- РАЗМЕР %s, был %s" % (новый.size, прежний.size)
        print("%-16s <- %-34s %s цвет %s (был %s)%s" % (
            имя, os.path.basename(откуда), новый.size, средний_цвет(новый),
            средний_цвет(прежний) if прежний else "-", размер))
        if not проверить:
            новый.save(путь, optimize=True)
    return 0


if __name__ == "__main__":
    sys.exit(главная())
