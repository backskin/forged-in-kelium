# -*- coding: utf-8 -*-
"""Чинит русский текст из PDF со сломанной таблицей ToUnicode.

В таких файлах порча двойная:

1. Кириллица уехала вниз ровно на 711 позиций (0x2C7) и попала
   в Latin Extended-A: Б(U+0411)->U+014A, О->U+0157, Т->U+015B,
   Ч->U+0160, ц->U+017F и так далее.
2. Всё остальное — цифры, точки, запятые, двоеточия, скобки —
   уехало вниз на 29 и стало управляющими байтами:
   '.'(0x2E)->0x11, ','->0x0F, ':'->0x1D, ';'->0x1E,
   '0'..'9'(0x30..0x39)->0x13..0x1C.

Первое чиним по всему диапазону: латиница оттуда в русских
правилах не встречается. Второе — только для управляющих байтов,
где разночтений быть не может (перевод строки и табуляцию не трогаем).

Использование: python починить-кириллицу.py файл.txt [ещё.txt ...]
"""
import io
import pathlib
import re
import sys

КИР_СДВИГ = 0x2C7
КИР_НИЖ, КИР_ВЕРХ = 0x0149, 0x017F
ЗНАК_СДВИГ = 29
ЦЕЛЫЕ = (0x09, 0x0A, 0x0D)
ПРОЧЕЕ = {"Ƞ": "—", "ƪ": ""}


def чинить(текст):
    out = []
    for c in текст:
        n = ord(c)
        if КИР_НИЖ <= n <= КИР_ВЕРХ:
            out.append(chr(n + КИР_СДВИГ))
        elif n < 0x20 and n not in ЦЕЛЫЕ:
            out.append(chr(n + ЗНАК_СДВИГ))
        else:
            out.append(ПРОЧЕЕ.get(c, c))
    s = "".join(out)
    s = re.sub(r"m([^}\n]{1,80})\}", "«" + r"\1" + "»", s)
    return s


if __name__ == "__main__":
    for имя in sys.argv[1:]:
        путь = pathlib.Path(имя)
        было = io.open(путь, encoding="utf-8").read()
        стало = чинить(было)
        io.open(путь, "w", encoding="utf-8", newline="").write(стало)
        порча = len(re.findall("[ŉ-ſȠ\x00-\x08\x0b\x0c\x0e-\x1f]", стало))
        print(путь.name, "осталось подозрительных:", порча)
