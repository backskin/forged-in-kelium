# -*- coding: utf-8 -*-
"""ЯЧЕЙКИ ЭНЕРГИИ В МАСКЕ ЗОН — ПО САМОЙ ПЕЧАТИ.

Замечание дизайнера 09.09.2026: «некорректные повороты энергии (не встают
точно в ячейку) на зданиях казармы, авиабазы, ЦУ вот при таких поворотах самих
зданий».

Причина не в игре. Игра кладёт кубик туда, где на маске зон (файл
``<жетон>.zones.png``) стоит КРАСНОЕ пятно. У зданий, нарисованных на крыле
гекса (казарма, завод, авиабаза, ЦУ), эти пятна нарисованы мимо: сдвинуты
примерно на 16 пикселей влево и 27 вниз и вдобавок наклонены не так, как сама
ячейка. Игра честно исполняла разметку — и кубик садился рядом с ячейкой и под
углом. У добытчиков разметка точная (у них ячейки под келемий, а не под
энергию), их скрипт не трогает.

Что делает скрипт: находит НАПЕЧАТАННУЮ ячейку на самой картинке
(тёмно-бордовый квадрат под жёлтой рамкой со значком молнии), считает её
повёрнутый квадрат и переписывает красный слой маски ровно по нему. Ячейки
бывают наклонены — у завода они идут по скосу крыла, — поэтому квадрат
кладётся со своим углом, а не по осям картинки. Остальные цвета маски (синяя
площадка запаса энергии, розовые сердца) не меняются.

ОДНА ПЕЧАТЬ НА ЧЕТЫРЕ ЦВЕТА. Жетон одного здания у четырёх игроков — одна и та
же печать в разной подкраске, и ячейки на ней стоят в одних и тех же пикселях.
На красном жетоне бордовую ячейку по цвету не отличить от фона, поэтому семья
считается целиком: где ячейки нашлись хоть на одном цвете, они пишутся всем
четырём.

Скрипт идемпотентен: второй прогон даёт тот же результат.

Запуск:  python tools/зоны-энергии-по-печати.py [--проверить]
С ключом ``--проверить`` только показывает, что нашёл, и ничего не пишет.
"""

import glob
import math
import os
import re
import sys

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage
from scipy.spatial import ConvexHull

ПАПКА = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                     "data", "textures", "token")

# Ячейку ищем по её тёмно-бордовой середине: такого цвета на жетонах больше
# нигде нет, а размер и почти идеальный квадрат отсеивают случайные пятна.
МИН_ПЛОЩАДЬ = 1500
КВАДРАТНОСТЬ = 0.14          # допуск на отношение сторон повёрнутого квадрата
ПЛОТНОСТЬ = 0.72             # доля повёрнутого квадрата, занятая пятном


def повёрнутый_квадрат(xs, ys):
    """Повёрнутый квадрат вокруг пятна: центр, стороны, угол.

    УГОЛ БЕРЁТСЯ ОТ САМОЙ ДЛИННОЙ КРОМКИ ОБОЛОЧКИ, а не перебором «где площадь
    меньше». У квадрата площадь описанного прямоугольника почти одинакова при
    любом угле, поэтому перебор выбирает угол по пиксельному шуму — из-за этого
    две одинаковые ячейки получали разный наклон (замечание дизайнера
    09.09.2026: «один кубик почему-то так, а другой перевёрнут»). Кромка же у
    квадрата настоящая и одна.
    """
    точки = np.stack([xs, ys], axis=1)
    оболочка = ConvexHull(точки)
    вершины = точки[оболочка.vertices]
    лучшая = (0.0, 0.0)
    for i in range(len(вершины)):
        a = вершины[i]
        b = вершины[(i + 1) % len(вершины)]
        длина = math.hypot(b[0] - a[0], b[1] - a[1])
        if длина > лучшая[0]:
            лучшая = (длина, math.atan2(b[1] - a[1], b[0] - a[0]))
    угол = лучшая[1] % (math.pi / 2)      # квадрату хватает четверти оборота
    c, s = math.cos(угол), math.sin(угол)
    u = xs * c + ys * s
    v = -xs * s + ys * c
    w = u.max() - u.min()
    h = v.max() - v.min()
    uc = (u.max() + u.min()) / 2.0
    vc = (v.max() + v.min()) / 2.0
    return uc * c - vc * s, uc * s + vc * c, w, h, угол


def ячейки(тек):
    """Повёрнутые квадраты напечатанных ячеек энергии на картинке жетона."""
    a = np.array(тек.convert("RGBA")).astype(int)
    r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    бордовый = ((al > 10) & (r > 70) & (r < 190) & (g < 95) & (b < 80)
                & (r > g + 35) & (g > b - 12))
    # Дырки внутри пятна (значок молнии, светлые уголки) закрываются: нужна
    # ячейка целиком, а не её тёмная часть.
    бордовый = ndimage.binary_fill_holes(ndimage.binary_closing(
        бордовый, np.ones((7, 7))))
    # ЖЁЛТАЯ РАМКА — ПРИЗНАК ЯЧЕЙКИ. Без неё в улов попадали красные сердца
    # прочности: они тоже тёмно-красные и тоже почти квадратные.
    жёлтый = (al > 10) & (r > 195) & (g > 150) & (b < 120)
    рамка = ndimage.binary_dilation(жёлтый, np.ones((9, 9)))
    метки, сколько = ndimage.label(бордовый)
    найдено = []
    for i in range(1, сколько + 1):
        ys, xs = np.nonzero(метки == i)
        if len(xs) < МИН_ПЛОЩАДЬ:
            continue
        кайма = ndimage.binary_dilation(метки == i, np.ones((13, 13))) & ~(метки == i)
        if (кайма & рамка).sum() < 0.25 * кайма.sum():
            continue                      # не в жёлтой рамке — это не ячейка
        cx, cy, w, h, угол = повёрнутый_квадрат(xs.astype(float), ys.astype(float))
        if abs(w - h) > КВАДРАТНОСТЬ * max(w, h):
            continue
        if len(xs) < ПЛОТНОСТЬ * w * h:
            continue
        найдено.append((cx, cy, w, h, угол))
    # Порядок как читается: сверху вниз, слева направо. Игра заполняет ячейки
    # по порядку, и порядок обязан быть один и тот же от прогона к прогону.
    найдено.sort(key=lambda c: (round(c[1]), round(c[0])))
    return найдено


def красный_слой(маска):
    a = np.array(маска.convert("RGBA")).astype(int)
    r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    красный = (al > 10) & (r > 150) & (g < 110) & (b < 110)
    метки, сколько = ndimage.label(красный)
    пятен = sum(1 for i in range(1, сколько + 1) if (метки == i).sum() > 300)
    return пятен, красный


def переписать(маска, клетки, красный):
    """Убрать старый красный слой и положить квадраты точно по ячейкам."""
    a = np.array(маска.convert("RGBA"))
    a[красный] = (0, 0, 0, 0)
    out = Image.fromarray(a, "RGBA")
    рисовать = ImageDraw.Draw(out)
    for cx, cy, w, h, угол in клетки:
        c, s = math.cos(угол), math.sin(угол)
        углы = []
        for dx, dy in ((-w / 2, -h / 2), (w / 2, -h / 2), (w / 2, h / 2), (-w / 2, h / 2)):
            углы.append((cx + dx * c - dy * s, cy + dx * s + dy * c))
        рисовать.polygon(углы, fill=(255, 0, 0, 255))
    return out


def семья(имя):
    """Имя жетона без номера цвета: ``barracks_p2`` → ``barracks``."""
    return re.sub(r"_(p[1-4]|trophy\d*)$", "", имя)


def main():
    проверить = "--проверить" in sys.argv
    маски = {}
    for путь in sorted(glob.glob(os.path.join(ПАПКА, "*.zones.png"))):
        имя = os.path.basename(путь)[: -len(".zones.png")]
        картинка = os.path.join(ПАПКА, имя + ".png")
        if not os.path.exists(картинка):
            print("нет картинки под маску: " + имя)
            continue
        тек = Image.open(картинка)
        if тек.size != Image.open(путь).size:
            print("маска другого размера, пропуск: " + имя)
            continue
        маски.setdefault(семья(имя), []).append((имя, путь, картинка))

    правок = 0
    for род, файлы in маски.items():
        # Печать одна на всю семью: где ячейки нашлись, там и берём.
        найдено = []
        for имя, _, картинка in файлы:
            клетки = ячейки(Image.open(картинка))
            if len(клетки) > len(найдено):
                найдено = клетки
                откуда = имя
        if not найдено:
            print("%-16s печатных ячеек энергии нет — не тронуто" % род)
            continue
        # КОЛИЧЕСТВО ЯЧЕЕК РЕШАЕТ ХУДОЖНИК, А НЕ СКРИПТ. Если красной разметки
        # на маске нет вовсе, значит ячеек энергии у жетона нет — что бы ни
        # похоже на них нашлось на картинке (у добытчика и станции такие
        # квадраты под келемий и под уровень). Скрипт правит МЕСТО, а не
        # состав: молча добавить жетону ячейку он не имеет права.
        есть_красное = any(красный_слой(Image.open(путь))[1].any()
                           for _, путь, _ in файлы)
        if not есть_красное:
            print("%-16s ячейки на печати есть, а красной разметки нет — не тронуто"
                  % род)
            continue
        печать = ", ".join("центр %.0f,%.0f сторона %.0f угол %.1f°"
                           % (cx, cy, (w + h) / 2, math.degrees(угол))
                           for cx, cy, w, h, угол in найдено)
        print("%-16s ячеек %d (по %s): %s" % (род, len(найдено), откуда, печать))
        if проверить:
            continue
        for имя, путь, _ in файлы:
            _, красный = красный_слой(Image.open(путь))
            переписать(Image.open(путь), найдено, красный).save(путь)
            правок += 1
    if not проверить:
        print("переписано масок: %d" % правок)


if __name__ == "__main__":
    main()
