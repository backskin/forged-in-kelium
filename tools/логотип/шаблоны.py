# -*- coding: utf-8 -*-
"""Шаблоны логотипа «Кристаллы Раздора» шрифтом Tektur (дизайнер 05.10.2026).

Буквы набираются настоящим шрифтом — одна высота, один вес, ровная линия, —
а нейросеть потом только «одевает» готовую форму (металл, свет, кристалл),
не рисуя буквы сама. Отсюда же — знак «КР» в квадрате для иконки игры.

Запуск: python tools/логотип/шаблоны.py  → tools/логотип/шаблоны/*.png
"""
import os

from PIL import Image, ImageDraw, ImageFont

D = os.path.dirname(os.path.abspath(__file__))
ВЫХОД = os.path.join(D, "шаблоны")
os.makedirs(ВЫХОД, exist_ok=True)
Ш = r"C:\Windows\Fonts"
ШРИФТЫ = {
    "Tektur Black": "Tektur-Black.ttf",
    "Tektur ExtraBold": "Tektur-ExtraBold.ttf",
    "Tektur Narrow Black": "TekturNarrow-Black.ttf",
    "Tektur Tight Black": "TekturTight-Black.ttf",
}
БЕЛЫЙ, ЧЁРНЫЙ = (255, 255, 255, 255), (0, 0, 0, 255)


def строка(текст, шрифт, разрядка):
    """Строка с разрядкой: ширина в точках и отрисовка на прозрачном слое."""
    d = ImageDraw.Draw(Image.new("L", (1, 1)))
    ширины = [d.textlength(б, font=шрифт) for б in текст]
    w = round(sum(ширины) + разрядка * (len(текст) - 1))
    asc, desc = шрифт.getmetrics()
    сл = Image.new("RGBA", (w + 4, asc + desc), (0, 0, 0, 0))
    dd = ImageDraw.Draw(сл)
    x = 0
    for б, шб in zip(текст, ширины):
        dd.text((x, 0), б, font=шрифт, fill=БЕЛЫЙ)
        x += шб + разрядка
    return сл.crop(сл.getbbox())


def по_ширине(текст, путь, ширина, разрядка_доля):
    """Подобрать кегль так, чтобы строка вышла ровно заданной ширины."""
    кегль = 400
    for _ in range(30):
        ш = ImageFont.truetype(путь, кегль)
        сл = строка(текст, ш, кегль * разрядка_доля)
        кегль = max(20, round(кегль * ширина / сл.width))
    ш = ImageFont.truetype(путь, кегль)
    return строка(текст, ш, кегль * разрядка_доля)


def два_этажа(имя, файл, разрядка=0.04):
    """Два варианта в два этажа.
    «ровно» — обе строки одного кегля, разрядка одна и та же, строки по центру;
    «крупно» — «РАЗДОРА» крупнее и той же ширины, что «КРИСТАЛЛЫ»."""
    путь = os.path.join(Ш, файл)
    W, H = 1792, 1008
    верх = по_ширине("КРИСТАЛЛЫ", путь, 1400, разрядка)
    к = 400
    for _ in range(30):
        к = round(к * 1400 / строка("КРИСТАЛЛЫ", ImageFont.truetype(путь, к), к * разрядка).width)
    ш = ImageFont.truetype(путь, к)
    низ_ровно = строка("РАЗДОРА", ш, к * разрядка)
    низ_крупно = по_ширине("РАЗДОРА", путь, 1400, разрядка)
    out = []
    for вид, низ in (("ровно", низ_ровно), ("крупно", низ_крупно)):
        холст = Image.new("RGBA", (W, H), ЧЁРНЫЙ)
        зазор = round(верх.height * 0.22)
        y = (H - верх.height - зазор - низ.height) // 2
        холст.alpha_composite(верх, ((W - верх.width) // 2, y))
        холст.alpha_composite(низ, ((W - низ.width) // 2, y + верх.height + зазор))
        холст.save(os.path.join(ВЫХОД, "два этажа %s — %s.png" % (вид, имя)))
        out.append(холст)
    return out


def одна_строка(имя, файл):
    путь = os.path.join(Ш, файл)
    W, H = 1792, 1008
    холст = Image.new("RGBA", (W, H), ЧЁРНЫЙ)
    сл = по_ширине("КРИСТАЛЛЫ РАЗДОРА", путь, 1600, 0.03)
    холст.alpha_composite(сл, ((W - сл.width) // 2, (H - сл.height) // 2))
    холст.save(os.path.join(ВЫХОД, "одна строка — %s.png" % имя))
    return холст


def знак(имя, файл, размер=1024):
    """«КР» в квадрате со скошенными углами — иконка игры, читается в 64×64."""
    путь = os.path.join(Ш, файл)
    холст = Image.new("RGBA", (размер, размер), (0, 0, 0, 0))
    d = ImageDraw.Draw(холст)
    с = round(размер * 0.14)                       # скос угла
    п = round(размер * 0.03)
    рамка = [(п + с, п), (размер - п - с, п), (размер - п, п + с), (размер - п, размер - п - с),
             (размер - п - с, размер - п), (п + с, размер - п), (п, размер - п - с), (п, п + с)]
    d.polygon(рамка, fill=БЕЛЫЙ)
    т = round(размер * 0.06)
    внутр = [(x + (т if x < размер / 2 else -т), y + (т if y < размер / 2 else -т)) for x, y in рамка]
    d.polygon(внутр, fill=ЧЁРНЫЙ)
    буквы = по_ширине("КР", путь, round(размер * 0.66), 0.06)
    холст.alpha_composite(буквы, ((размер - буквы.width) // 2, (размер - буквы.height) // 2))
    холст.save(os.path.join(ВЫХОД, "знак КР — %s.png" % имя))
    return холст


листы = []
for имя, файл in ШРИФТЫ.items():
    р, к = два_этажа(имя, файл)
    листы.append((имя, р, к, одна_строка(имя, файл), знак(имя, файл)))

# СВОДНЫЙ ЛИСТ: шаблоны рядом и знак в 256, 64 и 32 точки — проверка мелкого размера
К = 0.3
W = round(1792 * К) * 3 + 540
лист = Image.new("RGBA", (W, len(листы) * (round(1008 * К) + 40) + 20), (40, 40, 40, 255))
d = ImageDraw.Draw(лист)
подпись = ImageFont.truetype(os.path.join(Ш, "TekturNarrow-Bold.ttf"), 22)
y = 20
for имя, а, а2, б, з in листы:
    for i, im in enumerate((а, а2, б)):
        лист.alpha_composite(im.resize((round(1792 * К), round(1008 * К))), (10 + i * (10 + round(1792 * К)), y))
    x = 40 + 3 * round(1792 * К)
    for с in (256, 64, 32):
        лист.alpha_composite(з.resize((с, с), Image.LANCZOS), (x, y))
        x += с + 12
    d.text((x - 360, y + 270), имя, font=подпись, fill=(220, 220, 220, 255))
    y += round(1008 * К) + 40
лист.save(os.path.join(ВЫХОД, "_все шаблоны.png"))
print("ok", ВЫХОД)
