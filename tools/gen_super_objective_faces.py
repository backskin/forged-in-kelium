"""ЛИЦА СУПЕР-ЗАДАНИЙ по шаблонам дизайнера (набор 9.0.0 и дальше).

Дизайнер 25.09.2026 положил в «Общие компоненты\\экспорт-задания-супер»
рубашку («задания супер-1.png») и три пустых лица («-2», «-3», «-4»,
661×1028): два раздела с флажком финала, у верхнего плашка «Награда: по ★»,
у нижнего «Награда: по ★★», под плашкой — пустое место для условия. Его
слова: «Используй их как шаблоны и заполни».

Скрипт кладёт карты набора на три иллюстрации по кругу (1-я карта — на «-2»,
2-я — на «-3», 3-я — на «-4», 4-я — снова на «-2» …) и вписывает под каждую
плашку текст её условия (label категории в data/cards/super_objectives.<v>.yaml)
в манере печатных заданий: тёмный текст, под каждой строкой — светлая
полупрозрачная подложка. Номер карты — в правом нижнем углу, как на печатных
заданиях. Названия нет: на шаблоне ему нет места (как у карт рынка).

Шрифт — Tektur из gui/src/main/resources/fonts. Кегль подбирается сам, один на оба
раздела карты: самый крупный, при котором каждое условие входит в место под
своей плашкой.

    python tools/gen_super_objective_faces.py [версия]   # по умолчанию 9.0.0

Выход — data/textures/card/objective_super/<id>.png шириной 600, плюс лист
всех лиц «design-docs/СУПЕР-ЗАДАНИЯ <версия> — лист лиц.png» для проверки
глазами.
"""
import os
import sys

import yaml
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЭКСПОРТ = os.environ.get('KELIUM_EXPORT') or r'C:\shared\Yandex.Disk\Forged in Kelium'
ПАПКА = os.path.join(ЭКСПОРТ, 'Общие компоненты', 'экспорт-задания-супер')
ШАБЛОНЫ = ['задания супер-2.png', 'задания супер-3.png', 'задания супер-4.png']
ШРИФТЫ = os.path.join(ROOT, 'gui', 'src', 'main', 'resources', 'fonts')
ШИРИНА = 600

# Цвета сняты с шаблона: плашка «Награда: по» — (138, 113, 0).
ОЛИВА = (138, 113, 0)
ТЕКСТ = (84, 62, 4)              # темнее плашки: условие читается первым
ПОДЛОЖКА = (255, 250, 232, 205)  # светлая полупрозрачная, как на печатных заданиях

# Место под условие в координатах шаблона 661×1028 (замерено по картинке):
# левая жёлтая полоса с флажком кончается на x≈120, плашки — x 159..606,
# верхняя плашка — y 81..178, нижняя — y 532..630, секции кончаются на
# y≈495 и у нижнего края.
ЗОНЫ = [
    (140, 196, 628, 482),        # под «Награда: по ★»
    (140, 648, 628, 958),        # под «Награда: по ★★» (угол с номером — ниже)
]
НОМЕР_У = (632, 1012)            # правый нижний угол: правый край, низ


def шрифт(имя, размер):
    return ImageFont.truetype(os.path.join(ШРИФТЫ, имя), размер)


def слова(текст):
    """Слова для переноса; короткие (предлог, союз, число) не остаются в конце
    строки — они склеены со следующим словом, как в наборе книги."""
    out, висит = [], ''
    for слово in текст.split():
        w = (висит + ' ' + слово) if висит else слово
        висит = ''
        if len(слово) <= 2:
            висит = w
        else:
            out.append(w)
    if висит:
        out.append(висит)
    return out


def перенос(d, текст, f, ширина):
    строки, строка = [], ''
    for слово in слова(текст):
        проба = (строка + ' ' + слово).strip()
        if d.textlength(проба, font=f) <= ширина or not строка:
            строка = проба
        else:
            строки.append(строка)
            строка = слово
    if строка:
        строки.append(строка)
    return строки


def разметка(d, текст, зона, наибольший=42):
    """Самый крупный кегль (не больше наибольшего), при котором текст входит в
    зону; строки и шаг."""
    x0, y0, x1, y1 = зона
    поле = 14                                    # подложка шире строки на столько с боков
    for размер in range(наибольший, 23, -1):
        f = шрифт('Tektur-SemiBold.ttf', размер)
        строки = перенос(d, текст, f, x1 - x0 - 2 * поле)
        шаг = round(размер * 1.42)
        if max(d.textlength(s, font=f) for s in строки) + 2 * поле <= x1 - x0 \
                and len(строки) * шаг <= y1 - y0 and len(строки) <= 5:
            return f, строки, шаг, размер
    raise SystemExit('не входит: ' + текст)


def вписать(im, текст, зона, кегль):
    """Условие под плашкой: строки по центру зоны, у каждой своя подложка."""
    слой = Image.new('RGBA', im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(слой)
    f, строки, шаг, _ = разметка(d, текст, зона, кегль)
    x0, y0, x1, y1 = зона
    cx = (x0 + x1) / 2
    y = y0 + ((y1 - y0) - len(строки) * шаг) / 2 * 0.35   # ближе к плашке, чем к низу
    коробки = []
    for s in строки:
        w = d.textlength(s, font=f)
        l, t, r, b = d.textbbox((0, 0), s, font=f)
        высота = b - t
        верх = y + (шаг - высота) / 2 - t
        коробки.append((cx - w / 2, y + 3, cx + w / 2, y + шаг - 3, s, верх))
        y += шаг
    for (a, b, c, e, _, _) in коробки:
        d.rounded_rectangle((a - 12, b, c + 12, e), radius=10, fill=ПОДЛОЖКА)
    im = Image.alpha_composite(im, слой)
    слой = Image.new('RGBA', im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(слой)
    for (a, _, _, _, s, верх) in коробки:
        d.text((a, верх), s, font=f, fill=ТЕКСТ + (255,))
    return Image.alpha_composite(im, слой), коробки


def номер(im, n):
    слой = Image.new('RGBA', im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(слой)
    f = шрифт('Tektur-Bold.ttf', 34)
    s = '%02d' % n
    w = d.textlength(s, font=f)
    l, t, r, b = d.textbbox((0, 0), s, font=f)
    x, y = НОМЕР_У[0] - w, НОМЕР_У[1] - b
    d.rounded_rectangle((x - 8, y + t - 5, x + w + 8, y + b + 5), radius=8, fill=ПОДЛОЖКА)
    d.text((x, y), s, font=f, fill=ОЛИВА + (255,))
    return Image.alpha_composite(im, слой)


def лицо(шаблон, n, условия):
    im = шаблон.copy()
    # оба раздела одним кеглем: тот, что влезает в оба
    d = ImageDraw.Draw(im)
    кегль = min(разметка(d, текст, зона)[3] for текст, зона in zip(условия, ЗОНЫ))
    for текст, зона in zip(условия, ЗОНЫ):
        im, _ = вписать(im, текст, зона, кегль)
    return номер(im, n)


def main():
    версия = sys.argv[1] if len(sys.argv) > 1 else '9.0.0'
    данные = yaml.safe_load(open(os.path.join(ROOT, 'data', 'cards',
                                             'super_objectives.%s.yaml' % версия),
                                encoding='utf-8'))
    шаблоны = [Image.open(os.path.join(ПАПКА, имя)).convert('RGBA') for имя in ШАБЛОНЫ]
    куда = os.path.join(ROOT, 'data', 'textures', 'card', 'objective_super')
    os.makedirs(куда, exist_ok=True)
    лица = []
    for i, карта in enumerate(данные['super_objectives'], 1):
        кат = карта['categories']
        vp = карта.get('vp', [1] * len(кат))
        if vp != [1, 2]:
            raise SystemExit(карта['id'] + ': шаблон — раздел «по ★» и раздел «по ★★»')
        условия = [данные['categories'][c] for c in кат]
        im = лицо(шаблоны[(i - 1) % len(шаблоны)], i, условия)
        im = im.resize((ШИРИНА, round(im.height * ШИРИНА / im.width)), Image.LANCZOS)
        im.convert('RGB').save(os.path.join(куда, карта['id'] + '.png'), optimize=True)
        лица.append(im)
    # лист для проверки глазами: 6 в ряд
    w, h = лица[0].size
    ряд = 6
    лист = Image.new('RGB', (ряд * (w // 2) + (ряд + 1) * 8,
                             ((len(лица) + ряд - 1) // ряд) * (h // 2 + 8) + 8), (40, 40, 40))
    for k, im in enumerate(лица):
        мал = im.resize((w // 2, h // 2), Image.LANCZOS)
        лист.paste(мал.convert('RGB'), (8 + (k % ряд) * (w // 2 + 8), 8 + (k // ряд) * (h // 2 + 8)))
    лист_куда = os.path.join(ROOT, 'design-docs', 'СУПЕР-ЗАДАНИЯ %s — лист лиц.png' % версия)
    лист.save(лист_куда, optimize=True)
    print('лист:', лист_куда)
    print('супер-заданий:', len(лица), '->', куда)


if __name__ == '__main__':
    main()
