# СОБРАТЬ ОБЕ КНИГИ: markdown -> docx -> PDF -> отделка.
#
# ГЛАВНОЕ ПРАВИЛО ЭТОГО СКРИПТА: WORD И PYTHON НИКОГДА НЕ РАБОТАЮТ ОДНОВРЕМЕННО.
#
# Word, открывший .docx, держит файл. Если в это время python попытается его
# переписать, он встанет на записи - и сборка выглядит зависшей, хотя Word
# давно всё сделал. Ровно на этом здесь терялись часы. Поэтому каждый проход
# устроен так: python пишет (Word не запущен) -> Word открывает, считает и
# выгружает -> Word ПОЛНОСТЬЮ закрывается -> и только теперь следующий проход.
#
# ТРИ ПРОХОДА, И КАЖДЫЙ НУЖЕН РОВНО ЗА ОДНИМ.
#
#   1. Считаем страницы. Больше ничего про свёрстанную книгу заранее не
#      известно: ни сколько её всего, ни на какой полосе начнётся часть.
#   2. Добиваем до кратности четырём. Книжка на скрепке складывается из
#      листов, сложенных пополам: страниц всегда 4, 8, 12... Пустые листы
#      вставляются ПЕРЕД памяткой, чтобы она осталась последней полосой.
#   3. Проставляем номера частей в СОДЕРЖАНИЕ. Их снимает номера-частей.py с
#      выгруженного PDF: полем TOC это делать нельзя - Word обновляет его при
#      каждой выгрузке, и на книге с шестью десятками разделов выгрузка не
#      заканчивается вовсе. Снимать номера надо ПОСЛЕ добивки: она сдвигает
#      памятку.
#
# В конце фон-страниц.py кладёт иллюстрации, подложки под текст и рамки. Это
# только PDF: в docx ничего этого нет.
#
# Запуск: & .\tools\собрать-книги.ps1
param(
    [string]$Корень = "C:\shared\forged-in-kelium",
    [string]$Лог = "C:\shared\forged-in-kelium\tools\сборка.log"
)

Set-Location $Корень
$книги = [ordered]@{
    "рулбук"     = "РУЛБУК — Кристаллы Раздора"
    "справочник" = "СПРАВОЧНИК — Кристаллы Раздора"
}

Set-Content -Path $Лог -Value "" -Encoding utf8
function Сказать([string]$текст) {
    $строка = "{0:HH:mm:ss}  {1}" -f (Get-Date), $текст
    Write-Host $строка
    Add-Content -Path $Лог -Value $строка -Encoding utf8
}

function ЗакрытьWord {
    Get-Process winword -ErrorAction SilentlyContinue |
        Stop-Process -Force -ErrorAction SilentlyContinue
    Start-Sleep -Milliseconds 600
}

function Питон([string]$скрипт) {
    ЗакрытьWord
    $вывод = & python $скрипт
    foreach ($с in $вывод) { Сказать "  $с" }
}

# Собрать docx. Word перед этим обязан быть закрыт - иначе python не запишет.
function СобратьDocx { Питон "tools/книжки-в-docx.py" }

# Открыть, посчитать страницы, выгрузить PDF - и закрыть Word за собой.
# РЕЗУЛЬТАТ - В ПЕРЕМЕННОЙ СКРИПТА, а не возвратом функции. Функция в
# PowerShell возвращает ВСЁ, что попало в поток вывода, и одна лишняя строка от
# любого вызова внутри превращает хеш-таблицу в массив.
$script:Страниц = @{}

function ВыгрузитьВсе {
    $script:Страниц = @{}
    $word = New-Object -ComObject Word.Application
    $word.Visible = $false
    $word.DisplayAlerts = 0
    try {
        foreach ($имя in $книги.Keys) {
            $ч = [Diagnostics.Stopwatch]::StartNew()
            $docx = Join-Path $Корень ("rules\" + $книги[$имя] + ".docx")
            $pdf = Join-Path $Корень ("rules\" + $книги[$имя] + ".pdf")
            # Только для чтения: писать нам незачем, а замок Word тут лишний.
            $doc = $word.Documents.Open($docx, $false, $true)
            $n = $doc.ComputeStatistics(2)
            $doc.ExportAsFixedFormat($pdf, 17)
            $doc.Close($false)
            $script:Страниц[$имя] = $n
            Сказать ("  {0,-12} {1,3} страниц   за {2:N1} c" -f $имя, $n, $ч.Elapsed.TotalSeconds)
        }
    } finally {
        $word.Quit()
        [System.Runtime.InteropServices.Marshal]::ReleaseComObject($word) | Out-Null
        [GC]::Collect()
        ЗакрытьWord
    }
}

Сказать "сборка исходников"
Питон "tools/справочник.py"
Питон "tools/словарь-рулбука.py"

Сказать "проход 1: считаем страницы"
'{}' | Set-Content "tools\добивка.json" -Encoding utf8
СобратьDocx
ВыгрузитьВсе
if ($script:Страниц.Count -eq 0) { throw "выгрузка не дала ни одной книги" }

$добивка = @{}
$надоли = $false
foreach ($имя in $книги.Keys) {
    $надо = (4 - ($script:Страниц[$имя] % 4)) % 4
    $добивка[$имя] = $надо
    if ($надо -gt 0) { $надоли = $true }
    Сказать ("  {0,-12} добить {1}" -f $имя, $надо)
}

if ($надоли) {
    Сказать "проход 2: добиваем до кратности четырём"
    ($добивка | ConvertTo-Json -Compress) | Set-Content "tools\добивка.json" -Encoding utf8
    СобратьDocx
    ВыгрузитьВсе
} else {
    Сказать "проход 2 не нужен: обе книги уже кратны четырём"
}

Сказать "проход 3: номера частей в СОДЕРЖАНИЕ"
Питон "tools/номера-частей.py"
СобратьDocx
ВыгрузитьВсе

foreach ($имя in $книги.Keys) {
    $n = $script:Страниц[$имя]
    $метка = if ($n % 4 -eq 0) { "кратно 4" } else { "НЕ КРАТНО 4" }
    Сказать ("  {0,-12} {1,3} страниц — {2}" -f $имя, $n, $метка)
}

Сказать "отделка: фон, подложки, рамки"
Питон "tools/фон-страниц.py"
Сказать "ГОТОВО"
