def ресурс(строка):
    """«2 монеты» → [{иконка: 1, сколько: 2}], «спец спец» → [{26:1},{26:1}]."""
    сл = строка.split()
    if сл and сл[0].isdigit():
        n = int(сл[0])
        имя = ' '.join(сл[1:])
        return [{'иконка': РЕС[имя], 'сколько': n}]
    return [{'иконка': РЕС[w], 'сколько': 1} for w in сл]


def доп(список):
    out = []
    for w in список:
        if out and out[-1]['иконка'] == РЕС[w]:
            out[-1]['сколько'] += 1
        else:
            out.append({'иконка': РЕС[w], 'сколько': 1})
    return out


