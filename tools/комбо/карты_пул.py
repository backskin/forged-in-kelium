"""ПУЛ КАРТ-КАНДИДАТОВ для модели хода (13.10.2026).

A_ — арсенал (закрыт в руке до установки спец-действием; «сразу» — эффект
в момент установки, это и есть скрытый удар). O_ — задания (в руке
закрыто; требование, плата-жертва, награда — одно крупное действие или
ресурс, усиление).

Действия модели: extract (Добыча), power (Питание), supply (Снабжение),
command (Командование), develop (Развитие).
"""
from модель_хода import карта, ст, выход_добычи


def act(a):
    return lambda n: dict(n, acts=n['acts'] + (a,))


def res(**d):
    return lambda n: ст(n, **d)


def и(*fs):
    def f(n):
        for g in fs:
            n = g(n)
        return n
    return f


def ev(s, *events):
    return dict(s, _события=tuple(s.get('_события', ())) + events)


