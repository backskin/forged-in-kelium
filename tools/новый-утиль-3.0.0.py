#   * целое бесплатное действие без оговорок в колоде НЕ ОСТАЛОСЬ ни на одной
#     карте — там, где действие уместно, у него есть предел («одна операция»,
#     «два жетона», «двумя добытчиками») либо оно идёт с надбавкой вместо
#     широты («Стройка со скидкой», «Рынок обеими половинами»);
#   * появилась плата за ПОЛОЖЕНИЕ НА ПОЛЕ («по 2 монеты за каждое войско») —
