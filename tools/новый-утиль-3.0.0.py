# ============================================================================
#  НИЗ КАРТ НЕ ИЗМЕНЁН НИ У ОДНОЙ. Способности живут в коде, они проверены, и
#  трогать их этой правкой незачем: переделан только ВЕРХ — утиль.
#
#  ЧТО БЫЛО НЕ ТАК, ЗАМЕРОМ. Из 45 карт утиль «выполни действие» стоял на 15, и
#  ровно эти карты боты не устанавливали НИКОГДА: за 300 партий 26 карт не
