def приложение_и():
    строки = ['# Приложение И. Раскладки поля', '',
              'По четыре готовых раскладки на каждый состав. Соберите поле из',
              'блоков по картинке, положите тайлы зарождения и нейтральные',
              'постройки на отмеченные гексы, и каждый игрок ставит ЦУ и пехоту',
              'на свой стартовый гекс. Обозначения — под каждой страницей.', '']
    пропущено = []
    for состав, клетки in РАСКЛАДКИ:
        есть = [(к, п) for к, п in клетки
                if os.path.exists('docs/раскладки/%s.png' % к)]
        пропущено += ['docs/раскладки/%s.png' % к for к, _ in клетки
                      if not os.path.exists('docs/раскладки/%s.png' % к)]
        if not есть:
            continue
        строки += ['## ' + состав, '', ':сетка:']
        for ключ, подпись in есть:
            строки.append('docs/раскладки/%s.png | %s' % (ключ, подпись))
        строки += [':конец:', '',
                   '![](docs/раскладки/легенда.png){24}', '']
    if пропущено:
        строки += ['> Картинок нет: %s. Нарисуйте их прогоном'
                   % ', '.join(пропущено),
                   '> `tools/раскладки-в-png.ps1`.', '']
    return строки


