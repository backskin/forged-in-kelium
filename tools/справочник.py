def приложение_е(в):
    """СУПЕР-ЗАДАНИЯ 9.0: на карте два раздела — «по ★» и «по ★★».

    Карты без названий (как на печати), поэтому строка таблицы — номер карты
    в правом нижнем углу и оба условия ровно как под плашками. У набора 8.0
    полей vp нет: там оба раздела по одной звезде.
    """
    из = набор('super_objectives', в)
    имена = категории_супер(в)
    строки = ['# Приложение Е. Супер-задания', '',
              'Карт %d. Одна приходит втайне на подготовке, ещё по одной — '
              'за третью' % len(из),
              'ступень каждого трека технологий. Карту не выполняют и не сжигают:',
              'она лежит в руке до конца партии. В подсчёте очков каждый раздел',
              'карты платит за каждую свою единицу столько очков, сколько звёзд',
              'на его плашке: верхний «Награда: по ★» — 1, нижний',
              '«Награда: по ★★» — 2. Карты без названий, номер стоит в правом',
              'нижнем углу.', '',
              строка('№', 'Награда: по ★', 'Награда: по ★★'),
              '|---|---|---|']
    for n, c in enumerate(из, 1):
        пара = list(c.get('categories') or [])
        пара += [''] * (2 - len(пара))
        строки.append(строка('%02d' % n,
                             имена.get(пара[0], пара[0]),
                             имена.get(пара[1], пара[1])))
    return строки

