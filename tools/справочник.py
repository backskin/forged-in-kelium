"""СПРАВОЧНИК — вторая книга: полные списки карт, все иконки и раскладки поля.

Почему отдельной книгой. В рулбуке приложения занимали сорок процентов объёма,
а читают их иначе: правила читают подряд один раз, справочник открывают на
нужной странице посреди партии. Разведя их, обе книги стали короче той, что
была одна.

Что внутри:

* ПРИЛОЖЕНИЯ А-Ж — все карты игры, собранные ИЗ КОЛОД действующего свода.
  Руками эти списки не пишутся: они разошлись бы с колодами на первой же
  пересборке.
* ПРИЛОЖЕНИЕ З — все иконки, какие игре нужны. Пока это список, а не картинки:
  каждая строка — место под иконку, её имя и что она значит.
* ПРИЛОЖЕНИЕ И — готовые раскладки поля картинками. Картинки рисует
  `tools/раскладки-в-png.ps1` тем же холстом, что и конструктор.

Запуск: python tools/справочник.py
"""
