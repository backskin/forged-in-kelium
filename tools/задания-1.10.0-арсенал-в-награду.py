# -*- coding: utf-8 -*-
"""КАТАЛОГ ЗАДАНИЙ 1.10.0 — карта арсенала в награду шестнадцати картам.

Решение дизайнера 21.08.2026. Замер показал, что путь получения карт арсенала в
игре ровно один: обмен на планшете науки (3.51 случая за партию против 0.26 у
наград заданий). Карт арсенала в награду давали ДВЕ карты из шестидесяти, и обе
только в усиленной награде. Теперь — шестнадцать.

КАКИЕ ИМЕННО ШЕСТНАДЦАТЬ. Не по вкусу, а по замеру: взяты карты, которые
выполняются РЕЖЕ ВСЕГО (покрытие на 300 партиях). Логика дизайнера: чем труднее
условие, тем дороже награда, а карта арсенала — дорогая награда, потому что это
ВЫБОР из двух открытых на витрине, а не слепая тяга.

ЧТО ИМЕННО МЕНЯЕТСЯ. Только награды и печатный текст, условия не тронуты.
У восьми самых трудных карта арсенала берётся С ВИТРИНЫ (выбор из открытых), у
восьми следующих — обычная карта арсенала. Правило формы соблюдено: видов добра
в награде не больше трёх, поэтому карта арсенала ЗАМЕЩАЕТ самую мелкую позицию
награды, а не добавляется к ней.

Запуск: python tools/задания-1.10.0-арсенал-в-награду.py
"""
import io
import re
import sys

ИСТОЧНИК = "data/cards/objectives.1.9.0.yaml"
ЦЕЛЬ = "data/cards/objectives.1.10.1.yaml"

# Замер покрытия (300 партий, свод 1.21.0): доля выполнений от приходов.
# Восемь самых трудных — витрина; восемь следующих — обычная карта.
ВИТРИНА = ["o17", "o23", "o29", "o41", "o46", "o39", "o50", "o54"]
ОБЫЧНАЯ = ["o26", "o31", "o21", "o45", "o34", "o22", "o16", "o42"]

# Что убрать из награды, освобождая место под карту арсенала: самое мелкое.
# Порядок — от самого дешёвого к самому дорогому по прейскуранту ObjectiveHints
# (монета 1, боеприпас 1, обломок 1.5, карта задания 2, контейнер 1.5).
ДЕШЁВОЕ = ["coin", "ammo", "container", "debris", "objective_card"]


def правитьНаграду(текст, ключ, добавка):
    """Вписать в награду карту арсенала, сняв самую дешёвую позицию."""
    m = re.search(r"(" + ключ + r": \{)([^}]*)(\})", текст)
    if not m:
        return текст, False
    внутри = m.group(2)
    поля = [ч.strip() for ч in внутри.split(",") if ч.strip()]
    имена = [ч.split(":")[0].strip() for ч in поля]
    # ФОРМА КАРТЫ: видов добра не больше трёх. Если после добавления станет
    # больше — снимаем самое дешёвое, а не добавляем четвёртое.
    if len(поля) >= 3:
        for дешёвое in ДЕШЁВОЕ:
            if дешёвое in имена:
                поля = [ч for ч in поля if not ч.startswith(дешёвое + ":")]
                break
        else:
            поля = поля[:-1]
    поля.append(добавка)
    return текст[:m.start(2)] + ", ".join(поля) + текст[m.end(2):], True


ШАПКА_ДОБАВКА = """#
# ============================================================================
#  1.10.0 (21.08.2026): КАРТА АРСЕНАЛА В НАГРАДУ ШЕСТНАДЦАТИ КАРТАМ
# ============================================================================
#  Условия карт НЕ ТРОНУТЫ — изменены только награды и печатный текст.
#
#  ЗАЧЕМ. Замер путей получения арсенала: планшет науки 3.51 случая за партию,
#  награда задания 0.26, рынок и контейнеры — ноль. Карт арсенала в награду
#  давали ДВЕ карты из шестидесяти, и обе только в усиленной награде. Игрок за
#  партию берёт 1.5 карты арсенала на четыре с лишним десятка карт в колоде.
#
#  КАКИЕ ШЕСТНАДЦАТЬ И ПОЧЕМУ ИМЕННО ОНИ. Взяты карты, которые по замеру
#  покрытия (300 партий) выполняются РЕЖЕ ВСЕГО. Чем труднее условие, тем дороже
#  награда; карта арсенала дорога тем, что это ВЫБОР, а не слепая тяга.
#
#  ДВЕ СТЕПЕНИ НАГРАДЫ:
#    * восемь самых трудных — `arsenal_from_display: 1`: взять карту С ВИТРИНЫ,
#      то есть выбрать одну из двух ОТКРЫТЫХ (правило дизайнера);
#    * восемь следующих — `arsenal: 1`: обычная карта с верха колоды.
#
#  ФОРМА КАРТЫ СОБЛЮДЕНА: видов добра в одной награде не больше трёх, поэтому
#  карта арсенала ЗАМЕЩАЕТ самую дешёвую позицию награды, а не добавляется к ней.
# ============================================================================
"""


def main():
    s = io.open(ИСТОЧНИК, encoding="utf-8").read()
    s = s.replace("  id: 1.9.0", "  id: 1.10.1", 1)
    i = s.index("meta:")
    s = s[:i] + ШАПКА_ДОБАВКА + s[i:]

    сделано = []
    for cid, добавка in [(c, "arsenal_from_display: 1") for c in ВИТРИНА] \
            + [(c, "arsenal: 1") for c in ОБЫЧНАЯ]:
        начало = s.find("\n  - id: " + cid + "\n")
        if начало < 0:
            sys.exit("не нашёл карту " + cid)
        конец = s.find("\n  - id: ", начало + 1)
        конец = len(s) if конец < 0 else конец
        кусок = s[начало:конец]
        # Сначала пробуем усиленную награду: трудную карту чаще берут «в усилении».
        новый, ок = правитьНаграду(кусок, "special_reward", добавка)
        куда = "усиленная"
        if not ок:
            новый, ок = правитьНаграду(кусок, "base_reward", добавка)
            куда = "базовая"
        if not ок:
            sys.exit("у карты " + cid + " не нашлось награды")
        s = s[:начало] + новый + s[конец:]
        сделано.append(cid + " (" + куда + ", " + добавка.split(":")[0] + ")")

    io.open(ЦЕЛЬ, "w", encoding="utf-8", newline="").write(s)
    print("карт с картой арсенала в награде:", len(сделано))
    for x in сделано:
        print("  ", x)
    print("файл:", ЦЕЛЬ)


if __name__ == "__main__":
    main()
