# -*- coding: utf-8 -*-
"""ЭТАЛОННЫЙ НАБОР БЛОКОВ 4.0.0 — по спецификации дизайнера 07.09.2026.

Один набор, а не тридцать шесть: дизайнер назвал раскладку, которую сохраняет
как самую комфортную для игры, и её надо получить ровно одну.

СПЕЦИФИКАЦИЯ ДОСЛОВНО:
  * НИ НА ОДНОМ гексе не может быть пусто: гекс без энергии обязан несести
    контейнер. Точка. (Прежние наборы 3.*.* удалены как раз за это: 480 пустых
    гексов.)
  * энергия: 4 гекса из 5 на малом блоке, 5 из 6 на большом;
  * контейнеры: 3 из 5 на малом, 4 из 6 на большом,
    и ОДИН из них обязательно в ячейке авиации (сектор неба, индекс 6);
  * расположение энергии и контейнеров у любой пары сторон одного размера
    совпадает не более чем на ОДНОМ гексе.

ЧТО ЗНАЧИТ «СОВПАДАЕТ». Стороны одного размера содержат одинаковое число
гексов, и сравниваются они гекс к гексу в том порядке, в каком гексы лежат в
описании стороны. Совпадением считается один и тот же сектор на одном и том же
по счёту гексе — И ОТСУТСТВИЕ метки тоже: «здесь ни у той, ни у этой нет
энергии» — это тоже одинаковое расположение. Энергия и контейнеры считаются
ОТДЕЛЬНО, и каждому виду разрешено не больше одного совпадения на пару.

ПОЧЕМУ АРИФМЕТИКА СХОДИТСЯ. Прошлый заход развалился на том, что при энергии на
ВСЕХ гексах шесть ячеек занимают шесть секторов, и все большие стороны выходили
с одним и тем же набором [0..5] — меняться было нечему. Здесь энергии на один
гекс меньше, чем гексов: у большого блока это 5 секторов из 6 (шесть разных
наборов), у малого 4 из 6 (пятнадцать), и разнообразию есть откуда взяться.

ГЕОМЕТРИЯ НЕ МЕНЯЕТСЯ. Двадцать сторон (пять малых блоков по 5 гексов и пять
больших по 6, каждый двусторонний) — это физический картон, взят из авторского
набора 1.4.0 и не трогается.

НАБОР ФИКСИРОВАН НАВСЕГДА: зерно задано, повторный запуск даёт тот же файл.

Запуск:  python tools/эталонный-набор-блоков.py [--перезаписать]
"""
import io
import itertools
import os
import random
import sys
from collections import Counter

import yaml

ГЕОМЕТРИЯ_ИЗ = 'data/blocks/blocks.1.4.0.yaml'
ЦЕЛЬ = 'data/blocks/blocks.4.0.0.yaml'
ВЕРСИЯ = '4.0.0'

НЕБО = 6                       # сектор авиации — там и стоит обязательный контейнер
БОКОВЫЕ = list(range(6))       # 0..5 — наземные секторы гекса
ПУСТО = -1                     # метки нет

# сколько гексов несут метку, по размеру блока
ЭНЕРГИИ = {'small': 4, 'big': 5}
КОНТЕЙНЕРОВ = {'small': 3, 'big': 4}
ГЕКСОВ = {'small': 5, 'big': 6}

ПРЕДЕЛ_СОВПАДЕНИЙ = 1          # на пару сторон одного размера, по каждому виду
ЗЕРНО = 20260907
ПОПЫТОК = 4000                 # перезапусков поиска с новым зерном
КАНДИДАТОВ = 600               # сколько раскладок стороны пробовать за один шаг


def геометрия():
    """Двадцать сторон: (id блока, размер, сторона, [(q, r), ...])."""
    d = yaml.safe_load(io.open(ГЕОМЕТРИЯ_ИЗ, encoding='utf-8').read())
    стороны = []
    for b in d['blocks']:
        for имя in ('A', 'B'):
            гексы = (b.get('faces') or {}).get(имя)
            if not isinstance(гексы, list):
                continue
            стороны.append((b['id'], b['kind'], имя,
                            [(h['q'], h['r']) for h in гексы]))
    return стороны


def раскладка(размер, rnd):
    """
    Одна законная разметка стороны: список пар (сектор контейнера, сектор энергии)
    по гексам стороны.

    Собирается КОНСТРУКТИВНО, а не отбором: сперва выбирается гекс без энергии —
    и он сразу попадает в число контейнерных, потому что пустых гексов не бывает.
    """
    n = ГЕКСОВ[размер]
    гексы = list(range(n))

    # 1. Единственный гекс без энергии. Он ОБЯЗАН нести контейнер.
    безЭнергии = rnd.choice(гексы)

    # 2. Контейнеры: обязательно на безЭнергии, остальные — куда угодно.
    прочие = [h for h in гексы if h != безЭнергии]
    сКонтейнером = [безЭнергии] + rnd.sample(прочие, КОНТЕЙНЕРОВ[размер] - 1)

    # 3. Один контейнер — в ячейке авиации; какой именно, решает случай.
    вНебе = rnd.choice(сКонтейнером)
    наземныеКонтейнеры = [h for h in сКонтейнером if h != вНебе]
    секторыКонтейнеров = rnd.sample(БОКОВЫЕ, len(наземныеКонтейнеры))

    контейнер = {h: ПУСТО for h in гексы}
    контейнер[вНебе] = НЕБО
    for h, s in zip(наземныеКонтейнеры, секторыКонтейнеров):
        контейнер[h] = s

    # 4. Энергия на всех, кроме безЭнергии; секторы внутри стороны не повторяются.
    сЭнергией = [h for h in гексы if h != безЭнергии]
    секторыЭнергии = rnd.sample(БОКОВЫЕ, len(сЭнергией))
    энергия = {h: ПУСТО for h in гексы}
    for h, s in zip(сЭнергией, секторыЭнергии):
        энергия[h] = s

    # 5. На гексе, где есть и то и другое, секторы РАЗНЫЕ: одним жетоном обе
    #    ячейки не накрыть, и в авторских наборах совпадений нет ни одного.
    for h in гексы:
        if контейнер[h] != ПУСТО and энергия[h] == контейнер[h]:
            return None
    return [(контейнер[h], энергия[h]) for h in гексы]


def совпадений(a, b, поле):
    """Сколько гексов совпало по одному виду метки (0 — контейнер, 1 — энергия)."""
    return sum(1 for x, y in zip(a, b) if x[поле] == y[поле])


def подходит(кандидат, принятые):
    for уже in принятые:
        if совпадений(кандидат, уже, 0) > ПРЕДЕЛ_СОВПАДЕНИЙ:
            return False
        if совпадений(кандидат, уже, 1) > ПРЕДЕЛ_СОВПАДЕНИЙ:
            return False
    return True


def собрать(стороны, зерно):
    """Разметить все двадцать сторон. None — этим зерном не сошлось."""
    rnd = random.Random(зерно)
    принятые = {'small': [], 'big': []}
    разметка = []
    # Сперва большие: у них меньше свободы (5 секторов из 6), и если начать с
    # малых, большие упрутся в уже занятые расположения.
    порядок = sorted(range(len(стороны)),
                     key=lambda i: 0 if стороны[i][1] == 'big' else 1)
    for i in порядок:
        размер = стороны[i][1]
        выбор = None
        for _ in range(КАНДИДАТОВ):
            c = раскладка(размер, rnd)
            if c is None:
                continue
            if подходит(c, принятые[размер]):
                выбор = c
                break
        if выбор is None:
            return None
        принятые[размер].append(выбор)
        разметка.append((i, выбор))
    return dict(разметка)


def проверить(стороны, разметка):
    """Полная поверка готового набора — все правила разом, без снисхождения."""
    жалобы = []
    по_размеру = {'small': [], 'big': []}
    for i, (bid, размер, имя, гексы) in enumerate(стороны):
        m = разметка[i]
        по_размеру[размер].append((bid + имя, m))
        пустых = sum(1 for c, e in m if c == ПУСТО and e == ПУСТО)
        if пустых:
            жалобы.append('%s%s: пустых гексов %d' % (bid, имя, пустых))
        if sum(1 for c, e in m if e != ПУСТО) != ЭНЕРГИИ[размер]:
            жалобы.append('%s%s: не то число ячеек энергии' % (bid, имя))
        if sum(1 for c, e in m if c != ПУСТО) != КОНТЕЙНЕРОВ[размер]:
            жалобы.append('%s%s: не то число контейнеров' % (bid, имя))
        if sum(1 for c, e in m if c == НЕБО) != 1:
            жалобы.append('%s%s: контейнер в ячейке авиации не один' % (bid, имя))
        боковые = [c for c, e in m if c != ПУСТО and c != НЕБО]
        if len(set(боковые)) != len(боковые):
            жалобы.append('%s%s: секторы контейнеров повторяются' % (bid, имя))
        эн = [e for c, e in m if e != ПУСТО]
        if len(set(эн)) != len(эн):
            жалобы.append('%s%s: секторы энергии повторяются' % (bid, имя))
        if any(e == НЕБО for c, e in m):
            жалобы.append('%s%s: энергия в ячейке авиации' % (bid, имя))
        for c, e in m:
            if c != ПУСТО and c == e:
                жалобы.append('%s%s: контейнер и энергия в одной ячейке' % (bid, имя))
    for размер, список in по_размеру.items():
        for (n1, a), (n2, b) in itertools.combinations(список, 2):
            к = совпадений(a, b, 0)
            э = совпадений(a, b, 1)
            if к > ПРЕДЕЛ_СОВПАДЕНИЙ:
                жалобы.append('%s и %s: контейнеры совпали на %d гексах' % (n1, n2, к))
            if э > ПРЕДЕЛ_СОВПАДЕНИЙ:
                жалобы.append('%s и %s: энергия совпала на %d гексах' % (n1, n2, э))
    return жалобы


def замер(стороны, разметка):
    """Что написать в шапку: насколько стороны разошлись на самом деле."""
    out = {}
    for размер in ('small', 'big'):
        свои = [разметка[i] for i, s in enumerate(стороны) if s[1] == размер]
        пары = list(itertools.combinations(свои, 2))
        для = {}
        for поле, имя in ((0, 'контейнеры'), (1, 'энергия')):
            числа = [совпадений(a, b, поле) for a, b in пары]
            для[имя] = 'наибольшее совпадение %d, среднее %.2f' % (
                max(числа), sum(числа) / len(числа))
        наборы = len({tuple(sorted(e for c, e in m if e != ПУСТО)) for m in свои})
        для['разных наборов секторов энергии'] = '%d из %d сторон' % (наборы, len(свои))
        out['малые' if размер == 'small' else 'большие'] = для
    return out


def записать(стороны, разметка, замеры):
    d = yaml.safe_load(io.open(ГЕОМЕТРИЯ_ИЗ, encoding='utf-8').read())
    поИмени = {}
    for i, (bid, размер, имя, гексы) in enumerate(стороны):
        поИмени[(bid, имя)] = (гексы, разметка[i])
    блоки = []
    for b in d['blocks']:
        новый = {'id': b['id'], 'kind': b['kind'], 'faces': {}}
        for имя in ('A', 'B'):
            если = поИмени.get((b['id'], имя))
            if если is None:
                continue
            гексы, m = если
            новый['faces'][имя] = [
                {'q': q, 'r': r, 'cell': c, 'energy': e}
                for (q, r), (c, e) in zip(гексы, m)]
        блоки.append(новый)

    шапка = (
        '# CONTENT: blocks  version %s\n'
        '# ЭТАЛОННЫЙ НАБОР — спецификация дизайнера 07.09.2026.\n'
        '# Собран tools/эталонный-набор-блоков.py, зерно %d: набор фиксирован\n'
        '# навсегда, повторный запуск даёт тот же файл.\n'
        '#\n'
        '# ПУСТЫХ ГЕКСОВ НЕТ НИ ОДНОГО: гекс без энергии всегда несёт контейнер.\n'
        '# Энергия 4 из 5 (малый) и 5 из 6 (большой); контейнеры 3 из 5 и 4 из 6,\n'
        '# один из них — в ячейке авиации (сектор %d).\n'
        '# Расположение энергии и контейнеров у любой пары сторон одного размера\n'
        '# совпадает не больше чем на одном гексе.\n'
        '#\n'
        '# Геометрия сторон взята из авторского набора 1.4.0 и не менялась —\n'
        '# это физический картон.\n' % (ВЕРСИЯ, ЗЕРНО, НЕБО))

    данные = {
        'meta': {
            'id': ВЕРСИЯ,
            'type': 'blocks',
            'seed': ЗЕРНО,
            'эталон': True,
            'описание': 'энергия 4/5 и 5/6, контейнеры 3/5 и 4/6, один в ячейке авиации',
            'пустых_гексов': 0,
            'предел_совпадений_на_пару': ПРЕДЕЛ_СОВПАДЕНИЙ,
            'разброс': замеры,
            'сгенерировано': 'tools/эталонный-набор-блоков.py',
        },
        'blocks': блоки,
    }
    текст = yaml.dump(данные, allow_unicode=True, sort_keys=False, width=100)
    io.open(ЦЕЛЬ, 'w', encoding='utf-8', newline='').write(шапка + текст)


def main():
    if os.path.exists(ЦЕЛЬ) and '--перезаписать' not in sys.argv:
        print('%s уже есть — набор эталонный, руками его не пересобирают.' % ЦЕЛЬ)
        print('Если правда нужно: --перезаписать')
        return
    стороны = геометрия()
    малых = sum(1 for s in стороны if s[1] == 'small')
    больших = len(стороны) - малых
    print('сторон: малых %d, больших %d' % (малых, больших))

    for попытка in range(ПОПЫТОК):
        разметка = собрать(стороны, ЗЕРНО + попытка)
        if разметка is None:
            continue
        жалобы = проверить(стороны, разметка)
        if жалобы:
            continue
        замеры = замер(стороны, разметка)
        записать(стороны, разметка, замеры)
        print('готово с попытки %d (зерно %d): %s'
              % (попытка + 1, ЗЕРНО + попытка, ЦЕЛЬ))
        for размер, что in замеры.items():
            print('  %s:' % размер)
            for k, v in что.items():
                print('     %-34s %s' % (k, v))
        # для глаза: сколько какого сектора вышло
        к = Counter()
        э = Counter()
        for i in range(len(стороны)):
            for c, e in разметка[i]:
                if c != ПУСТО:
                    к[c] += 1
                if e != ПУСТО:
                    э[e] += 1
        print('  контейнеры по секторам 0..6:', [к.get(i, 0) for i in range(7)])
        print('  энергия     по секторам 0..5:', [э.get(i, 0) for i in range(6)])
        return
    print('НЕ СОШЛОСЬ за %d попыток — предел совпадений %d недостижим этим'
          ' способом.' % (ПОПЫТОК, ПРЕДЕЛ_СОВПАДЕНИЙ))
    print('Это не отговорка, а замер: см. вывод ниже, до чего удалось дойти.')


if __name__ == '__main__':
    main()
