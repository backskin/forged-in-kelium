def начальные_задания():
    карты = [c for c in набор("objectives") if c.get("kind") == "starting"]
    doc = документ(
        "Начальные задания 1.10.0",
        f"Кристаллы Раздора · карт в наборе: {len(карты)} шт · "
        "тексты — как их печатает сама карта",
        ["Начальные задания раздаются отдельной колодой в первом раунде: каждый "
         "игрок получает свои и играет их наравне с обычными заданиями.",
         "Условия здесь заведомо проще обычных: это первый шаг, который "
         "показывает игроку, как задание вообще выполняется.",
         "Усиления у начальных заданий нет — только базовая награда."])
    doc.add_heading("Все карты набора", level=1)
    таблица(doc,
            ["№", "Название", "Природа", "Условие", "Награда", "Утиль"],
            [Cm(1.4), Cm(3.4), Cm(4.6), Cm(9.4), Cm(4.6), Cm(3.6)],
            [[c["id"], c.get("name", ""),
              ПРИРОДА.get(str(c.get("type")), str(c.get("type"))).split(" — ")[0],
              условие(c, "requirement"), награда(c.get("base_reward")),
              (c.get("top") or {}).get("label", "—")] for c in карты])
    doc.add_page_break()
    doc.add_heading("Карты по одной — с печатным текстом", level=1)
    for c in карты:
        карточка(doc, f"{c['id']} · {c.get('name', '')}",
                 [("ПРИРОДА", ПРИРОДА.get(str(c.get("type")), str(c.get("type")))),
                  ("УСЛОВИЕ", условие(c, "requirement")),
                  ("НАГРАДА", награда(c.get("base_reward"))),
                  ("УТИЛЬ (сжечь ради этого)",
                   (c.get("top") or {}).get("label"))],
                 c.get("описание"))
    цель = "docs/КАРТЫ НАЧАЛЬНЫХ ЗАДАНИЙ 1.10.0.docx"
    doc.save(цель)
    return цель, len(карты)


