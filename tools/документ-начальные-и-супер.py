def награда(узел):
    if not узел:
        return "—"
    части = []
    for ключ, значение in узел.items():
        имя = НАГРАДЫ.get(ключ, ключ)
        if ключ == "module":
            части.append("жетон модуля "
                         + ("атаки" if значение == "attack" else "сборки"))
        elif значение == 1:
            части.append(имя)
        else:
            части.append(f"{значение} {имя}")
    return ", ".join(части)


def условие(карта, ключ):
    узел = карта.get(ключ)
    if not isinstance(узел, dict):
        return "—"
    return str(узел.get("условие", узел))


def набор(семейство):
    путь = f"data/cards/{семейство}.{СНИМОК}.yaml"
    return yaml.safe_load(io.open(путь, encoding="utf-8"))[семейство]


def документ(заголовок, подзаголовок, вводные):
    doc = Document()
    s = doc.sections[0]
    s.orientation = WD_ORIENT.LANDSCAPE
    s.page_width, s.page_height = s.page_height, s.page_width
    s.left_margin = s.right_margin = Cm(1.2)
    s.top_margin = s.bottom_margin = Cm(1.2)
    doc.add_heading(заголовок, level=0)
    сер(doc.add_paragraph(), подзаголовок, 10)
    doc.add_heading("Что в этом наборе", level=1)
    for т in вводные:
        doc.add_paragraph(т)
    return doc


def сер(п, текст, кегль=9):
    r = п.add_run(текст)
    r.font.size = Pt(кегль)
    r.font.color.rgb = RGBColor(0x60, 0x60, 0x60)
    return r


def таблица(doc, заголовки, ширины, строки):
    t = doc.add_table(rows=1, cols=len(заголовки))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (h, w) in enumerate(zip(заголовки, ширины)):
        cell = t.rows[0].cells[i]
        cell.width = w
        r = cell.paragraphs[0].add_run(h)
        r.bold = True
        r.font.size = Pt(9)
    for строка in строки:
        row = t.add_row()
        for i, (v, w) in enumerate(zip(строка, ширины)):
            cell = row.cells[i]
            cell.width = w
            r = cell.paragraphs[0].add_run(str(v))
            r.font.size = Pt(8)
            if i == 0:
                r.bold = True
    return t


def карточка(doc, заголовок, поля, описание):
    п = doc.add_paragraph()
    r = п.add_run(заголовок)
    r.bold = True
    r.font.size = Pt(11)
    for подпись, значение in поля:
        if значение and значение != "—":
            сер(doc.add_paragraph(), f"{подпись}: {значение}")
    if описание:
        p = doc.add_paragraph(str(описание))
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.space_after = Pt(10)


