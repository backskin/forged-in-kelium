def очки(карта):
    """ПО за карту: 2 за установку по своду плюс напечатанные на карте."""
    за_установку = 2
    печатные = int(карта.get("vp_on_card") or 0) + int(карта.get("vp_flat") or 0)
    если = за_установку + печатные
    return (f"{если} (2 за установку + {печатные} на карте)" if печатные
            else f"{если} (за установку)")


