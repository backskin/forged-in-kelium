def арсенал():
    a = yaml.safe_load(open(os.path.join(КАРТЫ, 'arsenal.7.2.0.yaml'), encoding='utf-8'))['arsenal']
    обычный, начальный = [], []
    for c in a:
        rec = {'id': c['id'], 'имя': c['name'], 'верх': c['top'].get('label'),
               'низ': c['bottom'].get('label'), 'звезда': bool(c.get('vp_on_card'))}
        if c['kind'] == 'starting':
            rec['лицо'] = 'лица/arsenal_start/%s.png' % c['id']
            rec['изменено'] = 'нет'
            начальный.append(rec)
            continue
        rec['лицо'] = 'лица/arsenal/%s.png' % c['id']
        rec['изменено'] = 'нет'
        if c['id'] in АРСЕНАЛ_ПРОЧТЕНИЕ:
            rec['прочтение'] = АРСЕНАЛ_ПРОЧТЕНИЕ[c['id']]
        if c['id'] in АРСЕНАЛ_ЗАМЕНА:
            где, текст, почему = АРСЕНАЛ_ЗАМЕНА[c['id']]
            rec[где] = текст
            rec['изменено'] = '%s переписан: %s; лицо перерисовано' % (где, почему)
        обычный.append(rec)
    sa = yaml.safe_load(open(os.path.join(КАРТЫ, 'super_arsenal.4.0.0.yaml'), encoding='utf-8'))
    супер = []
    for k, v in sa.items():
        if isinstance(v, list):
            for c in v:
                rec = {'id': c.get('id'), 'имя': c.get('name'),
                       'текст': c.get('label') or c.get('описание') or c.get('text'),
                       'лицо': 'лица/arsenal_super/%s.png' % c.get('id'), 'изменено': 'нет'}
                if c.get('id') in СУПЕР_ПРОЧТЕНИЕ:
                    rec['прочтение'] = СУПЕР_ПРОЧТЕНИЕ[c.get('id')]
                супер.append(rec)
    return обычный, начальный, супер


