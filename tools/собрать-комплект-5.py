def награда_в_ветки(base):
    if 'action' in base:
        части = base['action'].split('|')
        return [a for a in части]
    return None


def задания():
    o = yaml.safe_load(open(os.path.join(КАРТЫ, 'objectives.1.19.0.yaml'), encoding='utf-8'))
    обычные, начальные = [], []
    for c in o['objectives']:
        rec = {'id': c['id'], 'имя': c['name'],
               'верх': (c.get('top') or {}).get('label'),
               'условие': (c.get('requirement') or {}).get('условие'),
               'дополнительно': (c.get('enhanced') or {}).get('условие')}
        if c['kind'] == 'starting':
            rec['награда'] = 'трофей и карта задания'
            rec['лицо'] = 'лица/objective_start/%s.png' % c['id']
            rec['изменено'] = 'нет'
            начальные.append(rec)
            continue
        base = c.get('base_reward') or {}
        ветки = награда_в_ветки(base)
        if ветки:
            if c['id'] in СТРОЙКА:
                ветки = [СТРОЙКА[c['id']] if v == 'build' else v for v in ветки]
            rec['награда'] = ' или '.join(ВЕТКИ[v] for v in ветки)
            rec['награда_коды'] = '|'.join(ветки)
        else:
            rec['награда'] = '%d спец-действия' % base.get('spec_actions', 0)
        rec['доп_награда'] = c.get('special_reward')
        rec['лицо'] = 'лица/objective/%s.png' % c['id']
        rec['изменено'] = 'нет (иконки наград читаются как ветки, см. правила §6)'
        if c['id'] in СТРОЙКА:
            rec['изменено'] = ('награда «… или Стройка» стала «… или %s»; перерисована вторая '
                               'иконка награды' % ВЕТКИ[СТРОЙКА[c['id']]])
        if c['id'] in ЗАМЕНА:
            нов, имя, усл, доп = ЗАМЕНА[c['id']]
            rec.update({'id': нов, 'имя': имя, 'условие': усл, 'дополнительно': доп,
                        'лицо': 'лица/objective/%s.png' % нов,
                        'заменяет': c['id'],
                        'изменено': 'новая карта вместо %s: %s' % (c['id'], ПОЧЕМУ_ЗАМЕНА[c['id']])})
        обычные.append(rec)
    return обычные, начальные


