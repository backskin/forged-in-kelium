def иконка_награды(код, сторона):
    """Иконка ветки награды в квадрате сторона×сторона (px крупного холста)."""
    if код in РАЗВИЛКА_ВЕТКИ:
        холст = Image.new('RGBA', (сторона, сторона), (0, 0, 0, 0))
        осн = вписать(икона(И[РАЗВИЛКА_ВЕТКИ[код]]), int(сторона * 0.80), int(сторона * 0.80))
        холст.alpha_composite(осн, (0, 0))
        дом = вписать(икона(И['buildings']), int(сторона * 0.56), int(сторона * 0.56))
        холст.alpha_composite(дом, (сторона - дом.width, сторона - дом.height))
        return холст
    if код == 'crane':          # только для сверки со старой печатью
        return вписать(икона(31), сторона, int(сторона * 1.1))
    return вписать(икона(И[НАГРАДА_ИКОНКА[код]]), сторона, сторона)


def иконки_текста(цвет_обв):
    return {
        'ammo': lambda р: вписать(икона(И['ammo']), int(р * 1.25 * K), int(р * 1.25 * K)),
        'troops': lambda р: вписать(икона(И['troops']), int(р * 1.6 * K), int(р * 1.25 * K)),
        'building': lambda р: перекрасить_тёмное(
            вписать(икона(И['buildings']), int(р * 1.35 * K), int(р * 1.35 * K)), цвет_обв),
    }


def плашки_и_текст(im, строки, y0, шаг, р, правый=627):
    """Строки условия: красный текст по правому краю на белых полупрозрачных плашках."""
    d = ImageDraw.Draw(im)
    f = шрифт(ШР_УСЛ, р)
    слой = Image.new('RGBA', im.size, (0, 0, 0, 0))
    ds = ImageDraw.Draw(слой)
    for i, t in enumerate(строки):
        w = d.textlength(t, font=f)
        y = (y0 + i * шаг) * K
        ds.rectangle((правый * K - w - 10 * K, y - 22 * K, (правый + 10) * K, y + 22 * K),
                     fill=(255, 255, 255, 185))
    im.alpha_composite(слой)
    d = ImageDraw.Draw(im)
    for i, t in enumerate(строки):
        d.text((правый * K, (y0 + i * шаг) * K), t, font=f, fill=КРАСНЫЙ_ТЕКСТ, anchor='rm')


def текст_сжатый(im, cx, cy, текст, f, заливка, обводка, обв, сжатие, макс_ширина=None):
    """Строка, сжатая по ширине, центром в (cx, cy) px карты."""
    d = ImageDraw.Draw(im)
    b = d.textbbox((0, 0), текст, font=f, stroke_width=обв * K)
    w, h = b[2] - b[0], b[3] - b[1]
    слой = Image.new('RGBA', (w + 4, h + 4), (0, 0, 0, 0))
    ImageDraw.Draw(слой).text((2 - b[0], 2 - b[1]), текст, font=f, fill=заливка,
                              stroke_width=обв * K, stroke_fill=обводка)
    нов_w = w * сжатие
    if макс_ширина and нов_w > макс_ширина * K:
        нов_w = макс_ширина * K
    слой = слой.resize((max(1, round(нов_w)), слой.height), Image.LANCZOS)
    # центр по высоте — по середине заглавных, а не всей рамки
    cap = d.textbbox((0, 0), 'Н', font=f)
    сер = 2 - b[1] + (cap[1] + cap[3]) / 2
    im.alpha_composite(слой, (int(cx * K - слой.width / 2), int(cy * K - сер)))


def верх_задания(im, карта):
    """Верхняя треть: значок слота, плашка реакции, заголовок, текст."""
    слот = карта['слот']
    ic = вписать(икона(И['spec']), 89 * K, 89 * K) if слот == 'spec' \
        else вписать(икона(И['inf']), 84 * K, 40 * K)
    положить(im, в_сланец(ic), 64.5, 71 if слот == 'spec' else 80)
    строки = карта['верх']
    if карта.get('реакция'):
        пл = крупно(os.path.join(ЗАДАНИЯ_ШАБЛ, 'плашка боевого эффекта на задание.png'))
        im.alpha_composite(пл, (117 * K, 8 * K))
