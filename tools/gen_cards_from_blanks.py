def шрифт(имя, р):
    for папка in СИСТЕМНЫЕ_ШРИФТЫ:
        путь = os.path.join(папка, имя)
        if os.path.exists(путь):
            return ImageFont.truetype(путь, int(round(р * K)))
    raise FileNotFoundError(имя)


def в_сланец(ic):
    """Значок слота верха: бордовый → сланцево-синий, как на печати дизайнера."""
    from PIL import ImageOps
    альфа = ic.getchannel('A')
    цв = ImageOps.colorize(ic.convert('L'), black=(25, 32, 60), mid=(143, 153, 179),
                           white=(255, 255, 255), blackpoint=0, whitepoint=255, midpoint=134)
    цв = цв.convert('RGBA')
    цв.putalpha(альфа)
    return цв


def крупно(путь):
    im = Image.open(путь).convert('RGBA')
    return im.resize((im.width * K, im.height * K), Image.LANCZOS)


def мелко(im):
    return im.resize((im.width // K, im.height // K), Image.LANCZOS)


def положить(im, ic, cx, cy):
    """Иконку центром в точку (px карты)."""
    im.alpha_composite(ic, (int(cx * K - ic.width / 2), int(cy * K - ic.height / 2)))


def перекрасить_тёмное(ic, цвет):
    """Чёрную обводку иконки — в цвет обводки текста (как иконка зданий в тексте верха)."""
    px = ic.copy()
    d = px.load()
    for y in range(px.height):
        for x in range(px.width):
            r, g, b, a = d[x, y]
            тёмн = 1 - max(r, g, b) / 255
            if тёмн > 0.3:
                t = min(1, (тёмн - 0.3) / 0.5)
                d[x, y] = (round(r + (цвет[0] - r) * t), round(g + (цвет[1] - g) * t),
                           round(b + (цвет[2] - b) * t), a)
    return px


