def части(текст):
    """«**жирное**» и «{иконка}» → список (вид, значение)."""
    out = []
    for кусок in re.split(r'(\*\*[^*]+\*\*|\{[a-z_]+\})', текст):
        if not кусок:
            continue
        if кусок.startswith('**'):
            for w in кусок.strip('*').split():
                out.append(('ж', w))
        elif кусок.startswith('{'):
            out.append(('и', кусок[1:-1]))
        else:
            for w in кусок.split():
                out.append(('т', w))
    return out


def строка_с_иконками(im, текст, f, fж, x, y, якорь, заливка, обводка, ширина_обв,
                      иконки, р_иконки):
    """Одна строка: слова и иконки. якорь 'm' — центр по x, 'r' — правый край."""
    d = ImageDraw.Draw(im)
    пробел = d.textlength(' ', font=f)
    куски = []
    for вид, з in части(текст):
        if вид == 'и':
            ic = иконки[з](р_иконки)
            куски.append((вид, ic, ic.width))
        else:
            ff = fж if вид == 'ж' else f
            куски.append((вид, (з, ff), d.textlength(з, font=ff)))
    ш = 0
    for i, (вид, з, w) in enumerate(куски):
        прилип = вид != 'и' and з[0][:1] in ',.;:!?»)'
        if i and not прилип:
            ш += пробел
        ш += w
    x0 = x * K - (ш / 2 if якорь == 'm' else ш)
    cx = x0
    for i, (вид, з, w) in enumerate(куски):
        прилип = вид != 'и' and з[0][:1] in ',.;:!?»)'
        if i and not прилип:
            cx += пробел
        if вид == 'и':
            im.alpha_composite(з, (int(cx), int(y * K - з.height / 2)))
        else:
            d.text((cx, y * K), з[0], font=з[1], fill=заливка, anchor='lm',
                   stroke_width=int(ширина_обв * K), stroke_fill=обводка)
        cx += w
    return ш / K


