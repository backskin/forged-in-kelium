def в_сланец(ic):
    """Значок слота верха: бордовый → сланцево-синий, как на печати дизайнера."""
    from PIL import ImageOps
    альфа = ic.getchannel('A')
    цв = ImageOps.colorize(ic.convert('L'), black=(25, 32, 60), mid=(143, 153, 179),
                           white=(255, 255, 255), blackpoint=0, whitepoint=255, midpoint=134)
    цв = цв.convert('RGBA')
    цв.putalpha(альфа)
    return цв


def крупно(путь):
    im = Image.open(путь).convert('RGBA')
    return im.resize((im.width * K, im.height * K), Image.LANCZOS)


