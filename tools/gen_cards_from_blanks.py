_икон = {}


def икона(n):
    if n not in _икон:
        # иконки дизайнера: «все иконки-N.png» по номеру или по имени файла
        имя = ('все иконки-%d.png' % n) if isinstance(n, int) else n + '.png'
        im = Image.open(os.path.join(ИКОНКИ, имя)).convert('RGBA')
        _икон[n] = im.crop(im.getbbox())
    return _икон[n]


def вписать(im, w, h):
    k = min(w / im.width, h / im.height)
    return im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)


