def разбить(d, текст, f, fж, ик, ширина):
    """Слова и иконки по строкам не шире ширины (px крупного холста)."""
    пробел = d.textlength(' ', font=f)
    строки, cur, ш = [], [], 0
    for вид, з in части(текст):
        w = ик if вид == 'и' else d.textlength(з, font=fж if вид == 'ж' else f)
        прилип = вид != 'и' and з[:1] in ',.;:!?»)'
        if cur and not прилип and ш + пробел + w > ширина:
            строки.append(cur)
            cur, ш = [], 0
        if cur and not прилип:
            ш += пробел
        cur.append((вид, з))
        ш += w
    if cur:
        строки.append(cur)
    return строки


def собрать(строка):
    out = []
    for вид, з in строка:
        if вид == 'и':
            out.append('{%s}' % з)
        elif вид == 'ж':
            out.append('**%s**' % з)
        else:
            out.append(з)
    return ' '.join(out)


