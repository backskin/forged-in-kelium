def перенести(текст, р, ширина=480, строк=4):
    """Условие по строкам: как можно меньше строк не шире ширины (px карты), а
    внутри — РОВНО: самая длинная строка как можно короче, как у дизайнера."""
    if isinstance(текст, list):
        return текст
    f = шрифт(ШР_УСЛ, р)
    слова = текст.split()
    w = lambda a, b: ширина_строки(' '.join(слова[a:b]), f, р)
    n = len(слова)
    # лучшее разбиение на k строк: минимум самой длинной строки (перебор ДП)
    for k in range(1, строк + 1):
        best = {0: (0, [])}
        for _ in range(k):
            nxt = {}
            for a, (m, cuts) in best.items():
                for b in range(a + 1, n + 1):
                    ww = w(a, b)
                    if ww > ширина:
                        break
                    cand = (max(m, ww), cuts + [b])
                    if b not in nxt or cand[0] < nxt[b][0]:
                        nxt[b] = cand
            best = nxt
        if n in best:
            cuts = [0] + best[n][1]
            return [' '.join(слова[cuts[i]:cuts[i + 1]]) for i in range(len(cuts) - 1)]
    return None


def плашки_и_текст(im, строки, y0, шаг, р, правый=627, строк=4):
    """Строки условия: красный текст по правому краю на белых полупрозрачных плашках.
    В строке могут стоять иконки: {kel} {ammo} {coin} {box} {heart}."""
    while True:
        разбито = перенести(строки, р, строк=строк)
        if разбито is not None or р <= 28:
            break
        р -= 1          # не влезло в 4 строки — чуть мельче, как делает вёрстка
    строки = разбито
    f = шрифт(ШР_УСЛ, р)
    слой = Image.new('RGBA', im.size, (0, 0, 0, 0))
    ds = ImageDraw.Draw(слой)
    for i, t in enumerate(строки):
        w = ширина_строки(t, f, р) * K
        # строка не вылезает на красную полосу слева: край плашки ≥ 132 px
        if правый - w / K - 10 < 132:
            raise ValueError('строка шире белого поля: «%s»' % t)
        y = (y0 + i * шаг) * K
        ds.rectangle((правый * K - w - 10 * K, y - 22 * K, (правый + 10) * K, y + 22 * K),
                     fill=(255, 255, 255, 38))
    im.alpha_composite(слой)
    for i, t in enumerate(строки):
        строка_с_иконками(im, t, f, f, правый, y0 + i * шаг, 'r', КРАСНЫЙ_ТЕКСТ, БЕЛЫЙ, 0,
                          иконки_условия(), р)


def текст_сжатый(im, cx, cy, текст, f, заливка, обводка, обв, сжатие, макс_ширина=None):
    """Строка, сжатая по ширине, центром в (cx, cy) px карты."""
    d = ImageDraw.Draw(im)
    b = d.textbbox((0, 0), текст, font=f, stroke_width=обв * K)
    w, h = b[2] - b[0], b[3] - b[1]
    слой = Image.new('RGBA', (w + 4, h + 4), (0, 0, 0, 0))
    ImageDraw.Draw(слой).text((2 - b[0], 2 - b[1]), текст, font=f, fill=заливка,
                              stroke_width=обв * K, stroke_fill=обводка)
    нов_w = w * сжатие
    if макс_ширина and нов_w > макс_ширина * K:
        нов_w = макс_ширина * K
    слой = слой.resize((max(1, round(нов_w)), слой.height), Image.LANCZOS)
    # центр по высоте — по середине заглавных, а не всей рамки
    cap = d.textbbox((0, 0), 'Н', font=f)
    сер = 2 - b[1] + (cap[1] + cap[3]) / 2
    im.alpha_composite(слой, (int(cx * K - слой.width / 2), int(cy * K - сер)))


