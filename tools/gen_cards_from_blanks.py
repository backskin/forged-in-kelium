def все_задания():
    import yaml
    данные = yaml.safe_load(open(КОМПЛЕКТ_YAML, encoding='utf-8'))['задания']
    out = []
    for i, к in enumerate(данные):
        печать = i + 2
        верх = ВЕРХИ[str(к['верх']).split(' ')[0]]
        доп = к.get('дополнительно')
        шаблон = ШАБЛОН_ПЕЧАТИ[печать]
        пара = шаблон if шаблон % 2 == 0 else шаблон - 1
        шаблон = пара if доп else пара + 1
        условие, дополнительно = str(к['условие']), (str(доп) if доп else None)
        for поле, было, стало in ИКОНКИ_В_ТЕКСТЕ.get(к['id'], []):
            if поле == 'условие':
                assert было in условие, (к['id'], было)
                условие = условие.replace(было, стало)
            else:
                assert было in дополнительно, (к['id'], было)
                дополнительно = дополнительно.replace(было, стало)
        коды = к.get('награда_коды')
        награда = коды.split('|') if коды else ['spec3']
        ряд = []
        for ключ, v in (к.get('доп_награда') or {}).items():
            if ключ == 'module':
                ряд.append(('mod_attack' if v == 'attack' else 'mod_assembly', 1))
            else:
                ряд.append((ДОП_ИКОНКА[ключ], int(v)))
        # боеприпасы идут раньше спец-действия, монеты — как на печати, слева
        порядок = ['coin', 'ammo', 'trophy', 'arsenal', 'mod_attack', 'mod_assembly', 'gild',
                   'spec']
        ряд.sort(key=lambda x: порядок.index(x[0]))
        out.append(dict(верх, id=к['id'], печать=печать, номер=i + 1, шаблон=шаблон,
                        имя=к['имя'], семейство=к['имя'], условие=условие,
                        дополнительно=дополнительно, награда=награда, доп_награда=ряд))
    return out


