def место_для_контейнера(im, x0=332.5, x1=745.5, y0=176, r=25, низ=530):
    """Ячейка «Место для контейнера», как на печати: тёплая полупрозрачная
    заливка, рамка из круглых точек (шаг 9,5 px), скруглённые верхние углы,
    снизу рамка уходит за край карты; внутри ящик — иконка № 79."""
    import math
    слой = Image.new('RGBA', im.size, (0, 0, 0, 0))
    ds = ImageDraw.Draw(слой)
    ds.rounded_rectangle((x0 * K, y0 * K, x1 * K, низ * K), radius=r * K,
                         fill=(232, 215, 195, 153))
    точки = []
    шаг = 9.5

    def линия(ax, ay, bx, by):
        n = max(1, int(math.hypot(bx - ax, by - ay) / шаг))
        for i in range(n + 1):
            точки.append((ax + (bx - ax) * i / n, ay + (by - ay) * i / n))

    def дуга(cx, cy, от, до):
        n = max(1, int(r * abs(до - от) / шаг))
        for i in range(n + 1):
            t = math.radians(от + (до - от) * i / n)
            точки.append((cx + r * math.cos(t), cy + r * math.sin(t)))
    дуга(x0 + r, y0 + r, 180, 270)
    линия(x0 + r, y0, x1 - r, y0)
    дуга(x1 - r, y0 + r, 270, 360)
    линия(x0, y0 + r, x0, низ)
    линия(x1, y0 + r, x1, низ)
    for x, y in точки:
        ds.ellipse(((x - 2) * K, (y - 2) * K, (x + 2) * K, (y + 2) * K), fill=(100, 100, 100, 255))
    im.alpha_composite(слой)
    положить(im, вписать(икона(85), 132 * K, 132 * K), 540, 296)


