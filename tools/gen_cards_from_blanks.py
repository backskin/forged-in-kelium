def пунктир(d, box, шаг, цвет, ширина):
    x0, y0, x1, y1 = box
    for x in range(int(x0), int(x1), шаг * 2):
        d.line((x, y0, min(x + шаг, x1), y0), fill=цвет, width=ширина)
    for y in range(int(y0), int(y1), шаг * 2):
        d.line((x0, y, x0, min(y + шаг, y1)), fill=цвет, width=ширина)
        d.line((x1, y, x1, min(y + шаг, y1)), fill=цвет, width=ширина)


