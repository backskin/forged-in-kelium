# -*- coding: utf-8 -*-
"""КОЛОДА ЗАДАНИЙ 1.16.0 — сорок карт по таблице дизайнера плюс двенадцать начальных.

Колода собирается ИЗ КЛАССОВ: у карты задания источник правды — её класс, а файл
набора это его выгрузка. Здесь из общей пачки отбираются ровно те сорок карт,
что перечислены в таблице дизайнера 04-06.09.2026 (семь семейств), и к ним
добавляются двенадцать начальных.

ЧЕГО В КОЛОДЕ НЕТ. Тринадцать карт «непрерывного соседства» (o50-o62) в таблицу
не входят. Классы их остаются на месте, и вернуть их — правка одного списка
здесь: наборы неизменяемы, а состав колоды это данные, а не код.

Запуск:
  1) java kelium.ВыгрузкаЗаданий <куда.json>     — снимок классов
  2) python tools/собрать-задания-1-16-0.py <куда.json>
Пишет: data/cards/objectives.1.16.0.yaml
"""
import io
import json
import os
import sys

import yaml

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЦЕЛЬ = os.path.join(КОРЕНЬ, 'data', 'cards', 'objectives.1.16.0.yaml')

# Порядок — по семействам таблицы: так колоду читают глазами.
СЕМЕЙСТВА = [
    ('Выработка', ['o04', 'o05', 'o40', 'o08', 'o01']),
    ('Засада', ['o29', 'o03', 'o07', 'o27', 'o63']),
    ('Обеспечение', ['o33', 'o36', 'o34', 'o64']),
    ('Развёртывание', ['o17', 'o11', 'o18', 'o65', 'o15', 'o12', 'o20']),
    ('Расплата', ['o66', 'o67', 'o10', 'o06']),
    ('Устранение', ['o68', 'o69', 'o42', 'o25', 'o70', 'o71', 'o72', 'o21', 'o43', 'o73']),
    ('Экспансия', ['o74', 'o75', 'o02', 'o76', 'o77']),
]
НАЧАЛЬНЫЕ = ['n%d' % i for i in range(1, 13)]


def main():
    if len(sys.argv) < 2:
        raise SystemExit('нужен снимок классов: python %s <задания-из-кода.json>' % sys.argv[0])
    снимок = json.load(io.open(sys.argv[1], encoding='utf-8'))
    поId = {c['id']: c for c in снимок['classes']}

    карты = []
    беды = []
    for семья, ids in СЕМЕЙСТВА:
        for cid in ids:
            c = поId.get(cid)
            if c is None:
                беды.append('нет класса для %s (%s)' % (cid, семья))
                continue
            карты.append(c)
    for cid in НАЧАЛЬНЫЕ:
        c = поId.get(cid)
        if c is None:
            беды.append('нет класса начального задания %s' % cid)
            continue
        карты.append(c)
    if беды:
        raise SystemExit('колода не собрана:\n  ' + '\n  '.join(беды))

    обычных = sum(1 for c in карты if c.get('kind') == 'regular')
    if обычных != 40:
        raise SystemExit('обычных карт %d, а надо 40' % обычных)

    doc = {
        'meta': {
            'id': '1.16.0',
            'type': 'objectives',
            'выгружено': ('задания 1.16.0: колода по таблице дизайнера — семь семейств, '
                          'верхи «в моменте» (реакции) и подогнанные награды; '
                          'пятнадцать карт написаны заново, карты «непрерывного '
                          'соседства» в эту колоду не входят'),
        },
        'objectives': карты,
    }
    with io.open(ЦЕЛЬ, 'w', encoding='utf-8') as f:
        f.write('# CONTENT: objectives  version 1.16.0\n')
        f.write('#\n')
        f.write('# ВЫГРУЗКА ИЗ КЛАССОВ (tools/собрать-задания-1-16-0.py). Источник правды —\n')
        f.write('# классы kelium.cards.objectives; этот файл читают люди и таблицы.\n')
        f.write('#\n')
        for семья, ids in СЕМЕЙСТВА:
            f.write('# %-16s %s\n' % (семья + ':', ' '.join(ids)))
        f.write('\n')
        yaml.safe_dump(doc, f, allow_unicode=True, sort_keys=False, width=100)
    print('записано: %s' % ЦЕЛЬ)
    print('обычных %d, начальных %d' % (обычных, len(карты) - обычных))


main()
