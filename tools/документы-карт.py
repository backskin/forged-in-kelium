def печатный(узел):
    return str((узел or {}).get("label", "")) if isinstance(узел, dict) else ""


def награда(узел):
    if not узел:
        return "—"
    return ", ".join(количество(k, v) for k, v in узел.items())


def условие(карта, ключ):
    узел = карта.get(ключ)
    if not isinstance(узел, dict):
        return ""
    return str(узел.get("условие", узел))


