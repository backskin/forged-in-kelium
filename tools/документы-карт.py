def заливка(ячейка, цвет):
    tc = ячейка._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear")
    sh.set(qn("w:fill"), цвет)
    tc.append(sh)


def строка_текста(ячейка, части, первый=False):
    """Заполнить ячейку абзацами вида (подпись, текст, серый?)."""
    ячейка.text = ""
    п = ячейка.paragraphs[0]
    for i, (подпись, текст, серо) in enumerate(части):
        if not текст:
            continue
        if i and п.runs:
            п = ячейка.add_paragraph()
        п.paragraph_format.space_after = Pt(2)
        if подпись:
            r = п.add_run(подпись + ": ")
            r.bold = True
            r.font.size = Pt(8)
            r.font.name = ШРИФТ
        r = п.add_run(текст)
        r.font.size = Pt(8 if not первый else 9)
        r.font.name = ШРИФТ
        if серо:
            r.font.color.rgb = СЕРЫЙ
            r.italic = True


def документ(заголовок, подзаголовок, вводные):
    doc = Document()
    s = doc.sections[0]
    s.orientation = WD_ORIENT.LANDSCAPE
    s.page_width, s.page_height = s.page_height, s.page_width
    s.left_margin = s.right_margin = Cm(1.0)
    s.top_margin = s.bottom_margin = Cm(1.0)
    ст = doc.styles["Normal"]
    ст.font.name = ШРИФТ
    ст.font.size = Pt(9)

    h = doc.add_heading(заголовок, level=0)
    for r in h.runs:
        r.font.name = ШРИФТ
    п = doc.add_paragraph()
    r = п.add_run(подзаголовок)
    r.font.size = Pt(10)
    r.font.color.rgb = СЕРЫЙ
    for т in вводные:
        p = doc.add_paragraph(т)
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        for r in p.runs:
            r.font.size = Pt(9)
    return doc


def таблица_карт(doc, заголовки, ширины, строки):
    """Таблица с последней колонкой под замечания (жёлтая, пустая)."""
    t = doc.add_table(rows=1, cols=len(заголовки))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (h, w) in enumerate(zip(заголовки, ширины)):
        c = t.rows[0].cells[i]
        c.width = w
        заливка(c, ТЁМНЫЙ)
        p = c.paragraphs[0]
        r = p.add_run(h)
        r.bold = True
        r.font.size = Pt(9)
        r.font.name = ШРИФТ
        r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
    for части in строки:
        row = t.add_row()
        for i, (содержимое, w) in enumerate(zip(части, ширины)):
            c = row.cells[i]
            c.width = w
            if isinstance(содержимое, list):
                строка_текста(c, содержимое)
            else:
                строка_текста(c, [("", str(содержимое), False)], первый=(i == 0))
            if заголовки[i] == "Комментарии":
                заливка(c, ЖЁЛТЫЙ)
    return t


