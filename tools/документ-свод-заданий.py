# -*- coding: utf-8 -*-
"""СВОД ВСЕХ КАРТ ЗАДАНИЙ: сначала разрезы, потом полная таблица.

Почему так. Заданий шестьдесят и все разные — «по типам» их не свернёшь, как
контейнеры. Но вопросы к каталогу задаются именно разрезами: сколько карт какой
природы, что они требуют, чем платят, у скольких есть усиление и сколько дают
карту арсенала. Поэтому документ идёт двумя слоями: сводка отвечает на вопросы
о наборе, полная таблица — о конкретной карте.

Источник — снимок каталога, выгруженный ИЗ КОДА (kelium.ВыгрузкаКаталога):
у карт, живущих в коде, файл набора — зеркало.

Запуск:
    java kelium.ВыгрузкаКаталога objectives доксвод "снимок"
    python tools/документ-свод-заданий.py доксвод 1.10.0
"""
import collections
import io
import re
import sys

import yaml
from docx import Document
from docx.enum.section import WD_ORIENT
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt, RGBColor

СНИМОК = sys.argv[1] if len(sys.argv) > 1 else "доксвод"
ВЕРСИЯ = sys.argv[2] if len(sys.argv) > 2 else "1.10.0"
ЦЕЛЬ = f"docs/СВОД КАРТ ЗАДАНИЙ {ВЕРСИЯ}.docx"

# СЛОВОФОРМЫ: (1 штука, 2-4 штуки, 5 штук). Без этого в документе получается
# «трофеи» вместо «трофей» и «2 карта задания» — читать такое стыдно, а
# документ идёт дизайнеру и в вёрстку карт.
НАГРАДЫ = {
    "coin": ("монета", "монеты", "монет"),
    "ammo": ("боеприпас", "боеприпаса", "боеприпасов"),
    "trophy": ("трофей", "трофея", "трофеев"),
    "kelium": ("келемий", "келемия", "келемия"),
    "objective_card": ("карта задания", "карты задания", "карт задания"),
    "arsenal": ("карта арсенала", "карты арсенала", "карт арсенала"),
    "arsenal_from_display": ("карта арсенала НА ВЫБОР из открытых",
                             "карты арсенала НА ВЫБОР из открытых",
                             "карт арсенала НА ВЫБОР из открытых"),
    "module": ("жетон модуля", "жетона модуля", "жетонов модуля"),
    "storage_token": ("жетон хранилища", "жетона хранилища", "жетонов хранилища"),
    "vp": ("победное очко", "победных очка", "победных очков"),
}

# ЧТО ТРЕБУЕТ СДАТЬ КАРТА-ЖЕРТВА — те же словоформы для предмета жертвы.
ЖЕРТВЫ = {
    "trophies": ("уничтоженный жетон", "трофейных жетона", "уничтоженных жетонов"),
    "container": ("неоткрытый контейнер", "неоткрытых контейнера",
                  "неоткрытых контейнеров"),
    "units_off_base": ("войско вне своих гексов", "войска вне своих гексов",
                       "войск вне своих гексов"),
}


def словоформа(ключ, n, словарь=None):
    формы = (словарь or НАГРАДЫ).get(ключ)
    if формы is None:
        return str(ключ)
    if not isinstance(формы, tuple):
        return формы
    n = abs(int(n))
    хвост = n % 10
    сотня = n % 100
    if хвост == 1 and сотня != 11:
        return формы[0]
    if хвост in (2, 3, 4) and сотня not in (12, 13, 14):
        return формы[1]
    return формы[2]

ПРИРОДА = {
    "state": "СОСТОЯНИЕ — проверяется в любой момент",
    "incident": "ПРОИСШЕСТВИЕ — должно случиться В ЭТОТ ХОД",
    "sacrifice": "ЖЕРТВА — карта требует что-то сдать",
}

# О ЧЁМ КАРТА — по словам её условия. Грубая разметка, но именно она отвечает на
# вопрос «какие действия каталог заставляет играть»: если тема встречается у двух
# карт из шестидесяти, значит соответствующее действие каталог не требует.
ТЕМЫ = [
    ("война: бой и уничтожение", r"уничтож|атак|бой|ответн|снес|разруш"),
    ("чужие жетоны рядом", r"противник|чуж|соперник"),
    ("стройка и здания", r"здани|постро|казарм|завод|авиабаз|ЦУ|добытчик|энергостанц"),
    ("войска на поле", r"пехот|техник|авиаци|вышк|войск"),
    ("энергия", r"энерги|запитан|кубик"),
    ("наука и треки", r"трек|наук|шаг"),
    ("рынок и обмены", r"рынк|рынок|обмен|сделк"),
    ("добыча и келемий", r"келеми|добыч|жил|зарожден|грядк"),
    ("ресурсы в запасе", r"монет|боеприпас|трофе|хранилищ"),
    ("карты: задания, арсенал, контейнеры", r"карт|контейнер|арсенал"),
    ("модули", r"модул"),
]


def награда(узел):
    if not узел:
        return "—"
    части = []
    for ключ, значение in узел.items():
        if ключ == "module":
            части.append("жетон модуля "
                         + ("атаки" if значение == "attack" else "сборки"))
            continue
        n = значение if isinstance(значение, int) else 1
        части.append(f"{n} {словоформа(ключ, n)}")
    return ", ".join(части)


def условие(карта, ключ):
    узел = карта.get(ключ)
    if not isinstance(узел, dict):
        return "—"
    if "условие" in узел:
        return str(узел["условие"])
    # КАРТЫ-ЖЕРТВЫ. У них усиление записано предикатом «сдай больше», а не
    # текстом: печатный текст карты собирается из самой жертвы. Печатаем
    # по-человечески — сырой предикат в документе для дизайнера бесполезен.
    if узел.get("predicate") == "sacrifice_enhanced":
        п = узел.get("params") or {}
        n = п.get("amount", 1)
        return f"Сдай {n} {словоформа(п.get('resource'), n, ЖЕРТВЫ)}"
    return str(узел)


def сер(п, текст, кегль=9):
    r = п.add_run(текст)
    r.font.size = Pt(кегль)
    r.font.color.rgb = RGBColor(0x60, 0x60, 0x60)
    return r


def таблица(doc, заголовки, ширины, строки, кегль=9):
    t = doc.add_table(rows=1, cols=len(заголовки))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (h, w) in enumerate(zip(заголовки, ширины)):
        cell = t.rows[0].cells[i]
        cell.width = w
        r = cell.paragraphs[0].add_run(h)
        r.bold = True
        r.font.size = Pt(9)
    for строка in строки:
        row = t.add_row()
        for i, (v, w) in enumerate(zip(строка, ширины)):
            cell = row.cells[i]
            cell.width = w
            r = cell.paragraphs[0].add_run(str(v))
            r.font.size = Pt(кегль)
            if i == 0:
                r.bold = True
    return t


def main():
    карты = yaml.safe_load(
        io.open(f"data/cards/objectives.{СНИМОК}.yaml", encoding="utf-8"))["objectives"]
    обычные = [c for c in карты if c.get("kind") != "starting"]
    начальные = [c for c in карты if c.get("kind") == "starting"]
    всего = len(карты)

    doc = Document()
    s = doc.sections[0]
    s.orientation = WD_ORIENT.LANDSCAPE
    s.page_width, s.page_height = s.page_height, s.page_width
    s.left_margin = s.right_margin = Cm(1.2)
    s.top_margin = s.bottom_margin = Cm(1.2)

    doc.add_heading(f"Свод карт заданий {ВЕРСИЯ}", level=0)
    сер(doc.add_paragraph(),
        f"Кристаллы Раздора · карт в наборе: {всего} шт "
        f"(обычных {len(обычные)}, начальных {len(начальные)}) · "
        "условия и тексты — как их печатает сама карта", 10)

    # ---------------- разрез 1: природа условия ----------------
    doc.add_heading("Природа условия", level=1)
    сер(doc.add_paragraph(),
        "СОСТОЯНИЕ можно держать и предъявить когда угодно, ПРОИСШЕСТВИЕ обязано "
        "случиться в этот ход, ЖЕРТВА требует что-то отдать.", 9)
    прир = collections.Counter(c.get("type") for c in карты)
    таблица(doc, ["природа", "карт, шт", "доля набора"],
            [Cm(9.0), Cm(3.0), Cm(3.0)],
            [[ПРИРОДА.get(t, t).split(" — ")[0], n, f"{100 * n / всего:.0f} %"]
             for t, n in прир.most_common()])

    # ---------------- разрез 2: чем платит награда ----------------
    doc.add_heading("Чем платит награда", level=1)
    сер(doc.add_paragraph(),
        "Карта может давать несколько вещей — тогда она попадает в несколько "
        "строк. «Базовая» — за выполнение условия, «усиленная» — за усиление.", 9)
    база = collections.Counter()
    усил = collections.Counter()
    for c in карты:
        for k in (c.get("base_reward") or {}):
            база[k] += 1
        for k in (c.get("special_reward") or {}):
            усил[k] += 1
    ключи = sorted(set(база) | set(усил), key=lambda k: -(база[k] + усил[k]))
    таблица(doc, ["что даёт", "в базовой награде, карт", "в усиленной награде, карт",
                  "всего карт"],
            [Cm(7.4), Cm(4.0), Cm(4.2), Cm(3.0)],
            [[НАГРАДЫ.get(k, k), база[k], усил[k], база[k] + усил[k]] for k in ключи])

    п = doc.add_paragraph()
    сарсеналом = sum(1 for c in карты
                     if "arsenal" in str(c.get("base_reward")) + str(c.get("special_reward")))
    свитрины = sum(1 for c in карты
                   if "arsenal_from_display" in str(c.get("base_reward"))
                   + str(c.get("special_reward")))
    сер(п, f"Карту арсенала в награде дают {сарсеналом} карт из {всего}, "
           f"из них {свитрины} — картой НА ВЫБОР из открытых. Это правило от "
           "21.08.2026: прежде путь получения карт арсенала был ровно один "
           "(обмен на планшете науки), и карт игроку приходило полторы за партию.", 10)

    # ---------------- разрез 3: усиление ----------------
    doc.add_heading("Усиление", level=1)
    сусилением = sum(1 for c in карты if c.get("enhanced"))
    сер(doc.add_paragraph(),
        f"Усиление есть у {сусилением} карт из {всего}. У начальных заданий "
        "усиления нет вовсе — это первый шаг, а не выбор.", 9)

    # ---------------- разрез 4: о чём каталог ----------------
    doc.add_heading("О чём каталог заставляет играть", level=1)
    сер(doc.add_paragraph(),
        "Разметка по словам условия и усиления. Карта попадает в несколько тем, "
        "если требует нескольких вещей. Смысл разреза: тема, которой в каталоге "
        "почти нет, — это действие, которое каталог не требует играть.", 9)
    темы = collections.Counter()
    for c in карты:
        текст = условие(c, "requirement") + " " + условие(c, "enhanced")
        for имя, шаблон in ТЕМЫ:
            if re.search(шаблон, текст, re.IGNORECASE):
                темы[имя] += 1
    таблица(doc, ["тема", "карт, шт", "доля набора"],
            [Cm(10.0), Cm(3.0), Cm(3.0)],
            [[имя, n, f"{100 * n / всего:.0f} %"]
             for имя, n in темы.most_common()])

    # ---------------- полная таблица ----------------
    doc.add_page_break()
    doc.add_heading("Все карты набора", level=1)
    строки = []
    for c in карты:
        строки.append([
            c["id"],
            c.get("name", ""),
            "начальное" if c.get("kind") == "starting" else
            ПРИРОДА.get(str(c.get("type")), str(c.get("type"))).split(" — ")[0],
            условие(c, "requirement"),
            условие(c, "enhanced"),
            награда(c.get("base_reward")),
            награда(c.get("special_reward")),
            (c.get("top") or {}).get("label", "—"),
        ])
    таблица(doc,
            ["№", "название", "природа", "условие", "усиление", "награда",
             "усиленная награда", "утиль"],
            [Cm(1.2), Cm(2.8), Cm(2.2), Cm(7.4), Cm(5.4), Cm(3.4), Cm(3.4), Cm(2.6)],
            строки, кегль=7.5)

    doc.add_page_break()
    doc.add_heading("Печатные тексты карт", level=1)
    for заголовок, группа in [("Обычные карты", обычные), ("Начальные задания", начальные)]:
        if not группа:
            continue
        doc.add_heading(заголовок, level=2)
        for c in группа:
            п = doc.add_paragraph()
            r = п.add_run(f"{c['id']} · {c.get('name', '')}")
            r.bold = True
            r.font.size = Pt(11)
            if c.get("описание"):
                p = doc.add_paragraph(str(c["описание"]))
                p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
                p.paragraph_format.space_after = Pt(8)

    doc.save(ЦЕЛЬ)
    print("готово:", ЦЕЛЬ, "| карт:", всего)


if __name__ == "__main__":
    main()
