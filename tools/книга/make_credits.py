def убрать_старую(t):
    """Выкинуть уже стоящую полосу «Создатели игры» вместе с её разворотом.

    Ищем её по СОБСТВЕННОМУ КЛАССУ полосы, а не по комментарию-маркеру:
    reflow.py пересобирает хвост книги и комментарии не сохраняет, поэтому
    по маркеру страница не находилась и вставлялась второй раз.
    """
    k = t.find(ПОЛОСА)
    if k < 0:
        return t
    нач = t.rfind('<p class="подпись-разворота">', 0, k)
    if нач < 0:
        нач = t.rfind('<div class="разворот', 0, k)
    кон = t.index('class="колонцифра"', k)
    кон = t.index("</div>", кон) + len("</div>")    # конец колонцифры
    кон = t.index("</div>", кон) + len("</div>")    # конец полосы
    кон = t.index("</div>", кон) + len("</div>")    # конец разворота
    return t[:нач] + t[кон:].lstrip("\n")


