# -*- coding: utf-8 -*-
"""Разворот «Подготовка к игре»: снимок стола вместо схемы из пунктира.

Картинку стола собирает движок (kelium.gui.replay2.СнимокСтола) и кладёт рядом
файл якорей — точку на картинке для каждого шага подготовки. Здесь картинка
режется по сгибу на две полосы, раскладывается по страницам разворота и
подписывается кружками 1…18. Линия выноски идёт длинным прямым участком и
ломается один раз у самой точки — как все выноски книги.
"""
import base64
import glob
import io
import os

from PIL import Image

D = os.path.dirname(os.path.abspath(__file__))
ns = {"__file__": os.path.join(D, "figs.py")}
exec(open(os.path.join(D, "figs.py"), encoding="utf-8-sig").read().split("# планшет войск")[0], ns)
маршрут = ns["маршрут"]

PNG = os.path.join(D, "стол.png")
ТОЧКИ = os.path.join(D, "стол-якоря.txt")
КНИГА = glob.glob(r"C:\shared\forged-in-kelium\rules\Книга правил*\вёрстка\Книга правил.html")[0]

# ---- геометрия разворота, миллиметры страницы 220×220 ----
#
# Картинка без фона и обрезана по компонентам, поэтому её пропорция каждый раз
# своя. Окно под неё подбирается здесь: по высоте — вся полоса под заголовком,
# по ширине — сколько останется до текстовых столбцов. Картинка ЦЕНТРИРУЕТСЯ
# ПО СГИБУ, то есть ровно половина её уходит на каждую страницу.
ВЕРХ_ПОЛОСЫ = 30.0
НИЗ_ПОЛОСЫ = 206.0
ЛЕВЫЙ_ПРЕДЕЛ = 95.0     # текстовый столбец левой страницы кончается на 92
ПРАВЫЙ_ПРЕДЕЛ = 126.0   # текстовый столбец правой страницы начинается на 129

ЗНАЧОК = 7.0          # диаметр кружка выноски, мм
ЛИНИЯ = 0.45
ТОЧКА = 1.9

# ---- где стоит кружок каждого шага ----
#
# Координаты РАЗВОРОТА: X идёт от левого края левой страницы через сгиб (220)
# до правого края правой (440), Y — обычная координата страницы. Кружки стоят
# двумя столбиками в полях между текстом и картинкой: слева на 103, справа на
# 338. Так ни один не садится на компонент и линия идёт длинным прямым участком.
ЗНАЧКИ = {
    "7":  (103, 56),
    "4":  (103, 80),
    "2":  (103, 104),
    "5":  (103, 128),
    "9":  (103, 150),
    "12": (103, 168),
    "11": (103, 184),
    "15": (103, 200),
    "17": (338, 52),
    "18": (338, 70),
    "1":  (338, 90),
    "6":  (338, 110),
    "3":  (338, 130),
    "8":  (338, 148),
    "10": (338, 164),
    "14": (338, 178),
    "13": (338, 192),
    "16": (338, 204),
}

def окно(im):
    """Где лежит иллюстрация: (левый край на левой странице, верх, ширина, высота)."""
    доступно = (220.0 - ЛЕВЫЙ_ПРЕДЕЛ) + ПРАВЫЙ_ПРЕДЕЛ
    высота = НИЗ_ПОЛОСЫ - ВЕРХ_ПОЛОСЫ
    ширина = высота * im.width / im.height
    if ширина > доступно:
        ширина = доступно
        высота = ширина * im.height / im.width
    верх = ВЕРХ_ПОЛОСЫ + (НИЗ_ПОЛОСЫ - ВЕРХ_ПОЛОСЫ - высота) / 2
    return 220.0 - ширина / 2, верх, ширина, высота


def якоря():
    im = Image.open(PNG)
    w, h = im.size
    из = {}
    for line in io.open(ТОЧКИ, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        n, x, y = line.split()
        из[n] = (int(x) / w, int(y) / h)
    return im, из


def полоса(im, слева):
    """Половина картинки в base64. PNG с прозрачностью: фона у неё нет, и
    компоненты ложатся прямо на бумагу полосы."""
    w, h = im.size
    сгиб = w // 2
    кусок = im.crop((0, 0, сгиб, h) if слева else (сгиб, 0, w, h))
    цель = 1500                    # ~110 мм при 350 dpi
    if кусок.width > цель:
        кусок = кусок.resize((цель, round(кусок.height * цель / кусок.width)),
                             Image.LANCZOS)
    buf = io.BytesIO()
    кусок.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


def выноски(точки, слева, рамка):
    """Выноски одной страницы. Якорь приходит долями картинки, кружок задан в
    координатах разворота — обе точки переводятся в координаты своей страницы."""
    x0, y0, ш, в = рамка
    сдвиг = 0.0 if слева else 220.0
    g = []
    for номер, (bx, by) in ЗНАЧКИ.items():
        if номер not in точки:
            continue
        fpx, fpy = точки[номер]
        px_ = x0 + fpx * ш
        py_ = y0 + fpy * в
        своя = (bx <= 220 and px_ <= 220) if слева else (bx > 220 and px_ > 220)
        if not своя:
            continue
        x1, y1 = bx - сдвиг, by
        x2, y2 = px_ - сдвиг, py_
        лом = " ".join(f"{x:.1f},{y:.1f}" for x, y in маршрут(x1, y1, x2, y2))
        g.append(f'<polyline class="выноска" points="{лом}" stroke-width="{ЛИНИЯ}"/>'
                 f'<circle class="точка-выноски" cx="{x2:.1f}" cy="{y2:.1f}" '
                 f'r="{ТОЧКА / 2}"/>'
                 f'<circle class="номер-круг" cx="{x1:.1f}" cy="{y1:.1f}" '
                 f'r="{ЗНАЧОК / 2}"/>'
                 f'<text class="номер-текст" x="{x1:.1f}" y="{y1:.1f}">{номер}</text>')
    return "".join(g)


def страница(im, точки, слева, рамка):
    x0, y0, ш, в = рамка
    данные = полоса(im, слева)
    x = x0 if слева else x0 + ш / 2 - 220.0
    img = (f'<image x="{x:.2f}" y="{y0:.2f}" width="{ш / 2:.2f}" height="{в:.2f}" '
           f'preserveAspectRatio="none" '
           f'xlink:href="data:image/png;base64,{данные}"/>')
    return ('<svg class="схема" viewBox="0 0 220 220" '
            'xmlns="http://www.w3.org/2000/svg" '
            'xmlns:xlink="http://www.w3.org/1999/xlink">'
            + img + выноски(точки, слева, рамка) + '</svg>')


def заменить(t, класс, новая):
    i = t.index(класс)
    a = t.index('<svg class="схема"', i)
    b = t.index("</svg>", a) + len("</svg>")
    return t[:a] + новая + t[b:]


def main():
    im, точки = якоря()
    рамка = окно(im)
    print("окно иллюстрации: x=%.1f y=%.1f %.1f x %.1f мм" % рамка)
    t = io.open(КНИГА, encoding="utf-8").read()
    t = заменить(t, "подготовка левая-подг", страница(im, точки, True, рамка))
    t = заменить(t, "подготовка правая-подг", страница(im, точки, False, рамка))
    io.open(КНИГА, "w", encoding="utf-8").write(t)
    print("разворот подготовки обновлён")


if __name__ == "__main__":
    main()
