"""Фон внутренних полос — бесшовная мозаика (дизайнер 14.10.2026).

Узоры строятся как настоящие орнаменты, а не сетка с украшениями:

- «розетки» — метод Ханкина на паркете 4.6.12 (двенадцатиугольники,
  шестиугольники, квадраты): из середины каждого ребра выходят два луча
  под углом к ребру, лучи соседних рёбер сходятся, и по всему полю
  складываются двенадцатиконечные розетки, связанные звёздами;
- «звёзды» — тот же метод на паркете 3.4.6.4: шестиконечные розетки;
- «трюше» — гексы с тремя дугами в одной из двух ориентаций: дуги
  сходятся на серединах рёбер, и по полю текут непрерывные извилистые
  линии без начала и конца;
- «соты-ханкин» — метод Ханкина на гексах с острым углом: плетёные
  шестиконечные звёзды.

Слои у каждого: едва заметный паркет-основа и лента орнамента (широкий
штрих с прорезью цвета бумаги — читается как двойная линия). Всё строится
от решётки, поэтому плитка (один период решётки) стыкуется сама с собой:
лишнее за краем плитки срезает viewBox, а соседняя плитка дорисовывает то
же самое со своей стороны.

Запуск: python мозаика.py <папка> — пишет пробы всех узоров.
"""
import math
import random

К3 = math.sqrt(3)
ЧЕРНИЛА = "%232A2318"
БУМАГА = "%23F4EEDC"

ВЫБОР = "гекс-плата"                  # узор на полосах книги
ШИРИНА_ММ = 56.0                     # ширина плитки на полосе
ПРОЗРАЧНОСТЬ = .7                   # общая заметность узора


def _пересечь(p, d, q, e):
    """Точка пересечения прямых p + t·d и q + u·e."""
    det = d[0] * (-e[1]) - d[1] * (-e[0])
    if abs(det) < 1e-9:
        return None
    t = ((q[0] - p[0]) * (-e[1]) - (q[1] - p[1]) * (-e[0])) / det
    return p[0] + t * d[0], p[1] + t * d[1]


def _многоугольник(c, n, r, фи):
    """Вершины правильного n-угольника с апофемой r; середины рёбер — под углами фи + 360k/n."""
    R = r / math.cos(math.pi / n)
    return [(c[0] + R * math.cos(math.radians(фи) + math.pi / n * (2 * k + 1)),
             c[1] + R * math.sin(math.radians(фи) + math.pi / n * (2 * k + 1))) for k in range(n)]


def _ханкин(c, n, r, фи, тета):
    """Лучи Ханкина: от середины каждого ребра к точке схода с лучом соседнего ребра."""
    отр = []
    в = _многоугольник(c, n, r, фи)
    for k in range(n):
        a1 = math.radians(фи) + 2 * math.pi * k / n
        a2 = math.radians(фи) + 2 * math.pi * (k + 1) / n
        m1 = (c[0] + r * math.cos(a1), c[1] + r * math.sin(a1))
        m2 = (c[0] + r * math.cos(a2), c[1] + r * math.sin(a2))
        v = в[k]                              # общая вершина рёбер k и k+1
        # из середины ребра — к общей вершине, повернув внутрь на тета
        def луч(m):
            t = (v[0] - m[0], v[1] - m[1])
            дл = math.hypot(*t)
            t = (t[0] / дл, t[1] / дл)
            внутрь = (c[0] - m[0], c[1] - m[1])
            дл = math.hypot(*внутрь)
            внутрь = (внутрь[0] / дл, внутрь[1] / дл)
            т = math.radians(тета)
            return (math.cos(т) * t[0] + math.sin(т) * внутрь[0], math.cos(т) * t[1] + math.sin(т) * внутрь[1])
        p = _пересечь(m1, луч(m1), m2, луч(m2))
        if p:
            отр += [(m1, p), (m2, p)]
    return отр


def _звезда(c, n, r, фи, тета):
    """Контур звезды Ханкина: середина ребра, точка схода, середина следующего…"""
    отр = _ханкин(c, n, r, фи, тета)
    точки = [т for i in range(0, len(отр), 2) for т in отр[i]]
    return "M" + "L".join("%s %s" % (f(x), f(y)) for x, y in точки) + "Z"


def _решётка(d, H):
    for i in range(-2, 3):
        for j in range(-2, 4):
            yield (i * d + (j % 2) * d / 2, j * H / 2)


def _паркет_4612(a):
    """Плитка паркета 4.6.12: W×H и список (центр, n, апофема, фи)."""
    d = a * (3 + К3)
    W, H = d, d * К3
    фигуры = []
    for p in _решётка(d, H):
        фигуры.append((p, 12, a * (2 + К3) / 2, 0))
        for напр in (0, 60, 120):
            ф = math.radians(напр)
            фигуры.append(((p[0] + d / 2 * math.cos(ф), p[1] + d / 2 * math.sin(ф)), 4, a / 2, напр))
        for зн in (1, -1):
            фигуры.append(((p[0] + d / 2, p[1] + зн * d * К3 / 6), 6, a * К3 / 2, 30))
    return W, H, фигуры


def _паркет_3464(a):
    """Плитка паркета 3.4.6.4."""
    d = a * (К3 + 1)
    W, H = d, d * К3
    фигуры = []
    for p in _решётка(d, H):
        фигуры.append((p, 6, a * К3 / 2, 0))
        for напр in (0, 60, 120):
            ф = math.radians(напр)
            фигуры.append(((p[0] + d / 2 * math.cos(ф), p[1] + d / 2 * math.sin(ф)), 4, a / 2, напр))
        фигуры.append(((p[0] + d / 2, p[1] + d * К3 / 6), 3, a / (2 * К3), 270))
        фигуры.append(((p[0] + d / 2, p[1] - d * К3 / 6), 3, a / (2 * К3), 90))
    return W, H, фигуры


def _паркет_6(s):
    """Плоские гексы стороной s (ребро смотрит на соседа под 0°, 60°…)."""
    d = s * К3
    W, H = d, d * К3
    return W, H, [(p, 6, s * К3 / 2, 0) for p in _решётка(d, H)]


