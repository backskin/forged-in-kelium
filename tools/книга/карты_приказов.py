# -*- coding: utf-8 -*-
"""КАРТЫ ПРИКАЗОВ ИЗ ЭКСПОРТА ДИЗАЙНЕРА — в набор текстур движка.

Экспорт лежит безымянными номерами («карты-приказов-new-1..25»), а движок
ждёт говорящие имена. Соответствие ниже выведено по самим картам: у каждого
цвета свои четыре пары «выбранный / чужой приказ» и своя спец-плашка.

Запуск: python tools/книга/карты_приказов.py [--показать]
"""
import os
import shutil
import sys

ЭКСПОРТ = (r"C:\shared\Yandex.Disk\Forged in Kelium\Компоненты игрока"
           r"\экспорт-карты-приказов")
КОРЕНЬ = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                      "..", ".."))
ТЕКСТУРЫ = os.path.join(КОРЕНЬ, "data", "textures", "card", "orders")

# номер в экспорте → имя текстуры. В скобках — выбранный/чужой приказ и плашка.
ИМЕНА = {
    1: "blue_infra",        # Инфраструктура / Разработка · задание
    2: "blue_dev",          # Разработка / Наступление · без плашки
    3: "blue_acq",          # Приобретения / Инфраструктура · монета
    4: "blue_oper",         # Наступление / Приобретения · движение
    5: "red_infra",         # Инфраструктура / Приобретения · движение
    6: "red_dev",           # Разработка / Инфраструктура · монета
    7: "red_acq",           # Приобретения / Наступление · без плашки
    8: "red_oper",          # Наступление / Разработка · задание
    9: "green_infra",       # Инфраструктура / Наступление · монета
    10: "green_dev",        # Разработка / Приобретения · задание
    11: "green_acq",        # Приобретения / Разработка · движение
    12: "green_oper",       # Наступление / Инфраструктура · без плашки
    13: "yellow_infra",     # Инфраструктура / Разработка · без плашки
    14: "yellow_dev",       # Разработка / Приобретения · движение
    15: "yellow_acq",       # Приобретения / Инфраструктура · задание
    16: "yellow_oper",      # Наступление / Наступление · монета
    17: "security_blue",
    18: "security_scarlet",
    19: "security_green",
    20: "security_yellow",
    21: "back_blue",
    22: "back_scarlet",
    23: "back_green",
    24: "back_yellow",
    25: "back",
}


def main():
    обновлено, совпало, нет = [], [], []
    for номер, имя in sorted(ИМЕНА.items()):
        источник = os.path.join(ЭКСПОРТ, "карты-приказов-new-%d.png" % номер)
        цель = os.path.join(ТЕКСТУРЫ, имя + ".png")
        if not os.path.exists(источник):
            нет.append(имя)
            continue
        новое = open(источник, "rb").read()
        старое = open(цель, "rb").read() if os.path.exists(цель) else None
        if новое == старое:
            совпало.append(имя)
            continue
        shutil.copyfile(источник, цель)
        обновлено.append(имя)
    print("обновлено:", len(обновлено), (", ".join(обновлено) if обновлено else ""))
    print("без изменений:", len(совпало))
    if нет:
        print("нет в экспорте:", ", ".join(нет))


if __name__ == "__main__":
    main()
