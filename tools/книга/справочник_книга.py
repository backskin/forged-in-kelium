def разбить(список, по):
    """Поделить на полосы РОВНО, а не «по столько-то, сколько влезет».

    `по` — предел на полосу. Полос берётся столько, сколько нужно при этом
    пределе, и содержимое делится между ними поровну: 12 карточек при пределе
    10 — это 6 и 6, а не 10 и 2 с почти пустой второй полосой.
    """
    if not список:
        return []
    полос = max(1, -(-len(список) // по))
    на_полосу = -(-len(список) // полос)
    return [список[i:i + на_полосу]
            for i in range(0, len(список), на_полосу)]



