def _обложка(файл):
    """Готовая обложка дизайнера во всю полосу, с техно-рамкой поверх."""
    from PIL import Image
    im = Image.open(os.path.join(ОБЛОЖКИ, файл)).convert("RGB")
    ш = 2200
    if im.width > ш:
        im = im.resize((ш, round(im.height * ш / im.width)), Image.LANCZOS)
    буфер = io.BytesIO()
    im.save(буфер, "JPEG", quality=88, optimize=True)
    данные_ = base64.b64encode(буфер.getvalue()).decode()
    return ('<div class="рамка-техно"></div>'
            '<img src="data:image/jpeg;base64,%s" alt="">' % данные_)


def обложка(книга, файл, класс="обложка"):
    # Полоса 1 — ОБЛОЖКА, а не титул: она у справочника своя, нарисованная
    # (дизайнер прислал её 15.09.2026), и придумывать титул поверх незачем.
    n = len(книга.страницы) + 1
    книга.страницы.append('  <div class="стр %s">%s</div>\n'
                          % (класс, _обложка(файл)))
    return n


def содержание(книга, места):
    строки = "".join('<li><span class="б">%s</span><span class="т">%s</span>'
                     '<span class="с">%d</span></li>' % (б, и, n)
                     for б, и, n in места)
    книга.страницы[1] = книга.страницы[1].replace("ОГЛАВЛЕНИЕ-СЮДА",
                                                  строки)


