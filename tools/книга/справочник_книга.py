ИМЯ_ММ = 5.9                # строка названия с линейкой под ней
ПОЛЯ_ММ = 3.4               # поля карточки сверху и снизу
ЗАЗОР_ММ = 2.35              # промежуток между карточками
ШАПКА_ММ = 12.5             # шапка раздела


def высота_строки(текст):
    # ярлык стоит в своей колонке и строк не добавляет
    голый = re.sub(r'<span class="кл[^"]*">[^<]*</span>', "", текст)
    строк = 0
    for кусок in re.split(r"<br\s*/?>", голый):
        кусок = re.sub(r"<[^>]+>", "", кусок)
        # перенос по словам: строка рвётся на пробеле, а не посреди слова
        n, длина = 1, 0
        for слово in кусок.split():
            if длина and длина + 1 + len(слово) > ЗНАКОВ_В_СТРОКЕ:
                n, длина = n + 1, len(слово)
            else:
                длина += (1 if длина else 0) + len(слово)
        строк += n
    return строк * СТРОКА_ММ + 0.7


def высота_карточки(строки):
    return ИМЯ_ММ + ПОЛЯ_ММ + sum(высота_строки(с) for с in строки) + ЗАЗОР_ММ


# ЗАМЕР — настоящие высоты из браузера (tools/книга/замер_справочника.js):
# cards — карточка по ключу data-k, heads — от верха полосы до колонок по
# букве раздела, page — высота текстового поля. Пусто — первый проход, высоты
# по оценке выше.
ЗАМЕР = {"cards": {}, "heads": {}, "page": None}


def ключ_карточки(html):
    import hashlib
    return hashlib.md5(html.encode("utf-8")).hexdigest()[:12]


class Раскладчик:
    доп_шапка = 0.0
    """Набивает карточки в колонки полосы и сам решает, где рвать полосу."""

    ПОЛОСА = КОЛОНКА_ММ * 2         # сколько миллиметров текста держит полоса

    def __init__(self, книга):
        self.книга = книга
        self.полоса = []            # куски текущей полосы: шапки и карточки
        self.осталось = self.ПОЛОСА
        self.раздел = None
        self.копилка = None         # текущий раздел: (шапка, [(html, высота)])

    # ---------------------------------------------------------------- вывод
    def _сброс(self):
        if not self.полоса:
            return
        шапки = [x for x in self.полоса if 'class="прил"' in x]
        карты = [x for x in self.полоса if 'class="прил"' not in x]
        тело = ""
        if карты:
            тело = ('    <div class="карточки">\n' + "\n".join(карты)
                    + "\n    </div>")
        self.книга.стр("\n".join(шапки) + ("\n" if шапки and тело else "") + тело,
                       раздел=self.раздел)
        self.раздел = None
        self.полоса = []
        self.осталось = self.ПОЛОСА

    def _выложить(self):
        """Выложить накопленный раздел по ДВУМ КОЛОНКАМ, с новой полосы.

        Колонки рвутся только между карточками, поэтому полосу нельзя мерить
        общей суммой высот: в каждой колонке пропадает хвост, куда следующая
        карточка не влезла. Здесь колонки набиваются по очереди, как их
        набьёт браузер; при выравнивании колонок он уложит не выше.
        Раздел всегда начинается с новой полосы: шапка стоит над колонками,
        и посреди полосы ей места нет.
        """
        if not self.копилка:
            return
        (загол, ключ), карточки = self.копилка
        self.копилка = None
        колонка = ЗАМЕР["page"] or КОЛОНКА_ММ
        шапка_мм = ЗАМЕР["heads"].get(ключ[0], ШАПКА_ММ + self.доп_шапка)
        self.доп_шапка = 0.0
        self._сброс()
        self.полоса.append(загол)
        self.раздел = ключ
        кол, занято, предел = 0, 0.0, колонка - шапка_мм
        for html, в in карточки:
            if занято and занято + в > предел:
                if кол == 0:
                    кол, занято = 1, 0.0
                else:
                    self._сброс()
                    кол, занято, предел = 0, 0.0, колонка - ЗАМЕР["heads"].get("", 0.0)
            self.полоса.append(html)
            занято += в

    # ---------------------------------------------------------------- приём
    def раздел_начать(self, буква, имя, счёт, вступ="", вступ_мм=0.0):
        """Открыть раздел. ВСТУП — общее правило раздела, набранное один раз.

        Повторять одну и ту же оговорку в каждой карточке (как было у
        супер-заданий) — это шум: раздел объясняется сверху, карточка говорит
        только о себе.
        """
        self._выложить()
        загол = шапка(буква, имя, счёт).replace(
            '<div class="прил">', '<div class="прил" data-h="%s">' % буква, 1)
        if вступ:
            загол += '\n    <div class="вступ прил">%s</div>' % вступ
        self.копилка = ((загол, (буква, имя)), [])
        self.доп_шапка = (-(-len(вступ) // 100) * 3.95 + 4.5) if вступ else 0.0

    def карточка(self, html, высота):
        к = ключ_карточки(html)
        html = html.replace('<div class="кк', '<div data-k="%s" class="кк' % к, 1)
        # запас 0.4 мм на округления браузера
        self.копилка[1].append((html, ЗАМЕР["cards"][к] + 0.4 if к in ЗАМЕР["cards"]
                                else высота))

    def конец(self):
        self._выложить()
        self._сброс()

