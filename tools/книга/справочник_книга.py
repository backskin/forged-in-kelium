def разобрать_задание(описание):
    """Печатное описание задания → (требование, награда, дополнительно, заметка).

    Текст карты собран движком по одному образцу: «<требование> — награда
    <…>. Дополнительно — <требование>: <награда>.» У начальных вместо
    дополнительного требования — пояснение дизайнера.
    """
    т = _с(описание)
    т = т.replace(" Усиления у карты нет.", "").replace("Усиления у карты нет.", "")
    if " — награда" not in т:
        return т, "", "", ""
    треб, ост = т.split(" — награда", 1)
    треб = треб.rstrip(",")
    доп = ""
    if ". Дополнительно — " in ост:
        ост, доп = ост.split(". Дополнительно — ", 1)
        доп = доп.rstrip(".")
    заметка = ""
    m = re.match(r"^(.*?[^.])\. (.+)$", ост)
    if m and not доп:
        ост, заметка = m.group(1), m.group(2)
    ост = ост.strip().rstrip(".")
    ост = re.sub(r"^на выбор:\s*", "на выбор: ", ост)
    return треб, ост, доп, заметка


