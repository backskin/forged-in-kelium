def раскладки_по_составу():
    """Картинки сценариев: docs/раскладки/<N>и-<k>.png.

    Рисует их tools/раскладки-снимки.sh из data/scenarios/new — тех же
    файлов, что игра берёт в библиотеку полей.
    """
    out = {}
    for n, _ in СОСТАВЫ:
        out[n] = sorted(glob.glob(os.path.join(ПАПКА_РАСКЛАДОК, "%dи-*.png" % n)),
                        key=lambda п: int(re.search(r"-(\d+)\.png$", п).group(1)))
    return out


def раскладки(книга):
    легенда = os.path.join(ПАПКА_РАСКЛАДОК, "легенда.png")
    б = БУКВА.next()
    первая = True
    for n, состав in СОСТАВЫ:
        файлы = раскладки_по_составу()[n]
        клетки = ['      <figure><img src="%s" alt=""><figcaption>Сценарий %d</figcaption>'
                  '</figure>' % (карта_поля(п, 900), k + 1) for k, п in enumerate(файлы)]
        if not клетки:
            continue
        полосы = [клетки[i:i + 4] for i in range(0, len(клетки), 4)]
        for k, полоса in enumerate(полосы):
            # обозначения — полосой во всю ширину под сеткой, на каждой
            # полосе раздела: справочник открывают на нужном составе
            низ = ""
            if os.path.exists(легенда):
                низ = ('\n    <div class="легенда-поля"><img src="%s" alt=""></div>'
                       % b64(легенда, 1400))
            вступление = ""
            if первая:
                вступление = (
                    '\n    <div class="вступ">Сценарий — это раскладка поля: очертание, '
                    'тайлы зарождения, нейтральные постройки и стартовые гексы. '
                    'Соберите поле по картинке из блоков; контейнеры и круги энергии '
                    'напечатаны на самих блоках. Сценарии одного состава нарочно '
                    'разные: где-то зарождения общие и за них дерутся, где-то у каждого '
                    'свой угол и узкие проходы между постройками.</div>')
            заголовок = "Сценарии · " + состав
            if len(полосы) > 1:
                заголовок += " · %d из %d" % (k + 1, len(полосы))
            книга.стр(шапка(б, заголовок, "%d %s" % (len(файлы), _сценариев(len(файлы))))
                      + вступление
                      + '\n    <div class="раскл">\n' + "\n".join(полоса)
                      + "\n    </div>" + низ,
                      раздел=(б, "Сценарии поля") if первая else None)
            первая = False


def _сценариев(n):
    if n % 10 == 1 and n % 100 != 11:
        return "сценарий"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "сценария"
    return "сценариев"


