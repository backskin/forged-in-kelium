def _раскладок(n):
    """«4 раскладки», «8 раскладок» — счёт в шапке должен звучать по-русски."""
    if n % 10 == 1 and n % 100 != 11:
        return "%d раскладка" % n
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "%d раскладки" % n
    return "%d раскладок" % n


