    доп_шапка = 0.0
    """Набивает карточки в колонки полосы и сам решает, где рвать полосу."""

    ПОЛОСА = КОЛОНКА_ММ * 2         # сколько миллиметров текста держит полоса

    def __init__(self, книга):
        self.книга = книга
        self.полоса = []            # куски текущей полосы: шапки и карточки
        self.осталось = self.ПОЛОСА
        self.раздел = None
        self.копилка = None         # текущий раздел: (шапка, [(html, высота)])

    # ---------------------------------------------------------------- вывод
    def _сброс(self):
        if not self.полоса:
            return
        шапки = [x for x in self.полоса if 'class="прил"' in x]
        карты = [x for x in self.полоса if 'class="прил"' not in x]
        тело = ""
        if карты:
            тело = ('    <div class="карточки">\n' + "\n".join(карты)
                    + "\n    </div>")
        self.книга.стр("\n".join(шапки) + ("\n" if шапки and тело else "") + тело,
                       раздел=self.раздел)
        self.раздел = None
        self.полоса = []
        self.осталось = self.ПОЛОСА

    def _выложить(self):
        """Выложить накопленный раздел, раздав карточки полосам ПОРОВНУ.

        Если просто набивать полосу до отказа, последняя полоса раздела выходит
        почти пустой: девять длинных карт супер-арсенала — это полторы полосы,
        то есть полная и одна с единственной карточкой. Поэтому сперва считается,
        сколько полос вообще нужно, а потом высота делится между ними поровну.
        """
        if not self.копилка:
            return
        (загол, ключ), карточки = self.копилка
        self.копилка = None
        self.доп_шапка = 0.0
        всего = sum(в for _, в in карточки)
        свободно = self.осталось - ШАПКА_ММ - self.доп_шапка
        # Раздел продолжает текущую полосу, только если он там помещается
        # целиком и места осталось хотя бы на треть полосы: иначе шапка
        # повиснет над одной карточкой.
        if всего > свободно or свободно < self.ПОЛОСА * 0.34:
            self._сброс()
            свободно = self.ПОЛОСА - ШАПКА_ММ - self.доп_шапка
        # Карточки набиваются в полосу до отказа. Раздать их полосам поровну
        # я пробовал — выходит хуже: полос становится больше, и ни одна из них
        # не полная. Недобор на последней полосе раздела для справочника —
        # норма, он же не читается подряд.
        self.полоса.append(загол)
        self.раздел = ключ
        self.осталось = свободно
        for html, в in карточки:
            if в > self.осталось:
                self._сброс()
                self.осталось = self.ПОЛОСА
            self.полоса.append(html)
            self.осталось -= в

    # ---------------------------------------------------------------- приём
    def раздел_начать(self, буква, имя, счёт, вступ="", вступ_мм=0.0):
        """Открыть раздел. ВСТУП — общее правило раздела, набранное один раз.

        Повторять одну и ту же оговорку в каждой карточке (как было у
        супер-заданий) — это шум: раздел объясняется сверху, карточка говорит
        только о себе.
        """
        self._выложить()
        загол = шапка(буква, имя, счёт)
        if вступ:
            загол += '\n    <div class="вступ прил">%s</div>' % вступ
        self.копилка = ((загол, (буква, имя)), [])
        self.доп_шапка = вступ_мм

    def карточка(self, html, высота):
        self.копилка[1].append((html, высота))

    def конец(self):
        self._выложить()
        self._сброс()

