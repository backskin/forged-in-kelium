# Полоса 220×220 мм, поля 15/16 мм, две колонки. Высота колонки и ширина
# текста в карточке — в миллиметрах; по ним считается, сколько строк займёт
# каждая строка карточки и сколько карточек влезет в колонку.
КОЛОНКА_ММ = 183.0          # высота текстового поля полосы
ЗНАКОВ_В_СТРОКЕ = 48        # при 8.3 pt Tektur Narrow в колонке 92 мм
СТРОКА_ММ = 3.04
ИМЯ_ММ = 5.9                # строка названия с линейкой под ней
ПОЛЯ_ММ = 3.4               # поля карточки сверху и снизу
ЗАЗОР_ММ = 2.35              # промежуток между карточками
ШАПКА_ММ = 12.5             # шапка раздела


def высота_строки(текст):
    голый = re.sub(r"<[^>]+>", "", текст)
    строк = max(1, -(-len(голый) // ЗНАКОВ_В_СТРОКЕ))
    return строк * СТРОКА_ММ + 0.7


def высота_карточки(строки):
    return ИМЯ_ММ + ПОЛЯ_ММ + sum(высота_строки(с) for с in строки) + ЗАЗОР_ММ


