    import json
    окр = dict(os.environ)
    if CHROME and "KELIUM_CHROME" not in окр:
        окр["KELIUM_CHROME"] = CHROME
    r = subprocess.run(["node", os.path.join(D, "замер_справочника.js"), ВЫХОД]
                       + ([pdf] if pdf else []),
                       capture_output=True, text=True, encoding="utf-8", env=окр)
    if r.returncode != 0:
        print("замер не удался — раскладка по оценке:", r.stderr.strip()[-300:])
        return None
    return json.loads(r.stdout.strip().splitlines()[-1])


