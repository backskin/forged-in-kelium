#!/usr/bin/env bash
# Пересобрать все главы книги правил из md (кроме разворота подготовки, гл. 3,
# у него свой сборщик), потом памятку и вынос картинок.
set -e
cd "$(dirname "$0")/../.."
for ch in "01 — Об игре.md" "02 — Состав игры.md" "04 — Основы игры.md" "05 — Ход игры.md" \
          "06 — Постройка, энергия и хранилище.md" "07 — Добыча, Питание и Снабжение.md" \
          "08 — Командование.md" "09 — Развитие.md" "10 — Модули.md" "11 — Конец игры и подсчёт очков.md"; do
  python3 tools/книга/reflow.py "$ch"
done
python3 tools/книга/make_back.py
python3 tools/книга/вынести_картинки.py >/dev/null
