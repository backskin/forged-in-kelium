# -*- coding: utf-8 -*-
"""Разбор карты задания — крупно, выносками по бокам, на своей полосе.

Источник — текстура игры o72 («Атакуй дважды! / Против сильнейшего»).
"""
import os

D = os.path.dirname(os.path.abspath(__file__))
ns = {"__file__": os.path.join(D, "figs.py")}
exec(open(os.path.join(D, "figs.py"), encoding="utf-8-sig").read().split("# планшет войск")[0], ns)
figure = ns["figure"]

# Карта «Атакуй дважды! / Против сильнейшего» (o72): дизайнер попросил
# другую карту, с иной нижней наградой — здесь это 4 монеты (05.10.2026).
SRC = os.path.join(os.path.dirname(os.path.dirname(D)), "data", "textures", "card", "objective", "o72.png")

# Координаты — в пикселях карты (600×933). Значки выносок — за картой:
# слева x = −100, справа x = 700. Мелкие знаки и номер обведены кольцом
# (шестое число — радиус), чтобы точка их не закрывала.
marks = [
    ("А", 520, 170, 700, 120),         # верх карты: разовый эффект
    ("Б", 58, 165, -100, 165, 46),     # знак «сжечь карту»
    ("В", 60, 285, -100, 285, 44),     # знак спец-действия
    ("Г", 555, 262, 700, 262),         # название задания
    ("Д", 570, 455, 700, 420),         # требование
    ("Е", 456, 560, 700, 560),         # награда за выполнение — два действия на выбор
    ("Ж", 570, 745, 700, 720),         # дополнительное требование
    ("З", 255, 840, -100, 840),        # награда за дополнительное требование
    ("И", 563, 902, 700, 902, 28),     # номер карты
]

figure("карта-задания", SRC, 1400, 600, 933, marks, css_w="100%", pad="1.0mm 0 1.2mm", карта_мм=56.0, в_колонке=True)
print("ok")
