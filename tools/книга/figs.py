# НАСТОЯЩИЕ РАЗМЕРЫ КАРТ (мм) — по ним считается скругление углов в 3 мм,
# которое дизайнер просит показывать на всех картах в примерах (14.09.2026).
КАРТЫ_ММ = {"арсенал": 68.0, "задание": 56.0, "приказ": 56.0, "контейнер": 34.0}
СКРУГЛЕНИЕ_ММ = 3.0


def скруглить(im, ширина_мм, радиус_мм=СКРУГЛЕНИЕ_ММ):
    """Скруглить углы карты. Радиус — в миллиметрах ПЕЧАТНОЙ карты, а не в
    пикселях: иначе у мелкого контейнера и крупного арсенала углы разные."""
    im = im.convert("RGBA")
    r = радиус_мм * im.width / ширина_мм
    маска = Image.new("L", im.size, 0)
    ImageDraw.Draw(маска).rounded_rectangle([0, 0, im.width - 1, im.height - 1],
                                            radius=r, fill=255)
    out = im.copy()
    out.putalpha(ImageChops.multiply(im.split()[3], маска))
    return out


def карта(путь, вид, высота=None, ширина=None):
    """Открыть карту, скруглить её углы и при желании смасштабировать."""
    im = скруглить(Image.open(путь), КАРТЫ_ММ[вид])
    if высота:
        im = im.resize((round(im.width * высота / im.height), высота), Image.LANCZOS)
    elif ширина:
        im = im.resize((ширина, round(im.height * ширина / im.width)), Image.LANCZOS)
    return im


def b64(path, width):
    im = (path if isinstance(path, Image.Image) else Image.open(path)).convert("RGBA")
    h = round(im.height * width / im.width)
    im = im.resize((width, h), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode(), im.size


# ВСЕ РАЗМЕРЫ ВЫНОСОК СЧИТАЮТСЯ ОТ БУМАГИ, А НЕ ОТ КАРТИНКИ. Иначе кружок на
# широком планшете выходит втрое крупнее кружка на жетоне в колонке — ровно это
# и увидел дизайнер на страницах 14 и 16 (14.09.2026).
ПОЛЕ_ММ = 190.0          # ширина текстового поля полосы книги
КОЛОНКА_ММ = 92.0        # (190 − 6 промежуток) / 2
ЗНАЧОК_ММ = 6.0          # диаметр кружка выноски
ЛИНИЯ_ММ = 0.35          # толщина линии выноски
ОБВОДКА_ММ = 0.30        # толщина зелёного кольца кружка
ТОЧКА_ММ = 1.7           # диаметр точки на конце выноски
ЧЕРТА_ММ = 1.1           # толщина черты, которой подчёркивают элемент


def маршрут(bx, by, px, py, угол=45.0):
    """Ломаная от значка выноски к точке: длинный прямой участок и один излом.

    Линия идёт от значка СТРОГО по горизонтали или вертикали — насколько
    хватает, — и только у самой точки ломается под заданным углом. Так выноска
    не режет арт по диагонали через всю карту (просьба дизайнера 14.09.2026).
    """
    dx, dy = px - bx, py - by
    if abs(dx) < 1 or abs(dy) < 1:
        return [(bx, by), (px, py)]        # чистая горизонталь или вертикаль
    ход = 1.0 / math.tan(math.radians(угол))
    if abs(dx) >= abs(dy):                 # длинный участок горизонтальный
        косая = min(abs(dy) * ход, abs(dx))
        излом = px - math.copysign(косая, dx)
        return [(bx, by), (излом, by), (px, py)]
    косая = min(abs(dx) * ход, abs(dy))    # длинный участок вертикальный
    излом = py - math.copysign(косая, dy)
    return [(bx, by), (bx, излом), (px, py)]


def поля_под_выноски(vw, vh, marks, черты, значок_мм, основа, css_w):
    """Насколько расширить холст, чтобы НИ ОДИН значок не вылез за рисунок.

    Выноску удобно ставить «за краем» картинки — но SVG-слой лежит ровно по
    размеру картинки, и такой значок уезжает за её пределы: на странице 21 буквы
    А и В оказались выше заголовка полосы (замечание дизайнера 15.09.2026).
    Поэтому холст сам подрастает на нужные поля, а координаты сдвигаются.
    """
    л = в = п = н = 0
    xs = [m[3] for m in marks] + [m[1] for m in marks]
    ys = [m[4] for m in marks] + [m[2] for m in marks]
    for ч in черты:
        xs += [ч[0], ч[2]]
        ys += [ч[1], ч[3]]
    if not xs:
        return 0, 0, 0, 0
    мм = основа * float(str(css_w).rstrip("%")) / 100.0
    for _ in range(4):
        вед = (vw + л + п) / мм
        r = значок_мм / 2.0 * вед * 1.18
        новое = (max(0, round(r - min(xs))), max(0, round(r - min(ys))),
                 max(0, round(max(xs) + r - vw)), max(0, round(max(ys) + r - vh)))
        if новое == (л, в, п, н):
            break
        л, в, п, н = новое
    return л, в, п, н


def расширить(path, vw, vh, поля):
    """Положить картинку на прозрачный холст с полями (в единицах вьюбокса)."""
    л, в, п, н = поля
    im = (path if isinstance(path, Image.Image) else Image.open(path)).convert("RGBA")
    k = im.width / float(vw)
    холст = Image.new("RGBA", (round((vw + л + п) * k), round((vh + в + н) * k)),
                      (0, 0, 0, 0))
    холст.paste(im, (round(л * k), round(в * k)), im)
    return холст


def figure(name, path, width, vw, vh, marks, r=None, fs=None, css_w="93%", pad="1.2mm 0 1.2mm",
           значок_мм=ЗНАЧОК_ММ, угол=45.0, в_колонке=False, поле_мм=None, черты=(),
           карта_мм=None):
    """Рисунок с выносками.

    marks: (буква, x точки, y точки, x значка, y значка[, (dx, dy) отвод]).
    Отвод — короткий отрезок ОТ ТОЧКИ: линия сначала отходит от неё на (dx, dy),
    и только потом идёт длинным прямым участком к значку. Так выноску можно
    увести вбок двумя изломами, не перечёркивая арт (просьба дизайнера).

    черты: (x1, y1, x2, y2) — жирная прямая, которой подчёркивают элемент
    (например, сторону гекса).
    """
    if карта_мм:
        path = скруглить(Image.open(path) if not isinstance(path, Image.Image) else path,
                         карта_мм)
    основа = поле_мм if поле_мм else (КОЛОНКА_ММ if в_колонке else ПОЛЕ_ММ)
    л, в, п, н = поля_под_выноски(vw, vh, marks, черты, значок_мм, основа, css_w)
    if (л, в, п, н) != (0, 0, 0, 0):
        path = расширить(path, vw, vh, (л, в, п, н))
        marks = [tuple(m[:1]) + (m[1] + л, m[2] + в, m[3] + л, m[4] + в) + tuple(m[5:])
                 for m in marks]
        черты = [(x1 + л, y1 + в, x2 + л, y2 + в) for x1, y1, x2, y2 in черты]
        width = round(width * (vw + л + п) / float(vw))
        vw, vh = vw + л + п, vh + в + н
    data, _ = b64(path, width)
    мм = основа * float(str(css_w).rstrip("%")) / 100.0
    вед = vw / мм                          # единиц вьюбокса в одном миллиметре
    r = значок_мм / 2.0 * вед
    fs = r * 1.3
    линия = ЛИНИЯ_ММ * вед
    обводка = ОБВОДКА_ММ * вед
    точка = ТОЧКА_ММ / 2.0 * вед
    g = []
    for x1, y1, x2, y2 in черты:
        g.append(f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" class="черта" '
                 f'stroke-width="{ЧЕРТА_ММ * вед:.1f}" stroke-linecap="round"/>')
    for m in marks:
        lab, px, py, bx, by = m[:5]
        отвод = m[5] if len(m) > 5 else None
        if отвод:
            ex, ey = px + отвод[0], py + отвод[1]
            путь = маршрут(bx, by, ex, ey, угол) + [(px, py)]
        else:
            путь = маршрут(bx, by, px, py, угол)
        точки = " ".join(f"{x:.1f},{y:.1f}" for x, y in путь)
        g.append(f'<polyline points="{точки}" fill="none" class="выноска-л" '
                 f'stroke-width="{линия:.1f}" stroke-linejoin="round"/>'
                 f'<circle cx="{px}" cy="{py}" r="{точка:.1f}" class="выноска-т"/>'
                 f'<circle cx="{bx}" cy="{by}" r="{r:.1f}" class="номер-круг" '
                 f'stroke-width="{обводка:.1f}"/>'
                 f'<text x="{bx}" y="{by}" class="номер-текст" font-size="{fs:.1f}">{lab}</text>')
    NL = chr(10)
    кл = "рисунок-в-колонке" if в_колонке else "рисунок-во-всю"
    html = (f'        <div class="{кл}" style="padding:{pad}">' + NL
            + f'          <div class="рис" style="width:{css_w}">' + NL
            + f'            <img src="data:image/png;base64,{data}" alt="">' + NL
            + f'            <svg viewBox="0 0 {vw} {vh}" preserveAspectRatio="none">'
            + "".join(g) + '</svg>' + NL
            + '          </div>' + NL + '        </div>')
    open(os.path.join(D, f"_{name}.svg"), "w", encoding="utf-8").write(html)


