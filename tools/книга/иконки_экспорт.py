def main():
    os.makedirs(ВЫХОД, exist_ok=True)
    было = {f for f in os.listdir(ВЫХОД) if f.endswith(".png")}
    стало = set()
    for номер, имя in ИМЕНА.items():
        if isinstance(номер, str):
            источник = os.path.join(ЭКСПОРТ, номер + ".png")
        else:
            источник = os.path.join(ЭКСПОРТ, "все иконки-%d.png" % int(номер))
        if not os.path.exists(источник):
            print("нет в экспорте:", номер, имя)
            continue
        # Поля вокруг рисунка срезаются: в выгрузке 27.09 рисунок занимает
        # меньше половины квадрата, и в книге иконки выходили мелкими.
        from PIL import Image
        im = Image.open(источник).convert("RGBA")
        box = im.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
        if box:
            im = im.crop(box)
        w, h = im.size
        s = max(w, h)
        кв = Image.new("RGBA", (s, s), (0, 0, 0, 0))
        кв.paste(im, ((s - w) // 2, (s - h) // 2))
        кв.save(os.path.join(ВЫХОД, имя + ".png"), optimize=True)
        стало.add(имя + ".png")
    # Прежние файлы, которых нет в таблице, не удаляются: у части значков
    # (кубик трофея без шестерёнки) в новой выгрузке замены нет.
    print("иконок сохранено:", len(стало), "->", ВЫХОД)


if __name__ == "__main__":
    main()
