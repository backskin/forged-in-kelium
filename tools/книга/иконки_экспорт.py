def main():
    os.makedirs(ВЫХОД, exist_ok=True)
    было = {f for f in os.listdir(ВЫХОД) if f.endswith(".png")}
    стало = set()
    for номер, имя in sorted(ИМЕНА.items()):
        источник = os.path.join(ЭКСПОРТ, "все иконки-%d.png" % номер)
        if not os.path.exists(источник):
            print("нет в экспорте:", номер, имя)
            continue
        shutil.copyfile(источник, os.path.join(ВЫХОД, имя + ".png"))
        стало.add(имя + ".png")
    for лишний in sorted(было - стало):
        os.remove(os.path.join(ВЫХОД, лишний))
        print("убрано:", лишний)
    print("иконок сохранено:", len(стало), "->", ВЫХОД)


if __name__ == "__main__":
    main()
