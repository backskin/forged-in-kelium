# -*- coding: utf-8 -*-
"""Разбор карты арсенала — крупно, выносками по краям.

Источник — текстура игры a7_10 («Тяжёлое крыло»): низ работает ПОСТОЯННО,
пока карта установлена.
Карта горизонтальная, поэтому выноски идут и по бокам, и сверху-снизу.
"""
import os

D = os.path.dirname(os.path.abspath(__file__))
ns = {"__file__": os.path.join(D, "figs.py")}
exec(open(os.path.join(D, "figs.py"), encoding="utf-8-sig").read().split("# планшет войск")[0], ns)
figure = ns["figure"]

# «Тяжёлое крыло» (a7_10): дизайнер попросил пример ярче и сочнее
# (05.10.2026) — золотые монеты сверху, авиация с сердцем в эффекте.
SRC = os.path.join(os.path.dirname(os.path.dirname(D)), "data", "textures", "card", "arsenal", "a7_10.png")

# Координаты — в пикселях карты (600×389). Верхние знаки — сверху; всё,
# что слева и справа, уводится ВНИЗ (дизайнер 05.10.2026: «буквы слева и
# справа — вниз»): ломаная идёт вдоль края карты снаружи и опускается к
# значку. Мелкие знаки обведены кольцом (число — радиус).
marks = [
    ("А", 330, 45, 330, -70),                    # верх: разовый эффект
    ("Б", 45, 45, 45, -70, 34),                  # знак спец-действия у верха
    ("В", 125, 45, 160, -70, 34),                # знак «сжечь карту»
    ("Г", 40, 118, -75, 455, (-115, 0)),         # знак установленной карты
    ("Д", 45, 185, -15, 455, (-60, 0)),          # знак «постоянно»
    ("Е", 560, 130, 615, 455, (55, 0)),          # название карты
    ("Ж", 565, 225, 675, 455, (110, 0)),         # эффект установленной карты
    ("З", 572, 358, 555, 455, 24),                   # номер карты
]

figure("карта-арсенала", SRC, 1600, 600, 389, marks, css_w="66%", pad="1.2mm 0 1.6mm", карта_мм=68.0)
print("ok")
