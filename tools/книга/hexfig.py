# -*- coding: utf-8 -*-
"""Рисунок главы 4: гекс с выносками А-Г.

«Г» — это СТОРОНА гекса, а не его угол (поправка дизайнера 14.09.2026):
выноска смотрит в середину нижней правой стороны, и сама сторона подчёркнута
жирной чертой параллельно ей — чтобы «сторона» читалась с первого взгляда.
"""
import os

D = os.path.dirname(os.path.abspath(__file__))
ns = {"__file__": os.path.join(D, "figs.py")}
exec(open(os.path.join(D, "figs.py"), encoding="utf-8-sig").read().split("# планшет войск")[0], ns)
figure = ns["figure"]

SRC = r"C:\shared\Yandex.Disk\Forged in Kelium\Общие компоненты\экспорт-гексы\Гекс.png"

# Гекс 1030×927: вершины слева (0,463) и справа (1030,463), верх и низ — прямые.
# Нижняя правая сторона: (772,922) → (1030,463).
ax, ay, bx, by = 772.0, 922.0, 1030.0, 463.0
ex, ey = bx - ax, by - ay
L = (ex * ex + ey * ey) ** 0.5
nx, ny = ey / L * -1, ex / L * -1        # наружная нормаль
nx, ny = -nx, -ny
ОТСТУП = 15.0
черта = (ax + ex * 0.08 + nx * ОТСТУП, ay + ey * 0.08 + ny * ОТСТУП,
         ax + ex * 0.92 + nx * ОТСТУП, ay + ey * 0.92 + ny * ОТСТУП)
сер = (ax + ex * 0.5 + nx * ОТСТУП, ay + ey * 0.5 + ny * ОТСТУП)

figure("гекс", SRC, 900, 1030, 927, [
    ("А", 515, 190, -110, 190),
    ("Б", 515, 460, 1150, 330),
    ("В", 200, 455, -110, 600),
    ("Г", сер[0], сер[1], 1150, 700),
], css_w="68%", pad="2mm 0 3mm", в_колонке=True,
    черты=[(round(черта[0]), round(черта[1]), round(черта[2]), round(черта[3]))])
print("ok")
