"""Зелёная стрелка «лицо → оборот»: одна на все рисунки книги.

Ею показан переход стороны жетона — с лица на оборот, с обычной стороны
на золотую. Дизайнер попросил один и тот же приём везде (15.09.2026).
"""
from PIL import ImageDraw

ЗЕЛЁНЫЙ = (24, 108, 36, 255)


def нарисовать(холст, x0, x1, y, толщина=None):
    """Стрелка от x0 до x1 на высоте y (координаты холста)."""
    d = ImageDraw.Draw(холст)
    длина = x1 - x0
    ш = толщина or max(5, round(длина * 0.10))
    остриё = round(длина * 0.26)
    d.line((x0, y, x1 - остриё * 0.6, y), fill=ЗЕЛЁНЫЙ, width=ш)
    d.polygon([(x1, y), (x1 - остриё, y - остриё * 0.62),
               (x1 - остриё, y + остриё * 0.62)], fill=ЗЕЛЁНЫЙ)
