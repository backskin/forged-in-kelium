# -*- coding: utf-8 -*-
"""Переложить выноски готового рисунка `_имя.svg` (05.10.2026).

Генераторы части рисунков читают экспорт дизайнера, которого в облаке нет,
а выноски нужно переставлять: «вместо жирной точки — тонкое кольцо вокруг
элемента», «показывать с разных сторон, а не всё слева», «обводка линий, как
на развороте подготовки». Здесь картинка рисунка остаётся, а слой выносок
пишется заново по списку.

Выноска: (буква, x, y, x значка, y значка, кольцо, [изломы])
  кольцо — радиус кольца вокруг элемента (0 — обычная точка);
  изломы — промежуточные точки ломаной (необязательно).
Координаты — в единицах viewBox рисунка.

Размеры линий, точек и значков берутся из прежнего слоя: рисунок не меняет
масштаб выносок, только их место и вид.
"""
import math
import os
import re

D = os.path.dirname(os.path.abspath(__file__))


def переложить(имя, выноски):
    п = os.path.join(D, "_%s.svg" % имя)
    s = open(п, encoding="utf-8").read()
    a = s.index("<svg")
    b = s.index("</svg>", a) + len("</svg>")
    стар = s[a:b]
    vb = re.search(r'viewBox="([^"]+)"', стар).group(1)
    линия = float((re.findall(r'class="выноска-л" stroke-width="([\d.]+)"', стар) or ["5.9"])[0])
    обвод = float((re.findall(r'class="номер-круг" stroke-width="([\d.]+)"', стар) or ["5.0"])[0])
    r_зн = float((re.findall(r'r="([\d.]+)" class="номер-круг"', стар) or ["50"])[0])
    r_т = float((re.findall(r'r="([\d.]+)" class="выноска-т"', стар) or ["14"])[0])
    кегль = float((re.findall(r'font-size="([\d.]+)"', стар) or [str(r_зн * 1.3)])[0])
    фон, верх = [], []
    for в in выноски:
        буква, x, y, bx, by, кольцо = в[:6]
        изломы = list(в[6]) if len(в) > 6 else []
        точки = [(bx, by)] + изломы + [(x, y)]
        if кольцо:
            # линия кончается на кольце, а не в центре элемента
            px, py = точки[-2]
            d = math.hypot(x - px, y - py) or 1
            точки[-1] = (x - (x - px) / d * кольцо, y - (y - py) / d * кольцо)
        лом = " ".join("%.1f,%.1f" % т for т in точки)
        верх.append('<polyline points="%s" fill="none" class="выноска-л" stroke-width="%.1f" '
                    'stroke-linejoin="round" stroke-linecap="round"/>' % (лом, линия))
        if кольцо:
            верх.append('<circle cx="%s" cy="%s" r="%.1f" fill="none" class="выноска-л" '
                        'stroke-width="%.1f"/>' % (x, y, кольцо, линия * 1.3))
        else:
            верх.append('<circle cx="%s" cy="%s" r="%.1f" class="выноска-т"/>' % (x, y, r_т))
        верх.append('<circle cx="%s" cy="%s" r="%.1f" class="номер-круг" stroke-width="%.1f"/>'
                    '<text x="%s" y="%s" class="номер-текст" font-size="%.1f">%s</text>'
                    % (bx, by, r_зн, обвод, bx, by, кегль, буква))
    нов = ('<svg viewBox="%s" preserveAspectRatio="none">' % vb + "".join(фон) + "".join(верх) + "</svg>")
    from ореол import с_ореолом
    open(п, "w", encoding="utf-8").write(с_ореолом(s[:a] + нов + s[b:]))
    print("выноски переложены:", имя, len(выноски))


# Раскладки выносок рисунков, у которых генератор недоступен.
РАСКЛАДКИ = {
    # планшет науки (глава 9): сверху — карты треков, слева — ступень,
    # снизу — звёзды, справа — обмены; кольца на цене ступени и звезде
    "планшет-науки": [
        # правый (синий) трек: модуль трека, карты ступеней, вершина — значки
        # над треком, в пустом поле справа сверху (дизайнер 05.10.2026: «не всё
        # слева с краю — буквы в правую часть, примеры на правом треке»)
        ("Е", 2311, 809, 2230, 560, 0),
        ("Г", 2211, 969, 2050, 640, 0),
        ("З", 2451, 969, 2470, 560, 0),
        ("Ж", 2711, 969, 2740, 560, 0),
        ("К", 1569, 749, 2050, 380, 0),
        # средний (зелёный) трек: сам трек, цена, ячейки, звезда — значки
        # снизу слева, под левым шестиугольником
        ("И", 1194, 1464, 700, 1700, 0),
        ("Б", 1159, 1559, 780, 1840, 62),
        ("В", 1179, 1674, 860, 1975, 0),
        ("А", 1329, 1524, 1700, 1250, 0),
        ("Д", 1389, 2019, 1010, 2045, 70),
    ],
}

if __name__ == "__main__":
    import sys
    for имя in (sys.argv[1:] or РАСКЛАДКИ):
        переложить(имя, РАСКЛАДКИ[имя])
