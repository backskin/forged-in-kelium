# -*- coding: utf-8 -*-
"""ВЫНЕСТИ КАРТИНКИ ИЗ ВЁРСТКИ ВО ВНЕШНИЕ ФАЙЛЫ.

Зачем. Сборщики вставляют каждую картинку в HTML как `data:image/...;base64`,
и файл вёрстки распух до 57 МБ. Последствия видны сразу:

  * GitHub предупреждает на каждом пуше (порог 50 МБ, предел 100);
  * любая правка одной главы переписывает весь файл, и гит хранит ещё одну
    его копию целиком — история растёт десятками мегабайт за коммит;
  * одна и та же картинка лежит в файле по несколько раз: значок действия
    встречается до восьми раз, и каждый раз своими байтами.

Что делает. Каждый `data:`-URI выносится в `вёрстка/илл/<хеш>.<ext>`, а в HTML
остаётся относительная ссылка. Имя — по хешу содержимого, поэтому одинаковые
картинки складываются в один файл, а повторный запуск ничего не переименовывает.

ИДЕМПОТЕНТНО. Скрипт можно гонять после любой пересборки: уже вынесенные
ссылки он не трогает, новые `data:` выносит, а файлы, на которые в вёрстке
больше никто не ссылается, убирает.

ПЕЧАТЬ PDF. `build.py` печатает копию вёрстки из своей папки, поэтому он
переписывает `илл/…` в абсолютный `file:///` — иначе Chrome искал бы картинки
рядом с копией и печатал пустые места.

Запуск: python вынести_картинки.py
"""
import base64
import glob
import hashlib
import io
import os
import re
import sys

D = os.path.dirname(os.path.abspath(__file__))
ВЁРСТКА = glob.glob(os.path.join(
    os.path.dirname(os.path.dirname(D)), "rules", "Книга правил*", "вёрстка"))
if not ВЁРСТКА:
    ВЁРСТКА = glob.glob(r"C:\shared\forged-in-kelium\rules\Книга правил*\вёрстка")
ВЁРСТКА = ВЁРСТКА[0]
HTML = os.path.join(ВЁРСТКА, "Книга правил.html")
ПАПКА = "илл"
ОКНО = os.path.join(ВЁРСТКА, ПАПКА)

# Расширение по типу из data-URI. svg+xml сюда не попадает: инлайновый SVG
# вставляется разметкой, а не data-URI.
РАСШИРЕНИЯ = {"png": "png", "jpeg": "jpg", "jpg": "jpg", "webp": "webp",
              "gif": "gif"}

URI = re.compile(r'data:image/(\w+);base64,([A-Za-z0-9+/=]+)')


def main():
    t = io.open(HTML, encoding="utf-8").read()
    os.makedirs(ОКНО, exist_ok=True)
    записано, повторы, байт = 0, 0, 0
    использованы = set()

    def заменить(m):
        nonlocal записано, повторы, байт
        тип, b64 = m.group(1), m.group(2)
        ext = РАСШИРЕНИЯ.get(тип.lower())
        if ext is None:
            return m.group(0)                 # незнакомый тип оставляем как есть
        имя = hashlib.sha1(b64.encode("ascii")).hexdigest()[:16] + "." + ext
        путь = os.path.join(ОКНО, имя)
        использованы.add(имя)
        if os.path.exists(путь):
            повторы += 1
        else:
            данные = base64.b64decode(b64)
            open(путь, "wb").write(данные)
            записано += 1
            байт += len(данные)
        return ПАПКА + "/" + имя

    было = len(t)
    t = URI.sub(заменить, t)

    # Уже вынесенные ссылки прошлых запусков тоже считаются использованными —
    # иначе уборка снесёт файлы, на которые вёрстка ссылается.
    for m in re.finditer(re.escape(ПАПКА) + r"/([0-9a-f]{16}\.\w+)", t):
        использованы.add(m.group(1))

    # Уборка: картинки, на которые больше никто не ссылается.
    убрано = 0
    for f in os.listdir(ОКНО):
        if f not in использованы:
            os.remove(os.path.join(ОКНО, f))
            убрано += 1

    if len(t) != было:
        for попытка in range(12):
            try:
                io.open(HTML, "w", encoding="utf-8", newline="\n").write(t)
                break
            except OSError:
                if попытка == 11:
                    raise

    print("вынесено файлов: %d (%.1f МБ), повторов склеено: %d, убрано: %d"
          % (записано, байт / 1e6, повторы, убрано))
    print("вёрстка: %.1f МБ -> %.1f МБ" % (было / 1e6, len(t) / 1e6))
    print("картинки: %s" % ОКНО)
    return 0


if __name__ == "__main__":
    sys.exit(main())
