# -*- coding: utf-8 -*-
"""РЕВИЗИЯ ВЁРСТКИ — измерить на каждой полосе ВСЕ объекты, а не только текст.

Зачем. Прежняя проверка смотрела, где кончается последний ТЕКСТОВЫЙ блок, и
дважды доложила «переполнений нет», пока картинки свисали за низ полосы
(свалка на полстраницы, поле на всю полосу, гексы под колонцифрой). Цифра
врала, потому что мерила не то. Здесь меряется всё: текст, картинки, векторные
рисунки — против одной и той же рамки контента.

Что ищется на полосе:
  * ВЫЛЕТ   — объект ниже низа рамки или вне полей;
  * ПУСТОТА — большой незанятый хвост полосы (доля высоты рамки);
  * МЕЛКО   — текст кеглем ниже порога;
  * НАЛОЖЕНИЕ — текстовые блоки, пересекающиеся друг с другом или с картинкой;
  * ТЕСНО   — соседние блоки без зазора по вертикали.

Запуск: python ревизия.py [book.pdf] — печатает отчёт по полосам и пишет
_ревизия.json рядом.
"""
import json
import os
import sys

import pymupdf

D = os.path.dirname(os.path.abspath(__file__))
# КАКОЙ ФАЙЛ МЕРИМ. Обычно book.pdf; но если его держит открытым просмотрщик,
# сборка кладёт свежую печать рядом, в _book.pdf (см. build.py). Мерить надо
# СВЕЖУЮ — иначе отчёт описывает вчерашнюю книгу и вёрстка правится вслепую.
def _свежий():
    if len(sys.argv) > 1:
        return sys.argv[1]
    осн = os.path.join(D, "book.pdf")
    врем = os.path.join(D, "_book.pdf")
    if os.path.exists(врем) and (not os.path.exists(осн)
                                 or os.path.getmtime(врем) > os.path.getmtime(осн)):
        return врем
    return осн


PDF = _свежий()

# РАМКА КОНТЕНТА в пунктах. Полоса 220 мм = 623.6 pt. Поля страницы .стр по
# CSS: слева/справа 13 мм, сверху 12 мм; низ — колонцифра сидит на 593 pt,
# контент обязан кончаться выше её плашки.
MM = 72 / 25.4
# Поля .стр по CSS: padding 15mm 15mm 16mm — контент живёт внутри них.
ЛЕВО, ПРАВО = 15 * MM, 623.6 - 15 * MM
ВЕРХ = 15 * MM
НИЗ = 623.6 - 13 * MM
# ДОПУСК ПРИВОДКИ: 3 pt чуть больше миллиметра — в эти пределы укладывается
# и резка, и приводка печати. Меньший заход в поле не видно на бумаге.
ДОПУСК = 3.0
МИН_КЕГЛЬ = 7.9                  # pt; мельче — не читается на бумаге

# ПОЛОСЫ ВНЕ ПОТОКА ГЛАВ. У обложки, разворота подготовки, полосы создателей и
# задней памятки своя вёрстка и свои поля: памятка идёт под обрез, подготовка
# держит иллюстрацию во всю полосу. Мерить их общей рамкой значит топить отчёт
# в шуме. Для них проверяются только наложения — рамка и кегль у них свои.
ОСОБЫЕ = {1, 2, 3}               # обложка, мир, содержание
ПОДГОТОВКА = {6, 7}              # разворот подготовки — иллюстрация во всю полосу

# РАМКА ТЕКСТА НА РАЗВОРОТЕ ПОДГОТОВКИ. Иллюстрация там идёт под обрез
# и общей рамкой её мерить нельзя, а вот ТЕКСТ живёт в двух узких столбцах
# и переполняется так же, как всюду. Прежде разворот пропускался целиком —
# и его текст мог уезжать под обрез незамеченным. CSS: .столбец сверху
# 29 мм (левая) и 13 мм (правая), снизу 14 мм, ширина 80 мм.
# Заголовок главы на левой полосе разворота сидит на 12 мм — выше столбцов,
# и это вёрстка, а не вылет. Верхняя граница берётся по нему.
ПОДГ_ВЕРХ = 11 * MM
ПОДГ_НИЗ = 623.6 - 14 * MM
ПАМЯТКА_И_ВЫХОДНЫЕ = 2           # столько последних полос набраны по-своему
ПУСТОТА_ДОЛЯ = 0.28              # свободный хвост больше этой доли — полупустая
ЗАЗОР_МИН = 1.2 * MM             # меньше — блоки слипаются


def прямоугольники(page):
    """Все объекты полосы: текст (с кеглем), картинки, векторные рисунки."""
    объекты = []
    d = page.get_text("dict")
    for b in d["blocks"]:
        if b["type"] != 0:
            continue
        r = pymupdf.Rect(b["bbox"])
        кегли = [s["size"] for l in b["lines"] for s in l["spans"] if s["text"].strip()]
        текст = " ".join(s["text"] for l in b["lines"] for s in l["spans"]).strip()
        if not кегли or not текст:
            continue
        # колонцифра и подписи развёрта не считаются
        if r.y0 > 585 and len(текст) <= 3:
            continue
        объекты.append(("текст", r, min(кегли), текст[:60]))
    for img in page.get_images(full=True):
        for r in page.get_image_rects(img[0]):
            if r.width < 4 or r.height < 4:
                continue
            объекты.append(("картинка", r, None, ""))
    return объекты


def рамка_кайма(r):
    """Векторная кайма и фон занимают всю полосу — их из учёта убираем."""
    return r.width > 560 or r.height > 560


def ревизовать(page, номер, всего=0):
    беды = []
    подготовка = номер in ПОДГОТОВКА
    особая = (номер in ОСОБЫЕ or подготовка
              or (всего and номер > всего - ПАМЯТКА_И_ВЫХОДНЫЕ))
    объекты = [(t, r, k, s) for t, r, k, s in прямоугольники(page) if not рамка_кайма(r)]
    if not объекты:
        return беды, 0
    if подготовка:
        # На развороте подготовки проверяется только текст и только по высоте:
        # иллюстрация там нарочно идёт во всю полосу и под обрез.
        for тип, r, кегль, текст in объекты:
            if тип != "текст":
                continue
            if r.y1 > ПОДГ_НИЗ + ДОПУСК or r.y0 < ПОДГ_ВЕРХ - ДОПУСК:
                беды.append(("ВЫЛЕТ", "текст разворота y=%.0f..%.0f %s"
                                       % (r.y0, r.y1, текст)))
            if кегль < МИН_КЕГЛЬ:
                беды.append(("МЕЛКО", "%.1f pt: %s" % (кегль, текст)))
        return беды, 0
    низ = max(r.y1 for _, r, _, _ in объекты)
    for тип, r, кегль, текст in объекты:
        if особая:
            break
        if r.y1 > НИЗ + ДОПУСК or r.x1 > ПРАВО + ДОПУСК or r.x0 < ЛЕВО - ДОПУСК:
            беды.append(("ВЫЛЕТ", "%s до y=%.0f x=%.0f..%.0f %s" % (тип, r.y1, r.x0, r.x1, текст)))
        if тип == "текст" and кегль < МИН_КЕГЛЬ and номер not in (1, 2):
            беды.append(("МЕЛКО", "%.1f pt: %s" % (кегль, текст)))
    # наложения: текст на текст, текст на картинку
    тексты = [(r, s) for t, r, _, s in объекты if t == "текст"]
    картинки = [r for t, r, _, _ in объекты if t == "картинка"]
    for i, (r1, s1) in enumerate([] if особая else тексты):
        for r2, s2 in тексты[i + 1:]:
            п = r1 & r2
            малый = min(r1.get_area(), r2.get_area()) or 1
            # Кусок строки, отрезанный значком, — высотой в одну строку;
            # его пересечение с соседним куском мнимое.
            строчный = min(r1.height, r2.height) < 14
            if not п.is_empty and п.get_area() / малый > 0.25 and not строчный:
                беды.append(("НАЛОЖЕНИЕ", "текст на текст: «%s» / «%s»" % (s1[:30], s2[:30])))
        for rk in картинки:
            п = r1 & rk
            # выноски на рисунках — это буквы внутри картинки, их не считаем
            малый = min(r1.get_area(), rk.get_area()) or 1
            # Буквица стоит ВНУТРИ своего абзаца и обтекается им — это вёрстка,
            # а не наложение. Признак: середина картинки лежит в блоке текста.
            центр = pymupdf.Point((rk.x0 + rk.x1) / 2, (rk.y0 + rk.y1) / 2)
            if not п.is_empty and п.get_area() / малый > 0.25 and len(s1) > 3 \
                    and not rk.contains(r1) and not r1.contains(центр):
                беды.append(("НАЛОЖЕНИЕ", "текст на картинку: «%s»" % s1[:40]))
    # пустой хвост
    доля_пустоты = (НИЗ - низ) / (НИЗ - ВЕРХ)
    if доля_пустоты > ПУСТОТА_ДОЛЯ and not особая:
        беды.append(("ПУСТОТА", "свободно %.0f%% полосы снизу" % (доля_пустоты * 100)))
    return беды, доля_пустоты


def main():
    doc = pymupdf.open(PDF)
    отчёт = {}
    # ЗАНЯТОСТЬ КАЖДОЙ ПОЛОСЫ — доля рамки, которую занял контент.
    # Нужна верстальщику: по одному «пусто/не пусто» он гонял абзацы
    # туда-сюда бесконечно: подтянет большой кусок в полупустую полосу —
    # та переполнится, следующим кругом отдаст обратно.
    занятость = {}
    итог = {"ВЫЛЕТ": 0, "ПУСТОТА": 0, "МЕЛКО": 0, "НАЛОЖЕНИЕ": 0}
    for i, page in enumerate(doc, start=1):
        беды, пустота = ревизовать(page, i, len(doc))
        занятость[str(i)] = round(1.0 - пустота, 4)
        if беды:
            отчёт[i] = беды
            print("стр %2d:" % i)
            виды = {}
            for вид, что in беды:
                виды.setdefault(вид, []).append(что)
            for вид, список in виды.items():
                итог[вид] = итог.get(вид, 0) + 1
                print("   %-10s ×%d  %s" % (вид, len(список), список[0][:90]))
    print("\nполос:", len(doc), "| кратно четырём:", "да" if len(doc) % 4 == 0 else "НЕТ (%d)" % (len(doc) % 4))
    print("полос с бедами:", len(отчёт), "|", ", ".join("%s %d" % kv for kv in итог.items()))
    with open(os.path.join(D, "_ревизия.json"), "w", encoding="utf-8") as f:
        json.dump({"беды": {str(k): v for k, v in отчёт.items()},
                   "занятость": занятость,
                   "полос": len(doc)},
                  f, ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
