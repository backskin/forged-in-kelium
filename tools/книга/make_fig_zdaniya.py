# -*- coding: utf-8 -*-
"""Рисунки главы 4: нейтральная постройка и обороты жетонов зданий.

Оборот жетона — то, чем он становится, когда его уничтожили: на нём
напечатано, сколько трофеев он даёт и сколько карт контейнеров получает
владелец. В книге этого не было вовсе (замечание дизайнера 15.09.2026).

Соответствие «лицо → оборот» не подбиралось на глаз: обороты из папки
дизайнера совпали пиксель в пиксель с трофейными сторонами из набора текстур
движка (`token/*_trophy.png`), и отсюда известно, какой оборот чей.
"""
import os

from PIL import Image, ImageDraw, ImageFont

D = os.path.dirname(os.path.abspath(__file__))
ns = {"__file__": os.path.join(D, "figs.py")}
exec(open(os.path.join(D, "figs.py"), encoding="utf-8-sig").read().split("# планшет войск")[0], ns)
figure = ns["figure"]

Ж = r"C:\shared\Yandex.Disk\Forged in Kelium\Компоненты игрока\Жетоны"
ШРИФТ = r"C:\Windows\Fonts\TekturNarrow-Bold.ttf"

# ---------------------------------------------------------------- нейтральная

# Нейтральная постройка на 2 сектора, 736×428 — тот же формат, что казарма.
НЕЙТР = os.path.join(Ж, "_нейтральные", "жетоны зданий-61.png")
figure("жетон-нейтральный", НЕЙТР, 900, 736, 428, [
    ("А", 150, 300, -150, 300),      # сердечки прочности
    ("Б", 330, 150, 330, -120),      # силуэт гарнизона
    ("В", 600, 90, 880, 60),         # знак постройки
], css_w="82%", pad="1mm 0 2mm", в_колонке=True)

# ---------------------------------------------------------------- обороты

ПАРЫ = [
    (os.path.join(Ж, "Красный", "жетоны зданий-41.png"),
     os.path.join(Ж, "_оборот", "жетоны зданий-57.png"), "казарма"),
    (os.path.join(Ж, "Красный", "жетоны зданий-5.png"),
     os.path.join(Ж, "_оборот", "жетоны зданий-34.png"), "добытчик №2"),
]

H = 420
ЗАЗОР = 46
СТРЕЛКА = 130
подпись = ImageFont.truetype(ШРИФТ, 62)


def взять(путь):
    im = Image.open(путь).convert("RGBA")
    return im.resize((round(im.width * H / im.height), H), Image.LANCZOS)


блоки = []
for лицо, оборот, имя in ПАРЫ:
    a, b = взять(лицо), взять(оборот)
    ш = a.width + СТРЕЛКА + b.width
    к = Image.new("RGBA", (ш, H + 84), (0, 0, 0, 0))
    к.paste(a, (0, 0), a)
    к.paste(b, (a.width + СТРЕЛКА, 0), b)
    d = ImageDraw.Draw(к)
    y = H // 2
    x0 = a.width + 18
    x1 = a.width + СТРЕЛКА - 18
    d.line((x0, y, x1, y), fill=(24, 108, 36, 255), width=9)
    d.polygon([(x1 + 14, y), (x1 - 8, y - 15), (x1 - 8, y + 15)], fill=(24, 108, 36, 255))
    ш_п = d.textlength(имя, font=подпись)
    d.text(((ш - ш_п) / 2, H + 14), имя, font=подпись, fill=(42, 35, 24, 255))
    блоки.append(к)

ПРОМЕЖ = 110
W = sum(b.width for b in блоки) + ПРОМЕЖ * (len(блоки) - 1)
холст = Image.new("RGBA", (W, max(b.height for b in блоки)), (0, 0, 0, 0))
x = 0
for b in блоки:
    холст.paste(b, (x, 0), b)
    x += b.width + ПРОМЕЖ
png = os.path.join(D, "_обороты.png")
холст.save(png)
figure("обороты", png, 1500, холст.width, холст.height, [],
        css_w="82%", pad="1mm 0 1.2mm")
print("ok", холст.size)
