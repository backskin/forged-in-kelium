# -*- coding: utf-8 -*-
"""Рисунок главы 4: карта контейнера — рубашка и лицо.

Контейнеры до сих пор объяснялись только словами. Дизайнер просит показать
саму карту там же, где объясняется её место под планшетом войск (15.09.2026).
Карта печатается квадратом 34×34 мм — отсюда скругление углов.

ПОЛЯ ХОЛСТА НЕ ДЛЯ КРАСОТЫ: все значки выносок должны лежать ВНУТРИ вьюбокса,
иначе они улетают за пределы рисунка и всплывают выше заголовка полосы —
ровно это дизайнер видел на странице 21 (15.09.2026).
"""
import os

from PIL import Image

D = os.path.dirname(os.path.abspath(__file__))
ns = {"__file__": os.path.join(D, "figs.py")}
exec(open(os.path.join(D, "figs.py"), encoding="utf-8-sig").read().split("# планшет войск")[0], ns)
figure, карта = ns["figure"], ns["карта"]

G = r"C:\shared\Yandex.Disk\Forged in Kelium"
ЛИЦО = os.path.join(G, "Общие компоненты", "экспорт-контейнеры", "контейнеры-new-1.png")
РУБАШКА = os.path.join(G, "Общие компоненты", "экспорт-рубашки", "контейнеры.png")

S = 402
ВЕРХ, ПРАВО, ЗАЗОР = 170, 300, 150
лицо = карта(ЛИЦО, "контейнер", ширина=S)
руб = карта(РУБАШКА, "контейнер", ширина=S)

dx = S + ЗАЗОР
W, H = dx + S + ПРАВО, ВЕРХ + S
холст = Image.new("RGBA", (W, H), (0, 0, 0, 0))
холст.paste(руб, (0, ВЕРХ), руб)
холст.paste(лицо, (dx, ВЕРХ), лицо)
png = os.path.join(D, "_карта-контейнера.png")
холст.save(png)

зн = W - 130
figure("карта-контейнера", png, 1200, W, H, [
    ("А", 201, ВЕРХ + 200, 201, 62),
    ("Б", dx + 201, ВЕРХ + 129, dx + 201, 62),
    ("В", dx + 201, ВЕРХ + 250, зн, 250),
    ("Г", dx + 152, ВЕРХ + 333, зн, 370),
    ("Д", dx + 238, ВЕРХ + 336, зн, 490),
], css_w="100%", pad="1.0mm 0 0.6mm", в_колонке=True)
print("ok", (W, H))
