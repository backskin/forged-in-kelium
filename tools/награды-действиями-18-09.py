# -*- coding: utf-8 -*-
"""НАГРАДЫ ЗАДАНИЙ — ДЕЙСТВИЯ, А НЕ РЕСУРСЫ (ревизия дизайнера 18.09.2026).

Дословно: «не ресурсы ебаные давать заданием, а именно действия — которые ты
не успел отыграть. Выполнив задание, получить действие, которое оно предлагает».
И отдельно: «у нас 40 карт, а действий 8 — это 5 карт на действие».

Действий в игре восемь, но СМЕНА ЭНЕРГИИ из наград убрана — она и так стоит
в утиле семи карт, и второй раз ей там делать нечего («я бы её убрал»).
Восьмым местом встаёт ПОЗОЛОЧЕНИЕ МОДУЛЯ: дизайнер просил его в награды
отдельной строкой, и оно того же рода, что действие, — прогресс, а не ресурс.

    Стройка 5 · Снаряжение 5 · Добыча 5 · Манёвр 5
    Бой 5 · Рынок 5 · Наука 5 · Позолочение 5          = 40

РЕСУРС НЕ ИСЧЕЗ — он переехал целиком в УСИЛЕННУЮ награду, а она с 18.09.2026
берётся ВМЕСТЕ с базовой. Поэтому карта даёт действие И ресурс тому, кто
выполнил усиленное требование, и одно действие тому, кто выполнил простое.
Это же снимает единственное возражение против наград-действиями: действие
бывает нечем сыграть (нет денег на Стройку, нет боеприпасов на Бой) — но
ресурс с усиления приходит всегда.

Раздача идёт ПО СЕМЕЙСТВАМ: награда обязана отвечать тому, чем карта занята.
Выработка кормит Добычей и Рынком, Развёртывание — Снаряжением и Стройкой,
Устранение — Боем и Манёвром, Расплата — Наукой и позолотой.

Запуск: python tools/награды-действиями-18-09.py
Меняет таблицу-эталон: обнуляет колонки базовых ресурсов и заполняет новую
колонку «Награда: действие». Колоду пересобирает `занести-задания-18-09.py`.
"""

import csv
import io
import os
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ТАБЛИЦА = os.path.join(КОРЕНЬ, "data", "cards", "эталон",
                       "задания-40-таблица-дизайнера-18.09.2026.csv")
КОЛОНКА = "Награда: действие"

# Колонки базовой награды: их содержимое обнуляется — ресурс ушёл в усиление.
БАЗОВЫЕ_РЕСУРСЫ = ["монеты", "боеприпасы", "карты задания", "трофеи",
                   "карта арсенала", "жетон модуля атаки"]

СТРОЙКА = "СТРОЙКА"
СНАРЯЖЕНИЕ = "СНАРЯЖЕНИЕ"
ДОБЫЧА = "ДОБЫЧА"
МАНЁВР = "МАНЁВР"
БОЙ = "БОЙ"
РЫНОК = "РЫНОК"
НАУКА = "НАУКА"
ПОЗОЛОТА = "ПОЗОЛОЧЕНИЕ МОДУЛЯ"

РАЗДАЧА = {
    # Выработка (5) — хозяйство: добывает и торгует
    1: ДОБЫЧА, 2: ДОБЫЧА, 3: ДОБЫЧА, 4: РЫНОК, 5: РЫНОК,
    # Засада (5) — бой из укрытия и подход к нему
    6: БОЙ, 7: БОЙ, 8: МАНЁВР, 9: МАНЁВР, 10: ПОЗОЛОТА,
    # Обеспечение (4) — снабжение: производство и торговля
    11: СНАРЯЖЕНИЕ, 12: СНАРЯЖЕНИЕ, 13: РЫНОК, 14: РЫНОК,
    # Развёртывание (7) — производит и строит
    15: СНАРЯЖЕНИЕ, 16: СНАРЯЖЕНИЕ, 17: СНАРЯЖЕНИЕ,
    18: СТРОЙКА, 19: СТРОЙКА, 20: СТРОЙКА, 21: МАНЁВР,
    # Расплата (4) — долгая отдача: наука и позолота
    22: НАУКА, 23: НАУКА, 24: ПОЗОЛОТА, 25: ПОЗОЛОТА,
    # Устранение (10) — самое воинственное
    26: БОЙ, 27: БОЙ, 28: БОЙ, 29: МАНЁВР, 30: МАНЁВР,
    31: НАУКА, 32: НАУКА, 33: ПОЗОЛОТА, 34: ПОЗОЛОТА, 35: ДОБЫЧА,
    # Экспансия (5) — расширение вширь
    36: СТРОЙКА, 37: СТРОЙКА, 38: ДОБЫЧА, 39: РЫНОК, 40: НАУКА,
}


def main():
    with io.open(ТАБЛИЦА, encoding="utf-8-sig", newline="") as f:
        читатель = csv.DictReader(f)
        колонки = list(читатель.fieldnames)
        строки = list(читатель)

    if КОЛОНКА not in колонки:
        # Колонка встаёт СРАЗУ ЗА «Усилением»: базовая награда читается раньше
        # усиленной, как и на самой карте.
        место = колонки.index("Усиление") + 1 if "Усиление" in колонки else len(колонки)
        колонки.insert(место, КОЛОНКА)

    for с in строки:
        n = int(с["№"])
        с[КОЛОНКА] = РАЗДАЧА[n]
        for кол in БАЗОВЫЕ_РЕСУРСЫ:
            if кол in с:
                с[кол] = "0"

    with io.open(ТАБЛИЦА, "w", encoding="utf-8-sig", newline="") as f:
        писец = csv.DictWriter(f, fieldnames=колонки)
        писец.writeheader()
        писец.writerows(строки)

    счёт = {}
    for с in строки:
        счёт[с[КОЛОНКА]] = счёт.get(с[КОЛОНКА], 0) + 1
    print("базовые награды роздана:")
    for н, k in sorted(счёт.items(), key=lambda p: -p[1]):
        print("  %2d  %s" % (k, н))
    print("\nвсего %d карт, разных наград %d" % (len(строки), len(счёт)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
