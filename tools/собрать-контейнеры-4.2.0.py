# -*- coding: utf-8 -*-
"""КОНТЕЙНЕРЫ 4.2.0 — набор дизайнера от 02.09.2026 (32 карты).

Дизайнер прислал таблицу состава. От 4.1.0 она отличается ровно четырьмя
картами, число карт прежнее — 32:
    «2 монеты»      2 -> 1
    «арсенал»       2 -> 1
    «трофей»        2 -> 3   (трофей — это ТРОФЕЙ, уточнено 01.09.2026)
    «2 боеприпаса»  0 -> 1   (новая форма)
Остальные одиннадцать форм и их количества не менялись.

Освободившиеся места отданы новым картам, а не выброшены: c13 (был вторым
«2 монеты») стал «2 боеприпаса», c15 (был вторым арсеналом) — третьим
трофейным. Так номера карт остаются на своих местах, и старые записи партий
читаются без сюрпризов.

Запуск: python tools/собрать-контейнеры-4.2.0.py
"""
import io

import yaml

ИСТОЧНИК = 'data/cards/containers.4.1.0.yaml'
ЦЕЛЬ = 'data/cards/containers.4.2.0.yaml'

# Что положить на освободившиеся места: id -> (имя, эффект, описание)
ЗАМЕНЫ = {
    'c13': ('Ящик боекомплекта',
            {'effect': 'gain', 'params': {'ammo': 2}, 'label': '2 боеприпаса'},
            'Ящик с полным боекомплектом, снятый с подбитой машины. '
            'Заберите 2 боеприпаса.'),
    'c15': ('Разбитый остов',
            {'effect': 'gain', 'params': {'trophy': 1}, 'label': '1 трофей'},
            'Остов машины, догоревшей ещё в прошлом бою. Возьмите 1 трофей.'),
}

ШАПКА = """# CONTENT: containers  version 4.2.0
# ============================================================================
#  КОНТЕЙНЕРЫ 4.2 - НАБОР ДИЗАЙНЕРА 02.09.2026 (32 карты)
# ============================================================================
#  Состав прислан таблицей. Против 4.1.0 разошлись ровно четыре карты, всего
#  карт по-прежнему 32:
#    «2 монеты»      2 -> 1
#    «арсенал»       2 -> 1
#    «трофей»        2 -> 3
#    «2 боеприпаса»  0 -> 1  (новая форма)
#  «Трофей» в таблице дизайнера - это ТРОФЕЙ (Resource.TROPHY), уточнено
#  01.09.2026; жетон destroyedTokens из боя тут ни при чём.
#
#  Освободившиеся места отданы новым картам, а не выброшены: c13 стал
#  «2 боеприпаса», c15 - третьим трофейным. Номера остальных карт не
#  сдвинулись, поэтому прежние записи партий читаются как есть.
#
#  СОСТАВ ЦЕЛИКОМ (форма - сколько карт):
#    монета + боеприпас 3, задание + келемий 3, задание + боеприпас 3,
#    2 задания 2, 2 монеты 1, 2 боеприпаса 1, арсенал 1, келемий 3,
#    трофей 3, задание 4, монета 3, боеприпас 3, 1 пехота 1, 1 техника 1.
"""

# Таблица дизайнера, ключ - что именно выдаёт карта.
ОЖИДАЕМО = {
    (('ammo', 1), ('coin', 1)): 3,
    (('kelium', 1), ('objective_cards', 1)): 3,
    (('ammo', 1), ('objective_cards', 1)): 3,
    (('objective_cards', 2),): 2,
    (('coin', 2),): 1,
    (('ammo', 2),): 1,
    (('arsenal', 1),): 1,
    (('kelium', 1),): 3,
    (('trophy', 1),): 3,
    (('objective_cards', 1),): 4,
    (('coin', 1),): 3,
    (('ammo', 1),): 3,
    ('десант', 'infantry'): 1,
    ('десант', 'vehicle'): 1,
}


def форма(c):
    """Что карта выдаёт - в виде ключа, по которому её можно сосчитать."""
    a = c['a']
    if a['effect'] == 'landing':
        return ('десант',) + tuple(a['params']['types'])
    return tuple(sorted((k, int(v)) for k, v in a['params'].items()))


def main():
    d = yaml.safe_load(io.open(ИСТОЧНИК, encoding='utf-8').read())
    карты = []
    for c in d['containers']:
        c = dict(c)
        if c['id'] in ЗАМЕНЫ:
            имя, эффект, описание = ЗАМЕНЫ[c['id']]
            c['name'] = имя
            c['a'] = эффект
            c['описание'] = описание
        карты.append(c)

    # Сверка с таблицей дизайнера: считаем формы, а не верим глазам.
    from collections import Counter
    сводка = Counter(форма(c) for c in карты)
    if сводка != Counter(ОЖИДАЕМО):
        for ключ in sorted(set(сводка) | set(ОЖИДАЕМО), key=str):
            if сводка.get(ключ, 0) != ОЖИДАЕМО.get(ключ, 0):
                print(f'  РАСХОЖДЕНИЕ {ключ}: вышло {сводка.get(ключ, 0)}, '
                      f'в таблице {ОЖИДАЕМО.get(ключ, 0)}')
        raise SystemExit('состав не совпал с таблицей дизайнера')
    if len(карты) != 32:
        raise SystemExit(f'карт {len(карты)}, а надо 32')

    d['meta'] = {'id': '4.2.0', 'type': 'containers'}
    d['containers'] = карты
    io.open(ЦЕЛЬ, 'w', encoding='utf-8').write(
        ШАПКА + yaml.safe_dump(d, allow_unicode=True, sort_keys=False, width=100))
    print(f'готово: {ЦЕЛЬ}, карт {len(карты)}')
    for ключ, сколько in sorted(сводка.items(), key=str):
        print(f'  {str(ключ):46s} {сколько}')


if __name__ == '__main__':
    main()
