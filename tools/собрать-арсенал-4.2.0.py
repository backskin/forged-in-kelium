# -*- coding: utf-8 -*-
"""АРСЕНАЛ 4.2.0 — двадцать восемь РАЗНЫХ карт, без копий.

Заказ дизайнера 31.08.2026. В 4.1.0 колода из 28 мест собиралась как 20 карт,
восемь из которых лежали в двух копиях. Теперь нужно 28 РАЗНЫХ: копии убраны,
вместо них возвращены восемь карт из семнадцати выброшенных.

КАК ВЫБРАНЫ ВОСЕМЬ. Пять — по замеру толка (установки плюс применения за 80
партий), это единственные из выброшенных, у кого он вообще был:
    v04 Второй эшелон  4
    b03 Облегчённая броня  3
    b11 Энергосбыт  3
    b21 Маркшейдер  3
    b13 Трофейный склад  2
У остальных двенадцати толк ноль, и замер про них не говорит НИЧЕГО — значит
выбирать надо по правилу дизайнера: арсенал ускоряет то действие, которого
игроку не хватает, плюс военные способности. По нему взяты три:
    b06 Мобилизация    — СПЕЦ: боеприпас и найм любым запитанным зданием.
                         Прямо в сегодняшнюю беду: войск на поле мало.
    b25 Второй контур  — второй гекс Смены энергии без надбавки. Тоже в
                         сегодняшнюю находку: энергию надо перекатывать, и
                         именно на этом стояла незапитанная авиабаза.
    b14 Наводчик       — в Бою цель на расстоянии 2, если на гексе своя
                         авиация; верх даёт лишний Бой. Военная карта, и она
                         даёт авиации смысл, которого у неё сейчас нет.
Все восемь пассивок проверены на реализованность в движке — мёртвых нет.

Запуск: python (этот файл) из корня репозитория.
"""
import io

import yaml

ИСТОЧНИК = 'data/cards/arsenal.3.0.0.yaml'
ЦЕЛЬ = 'data/cards/arsenal.4.2.0.yaml'

# Двадцать из 4.1.0 (лучшие по толку) плюс восемь возвращённых.
ДВАДЦАТЬ = ['b04', 'b05', 'b07', 'b08', 'b16', 'b09', 'v02', 'b10', 'b31',
            'b15', 'b20', 'b27', 'b23', 'b24', 'b22', 'b30', 'v05', 'v01',
            'b26', 'b12']
ВОЗВРАЩЁННЫЕ = ['v04', 'b03', 'b11', 'b21', 'b13', 'b06', 'b25', 'b14']

ШАПКА = """# CONTENT: arsenal  version 4.2.0
# ============================================================================
#  ОБЫЧНЫЙ АРСЕНАЛ — 28 РАЗНЫХ КАРТ, БЕЗ КОПИЙ
# ============================================================================
#  Заказ дизайнера 31.08.2026. В 4.1.0 те же 28 мест колоды складывались из 20
#  карт, восемь из которых лежали в двух копиях. Здесь 28 РАЗНЫХ: копии сняты,
#  вместо них возвращены восемь карт из семнадцати выброшенных.
#
#  Пять возвращены по замеру толка (установки плюс применения, 80 партий) - это
#  единственные из выброшенных, у кого он был вообще: v04 (4), b03, b11, b21 (3),
#  b13 (2). У остальных двенадцати толк ноль, и замер про них не говорит ничего,
#  поэтому три последние выбраны по правилу дизайнера «арсенал ускоряет то
#  действие, которого не хватает, плюс военные способности»:
#    b06 «Мобилизация»   - СПЕЦ за боеприпас нанимает любым запитанным зданием;
#    b25 «Второй контур» - второй гекс Смены энергии без надбавки;
#    b14 «Наводчик»      - в Бою цель на расстоянии 2 при своей авиации.
#  Первые две бьют в найденные сегодня узкие места (мало войск, энергия не
#  перекатывается), третья даёт авиации смысл. Все восемь пассивок проверены на
#  реализованность в движке.
#
#  ЧЕМ ПОЖЕРТВОВАЛИ. Копии затевались, чтобы сильная карта не была монополией
#  одного игрока. Разных карт теперь больше, но каждая снова в единственном
#  экземпляре - это осознанный размен разнообразия на неповторимость.
#
#  Стартовые 8 - без изменений, все уникальные.
"""


def main():
    d = yaml.safe_load(io.open(ИСТОЧНИК, encoding='utf-8').read())
    все = {c['id']: c for c in d['arsenal']}
    нужны = ДВАДЦАТЬ + ВОЗВРАЩЁННЫЕ
    нет = [i for i in нужны if i not in все]
    if нет:
        raise SystemExit(f'нет в наборе-источнике: {нет}')

    out = []
    # Порядок как в источнике: так проще сверять глазами с прежними наборами.
    for c in d['arsenal']:
        if c.get('kind') == 'starting':
            out.append(c)
        elif c['id'] in нужны:
            c = dict(c)
            c.pop('copies', None)      # копий больше нет ни у одной карты
            out.append(c)

    обычных = [c for c in out if c.get('kind') != 'starting']
    стартовых = [c for c in out if c.get('kind') == 'starting']
    if len(обычных) != 28:
        raise SystemExit(f'обычных вышло {len(обычных)}, а надо 28')

    io.open(ЦЕЛЬ, 'w', encoding='utf-8').write(
        ШАПКА + yaml.safe_dump({'meta': {'id': '4.2.0'}, 'arsenal': out},
                               allow_unicode=True, sort_keys=False, width=100))
    print(f'обычных: {len(обычных)}, стартовых: {len(стартовых)}, '
          f'копий: {sum(c.get("copies", 1) - 1 for c in обычных)}')
    print('возвращены:', ', '.join(f"{i} «{все[i].get('name')}»" for i in ВОЗВРАЩЁННЫЕ))


if __name__ == '__main__':
    main()
