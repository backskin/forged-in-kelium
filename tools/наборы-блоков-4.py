    база = ЗЕРНО + номер * 1000000
    for попытка in range(ПОПЫТОК):
        разметка = собрать(стороны, база + попытка, энергии, контейнеров)
        if разметка is None:
            continue
        if проверить(стороны, разметка, энергии, контейнеров):
            continue
        замеры = замер(стороны, разметка)
        записать(стороны, разметка, замеры, версия, база + попытка,
                 энергии, контейнеров, эталон)
        кон = max(int(з['контейнеры'].split()[2].rstrip(','))
                  for з in замеры.values())
        эн = max(int(з['энергия'].split()[2].rstrip(',')) for з in замеры.values())
        return ('%s — готово с попытки %d: контейнеры %d/%d, энергия %d/%d, '
                'наибольшее совпадение конт %d, энерг %d'
                % (версия, попытка + 1, контейнеров['small'], контейнеров['big'],
                   энергии['small'], энергии['big'], кон, эн))
    return ('%s — НЕ СОШЛОСЬ за %d попыток: предел совпадений %d этим сочетанием '
            'недостижим' % (версия, ПОПЫТОК, ПРЕДЕЛ_СОВПАДЕНИЙ))


