# -*- coding: utf-8 -*-
"""
РАЗМЕТКА ЗОН ЖЕТОНОВ ЗДАНИЙ — из масок дизайнера.

Дизайнер рисует ОДНУ маску на форму здания (казармы, завод, авиабаза, ЦУ,
добытчик с одной и с двумя ячейками), а жетонов у каждой формы четыре — по
цвету игрока. Этот скрипт раскладывает маску по всем четырём и кладёт рядом с
текстурой файл <ключ>.zones.png, который читает kelium.report.Zones.

ЦВЕТА ДИЗАЙНЕРА (11.09.2026):
    жёлтый    #EEEB00  — ячейка под энергию (по одной на квадрат)
    белый     #FEFEFE  — гнездо гарнизона: куда кладут жетон войска внутри
    оранжевый #F5C255  — площадь появления свободной энергии (ЦУ)
    чёрный             — силуэт жетона, нужен только чтобы совместить маску
                         с текстурой; в разметку не идёт

СЕРДЦА ПРОЧНОСТИ дизайнер не размечает — они переносятся розовыми пятнами из
прежней маски того же жетона, если она была.

РАЗМЕР МАСКИ МОЖЕТ НЕ СОВПАСТЬ с размером текстуры (экспорт бывает выше на
десяток пикселей). Совмещаем не на глаз: пробуем натянуть, прижать к верху и
прижать к низу, и берём то, где силуэт маски лучше всего ложится на непрозрачную
часть текстуры.

Запуск:  python tools/gen_token_zones.py
"""

import os
import sys

from PIL import Image
import numpy as np

КОРЕНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ПАПКА = os.path.join(КОРЕНЬ, "data", "textures", "token")
# Маски дизайнера лежат отдельной папкой: в token/ по именам файлов ищутся
# ТЕКСТУРЫ, и посторонний png там читался бы как жетон.
МАСКИ = os.path.join(ПАПКА, "маски-дизайнера")

# какая маска на какие ключи текстур ложится
РАСКЛАД = {
    "жетоны зданий казармы.png": ["barracks_p%d"],
    "жетоны зданий завод.png": ["factory_p%d"],
    "жетоны зданий авиабаза.png": ["airbase_p%d"],
    "жетоны зданий ЦУ.png": ["command_center_p%d"],
    # ячеек энергии у добытчика столько, сколько написано в boards.3.0.0.yaml:
    # уровни 1 и 3 просят две, уровни 2 и 4 — одну
    "жетоны зданий добытчик 2 энергии.png": ["miner_l1_p%d", "miner_l3_p%d"],
    "жетоны зданий добытчик 1 энергии.png": ["miner_l2_p%d", "miner_l4_p%d"],
}

РОЗОВЫЙ = (255, 0, 255, 255)


def маска_цвета(a, проверка):
    return проверка(a[..., 0], a[..., 1], a[..., 2]) & (a[..., 3] > 128)


def жёлтый(r, g, b):
    return (r > 140) & (g > 140) & (b < 60) & (abs(r - g) < 70)


def белый(r, g, b):
    return (r > 200) & (g > 200) & (b > 200)


def оранжевый(r, g, b):
    return (r > 180) & (g > 120) & (g < 230) & (b >= 40) & (b < 160)


def совместить(маска, размер):
    """Маска дизайнера → полотно текстуры. Возвращает (картинка, как совмещали)."""
    W, H = размер
    if маска.size == (W, H):
        return маска, "точно"
    цели = []
    цели.append(("натянуть", маска.resize((W, H), Image.NEAREST)))
    for имя, сверху in (("по верху", 0), ("по низу", H - маска.size[1])):
        полотно = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        полотно.paste(маска, (0, сверху))
        цели.append((имя, полотно))
    return цели


def лучшее(маска, текстура):
    W, H = текстура.size
    силуэт_текстуры = np.array(текстура)[..., 3] > 16
    варианты = совместить(маска, (W, H))
    if isinstance(варианты, tuple):
        return варианты
    лучший = None
    for имя, картинка in варианты:
        силуэт = np.array(картинка)[..., 3] > 128
        общее = (силуэт | силуэт_текстуры).sum()
        доля = (силуэт & силуэт_текстуры).sum() / max(1, общее)
        if лучший is None or доля > лучший[0]:
            лучший = (доля, имя, картинка)
    return лучший[2], "%s (совпадение %.3f)" % (лучший[1], лучший[0])


def сделать(файл_маски, ключ):
    текстура = Image.open(os.path.join(ПАПКА, ключ + ".png")).convert("RGBA")
    маска = Image.open(os.path.join(МАСКИ, файл_маски)).convert("RGBA")
    легла, как = лучшее(маска, текстура)
    a = np.array(легла).astype(int)

    W, H = текстура.size
    out = np.zeros((H, W, 4), dtype=np.uint8)
    # Цвета дизайнера кладём КАК ЕСТЬ: Zones читает и их, и прежнюю палитру.
    for проверка in (жёлтый, белый, оранжевый):
        сюда = маска_цвета(a, проверка)
        out[сюда] = a[сюда].astype(np.uint8)

    # СЕРДЦА — из прежней маски: дизайнер их не размечает.
    сердец = 0
    прежняя = os.path.join(ПАПКА, ключ + ".zones.png")
    if os.path.exists(прежняя):
        p = np.array(Image.open(прежняя).convert("RGBA")).astype(int)
        if p.shape[0] == H and p.shape[1] == W:
            розовое = ((p[..., 0] > 140) & (p[..., 2] > 140) & (p[..., 1] < 110)
                       & (p[..., 3] > 128))
            свободно = розовое & (out[..., 3] == 0)
            out[свободно] = РОЗОВЫЙ
            сердец = int(свободно.sum())

    Image.fromarray(out, "RGBA").save(прежняя)
    return как, сердец


def главная():
    if not os.path.isdir(МАСКИ):
        print("нет папки с масками дизайнера:", МАСКИ)
        return 1
    всего = 0
    for файл, шаблоны in РАСКЛАД.items():
        путь = os.path.join(МАСКИ, файл)
        if not os.path.exists(путь):
            print("ПРОПУСК, нет маски:", файл)
            continue
        for шаблон in шаблоны:
            for место in range(1, 5):
                ключ = шаблон % место
                if not os.path.exists(os.path.join(ПАПКА, ключ + ".png")):
                    print("ПРОПУСК, нет текстуры:", ключ)
                    continue
                как, сердец = сделать(файл, ключ)
                print("%-20s %-14s %s, сердец %d" % (ключ, файл[14:-4], как, сердец))
                всего += 1
    print("готово, разметок:", всего)
    return 0


if __name__ == "__main__":
    sys.exit(главная())
