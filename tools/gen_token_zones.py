# ---------------------------------------------------------------- цвета маски
def маска_цвета(a, проверка):
    return проверка(a[..., 0], a[..., 1], a[..., 2]) & (a[..., 3] > 128)


def жёлтый(r, g, b):
    return (r > 140) & (g > 140) & (b < 60) & (abs(r - g) < 70)


def белый(r, g, b):
    return (r > 200) & (g > 200) & (b > 200)


def оранжевый(r, g, b):
    return (r > 180) & (g > 120) & (g < 230) & (b >= 40) & (b < 160)


def синий(r, g, b):
    return (b > 140) & (r < 110)


# ------------------------------------------------------ совмещение маски
def совместить(маска, размер):
    """Маска дизайнера → полотно текстуры: натянуть, прижать к верху или к низу."""
    W, H = размер
    if маска.size == (W, H):
        return [("точно", маска)]
    цели = [("натянуть", маска.resize((W, H), Image.NEAREST))]
    for имя, сверху in (("по верху", 0), ("по низу", H - маска.size[1])):
        полотно = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        полотно.paste(маска, (0, сверху))
        цели.append((имя, полотно))
    return цели


def лучшее(маска, текстура):
    силуэт_текстуры = np.array(текстура)[..., 3] > 16
    лучший = None
    for имя, картинка in совместить(маска, текстура.size):
        силуэт = np.array(картинка)[..., 3] > 128
        доля = (силуэт & силуэт_текстуры).sum() / max(1, (силуэт | силуэт_текстуры).sum())
        if лучший is None or доля > лучший[0]:
            лучший = (доля, имя, картинка)
    return np.array(лучший[2]).astype(int), "%s %.3f" % (лучший[1], лучший[0])


# ------------------------------------------------------ сдвиг за печатью
def эталон(ключ):
    """Прежняя текстура из коммита ЭТАЛОН (по ней рисовалась маска) или None."""
    try:
        байты = subprocess.run(
            ["git", "-C", КОРЕНЬ, "show", "%s:data/textures/token/%s.png" % (ЭТАЛОН, ключ)],
            capture_output=True, check=True).stdout
        return Image.open(io.BytesIO(байты)).convert("RGBA")
    except Exception:
        return None


def контур(img):
    g = np.array(img.convert("L")).astype(float)
    a = np.array(img)[..., 3] > 128
    return np.hypot(ndimage.sobel(g, 1), ndimage.sobel(g, 0)) * a


def сдвиг(старая, новая, область, радиус=40):
    """Куда уехал кусок печати под областью маски: (dx, dy, качество)."""
    if старая is None or старая.size != новая.size:
        return 0, 0, float("nan")
    ys, xs = np.nonzero(область)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    go, gn = контур(старая), контур(новая)
    H, W = gn.shape
    t = go[y0:y1, x0:x1]
    t = (t - t.mean()) / (t.std() + 1e-9)

    def оценка(dx, dy):
        if y0 + dy < 0 or x0 + dx < 0 or y1 + dy > H or x1 + dx > W:
            return -1.0
        p = gn[y0 + dy:y1 + dy, x0 + dx:x1 + dx]
        return float((t * (p - p.mean()) / (p.std() + 1e-9)).mean())

    лучшая = max(((оценка(dx, dy), dx, dy) for dy in range(-радиус, радиус + 1, 2)
                  for dx in range(-радиус, радиус + 1, 2)))
    _, bx, by = лучшая
    лучшая = max(((оценка(dx, dy), dx, dy) for dy in range(by - 2, by + 3)
                  for dx in range(bx - 2, bx + 3)))
    return лучшая[1], лучшая[2], лучшая[0]


def сдвинуть(область, dx, dy):
    out = np.zeros_like(область)
    H, W = область.shape
    ys, xs = np.nonzero(область)
    xs, ys = xs + dx, ys + dy
    ок = (xs >= 0) & (ys >= 0) & (xs < W) & (ys < H)
    out[ys[ок], xs[ок]] = True
    return out


# ------------------------------------------------------ печать: сердца и ячейки
def сердца(a):
    """Пятна сердец (с белым крестом внутри) и число крестов."""
    r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    видно = al > 200
    лицо = видно & (r > 200) & (g > 40) & (g < 125) & (b > 30) & (b < 120) & (r - g > 110)
    лицо = ndimage.binary_opening(лицо, np.ones((3, 3)))
    сплошь = ndimage.binary_fill_holes(ndimage.binary_closing(лицо, np.ones((9, 9))))
    белое = видно & (r > 225) & (g > 195) & (b > 185)     # у вышки крест розоватый (241,213,203)
    крест = белое & ndimage.binary_erosion(сплошь, np.ones((5, 5)))
    мк, nк = ndimage.label(крест)
    кресты = [i for i in range(1, nк + 1) if (мк == i).sum() > 40]
    мс, _ = ndimage.label(сплошь)
    с_крестом = {int(мс[мк == i].max()) for i in кресты} - {0}
    return np.isin(мс, list(с_крестом)), len(кресты)


def повёрнутый_квадрат(xs, ys):
    """Повёрнутый квадрат ячейки: центр, стороны, угол.

    У напечатанной ячейки уголки срезаны светлыми скобками рамки, и пятно
    выходит восьмиугольником. Ни «самая длинная кромка оболочки» (как в
    зоны-энергии-по-печати.py), ни наименьшая коробка на нём не работают:
    обе ловят диагональ среза, и квадрат выходил 88×75 под 7° вместо 81×81
    ровно. Поэтому угол — ГОЛОСОВАНИЕ КРОМОК: каждая кромка оболочки голосует
    своей длиной за свой наклон (по модулю 90°), и побеждают четыре прямые
    стороны — они длиннее четырёх срезов."""
    точки = np.stack([xs, ys], axis=1)
    вершины = точки[ConvexHull(точки).vertices]
    голоса = np.zeros(90)
    for i in range(len(вершины)):
        p, q = вершины[i], вершины[(i + 1) % len(вершины)]
        d = math.hypot(q[0] - p[0], q[1] - p[1])
        голоса[int(round(math.degrees(math.atan2(q[1] - p[1], q[0] - p[0])))) % 90] += d
    окно = np.array([sum(голоса[(k + j) % 90] for j in range(-3, 4)) for k in range(90)])
    k = int(окно.argmax())
    веса = [(голоса[(k + j) % 90], k + j) for j in range(-3, 4)]
    угол = math.radians(sum(в * у for в, у in веса) / max(1e-9, sum(в for в, _ in веса)))
    if угол > math.pi / 4:
        угол -= math.pi / 2               # квадрату хватает ±45°
    c, s = math.cos(угол), math.sin(угол)
    u, v = xs * c + ys * s, -xs * s + ys * c
    uc, vc = (u.max() + u.min()) / 2, (v.max() + v.min()) / 2
    return uc * c - vc * s, uc * s + vc * c, u.max() - u.min() + 1, v.max() - v.min() + 1, угол


def круг(R):
    yy, xx = np.mgrid[-R:R + 1, -R:R + 1]
    return xx * xx + yy * yy <= R * R


# ОБРАЗЕЦ ЯЧЕЙКИ — измерен по печати синих казарм (экспорт 25.09.2026):
# бурый квадрат ячейки 86×86 px стоит ровно по осям с центром в (430, 274).
# Ячейка одна и та же на всех жетонах (бордовое нутро, молния, скобки в
# углах), разнится только рамка — в цвет фракции. Поэтому ячейка ищется
# СРАВНЕНИЕМ С ОБРАЗЦОМ по нутру (круг радиусом 34 px, рамка в него не
# входит): так она находится и на красных жетонах, где бурое не отличить от
# красной каймы, и там, где кромка жетона срезала ячейке угол (завод).
ОБРАЗЕЦ = ("barracks_p1", 430, 274, 86)
_образец = None


def образец():
    global _образец
    if _образец is None:
        ключ, cx, cy, _ = ОБРАЗЕЦ
        серое = Image.open(os.path.join(ПАПКА, ключ + ".png")).convert("L")
        _образец = серое.crop((cx - 60, cy - 60, cx + 60, cy + 60))
    return _образец


def сверить_с_образцом(серое, cx, cy):
    """Лучший угол и центр ячейки около (cx, cy): (качество, cx, cy, угол°)."""
    R = 34
    маска = круг(R)
    H, W = серое.shape

    def перебор(углы, xs, ys, лучший):
        for угол in углы:
            t = np.array(образец().rotate(-угол, resample=Image.BILINEAR)).astype(float)
            t = t[60 - R:60 + R + 1, 60 - R:60 + R + 1][маска]
            t = (t - t.mean()) / (t.std() + 1e-9)
            for y in ys:
                for x in xs:
                    if x - R < 0 or y - R < 0 or x + R >= W or y + R >= H:
                        continue
                    p = серое[y - R:y + R + 1, x - R:x + R + 1][маска]
                    оценка = float((t * (p - p.mean())).mean() / (p.std() + 1e-9))
                    if оценка > лучший[0]:
                        лучший = (оценка, x, y, угол)
        return лучший

    x0, y0 = int(round(cx)), int(round(cy))
    # грубо: угол через 3°, сдвиг через 2 px в пределах ±12; потом точно
    грубо = перебор(range(-45, 45, 3), range(x0 - 12, x0 + 13, 2),
                    range(y0 - 12, y0 + 13, 2), (-1.0, x0, y0, 0))
    _, x1, y1, u1 = грубо
    return перебор(range(u1 - 2, u1 + 3), range(x1 - 2, x1 + 3),
                   range(y1 - 2, y1 + 3), грубо)


def ячейки(a, сердца_пятно):
    """Напечатанные ячейки энергии: (cx, cy, сторона, сторона, угол в радианах).

    Кандидаты — тёмно-бордовые ядра (такого цвета на лице жетона больше нет,
    кроме теневой стороны сердец: её срезает отступ от сердца и открытие
    кругом 12 px — тонкие серпы тени исчезают, ядро ячейки остаётся). Каждое
    ядро сверяется с образцом ячейки; угол берётся из сверки — у завода ячейки
    повёрнуты по скосу крыла на −30°."""
    r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    ядро = (al > 200) & (r > 45) & (r < 150) & (g < 55) & (b < 55) & (r > g + 25)
    ядро &= ~ndimage.binary_dilation(сердца_пятно, np.ones((5, 5)))
    ядро = ndimage.binary_fill_holes(ndimage.binary_closing(ядро, np.ones((7, 7))))
    ядро = ndimage.binary_opening(ядро, круг(12))
    серое = (0.299 * r + 0.587 * g + 0.114 * b) * (al > 0) + 255 * (al == 0)
    м, n = ndimage.label(ядро)
    сторона = ОБРАЗЕЦ[3]
    out = []
    for i in range(1, n + 1):
        ys, xs = np.nonzero(м == i)
        if len(xs) < 1500:
            continue
        # середина коробки ядра, а не центр тяжести: у срезанной кромкой
        # ячейки центр тяжести уезжает внутрь жетона
        кач, x, y, угол = сверить_с_образцом(серое, (xs.min() + xs.max()) / 2,
                                            (ys.min() + ys.max()) / 2)
        if кач < 0.6:
            continue
        out.append((float(x), float(y), сторона, сторона, math.radians(угол)))
    out.sort(key=lambda c: (round(c[1] / 20), c[0]))
    return out


def нарисовать_квадраты(out, клетки):
    img = Image.fromarray(out, "RGBA")
    d = ImageDraw.Draw(img)
    for cx, cy, w, h, угол in клетки:
        c, s = math.cos(угол), math.sin(угол)
        d.polygon([(cx + dx * c - dy * s, cy + dx * s + dy * c)
                   for dx, dy in ((-w / 2, -h / 2), (w / 2, -h / 2), (w / 2, h / 2), (-w / 2, h / 2))],
                  fill=ЖЁЛТЫЙ)
    return np.array(img)


# ------------------------------------------------------ один жетон
def сделать(путь_текстуры, форма, место, печать):
    текстура = Image.open(путь_текстуры).convert("RGBA")
    a = np.array(текстура).astype(int)
    H, W = a.shape[:2]
    out = np.zeros((H, W, 4), dtype=np.uint8)
    отчёт = []

    пятно_сердец, крестов = сердца(a)

    файл_маски = МАСКА.get(форма)
    if файл_маски:
        маска, как = лучшее(Image.open(os.path.join(МАСКИ, файл_маски)).convert("RGBA"), текстура)
        старая = эталон(os.path.basename(путь_текстуры)[:-4])
        слои = [(белый, "гнездо"), (оранжевый, "площадь")]
        if форма.startswith("miner"):
            слои.append((жёлтый, "ячейки"))
        for проверка, имя in слои:
            область = маска_цвета(маска, проверка)
            if not область.any():
                continue
            dx, dy, кач = сдвиг(старая, текстура, область)
            сюда = сдвинуть(область, dx, dy)
            цвет = маска[область][0].astype(np.uint8)
            out[сюда] = цвет
            отчёт.append("%s %+d,%+d (%.2f)" % (имя, dx, dy, кач))
        отчёт.insert(0, "маска " + как)

    клеток = None
    if форма in ВОЕННЫЕ:
        клетки = ячейки(a, пятно_сердец)
        out = нарисовать_квадраты(out, клетки)
        клеток = len(клетки)
    elif форма.startswith("miner"):
        клеток = ndimage.label(маска_цвета(out.astype(int), жёлтый))[1]

    # площадь энергии энергостанции — из прежней разметки
    прежняя = путь_текстуры[:-4] + ".zones.png"
    if форма.startswith("power_plant") and os.path.exists(прежняя):
        p = np.array(Image.open(прежняя).convert("RGBA")).astype(int)
        if p.shape[:2] == (H, W):
            сюда = маска_цвета(p, синий) & (out[..., 3] == 0)
            out[сюда] = p[сюда].astype(np.uint8)
            отчёт.append("синяя площадь из прежней")

    свободно = пятно_сердец & (out[..., 3] == 0)
    out[свободно] = РОЗОВЫЙ

    # сверка с печатью, выписанной глазами
    вопрос = ""
    if печать is not None:
        ждём_яч, ждём_серд = печать
        if ждём_серд is not None and крестов != ждём_серд:
            вопрос += "  <-- СЕРДЕЦ %d, по печати %d" % (крестов, ждём_серд)
        if ждём_яч is not None and клеток is not None and клеток != ждём_яч:
            вопрос += "  <-- ЯЧЕЕК %d, по печати %d" % (клеток, ждём_яч)
    return out, крестов, клеток, ", ".join(отчёт), вопрос


def печать_жетона(art, форма, место):
    """(ячеек, сердец) из таблицы ПЕЧАТЬ gen_token_art.py или None."""
    цвет = ГНЁЗДА.get(место)
    if форма in ВОЕННЫЕ:
        return art.ПЕЧАТЬ[цвет]["buildings"][форма]
    if форма == "tower":
        return (None, art.ПЕЧАТЬ[цвет]["units"]["tower"])
    if форма.startswith("miner"):
        return art.ПЕЧАТЬ_ДОБЫТЧИК[int(форма[-1])]
    if форма.startswith("power_plant"):
        return (None, art.ПЕЧАТЬ_СТАНЦИЯ[int(форма[-1])][0])
    return None


