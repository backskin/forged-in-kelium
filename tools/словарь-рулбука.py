# «Ё» идёт сразу за «Е», а не в конце: иначе «жёлтый» уезжает из своего места.
ПОРЯДОК = 'абвгдеёжзийклмнопрстуфхцчшщъыьэюя'


def ключ(термин):
    т = термин.lower().replace('-', ' ')
    return [ПОРЯДОК.index(c) if c in ПОРЯДОК else -1 for c in т]


def main():
    имена = [т for т, _ in ТЕРМИНЫ]
    двойные = {т for т in имена if имена.count(т) > 1}
    if двойные:
        raise SystemExit('термин повторяется: ' + ', '.join(sorted(двойные)))
    # ЛАТИНИЦА В РУССКОМ СЛОВЕ — та ошибка, которую глазами не видно вовсе:
    # «Заданиe» с латинской «e» уезжает в конец алфавита и выглядит нормально.
    for т in имена:
        чужие = {c for c in т if c.isalpha()
                 and not ('А' <= c.upper() <= 'Я' or c in 'Ёё')}
        if чужие:
            raise SystemExit('латиница в термине «%s»: %s' % (т, ''.join(чужие)))

    куски = [НАЧАЛО, '', '# ЧАСТЬ 16. СЛОВАРЬ', '',
             'Все термины игры по алфавиту. Слова, которого здесь нет, в правилах',
             'нет тоже.', '']
    for термин, определение in sorted(ТЕРМИНЫ, key=lambda п: ключ(п[0])):
        куски.append('**%s** — %s' % (термин, определение))
        куски.append('')
    куски.append(КОНЕЦ)
    куски.append('')

    текст = io.open(РУЛБУК, encoding='utf-8').read()
    новое = '\n'.join(куски)
    if НАЧАЛО in текст:
        i = текст.index(НАЧАЛО)
        j = текст.index(КОНЕЦ) + len(КОНЕЦ) + 1
        текст = текст[:i] + новое + текст[j:]
    else:
        # Первый раз — на место прежней части 16.
        i = текст.index('# ЧАСТЬ 16. СЛОВАРЬ')
        j = текст.index('<!-- ПРИЛОЖЕНИЯ')
        текст = текст[:i] + новое + '---\n\n' + текст[j:]
    io.open(РУЛБУК, 'w', encoding='utf-8', newline='').write(текст)
    print('словарь собран, терминов:', len(ТЕРМИНЫ))


if __name__ == '__main__':
    main()
