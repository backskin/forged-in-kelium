# -*- coding: utf-8 -*-
"""DOCX ПО ЧЕРНОВИКУ СУПЕР-ЗАДАНИЙ 5.0 — в том же виде, что остальные карты.

Двенадцать карт «суперутиль или накопитель» в игровой набор ещё не вошли: их
надо править, а править удобно в таблице с колонкой под замечания — как и все
прочие типы карт.

Источник один: design-docs/супер-задания-5.0-черновик.yaml. Разбор замысла и
чисел — в «ЧЕРНОВИК — супер-задания 5.0 (12 карт).md»; документ его не
пересказывает, а показывает карты по одной.

Оформление берётся из tools/документы-карт.py — тот же шрифт, та же тёмная
шапка, та же жёлтая колонка «Комментарии». Модуль подгружается по пути, потому
что в его имени дефис и обычным import его не взять.

Запуск: python tools/документ-супер-заданий.py
"""
import importlib.util
import io
import os

import yaml
from docx.shared import Cm

ЧЕРНОВИК = "design-docs/супер-задания-5.0-черновик.yaml"


def подгрузить_оформление():
    путь = os.path.join(os.path.dirname(__file__), "документы-карт.py")
    spec = importlib.util.spec_from_file_location("оформление", путь)
    модуль = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(модуль)
    return модуль


def main():
    о = подгрузить_оформление()
    данные = yaml.safe_load(io.open(ЧЕРНОВИК, encoding="utf-8"))
    карты = данные["карты"]

    doc = о.документ(
        "Супер-задания 5.0 — черновик",
        f"Кристаллы Раздора · черновик набора · карт: {len(карты)} шт · "
        "в игру ещё не введены",
        ["Каждому игроку в подготовку раздаётся ОДНА такая карта, втайне. На ней "
         "две половины, и сыграть можно только одну: СУПЕРУТИЛЬ — разовый эффект "
         "чудовищной силы, сжигается спец-действием в любой момент; НАКОПИТЕЛЬ — "
         "победные очки в конце партии, если карта дожила до конца нетронутой.",
         "Рубашка у всех карт одинаковая и заметная: соперник не знает, ЧТО у "
         "тебя, но знает, что оно есть и может выстрелить в любой ход. "
         "Неожиданность должна быть в том, какой эффект, а не в том, что он "
         "вообще существует.",
         "НАКОПИТЕЛЬ ВСЕГДА ПЕРЕЧИТ ОБЫЧНОЙ ИГРЕ. Карта, которая платит за то, "
         "что игрок и так делает, — не задание, а доплата. Поэтому оси взяты "
         "против того, что происходит само: числа в колонке «Против чего идёт» "
         "взяты из замеров на четверых.",
         "ОБЕ ПОЛОВИНЫ СТОЯТ ПРИМЕРНО ОДИНАКОВО. Победитель набирает 14–17 "
         "очков, поэтому накопитель рассчитан на 4–6 и всегда закрыт потолком — "
         "без потолка одна партия дала бы 3 очка, другая 14. Суперутиль подобран "
         "под ту же цену: это не «лишнее действие», а ход, разворачивающий "
         "партию.",
         "ПРОВЕРЯТЬ БУДЕМ ОДНИМ ЧИСЛОМ: как часто карту жгут против того, как "
         "часто держат. Цель — примерно поровну.",
         о.ВВОДНАЯ_КОММЕНТАРИИ])

    заголовки = ["№", "Название", "Накопитель (очки в конце)",
                 "Суперутиль (сжечь карту)", "Как это работает", "Комментарии"]
    ширины = [Cm(1.2), Cm(3.4), Cm(6.4), Cm(6.4), Cm(6.6), Cm(4.6)]
    строки = []
    for i, к in enumerate(карты, start=1):
        накопитель = [
            ("", str(к["накопитель"]), False),
            ("ПОТОЛОК", f"{к['потолок']} победных очков", False),
        ]
        утиль = [("", str(к["утиль"]), False)]
        работа = [
            ("ПРОТИВ ЧЕГО ИДЁТ", str(к["против"]), False),
            ("ЧЕМ ПЛАТИШЬ", str(к["цена"]), False),
            ("ПОЛОВИНЫ СПОРЯТ", str(к["спор"]), True),
        ]
        строки.append([f"S{i:02}", к["имя"], накопитель, утиль, работа, ""])

    о.таблица_карт(doc, заголовки, ширины, строки)
    о.сохранить(doc, "КАРТЫ СУПЕР-ЗАДАНИЙ 5.0 (черновик)")


if __name__ == "__main__":
    main()
