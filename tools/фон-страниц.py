# -*- coding: utf-8 -*-
"""Отделка готовой книги: фоновые иллюстрации, подложки под текст и двойная
рамка. Работает по выгруженному PDF, потому что в docx ничего этого нет.

ЧТО ДЕЛАЕТ С КАЖДОЙ ПОЛОСОЙ (кроме первой — она обложечная):

1. Кладёт под содержимое иллюстрацию. Четыре штуки чередуются по кругу,
   последней полосе — своя (5 у рулбука, 6 у справочника). Картинки в
   rules/фон/ заранее сведены с цветом страницы при 10 % видимости, поэтому
   ложатся непрозрачно.
2. Гасит сплошную заливку цвета страницы, которой Word иначе накрывает
   подложку первой же операцией потока.
3. Под каждым блоком текста рисует подложку цвета страницы с непрозрачностью
   90 % и полями шире текста — чтобы буквам был «воздух», а иллюстрация не
   лезла под строку. Таблицы поверх этого высветляются белым: их сетка тоньше
   текста и просвечивающий фон читается хуже всего.
4. Поверх всего — двойная рамка: широкая глухая по самой кромке листа и
   тонкая чуть внутри.
"""
import re
import sys
import pathlib

import pymupdf

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ФОН = КОРЕНЬ / 'rules' / 'фон'
# Своя картинка на последнюю полосу каждой книги.
ПОСЛЕДНЯЯ = {'РУЛБУК': '5.jpg', 'СПРАВОЧНИК': '6.jpg'}

ЧЕРНИЛА = (0x2A / 255, 0x23 / 255, 0x18 / 255)
ЦВЕТ_СТРАНИЦЫ = (0xF7 / 255, 0xF1 / 255, 0xE1 / 255)

ГЛУХАЯ_ШИРИНА = 12.0   # широкая рамка по кромке: закрывает край наглухо
ТОНКАЯ_ОТСТУП = 17.0   # тонкая рамка — чуть внутри
ТОНКАЯ_ШИРИНА = 0.9

ПОЛЕ_ПОДЛОЖКИ = 7.0    # «воздух» вокруг блока текста
НЕПРОЗРАЧНОСТЬ = 0.90
ВЫСВЕТЛИТЬ_ТАБЛИЦУ = 0.45   # сколько белого добавить под таблицу

ЗАЛИВКА = re.compile(
    rb'0\.969 0\.945 0\.882 rg(\s+-?[\d.]+ -?[\d.]+ [\d.]+ [\d.]+ re\s+)f\*')


def погасить_заливку(doc, стр):
    for xref in стр.get_contents():
        поток = doc.xref_stream(xref)
        новый = ЗАЛИВКА.sub(rb'0.969 0.945 0.882 rg\1n', поток)
        if новый != поток:
            doc.update_stream(xref, новый)


def слить(прямоугольники):
    """Склеивает пересекающиеся подложки в одну, чтобы 90 % не наложились
    дважды и стык двух абзацев не темнел полосой."""
    итог = []
    for r in прямоугольники:
        r = pymupdf.Rect(r)
        слилось = True
        while слилось:
            слилось = False
            for готовый in list(итог):
                if r.intersects(готовый):
                    r |= готовый
                    итог.remove(готовый)
                    слилось = True
        итог.append(r)
    return итог


def подложки(стр):
    """Прямоугольники под блоками текста — с полями и уже слитые."""
    сырые = []
    for блок in стр.get_text('blocks'):
        x0, y0, x1, y1, текст, _, вид = блок
        if вид != 0 or not текст.strip():
            continue
        сырые.append(pymupdf.Rect(x0, y0, x1, y1)
                     + (-ПОЛЕ_ПОДЛОЖКИ, -ПОЛЕ_ПОДЛОЖКИ,
                        ПОЛЕ_ПОДЛОЖКИ, ПОЛЕ_ПОДЛОЖКИ))
    return слить(сырые)


def таблицы(стр):
    try:
        return [pymupdf.Rect(т.bbox) + (-3, -3, 3, 3)
                for т in стр.find_tables().tables]
    except Exception:
        return []


def отделать(pdf):
    doc = pymupdf.open(pdf)
    последняя = ПОСЛЕДНЯЯ.get(pathlib.Path(pdf).name.split(' ')[0])
    n = doc.page_count
    сделано = 0
    for i in range(n):
        if i == 0:
            continue
        стр = doc[i]
        картинка = (ФОН / последняя) if (i == n - 1 and последняя) \
            else (ФОН / f'{i % 4 + 1}.jpg')
        стр.insert_image(стр.rect, filename=str(картинка), overlay=False)
        погасить_заливку(doc, стр)
        # Подложки и высветление таблиц — тоже ПОД содержимым, но ПОВЕРХ
        # иллюстрации: overlay=False дописывает в тот же нижний слой.
        for r in подложки(стр):
            стр.draw_rect(r, color=None, fill=ЦВЕТ_СТРАНИЦЫ,
                          fill_opacity=НЕПРОЗРАЧНОСТЬ, overlay=False)
        for r in таблицы(стр):
            стр.draw_rect(r, color=None, fill=(1, 1, 1),
                          fill_opacity=ВЫСВЕТЛИТЬ_ТАБЛИЦУ, overlay=False)
        # Рамки — поверх всего.
        п = ГЛУХАЯ_ШИРИНА / 2
        стр.draw_rect(стр.rect + (п, п, -п, -п),
                      color=ЧЕРНИЛА, width=ГЛУХАЯ_ШИРИНА, overlay=True)
        стр.draw_rect(стр.rect + (ТОНКАЯ_ОТСТУП, ТОНКАЯ_ОТСТУП,
                                  -ТОНКАЯ_ОТСТУП, -ТОНКАЯ_ОТСТУП),
                      color=ЧЕРНИЛА, width=ТОНКАЯ_ШИРИНА, overlay=True)
        сделано += 1
    doc.save(str(pdf) + '.tmp', garbage=3, deflate=True)
    doc.close()
    pathlib.Path(str(pdf) + '.tmp').replace(pdf)
    return сделано


if __name__ == '__main__':
    цели = sys.argv[1:] or [
        str(КОРЕНЬ / 'rules' / 'РУЛБУК — Кристаллы Раздора.pdf'),
        str(КОРЕНЬ / 'rules' / 'СПРАВОЧНИК — Кристаллы Раздора.pdf'),
    ]
    for ц in цели:
        п = pathlib.Path(ц)
        print(п.name, '—', отделать(п), 'полос отделано')
