# ---------- строка с иконками: [('т', текст) | ('ж', текст) | ('и', иконка)] ----------

def разбить(части):
    """Части → слова (с признаком жирности) и иконки для переноса по словам."""
    out = []
    for вид, знач in части:
        if вид == 'и':
            out.append(('и', знач))
        else:
            слова = знач.split(' ')
            for i, w in enumerate(слова):
                if w:
                    out.append((вид, w))
                if i < len(слова) - 1:
                    out.append(('_', ' '))
    return out


def абзац(холст, x, y, ширина, части, р, отступ2=0):
    """Рисует абзац с переносом; возвращает высоту. отступ2 — отступ строк после первой."""
    d = ImageDraw.Draw(холст)
    fо, fж = шрифт(ОБЫЧНЫЙ, р * K), шрифт(ЖИРНЫЙ, р * K)
    ик = int(р * K * 1.08)
    пробел = d.textlength(' ', font=fо)
    макс = ширина * K
    # ПЕРЕНОС — ТОЛЬКО ЕСЛИ ОН ЭКОНОМИТ СТРОКУ (дизайнер 27.09): раскладка
    # делается без переносов и с ними; переносы остаются, лишь если строк меньше
    без = _строки(d, части, fо, fж, ик, пробел, макс, отступ2, False)
    с = _строки(d, части, fо, fж, ик, пробел, макс, отступ2, True)
    строки = с if len(с) < len(без) else без
    return _нарисовать(холст, d, строки, x, y, р, fо, fж, ик, отступ2)


def _строки(d, части, fо, fж, ик, пробел, макс, отступ2, переносить):
    строки, строка, ш = [], [], 0
    for вид, знач in разбить(части):
        if вид == '_':
            if строка:
                строка.append(('_', пробел))
                ш += пробел
            continue
        f_ = fж if вид == 'ж' else fо
        w = ик if вид == 'и' else d.textlength(знач, font=f_)
        лимит = макс - (отступ2 * K if строки else 0)
        # ПЕРЕНОС ПО СЛОГАМ (просьба дизайнера 27.09): не влезает слово —
        # отрезаем от него самый длинный кусок по слогам, что влезает с дефисом
        if переносить and вид != 'и' and строка and ш + w > лимит and _СЛОГИ and len(знач) > 4:
            for левая, правая in _СЛОГИ.iterate(знач):
                # короткий хвост на новой строке хуже, чем слово целиком
                if len(левая) < 3 or len(правая) < 4:
                    continue
                wl = d.textlength(левая + '-', font=f_)
                if ш + wl <= лимит:
                    строка.append((вид, левая + '-', wl))
                    строки.append(строка)
                    строка, ш = [], 0
                    знач = правая
                    w = d.textlength(знач, font=f_)
                    break
        if строка and ш + w > лимит:
            while строка and строка[-1][0] == '_':
                ш -= строка.pop()[1]
            строки.append(строка)
            строка, ш = [], 0
        строка.append((вид, знач if вид != 'и' else знач, w) if вид != '_' else ('_', w))
        ш += w
    if строка:
        строки.append(строка)
    return строки


def _нарисовать(холст, d, строки, x, y, р, fо, fж, ик, отступ2):
    шаг = р * K * 1.22
    yy = y * K
    for n, стр in enumerate(строки):
        xx = x * K + (отступ2 * K if n else 0)
        for эл in стр:
            if эл[0] == '_':
                xx += эл[1]
                continue
            вид, знач, w = эл
            if вид == 'и':
                im = вписать(икона(знач), ик, ик)
                холст.alpha_composite(im, (round(xx), round(yy + шаг * 0.5 - im.height / 2)))
            else:
                d.text((xx, yy + шаг * 0.5), знач, font=fж if вид == 'ж' else fо,
                       fill=ЗЕЛЁНЫЙ, anchor='lm')
            xx += w
        yy += шаг
    return len(строки) * шаг / K


def треугольник(d, x, y, р):
    s = р * K * 0.36
    cx, cy = x * K, y * K
    d.polygon([(cx - s * 0.5, cy - s * 0.6), (cx - s * 0.5, cy + s * 0.6), (cx + s * 0.6, cy)],
              fill=(40, 45, 45))


def пунктир(d, y, x0=55, x1=775):
    x = x0 * K
    while x < x1 * K:
        d.ellipse((x, y * K - 2 * K, x + 4 * K, y * K + 2 * K), fill=ПУНКТИР)
        x += 11 * K


НАХЛЁСТ = 8          # вертикальная подпись заходит на кружок (просьба дизайнера 27.09)


def высота_раздела(иконка, подпись, строки, р=40):
    """Сколько раздел займёт по высоте: текст или кружок с подписью, что выше."""
    пусто = Image.new('RGBA', (827 * K, 2000 * K))
    конец_текста = раздел(пусто, 0, 10 ** 6, иконка, подпись, строки, р, только_текст=True)
    h = max(конец_текста, 72 + 56 + 150)
    # подпись одной строкой (с заходом на кружок, кегль 46) — если ради неё
    # раздел вырастает не больше чем на 60 px; иначе пусть переносится
    нужно = 72 + 56 - НАХЛЁСТ + шрифт(ОБЫЧНЫЙ, 48 * K).getlength(подпись) / K + 12
    if нужно <= h + 30:
        h = max(h, нужно)
    return h


def раздел(холст, y0, y1, иконка, подпись, строки, р=40, только_текст=False):
    """Левая колонка: кружок и вертикальная подпись; справа — строки."""
    d = ImageDraw.Draw(холст)
    if только_текст:
        return _текст(холст, d, y0, строки, р)
    # кружок действия
    cx, cy, r = 115, y0 + 72, 56
    круг = вписать(икона('ring'), 2 * r * K, 2 * r * K)
    холст.alpha_composite(круг, (round(cx * K - круг.width / 2), round(cy * K - круг.height / 2)))
    ико = вписать(икона(иконка), 2.15 * r * K, 2.15 * r * K)
    холст.alpha_composite(ико, (round(cx * K - ико.width / 2), round(cy * K - ико.height / 2 - 6 * K)))
    # ВЕРТИКАЛЬНАЯ ПОДПИСЬ (дизайнер 27.09): по центру свободного места под
    # кружком, с дыханием; не влезает крупно — в две строки по слогам
    # («снаб-/жения»); на кружок заходит, только если иначе тесно
    зазор_к = 14
    верх_п, низ_п = cy + r + зазор_к, y1 - 6
    место = (низ_п - верх_п) * K
    размер = 52 * K
    f = шрифт(ОБЫЧНЫЙ, размер)
    строки_п = [подпись]
    # порядок: одна строка → одна строка с заходом на кружок → она же чуть
    # мельче (до 44) → две строки по слогам
    if f.getlength(подпись) > место:
        с_нахлёстом = место + (НАХЛЁСТ + зазор_к) * K
        for пробный in range(размер, 47 * K, -2 * K):
            if шрифт(ОБЫЧНЫЙ, пробный).getlength(подпись) <= с_нахлёстом:
                верх_п -= НАХЛЁСТ + зазор_к
                место = с_нахлёстом
                размер = пробный
                f = шрифт(ОБЫЧНЫЙ, размер)
                break
    if f.getlength(подпись) > место and _СЛОГИ:
        лучшая = None
        for левая, правая in _СЛОГИ.iterate(подпись):
            ш = max(f.getlength(левая + '-'), f.getlength(правая))
            if лучшая is None or ш < лучшая[0]:
                лучшая = (ш, [левая + '-', правая])
        if лучшая and лучшая[0] <= место:
            строки_п = лучшая[1]
    длина = max(f.getlength(t) for t in строки_п)
    if длина > место:                        # тесно: заходим на кружок
        верх_п -= НАХЛЁСТ + зазор_к
        место = (низ_п - верх_п) * K
    while max(f.getlength(t) for t in строки_п) > место and размер > 24 * K:
        размер -= 2 * K
        f = шрифт(ОБЫЧНЫЙ, размер)
    длина = max(f.getlength(t) for t in строки_п)
    шаг_строк = int(размер * 1.05)
    tw = int(длина) + 8 * K
    th = шаг_строк * len(строки_п) + int(размер * 0.3)
    лист = Image.new('RGBA', (tw, th), (0, 0, 0, 0))
    dl = ImageDraw.Draw(лист)
    for i, t in enumerate(строки_п):
        dl.text((4 * K, int(размер * 0.62) + i * шаг_строк), t, font=f, fill=СЛАНЕЦ, anchor='lm')
    лист = лист.rotate(90, expand=True)
    y_центр = (верх_п * K + низ_п * K) / 2
    холст.alpha_composite(лист, (round(cx * K - лист.width / 2),
                                 round(y_центр - лист.height / 2)))
    return _текст(холст, d, y0, строки, р)


def _текст(холст, d, y0, строки, р):
    y = y0 + 14
    x = 180
    права = 775                       # внутренний край рамки шаблона (797) с полем
    for вид, части in строки:
        if вид == 'заг':
            y += абзац(холст, x, y, права - x, части, р) + 4
        elif вид == 'ветка':
            треугольник(d, x + 12, y + р * 0.62, р)
            y += абзац(холст, x + 30, y, права - x - 30, части, р + 2) + 2
        elif вид == 'под':
            y += абзац(холст, x + 30, y, права - x - 30, части, р - 3, отступ2=16)
        elif вид == 'прим':
            y += 6
            y += абзац(холст, x, y, права - x, части, р - 4)
        elif вид == 'зазор':
            y += части
    return y


