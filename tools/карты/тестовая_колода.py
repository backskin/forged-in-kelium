def main():
    out = []
    for i, (id_, имя, стр, тр, ус, нагр, сверх, жертва) in enumerate(КАРТЫ):
        я = {'имя': имя, 'требование': тр, 'награда': нагр, 'верх': ВЕРХ[i % len(ВЕРХ)],
             'значок': ЗНАЧОК[стр], 'стратегия': стр}
        if ус:
            я['усиление'] = ус
        if сверх:
            я['сверх'] = сверх
        if жертва:
            я['жертва'] = жертва
        out.append({'id': id_, 'язык': я})
    старый = yaml.safe_load(open(os.path.join(КОРЕНЬ, 'data', 'cards', 'objectives.3.0.0.yaml'),
                                 encoding='utf-8'))
    нач = [o for o in старый['objectives'] if str(o['id']).startswith('n')]
    d = {'meta': {'id': '90.0.0', 'type': 'objectives'}, 'objectives': out + нач}
    шапка = ('# 90.0.0 — ТЕСТОВАЯ КОЛОДА (07.10.2026): все виды требований, усилений и наград.\n'
             '# Полигон для ботов, в игру не идёт. Собрана tools/карты/тестовая_колода.py — правьте там.\n'
             '# CONTENT: objectives  version 90.0.0\n')
    путь = os.path.join(КОРЕНЬ, 'data', 'cards', 'objectives.90.0.0.yaml')

    class БезЯкорей(yaml.SafeDumper):
        def ignore_aliases(self, data):
            return True

    open(путь, 'w', encoding='utf-8').write(
        шапка + yaml.dump(d, Dumper=БезЯкорей, allow_unicode=True, sort_keys=False, width=120))
    print('карт:', len(out), '→', путь)


if __name__ == '__main__':
    main()
