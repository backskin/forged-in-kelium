# РАСКЛАДКИ КАРТИНКАМИ — прогон СнимокРаскладки по готовым файлам .kmap.
#
# Отдельным скриптом, потому что классы модулей ОБЯЗАНЫ стоять в classpath
# раньше, чем kelium-engine.jar из локального репозитория: иначе подтянется
# старый движок, ровно как с `mvn -pl gui` без `-am`.
#
# Запуск: powershell -File tools\раскладки-в-png.ps1
param(
    [string]$Корень = "C:\shared\forged-in-kelium",
    [string]$Куда = "docs\раскладки",
    [int]$Ширина = 1500,
    [int]$Высота = 1500
)

Set-Location $Корень
$зависимости = Get-Content (Join-Path $Корень "cp-gui.txt")
$cp = "gui\target\classes;engine\target\classes;cards\target\classes;$зависимости"

# Какие раскладки идут в справочник. Страница справочника — сетка 2x2,
# поэтому число раскладок в составе кратно четырём: вдвоём и втроём по
# четыре, вчетвером — все восемь авторских.
$выбор = @(
    @{ файл = "new\сценарий 2 игрока 1.kmap"; имя = "2и-1" },
    @{ файл = "new\сценарий 2 игрока 2.kmap"; имя = "2и-2" },
    @{ файл = "new\сценарий 2 игрока 3.kmap"; имя = "2и-3" },
    @{ файл = "new\сценарий 2 игрока 4.kmap"; имя = "2и-4" },
    @{ файл = "new\сценарий 3 игрока 1.kmap"; имя = "3и-1" },
    @{ файл = "new\сценарий 3 игрока 2.kmap"; имя = "3и-2" },
    @{ файл = "new\сценарий 3 игрока 3.kmap"; имя = "3и-3" },
    @{ файл = "new\сценарий 3 игрока 4.kmap"; имя = "3и-4" },
    @{ файл = "new\сценарий 4 игрока 1.kmap"; имя = "4и-1" },
    @{ файл = "new\сценарий 4 игрока 2.kmap"; имя = "4и-2" },
    @{ файл = "new\сценарий 4 игрока 3.kmap"; имя = "4и-3" },
    @{ файл = "new\сценарий 4 игрока 4.kmap"; имя = "4и-4" },
    @{ файл = "new\сценарий 4 игрока 5.kmap"; имя = "4и-5" },
    @{ файл = "new\сценарий 4 игрока 6.kmap"; имя = "4и-6" },
    @{ файл = "new\сценарий 4 игрока 7.kmap"; имя = "4и-7" },
    @{ файл = "new\сценарий 4 игрока 8.kmap"; имя = "4и-8" }
)

New-Item -ItemType Directory -Force -Path $Куда | Out-Null
foreach ($р in $выбор) {
    $вход = Join-Path "data\scenarios" $р.файл
    $выход = Join-Path $Куда ($р.имя + ".png")
    if (-not (Test-Path $вход)) { "нет файла: $вход"; continue }
    & java "-Djava.awt.headless=false" -cp $cp kelium.gui.СнимокРаскладки слияние $выход $вход $Ширина $Высота
}

# Легенда — одна на все раскладки, в книге печатается один раз.
& java "-Djava.awt.headless=false" -cp $cp kelium.gui.СнимокРаскладки легенда (Join-Path $Куда "легенда.png")
