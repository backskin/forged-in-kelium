# -*- coding: utf-8 -*-
"""РЫНОК 2.0.0 — набор карт по таблице дизайнера 02.09.2026.

Карты живут в КОДЕ (cards/market/СделкиНаРынке2.java) — он источник правды. Этот
файл лишь порождает YAML-зеркало набора: движок читает из него состав набора, а
текст и параметры каждой карты всё равно накрывает выгрузка класса
(CardRegistry.bindAll). Поэтому здесь только номера и порядок, а не тексты — их
дублирование расходилось бы с кодом при первой же правке.

Запуск: python tools/собрать-рынок-2-0-0.py
"""
import io

НОМЕРА = ['m2_contract', 'm2_convoy', 'm2_energy_office', 'm2_arms_fair',
          'm2_alarm', 'm2_corps_hq', 'm2_civil', 'm2_science']

ЦЕЛЬ = 'data/cards/market.2.0.0.yaml'

ШАПКА = """# CONTENT: market  version 2.0.0
# ============================================================================
#  КАРТЫ РЫНКА 2.0 - НАБОР ДИЗАЙНЕРА 02.09.2026 (8 карт)
# ============================================================================
#  ИСТОЧНИК ПРАВДЫ - КОД: cards/src/main/java/kelium/cards/market/
#  СделкиНаРынке2.java. Здесь только номера и порядок; тексты и параметры
#  половин движок берёт из классов (CardRegistry.bindAll), а файл держит
#  СОСТАВ набора. Правьте класс, а этот файл перегенерируйте инструментом
#  tools/собрать-рынок-2-0-0.py.
#
#  НОМЕРА НОВЫЕ (m2_*), а не как в 1.2.0. Класс накрывает собой запись с тем же
#  номером в ЛЮБОМ наборе: правь классы 1.2.0 - и набор, на котором сыграны все
#  прежние замеры, задним числом покажет новый текст. С новыми номерами 1.2.0
#  остаётся точно таким, каким на нём играли.
#
#  ЧТО ИЗМЕНИЛОСЬ против 1.2.0: карты «Военный подряд», «Теневой обоз», «Штаб
#  корпуса» и правая половина «Гражданского подряда» держатся как были; у
#  «Энергетической конторы» и «Научной миссии» новые обе половины; у «Оружейной
#  ярмарки» - обе; у «Военной тревоги» боеприпасов стало по два вместо одного;
#  у «Гражданского подряда» переписано левое предложение.
#
#  ДВА ПРЕДЛОЖЕНИЯ БЕЗ ЯЧЕЙКИ (пометка no_cell в классе): «установка келемия
#  вместо энергии» и «купить келемий за монету». Они не занимают ячейку
#  предложения, то есть доступны каждому и сколько угодно раз за раунд - мелкие
#  сделки держат планшет живым, когда крупные ячейки уже разобрали.
"""


def main():
    строки = [ШАПКА, 'meta:\n  id: 2.0.0\n  type: market\n\nmarket:\n']
    for номер in НОМЕРА:
        строки.append(f'  - id: {номер}\n')
    io.open(ЦЕЛЬ, 'w', encoding='utf-8').write(''.join(строки))
    print(f'готово: {ЦЕЛЬ}, карт {len(НОМЕРА)}')


if __name__ == '__main__':
    main()
