# -*- coding: utf-8 -*-
"""ЛИЦА КАРТ С ЭКСПОРТА ДИЗАЙНЕРА — перезапускать при новом экспорте.

Движок ищет лицо карты по её идентификатору:
    kelium.report.Textures.cardFace("<колода>", "<id>")
        -> data/textures/card/<колода>/<id>.png
Экспорт дизайнера пронумерован по файлам, а не по картам, поэтому у каждой
колоды здесь своя ТАБЛИЦА «номер файла -> id карты», прочитанная по самим
рисункам (печатное условие, награда, верх), и свой РАЗДЕЛ — отдельная функция.
Разделы независимы: новую колоду добавляют новой функцией и строкой в РАЗДЕЛЫ,
не трогая соседние.

Лицо ужимается до ширины ШИРИНА (LANCZOS), в RGBA. Рубашка колоды ложится
рядом под именем back.png.

Запуск:
    python tools/gen_card_art.py                  — все разделы
    python tools/gen_card_art.py objective        — только названные
Корень экспорта по умолчанию — Yandex.Disk/Forged in Kelium/Общие компоненты;
другой можно задать переменной окружения KELIUM_EXPORT.
"""
import os
import sys

from PIL import Image

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЭКСПОРТ = os.environ.get('KELIUM_EXPORT') or os.path.join(
    os.path.expanduser('~'), 'Yandex.Disk', 'Forged in Kelium', 'Общие компоненты')
КАРТЫ = os.path.join(КОРЕНЬ, 'data', 'textures', 'card')

# Карта на экране не бывает шире трёхсот пикселей; шестьсот — запас вдвое.
ШИРИНА = 600


def положить(src, колода, имя):
    """Ужать картинку экспорта и положить лицом карты колоды под именем id."""
    куда = os.path.join(КАРТЫ, колода)
    os.makedirs(куда, exist_ok=True)
    im = Image.open(src).convert('RGBA')
    w, h = im.size
    if w != ШИРИНА:
        im = im.resize((ШИРИНА, round(h * ШИРИНА / w)), Image.LANCZOS)
    путь = os.path.join(куда, имя + '.png')
    im.save(путь, optimize=True)
    return путь


def разложить(колода, папка, шаблон, таблица):
    """Общий ход раздела: каждую строку таблицы «номер файла -> id» в лицо карты."""
    беды = []
    for номер, cid in таблица:
        src = os.path.join(папка, шаблон % номер)
        if not os.path.isfile(src):
            беды.append('нет файла %s (для %s)' % (src, cid))
            continue
        положить(src, колода, cid)
    print('%s: %d лиц -> %s' % (колода, len(таблица) - len(беды),
                                os.path.join(КАРТЫ, колода)))
    for б in беды:
        print('  !! ' + б)
    return not беды


# ============================================================================
#  ЗАДАНИЯ (objective) — колода 1.19.0
# ============================================================================
#  Экспорт «награды-действия»: задания-с-действи-N.png. Файл 1 — рубашка, файлы
#  2..41 — печатные номера 01..40 (номер стоит в правом нижнем углу карты).
#  Заголовок карты — семейство; карта опознана по условию и награде.
#  Файлы родительской папки экспорт-задания (задания-N.png) — старая версия.
ЗАДАНИЯ = [
    (1, 'back'),
    # Выработка 01-05
    (2, 'o04'), (3, 'o05'), (4, 'o40'), (5, 'o08'), (6, 'o01'),
    # Засада 06-10
    (7, 'o29'), (8, 'o03'), (9, 'o07'), (10, 'o27'), (11, 'o63'),
    # Обеспечение 11-14
    (12, 'o33'), (13, 'o36'), (14, 'o34'), (15, 'o64'),
    # Развёртывание 15-21
    (16, 'o17'), (17, 'o11'), (18, 'o18'), (19, 'o65'), (20, 'o12'), (21, 'o15'),
    (22, 'o20'),
    # Расплата 22-25
    (23, 'o66'), (24, 'o67'), (25, 'o10'), (26, 'o06'),
    # Устранение 26-35
    (27, 'o68'), (28, 'o69'), (29, 'o42'), (30, 'o25'), (31, 'o70'), (32, 'o71'),
    (33, 'o72'), (34, 'o21'), (35, 'o43'), (36, 'o73'),
    # Экспансия 36-40
    (37, 'o74'), (38, 'o02'), (39, 'o75'), (40, 'o76'), (41, 'o77'),
]


def objective():
    return разложить('objective',
                     os.path.join(ЭКСПОРТ, 'экспорт-задания', 'награды-действия'),
                     'задания-с-действи-%d.png', ЗАДАНИЯ)


# ============================================================================
#  НАЧАЛЬНЫЕ ЗАДАНИЯ (objective_start)
# ============================================================================
#  «Задания начальные-N.png»: файл 1 — рубашка, 2..13 — печатные номера 01..12.
#  deck-*.png и .tsdb в той же папке — листы для TTS, не карты.
НАЧАЛЬНЫЕ = [
    (1, 'back'),
    (2, 'n1'), (3, 'n2'), (4, 'n3'), (5, 'n4'), (6, 'n5'), (7, 'n6'), (8, 'n7'),
    (9, 'n10'),   # № 08 «на свалке хотя бы один жетон»
    (10, 'n9'),   # № 09 «первый шаг трека технологий»
    (11, 'n8'),   # № 10 «2 неоткрытых контейнера»
    (12, 'n11'), (13, 'n12'),
]


def objective_start():
    return разложить('objective_start',
                     os.path.join(ЭКСПОРТ, 'экспорт-задания-начальные'),
                     'Задания начальные-%d.png', НАЧАЛЬНЫЕ)


# ============================================================================
#  РАЗДЕЛЫ: имя -> функция. Новая колода — новая строка.
# ============================================================================
РАЗДЕЛЫ = {
    'objective': objective,
    'objective_start': objective_start,
}


def main():
    имена = sys.argv[1:] or list(РАЗДЕЛЫ)
    неизвестные = [и for и in имена if и not in РАЗДЕЛЫ]
    if неизвестные:
        raise SystemExit('нет разделов: %s (есть: %s)' % (
            ', '.join(неизвестные), ', '.join(РАЗДЕЛЫ)))
    ok = all([РАЗДЕЛЫ[и]() for и in имена])
    if not ok:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
