# -*- coding: utf-8 -*-
"""ЛИЦА КАРТ — раскладка печатного экспорта дизайнера по номерам карт.

Движок ищет лицо карты так: kelium.report.Textures.cardFace(<колода>, <id>) ->
data/textures/card/<колода>/<id>.png. Имя файла — ТОЧНЫЙ id карты из набора,
поэтому у каждого раздела своя таблица «файл экспорта -> id», прочитанная по
самим картинкам (название, текст, печатный номер в правом нижнем углу).

СКРИПТ СОБРАН ИЗ НЕЗАВИСИМЫХ РАЗДЕЛОВ — по разделу на колоду. Раздел знает
свою папку экспорта, свою таблицу и свою папку назначения и ни от чего больше
не зависит: разделы других колод (задания и т. п.) дописываются рядом такими же
функциями и регистрируются в РАЗДЕЛЫ внизу файла.

Запуск:
    python tools/gen_card_art.py                      # все разделы
    python tools/gen_card_art.py arsenal arsenal_super  # только названные
Корень экспорта — переменная KELIUM_EXPORT или ~/Yandex.Disk/Forged in Kelium.
Пишет: data/textures/card/<колода>/<id>.png — ширина 600, RGBA, LANCZOS.
"""
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЭКСПОРТ = os.environ.get('KELIUM_EXPORT') or os.path.join(
    os.path.expanduser('~'), 'Yandex.Disk', 'Forged in Kelium')
ОБЩИЕ = os.path.join(ЭКСПОРТ, 'Общие компоненты')

# Карта на экране не бывает шире трёхсот пикселей; шестьсот — запас вдвое.
ШИРИНА = 600


def разложить(папка, таблица, колода):
    """Общая работа раздела: каждый файл таблицы -> card/<колода>/<id>.png."""
    куда = os.path.join(ROOT, 'data', 'textures', 'card', колода)
    os.makedirs(куда, exist_ok=True)
    нет = []
    for файл, cid in таблица:
        путь = os.path.join(папка, файл)
        if not os.path.isfile(путь):
            нет.append(файл)
            continue
        im = Image.open(путь).convert('RGBA')
        w, h = im.size
        im = im.resize((ШИРИНА, round(h * ШИРИНА / w)), Image.LANCZOS)
        im.save(os.path.join(куда, cid + '.png'), optimize=True)
    print('%-14s %2d лиц -> %s' % (колода, len(таблица) - len(нет), куда))
    for файл in нет:
        print('    НЕТ ФАЙЛА:', os.path.join(папка, файл))


# ============================================================================
#  РАЗДЕЛ: АРСЕНАЛ (обычный) — набор arsenal.7.0.0
# ============================================================================
# Серия «арсенал-N.png» от 13.09.2026 — та, из которой собран лист TTS
# «deck-арсенал new» (17.09.2026). Печатный номер карты = N - 1: файл
# «арсенал-1» — рубашка, «арсенал-34» (печатный №33) — заготовка без текста.
# Серия «арсенал-01…07» (05.09.2026) — прежняя редакция №1–6, не используется.
def раздел_арсенал():
    таблица = [('арсенал-%d.png' % (n + 1), 'a7_%02d' % n) for n in range(1, 33)]
    разложить(os.path.join(ОБЩИЕ, 'экспорт-арсенал'), таблица, 'arsenal')


# ============================================================================
#  РАЗДЕЛ: НАЧАЛЬНЫЙ АРСЕНАЛ — карты kind: starting набора arsenal.7.0.0
# ============================================================================
# «арсенал-начальный-1» — рубашка; 2…5 — печатные №1–4 (они и в листе TTS
# «deck-арсенал-начальный» 17.09.2026). 6 и 7 — без номера, с чужими
# названиями (черновики), 8 и 9 — пустые заготовки «Купол»: не карты.
def раздел_арсенал_начальный():
    таблица = [('арсенал-начальный-%d.png' % (n + 1), 'bs7_%d' % n) for n in range(1, 5)]
    разложить(os.path.join(ОБЩИЕ, 'экспорт-арсенал-начальный'), таблица, 'arsenal_start')


# ============================================================================
#  РАЗДЕЛ: СУПЕР-АРСЕНАЛ — набор super_arsenal.3.0.0
# ============================================================================
# «арсенал-супер-1» — рубашка; 2…5 — четыре супер-войска; 6 («Супер-вышка»
# без текста) и 7…10 («Арсенал» без текста) — заготовки.
def раздел_арсенал_супер():
    таблица = [
        ('арсенал-супер-2.png', 'sa3_01'),   # Супер-пехота
        ('арсенал-супер-3.png', 'sa3_02'),   # Супер-техника
        ('арсенал-супер-4.png', 'sa3_03'),   # Супер-авиация
        ('арсенал-супер-5.png', 'sa3_04'),   # Супер-вышка
    ]
    разложить(os.path.join(ОБЩИЕ, 'экспорт-арсенал-супер'), таблица, 'arsenal_super')


# Разделы по имени колоды. Новый раздел — новая функция и строка здесь.
РАЗДЕЛЫ = {
    'arsenal': раздел_арсенал,
    'arsenal_start': раздел_арсенал_начальный,
    'arsenal_super': раздел_арсенал_супер,
}


if __name__ == '__main__':
    имена = sys.argv[1:] or list(РАЗДЕЛЫ)
    for имя in имена:
        if имя not in РАЗДЕЛЫ:
            print('нет раздела', имя, '- есть:', ', '.join(РАЗДЕЛЫ))
            continue
        РАЗДЕЛЫ[имя]()
