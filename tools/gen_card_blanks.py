ЦВЕТ_ВЕРХ = (250, 246, 242)          # светлая заливка верха, бордовая обводка
ОБВОДКА_ВЕРХ = (132, 76, 76)
НАЧ_НАЗВАНИЕ = (62, 118, 50)
НАЧ_ТЕЛО = (50, 98, 42)
НАЧ_НОМЕР = (74, 130, 50)
ОБЫЧ_НАЗВАНИЕ = (252, 252, 252)      # светлая заливка, бирюзовая обводка
ОБЫЧ_ОБВОДКА = (66, 130, 146)
ОБЫЧ_ТЕЛО = (2, 66, 74)
ОБЫЧ_НОМЕР = (90, 130, 162)
СУПЕР_ЦВЕТ = (106, 82, 154)


def стиль_верха(доля=1.0):
    р = round(по_высоте(ЖИРНЫЙ, 'добыча 1 добытчиком', 97 - 56, 3) * доля)
    return {'шрифт': шрифт(ЖИРНЫЙ, р), 'цвет': ЦВЕТ_ВЕРХ,
            'обводка': 3, 'цвет_обводки': ОБВОДКА_ВЕРХ}


def база_верха(стиль):
    return базовая('добыча 1 добытчиком', стиль['шрифт'], 97, 3)


def название(лицо, текст, эталон, верх, низ, правый, левый_предел, цвет,
             обводка_цвет=(255, 255, 255)):
    """Название: по высоте печатного соседа, не шире полосы названия."""
    р = по_высоте(ЖИРНЫЙ, эталон, низ - верх, 3)
    f = шрифт(ЖИРНЫЙ, р)
    база_y = базовая(эталон, f, низ, 3)
    while ширина_строки(текст, f, 3) > правый - левый_предел and р > 16:
        р -= 1
        f = шрифт(ЖИРНЫЙ, р)
    стиль = {'шрифт': f, 'цвет': цвет, 'обводка': 3, 'цвет_обводки': обводка_цвет}
    положить(лицо, слой_строки(текст, стиль), база_y, правый=правый)


def тело(лицо, строки, эталон, x0, x1, низ, шаг, правый, цвет, обводка=0, первая=0):
    """Строки тела справа: размер по ширине эталонной строки соседа, первая
    базовая линия — по её низу (эталон стоит в печати строкой номер
    {первая}), дальше с шагом {шаг}."""
    р = по_ширине(ТЕЛО, эталон, x1 - x0, обводка)
    стиль = {'шрифт': шрифт(ТЕЛО, р), 'жирный': шрифт(ТЕЛО_ЖИРНЫЙ, р), 'цвет': цвет,
             'обводка': обводка}
    б = базовая(эталон, стиль['шрифт'], низ, обводка) - шаг * первая
    for k, т in enumerate(строки):
        положить(лицо, слой_строки(т, стиль), б + шаг * k, правый=правый)


def номер(лицо, текст, правый, цвет):
    слой = слой_строки(текст, {'шрифт': шрифт(ЖИРНЫЙ, 30), 'цвет': цвет})
    положить(лицо, слой, 495, правый=правый)


