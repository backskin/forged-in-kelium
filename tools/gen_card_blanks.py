"""ЛИЦА КАРТ НА ПУСТЫХ ЗАГОТОВКАХ — арсенал, начальный и супер (25.09.2026).

Дизайнер положил в экспорт последними картами пустые лица-шаблоны («арсенал-34»,
«арсенал-начальный-8», «арсенал-супер-8…10») и попросил заполнить их самим —
картами, которых в игре пока нет. Эффекты придуманы и внесены в движок
(Арсенал7.карты71 / начальные71, СуперАрсенал4); этот скрипт рисует их лица.
Лица нарисованных дизайнером карт раскладывает tools/gen_card_art.py.

КАК РИСУЕТСЯ. Лицо — сама заготовка дизайнера, поверх неё:
  * знаки ∞ и звезда — СПРАЙТЫ, снятые с печатных соседей с ТЕМ ЖЕ фоном: у
    заготовки и у соседней карты общий рисунок, поэтому разница двух файлов —
    ровно напечатанный знак (начальный-6 ↔ начальный-8, арсенал-33 ↔
    арсенал-34, супер-7 ↔ супер-10). На заготовки супер-8 и супер-9 с другим
    фоном знак ложится той же маской с мягким краем;
  * значки в тексте — из rules/иконки-экспорт (те же рисунки, что на картах);
  * текст — шрифтами Tektur из gui/src/main/resources/fonts: тело — узкий
    Tektur Narrow (им набраны печатные карты), название и верх — Tektur Bold;
  * места, размеры и цвета строк сняты с соседних печатных карт той же колоды
    (см. ПОЛОЖЕНИЕ ниже). Строки ставятся по БАЗОВОЙ ЛИНИИ печатного соседа:
    эталонная строка соседа рисуется нашим шрифтом, и её низ совмещается с
    низом печатной — так «й», «д» и значки не сдвигают строку.

Запуск:  python tools/gen_card_blanks.py [--лист <png>]
Корень экспорта — KELIUM_EXPORT или ~/Yandex.Disk/Forged in Kelium.
Пишет:   data/textures/card/<колода>/<id>.png — ширина 600, как gen_card_art.py.
         --лист <png> — вдобавок лист всех пяти лиц для просмотра глазами.
"""
import os
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЭКСПОРТ = os.environ.get('KELIUM_EXPORT') or os.path.join(
    os.path.expanduser('~'), 'Yandex.Disk', 'Forged in Kelium')
ОБЩИЕ = os.path.join(ЭКСПОРТ, 'Общие компоненты')
ШРИФТЫ = os.path.join(ROOT, 'gui', 'src', 'main', 'resources', 'fonts')
ИКОНКИ = os.path.join(ROOT, 'rules', 'иконки-экспорт')
ШИРИНА = 600

НАЧ = os.path.join(ОБЩИЕ, 'экспорт-арсенал-начальный', 'арсенал-начальный-%d.png')
ОБЫЧ = os.path.join(ОБЩИЕ, 'экспорт-арсенал', 'арсенал-%d.png')
СУПЕР = os.path.join(ОБЩИЕ, 'экспорт-арсенал-супер', 'арсенал-супер-%d.png')

ЖИРНЫЙ = 'Tektur-Bold'
ТЕЛО = 'TekturNarrow-Regular'
ТЕЛО_ЖИРНЫЙ = 'TekturNarrow-Bold'
БАЗА = 170                                   # базовая линия внутри холста строки


# ============================================================================
#  ИНСТРУМЕНТЫ
# ============================================================================

def картинка(путь):
    return Image.open(путь).convert('RGBA')


def шрифт(имя, размер):
    return ImageFont.truetype(os.path.join(ШРИФТЫ, имя + '.ttf'), размер)


def спрайт(печать, заготовка, рамка, порог=14):
    """Напечатанный знак: пиксели печатной карты там, где она отличается от
    заготовки с тем же фоном. Возвращает (RGBA, левый-верх рамки)."""
    a = картинка(печать).crop(рамка)
    b = картинка(заготовка).crop(рамка)
    d = ImageChops.difference(a.convert('RGB'), b.convert('RGB')).convert('L')
    маска = d.point(lambda v: 255 if v > порог else 0)
    маска = маска.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(0.8))
    a.putalpha(маска)
    return a, (рамка[0], рамка[1])


def иконка(имя, высота):
    im = картинка(os.path.join(ИКОНКИ, имя + '.png'))
    im = im.crop(im.getbbox())
    w, h = im.size
    return im.resize((max(1, round(w * высота / h)), высота), Image.LANCZOS)


def рамка_текста(текст, f, обводка=0):
    """Рамка строки относительно базовой линии (x0, y0, x1, y1)."""
    return ImageDraw.Draw(Image.new('L', (1, 1))).textbbox(
        (0, 0), текст, font=f, anchor='ls', stroke_width=обводка)


def ширина_строки(текст, f, обводка=0):
    b = рамка_текста(текст, f, обводка)
    return b[2] - b[0]


def по_ширине(имя, эталон, ширина, обводка=0):
    """Размер, при котором эталонная строка соседа имеет его ширину (тело: оно
    набрано тем же Tektur Narrow, и ширина — самый точный признак)."""
    лучший = 10
    for размер in range(10, 90):
        if ширина_строки(эталон, шрифт(имя, размер), обводка) <= ширина:
            лучший = размер
    return лучший


def по_высоте(имя, эталон, высота, обводка=0):
    """Размер, при котором эталонная строка соседа имеет его высоту (названия
    и верх: печатный шрифт шире нашего, по ширине они вышли бы мельче)."""
    лучший = 10
    for размер in range(10, 90):
        b = рамка_текста(эталон, шрифт(имя, размер), обводка)
        if b[3] - b[1] <= высота:
            лучший = размер
    return лучший


def базовая(эталон, f, низ_печати, обводка=0):
    """Базовая линия печатной строки: её низ минус свисание нашей эталонной."""
    return низ_печати - рамка_текста(эталон, f, обводка)[3]


def строка(текст):
    """«Выполнив {карта-задания:40} задание,» -> части: текст и (значок, высота)."""
    out = []
    while '{' in текст:
        до, после = текст.split('{', 1)
        знак, текст = после.split('}', 1)
        if до:
            out.append(до)
        имя, высота = знак.split(':')
        out.append((имя, int(высота)))
    if текст:
        out.append(текст)
    return out


def слой_строки(текст, стиль):
    """Одна строка: текст (**жирное** — в звёздочках) и значки {имя:высота}.
    Возвращает (RGBA-слой, обрезанный по видимым пикселям; положение базовой
    линии внутри слоя). Значок стоит по центру строчных букв."""
    f = стиль['шрифт']
    fb = стиль.get('жирный', f)
    обв = стиль.get('обводка', 0)
    куски = []
    for часть in строка(текст):
        if isinstance(часть, tuple):
            куски.append(('icon', часть))
            continue
        жирно = False
        for кусок in часть.split('**'):
            if кусок:
                куски.append(('text', (кусок, fb if жирно else f)))
            жирно = not жирно
    холст = Image.new('RGBA', (1800, 300), (0, 0, 0, 0))
    d = ImageDraw.Draw(холст)
    x = 20.0
    строчные = рамка_текста('оаме', f)
    центр = БАЗА + (строчные[1] + строчные[3]) / 2
    for вид, что in куски:
        if вид == 'text':
            текст_куска, шр = что
            d.text((x, БАЗА), текст_куска, font=шр, anchor='ls', fill=стиль['цвет'],
                   stroke_width=обв,
                   stroke_fill=стиль.get('цвет_обводки', (255, 255, 255)))
            x += d.textlength(текст_куска, font=шр)
        else:
            имя, высота = что
            ик = иконка(имя, высота)
            холст.alpha_composite(ик, (round(x + 5), round(центр - высота / 2)))
            x += ик.size[0] + 10
    рамка = холст.getbbox()
    return холст.crop(рамка), БАЗА - рамка[1]


def положить(лицо, слой_и_база, база_y, правый=None, левый=None, центр_x=None):
    слой, база = слой_и_база
    w = слой.size[0]
    if правый is not None:
        x = правый - w
    elif центр_x is not None:
        x = центр_x - w / 2
    else:
        x = левый
    лицо.alpha_composite(слой, (round(x), round(база_y - база)))


def сохранить(лицо, колода, cid):
    куда = os.path.join(ROOT, 'data', 'textures', 'card', колода)
    os.makedirs(куда, exist_ok=True)
    w, h = лицо.size
    лицо = лицо.resize((ШИРИНА, round(h * ШИРИНА / w)), Image.LANCZOS)
    путь = os.path.join(куда, cid + '.png')
    лицо.save(путь, optimize=True)
    print('%-14s %-8s -> %s' % (колода, cid, путь))
    return путь


