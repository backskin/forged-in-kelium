def начальная_7():
    """bs7_7 «Сдача тары»: верх «манёвр 1 войском», ∞ «Вскрывая контейнер,
    получи ещё 1 монету.» Заготовка «арсенал-начальный-8»."""
    лицо = картинка(НАЧ % 8)
    беск, где = спрайт(НАЧ % 6, НАЧ % 8, (8, 205, 128, 285))
    лицо.alpha_composite(беск, где)

    с = стиль_верха()
    положить(лицо, слой_строки('манёвр 1 войском', с), база_верха(с), левый=326)
    название(лицо, 'Сдача тары', 'Полевой генератор', 152, 198, 743, 110, НАЧ_НАЗВАНИЕ)
    тело(лицо, ['Вскрывая контейнер,', 'получи ещё 1 монету.'],
         'в конце Боя, если уничтожил', 307, 745, 253, 54, 744, НАЧ_ТЕЛО)
    номер(лицо, '7', 772, НАЧ_НОМЕР)
    return сохранить(лицо, 'arsenal_start', 'bs7_7')


def обычная_33():
    """a7_33 «Боевое довольствие»: верх «Действие «Манёвр»», ∞ «Выполнив
    задание, получи 1 боеприпас.» Заготовка «арсенал-34»."""
    лицо = картинка(ОБЫЧ % 34)
    # знак ∞ — с №32 («арсенал-33»): у него тот же рисунок
    беск, где = спрайт(ОБЫЧ % 33, ОБЫЧ % 34, (6, 230, 126, 305))
    лицо.alpha_composite(беск, где)

    # верх в две строки по центру между двоеточием и значком — как
    # «Действие / «Снаряжение»» на №14 и №15; значок действия справа, как
    # кулак у «Действие «Бой»» на №2
    с = стиль_верха(0.9)
    for k, т in enumerate(['Действие', '«Манёвр»']):
        положить(лицо, слой_строки(т, с), 62 + 42 * k, центр_x=430)
    лицо.alpha_composite(иконка('манёвр', 84), (664, 30))

    название(лицо, 'Боевое довольствие', 'Аварийное питание', 151, 198, 748, 110,
             ОБЫЧ_НАЗВАНИЕ, ОБЫЧ_ОБВОДКА)
    тело(лицо, ['Выполнив {карта-задания:46} задание,',
                'получи **1** {боеприпас:42} боеприпас.'],
         'Разыграв верхний приказ', 319, 740, 253, 62, 741, ОБЫЧ_ТЕЛО)
    номер(лицо, '33', 781, ОБЫЧ_НОМЕР)
    return сохранить(лицо, 'arsenal', 'a7_33')


def супер(файл, cid, название_текст, строки):
    """Супер-способность ∞ со звездой на заготовке «арсенал-супер-<файл>»."""
    лицо = картинка(СУПЕР % файл)
    беск, где = спрайт(СУПЕР % 7, СУПЕР % 10, (6, 125, 128, 202))
    лицо.alpha_composite(беск, где)
    звезда, где = спрайт(СУПЕР % 7, СУПЕР % 10, (18, 400, 116, 505))
    лицо.alpha_composite(звезда, где)

    название(лицо, название_текст, 'Келемиевый рудник', 34, 81, 749, 118, СУПЕР_ЦВЕТ)
    тело(лицо, строки, 'из общего запаса', 399, 754, 239, 69, 754, СУПЕР_ЦВЕТ,
         обводка=2, первая=1)
    return сохранить(лицо, 'arsenal_super', cid)


