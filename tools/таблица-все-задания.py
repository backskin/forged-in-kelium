def лист(wb, имя, заголовки, ширины):
    ws = wb.create_sheet(имя) if wb.sheetnames != ['Sheet'] else wb.active
    ws.title = имя
    ws.append(заголовки)
    for i, (з, ш) in enumerate(zip(заголовки, ширины), start=1):
        c = ws.cell(row=1, column=i)
        c.font = Font(bold=True, color='FFFFFFFF')
        c.fill = PatternFill('solid', fgColor=ШАПКА)
        c.alignment = Alignment(vertical='center', wrap_text=True)
        c.border = РАМКА
        ws.column_dimensions[get_column_letter(i)].width = ш
    ws.row_dimensions[1].height = 34
    ws.freeze_panes = 'A2'
    return ws


def дописать(ws, строка, тревога=False):
    ws.append(строка)
    r = ws.max_row
    for i in range(1, len(строка) + 1):
        c = ws.cell(row=r, column=i)
        c.alignment = Alignment(vertical='top', wrap_text=True)
        c.border = РАМКА
        if тревога:
            c.fill = PatternFill('solid', fgColor=ТРЕВОГА)
        elif r % 2 == 0:
            c.fill = PatternFill('solid', fgColor=ЧЁТ)


def main():
    свод_id, свод = действующий_свод()
    версии = свод['content_versions']
    снимок = из_кода()
    if снимок:
        зад = снимок['objectives']
        сверх = снимок['super_objectives']
        источник = 'снимок из кода (%s)' % os.path.basename(sys.argv[1])
    else:
        зад = набор('objectives', версии['objectives'])['objectives']
        сверх = набор('super_objectives', версии['super_objectives'])['super_objectives']
        источник = 'файлы набора data/cards'
    К, УТИЛИ = таблица_дизайнера()

    обычные = [c for c in зад if c.get('kind') == 'regular']
    начальные = [c for c in зад if c.get('kind') == 'starting']

    # СЛИЧЕНИЕ: каждой карте данных ищем строку таблицы по смыслу требования.
    пары = {}
    свободные = list(range(len(К)))
    for c in обычные:
        лучшее, где = 0.0, None
        for i in свободные:
            s = похоже(c['requirement'].get('условие'), К[i][2])
            if s > лучшее:
                лучшее, где = s, i
        if где is not None and лучшее >= 0.5:
            пары[c['id']] = (где, лучшее)
            свободные.remove(где)

    wb = Workbook()
    расхождения = []

    # ---------------- обычные ----------------
    ws = лист(wb, 'ОБЫЧНЫЕ %d' % len(обычные),
              ['№', 'id', 'название', 'тип', 'ТРЕБОВАНИЕ', 'УСИЛЕНИЕ',
               'награда', 'усиленная награда', 'цена платится',
               'ВЕРХ (в игре сейчас)', 'ВЕРХ по таблице дизайнера', 'сверка',
               'описание'],
              [4, 7, 20, 12, 44, 34, 20, 18, 18, 30, 44, 26, 60])
    for n, c in enumerate(обычные, start=1):
        строка = пары.get(c['id'])
        если_есть = К[строка[0]] if строка else None
        по_таблице = ('%s: %s' % (УТИЛИ[если_есть[7]][0], УТИЛИ[если_есть[7]][1])
                      if если_есть else 'строка таблицы не найдена')
        # СВЕРКА ПО СУЩЕСТВУ: совпадает ли РОД верха. Таблица 04.09.2026
        # перевела половину верхов в реакции («в моменте»), а в данных верхи
        # остались прежними действиями — вот это и надо увидеть.
        в_игре = верх(c)
        сошлось = если_есть is not None and совпал(в_игре, если_есть[7])
        итог = 'сходится' if сошлось else 'РАСХОЖДЕНИЕ'
        дописать(ws, [n, c['id'], c['name'], c.get('type', ''),
                      c['requirement'].get('условие', ''),
                      (c.get('enhanced') or {}).get('условие', '—'),
                      награда(c.get('base_reward')),
                      награда(c.get('special_reward')),
                      жертва(c), в_игре, по_таблице, итог,
                      c.get('описание', '')], тревога=not сошлось)
        if not сошлось:
            расхождения.append([c['id'], c['name'],
                                c['requirement'].get('условие', ''), в_игре, по_таблице])

    # ---------------- начальные ----------------
    ws = лист(wb, 'НАЧАЛЬНЫЕ %d' % len(начальные),
              ['№', 'id', 'название', 'тип', 'ТРЕБОВАНИЕ', 'УСИЛЕНИЕ',
               'награда', 'усиленная награда', 'ВЕРХ', 'описание'],
              [4, 7, 20, 12, 46, 34, 20, 18, 26, 60])
    for n, c in enumerate(начальные, start=1):
        дописать(ws, [n, c['id'], c['name'], c.get('type', ''),
                      c['requirement'].get('условие', ''),
                      (c.get('enhanced') or {}).get('условие', '—'),
                      награда(c.get('base_reward')),
                      награда(c.get('special_reward')),
                      верх(c), c.get('описание', '')])

    # ---------------- супер ----------------
    ws = лист(wb, 'СУПЕР %d' % len(сверх),
              ['№', 'id', 'название', 'ВЕРХ: множитель в финале',
               'НИЗ: требование', 'НИЗ: награда', 'описание'],
              [4, 8, 22, 46, 46, 46, 62])
    for n, c in enumerate(сверх, start=1):
        дописать(ws, [n, c['id'], c['name'], c.get('multiplier', ''),
                      c.get('requirement', ''), c.get('reward', ''),
                      c.get('описание', '')])

    # ---------------- утили ----------------
    ws = лист(wb, 'УТИЛИ',
              ['код', 'род', 'что делает верх', 'надо по таблице',
               'сейчас в данных (похожих карт)'],
              [6, 16, 60, 16, 26])
    в_данных = Counter()
    for c in обычные:
        в_данных[(c.get('top') or {}).get('label', '—')] += 1
    for код, (род, текст, надо) in УТИЛИ.items():
        есть = sum(n for м, n in в_данных.items() if совпал(м, код))
        дописать(ws, [код, род, текст, надо, есть], тревога=есть != надо)
    дописать(ws, ['', 'ВСЕГО В ДАННЫХ', '; '.join('%s ×%d' % (м, n)
                                                   for м, n in в_данных.items()),
                  sum(н for *_, н in УТИЛИ.values()), sum(в_данных.values())])

    # ---------------- продиктованная колода ----------------
    # ДВЕ КОЛОДЫ В ОДНОЙ КНИГЕ, и это не дублирование. В игре сейчас одна
    # колода, дизайнером продиктована другая; пока вторая не собрана классами,
    # честно показать обе — единственный способ не выдать замысел за игру.
    ws = лист(wb, 'ПРОДИКТОВАНО 40',
              ['№', 'семейство', 'природа', 'ТРЕБОВАНИЕ', 'УСИЛЕНИЕ', 'награда',
               'цена', 'усиленная награда', 'ВЕРХ (утиль)', 'зачем такая пара'],
              [4, 16, 12, 46, 34, 22, 7, 18, 44, 60])
    for n, к in enumerate(К, start=1):
        т, мон, бпр, зад_ = к[4]
        награда_ = ', '.join(x for x in [
            '%d трофей' % т if т else '', '%d монет' % мон if мон else '',
            '%d БПР' % бпр if бпр else '', '%d карт задания' % зад_ if зад_ else ''] if x)
        род, текст, _ = УТИЛИ[к[7]]
        дописать(ws, [n, к[0], к[1], к[2], к[3], награда_, к[5], к[6],
                      '%s · %s: %s' % (к[7], род, текст), к[8]])

    # ---------------- расхождения ----------------
    ws = лист(wb, 'РАСХОЖДЕНИЯ',
              ['id', 'название', 'требование', 'ВЕРХ в игре', 'ВЕРХ по таблице'],
              [8, 22, 50, 32, 50])
    for r in расхождения:
        дописать(ws, r, тревога=True)

    os.makedirs(os.path.dirname(ЦЕЛЬ), exist_ok=True)
    wb.save(ЦЕЛЬ)
    print('свод %s: задания %s, супер %s; источник — %s'
          % (свод_id, версии['objectives'], версии['super_objectives'], источник))
    print('обычных %d, начальных %d, супер %d'
          % (len(обычные), len(начальные), len(сверх)))
    print('сличено с таблицей дизайнера: %d из %d' % (len(пары), len(обычные)))
    print('расхождений по верхам: %d' % len(расхождения))
    print('записано: %s' % ЦЕЛЬ)


# Соответствие «метка верха в данных» -> «код утиля таблицы». Метки в данных
# короткие и печатные, коды таблицы — буквенные; связать их иначе нечем.
МЕТКА_КОД = {
    'СМЕНА ЭНЕРГИИ ИЛИ СМЕНА МОДУЛЕЙ': 'E',
    'АТАКА ОДНИМ ВОЙСКОМ': 'T',
    'СНЯТЬ ВЕСЬ УРОН СО ВСЕХ ЖЕТОНОВ НА ГЕКСЕ': 'H',
    'РАЗЫГРАЙ БОЙ ПЕРЕД ЧУЖИМ БОЕМ': 'P',
    'ОТВЕТНЫЙ ОГОНЬ': 'O',
    'ЗАГРАДИТЕЛЬНЫЙ ОГОНЬ': 'Z',
    'ОТХОД': 'D',
    'РИКОШЕТ': 'R',
    'ЭВАКУАЦИЯ ТРОФЕЕВ': 'V',
}


def совпал(метка_или_верх, код):
    """Тот ли это верх, что назначен таблицей."""
    m = (метка_или_верх or '').upper()
    for метка, к in МЕТКА_КОД.items():
        if метка in m:
            return к == код
    if 'ОБМЕН' in m:
        return код == 'X'
    if 'БОЕПРИПАС' in m and 'ОПЕРАЦИ' in m:
        return код == 'A'
    return False


if __name__ == '__main__':
    main()
