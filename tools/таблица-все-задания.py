РЕСУРС = {'trophy': 'трофей', 'coin': 'монет', 'ammo': 'БПР',
          'objective_card': 'карт задания', 'kelium': 'келемий',
          'arsenal': 'карта арсенала', 'module': 'модуль'}


def награда(d):
    if not d:
        return '—'
    return ', '.join('%s %s' % (v, РЕСУРС.get(k, k)) for k, v in d.items())


def верх(c):
    t = c.get('top') or {}
    метка = t.get('label', '')
    эффект = t.get('effect', '')
    пар = t.get('params') or {}
    хвост = ' '.join('%s=%s' % (k, v) for k, v in пар.items())
    return ('%s [%s%s]' % (метка, эффект, (' ' + хвост) if хвост else '')).strip()


def жертва(c):
    ж = c.get('sacrifice')
    if not ж:
        return ''
    return 'платит: %s %s' % (ж.get('amount'), ж.get('resource'))


