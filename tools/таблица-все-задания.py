"""ВСЕ ЗАДАНИЯ ОДНОЙ КНИГОЙ: обычные, начальные, супер — и сверка с таблицей.

Зачем отдельный файл, когда есть три готовых таблицы. Их три, и каждая про
своё: «ЗАДАНИЯ 1.15.0 — карты целиком» показывает ПРОДИКТОВАННУЮ дизайнером
таблицу (она живёт в tools/таблица-задания-1-15-0.py), «СУПЕР ЗАДАНИЯ 7.0.0» —
данные, а начальных нет вовсе нигде. Разложить их рядом было нельзя, и вопрос
«что сейчас в игре» упирался в три разных ответа.

Здесь книга собирается ИЗ ДАННЫХ, по которым играет движок
(data/cards/objectives.<версия>.yaml и super_objectives.<версия>.yaml, версии
берутся из действующего свода), и рядом ставится колонка «по таблице
дизайнера». Где они расходятся — видно строкой, а не памятью.

Листы:
  ОБЫЧНЫЕ 40    — низ карты, награды, верх (утиль) и сверка с таблицей
  НАЧАЛЬНЫЕ 12  — карты первого раунда
  СУПЕР 17      — множитель в финале и жёсткое требование
  УТИЛИ         — сколько каких верхов в колоде, по данным и по таблице
  РАСХОЖДЕНИЯ   — только те строки, где данные и таблица не совпали

Запуск: python tools/таблица-все-задания.py
"""
