# ---------------------------------------------------------------------------
#  ОТКУДА БЕРУТСЯ ВЕРСИИ: из действующего свода, а не из имён файлов. Иначе
#  книга однажды покажет набор, которым никто не играет.
# ---------------------------------------------------------------------------
def действующий_свод():
    """Свод по умолчанию — тот же, что играет движок.

    Имя берётся из GameConfig.DEFAULT_RULESET, а не «последний по алфавиту»:
    в data/rulesets лежат и опытные ветки вроде 1.7.1-trophy-vp, и такая
    сортировка однажды уже выбрала не тот свод.
    """
    исходник = os.path.join(КОРЕНЬ, 'engine', 'src', 'main', 'java', 'kelium',
                            'dataio', 'GameConfig.java')
    текст = io.open(исходник, encoding='utf-8').read()
    m = re.search(r'kelium\.ruleset",\s*"([^"]+)"', текст)
    if not m:
        raise SystemExit('в GameConfig не нашёлся свод по умолчанию')
    имя = m.group(1)
    d = yaml.safe_load(io.open(os.path.join(СВОД, имя + '.yaml'), encoding='utf-8'))
    return имя, d


def набор(тип, версия):
    путь = os.path.join(КОРЕНЬ, 'data', 'cards', '%s.%s.yaml' % (тип, версия))
    return yaml.safe_load(io.open(путь, encoding='utf-8'))


def из_кода():
    """Снимок карт ИЗ КОДА, если он передан первым доводом.

    Карты заданий живут классами, а файл набора — их выгрузка, сделанная
    когда-то. Совпадать они обязаны, но обязанность не проверяет себя сама:
    снимок делается запуском {@code kelium.ВыгрузкаЗаданий}, и если он передан,
    таблица собирается по нему — то есть по игре, а не по последней выгрузке.
    """
    if len(sys.argv) < 2:
        return None
    d = json.load(io.open(sys.argv[1], encoding='utf-8'))
    return d


# ---------------------------------------------------------------------------
#  ТАБЛИЦА ДИЗАЙНЕРА — импортируется как модуль: она и есть источник замысла.
# ---------------------------------------------------------------------------
def таблица_дизайнера():
    путь = os.path.join(КОРЕНЬ, 'tools', 'таблица-задания-1-15-0.py')
    spec = importlib.util.spec_from_file_location('таблица_1_15_0', путь)
    m = importlib.util.module_from_spec(spec)
    # Модуль при импорте только объявляет таблицы: main() под __main__.
    sys.modules['таблица_1_15_0'] = m
    spec.loader.exec_module(m)
    return m.К, m.УТИЛИ


def ключ(текст):
    """Требование, приведённое к виду, по которому карты сличаются.

    Формулировки в данных и в таблице отличаются знаками препинания, регистром
    и приписками «В ЭТОТ ХОД» — сличать надо по существу, иначе разойдутся все
    сорок строк, и сверка станет бесполезной.
    """
    t = (текст or '').lower().replace('ё', 'е')
    t = t.replace('в этот ход', ' ')
    t = re.sub(r'[^a-zа-я0-9 ]+', ' ', t)
    return ' '.join(t.split())


def похоже(a, b):
    """Совпадают ли требования: по словам, а не побуквенно."""
    A, B = set(ключ(a).split()), set(ключ(b).split())
    if not A or not B:
        return 0.0
    return len(A & B) / max(len(A), len(B))


