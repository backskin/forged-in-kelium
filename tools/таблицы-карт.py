def свод():
    """Действующий свод — тот, что стоит в GameConfig.DEFAULT_RULESET."""
    s = io.open("engine/src/main/java/kelium/dataio/GameConfig.java",
                encoding="utf-8").read()
    m = re.search(r'kelium\.ruleset",\s*"([^"]+)"', s)
    if not m:
        raise SystemExit("не нашёл действующий свод в GameConfig")
    return m.group(1)


def версии(свод_id):
    """Какую версию каждой колоды пинит свод (блок content_versions)."""
    s = io.open("data/rulesets/%s.yaml" % свод_id, encoding="utf-8").read()
    блок = re.search(r"(?ms)^content_versions:\s*\n(.*?)(?=^\S|\Z)", s)
    return dict(re.findall(r"^\s{2}([a-z_]+):\s*([0-9][0-9.]*)",
                           блок.group(1), re.M))


СВОД = свод()
ВЕРСИИ = версии(СВОД)


def ключ_свода(путь, поумолчанию):
    """Значение ключа действующего свода (плоский поиск по отступам)."""
    s = io.open("data/rulesets/%s.yaml" % СВОД, encoding="utf-8").read()
    m = re.search(r"^\s+%s:\s*(-?\d+)" % re.escape(путь.split(".")[-1]),
                  s, re.M)
    return int(m.group(1)) if m else поумолчанию


# Сколько ПО свод платит за саму удерживаемую карту супер-арсенала.
ПО_ЗА_СУПЕР_КАРТУ = ключ_свода("economy.vp_per_installed_super_arsenal", 2)


def набор(тип):
    путь = f"data/cards/{тип}.{ВЕРСИИ[тип]}.yaml"
    return yaml.safe_load(io.open(путь, encoding="utf-8"))[тип]


def награда(узел):
    if not узел:
        return ""
    части = []
    for ключ, значение in узел.items():
        имя = НАГРАДЫ.get(ключ, ключ)
        if ключ == "module":
            части.append("жетон модуля "
                         + ("атаки" if значение == "attack" else "сборки"))
        elif значение == 1:
            части.append(имя)
        else:
            части.append(f"{значение} {имя}")
    return ", ".join(части)


def условие(карта, ключ):
    узел = карта.get(ключ)
    if not isinstance(узел, dict):
        return ""
    return str(узел.get("условие", узел))


def верх(карта):
    в = карта.get("top") or {}
    return str(в.get("label", ""))


def низ(карта):
    н = карта.get("bottom") or {}
    return str(н.get("label", ""))


def ячейки(карта):
    return ", ".join(f"{я.get('amount', 1)} {ЯЧЕЙКИ.get(я.get('kind'), я.get('kind'))}"
                     for я in (карта.get("cells") or []))


def лист(wb, имя, заголовки, строки, ширины, заполняемые=()):
    """Один лист: шапка, строки, ширины колонок, жёлтые колонки под правку."""
    ws = wb.create_sheet(имя)
    ws.append(заголовки)
    for i, з in enumerate(заголовки, start=1):
        c = ws.cell(row=1, column=i)
        c.font = ШАПКА_ТЕКСТ
        c.fill = ШАПКА_ФОН
        c.alignment = Alignment(vertical="center", wrap_text=True)
    for строка in строки:
        ws.append(строка)
    for r in range(2, ws.max_row + 1):
        for i in range(1, len(заголовки) + 1):
            c = ws.cell(row=r, column=i)
            c.font = ЖИРНЫЙ if i == 1 else ТЕКСТ
            c.alignment = Alignment(vertical="top", wrap_text=True)
            c.border = РАМКА
            if заголовки[i - 1] in заполняемые:
                c.fill = ЗАПОЛНИТЬ
    for i, ш in enumerate(ширины, start=1):
        ws.column_dimensions[get_column_letter(i)].width = ш
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(заголовки))}{ws.max_row}"
    return ws


def main():
    задания = набор("objectives")
    арсенал = набор("arsenal")
    суперзадания = набор("super_objectives")
    суперарсенал = набор("super_arsenal")
