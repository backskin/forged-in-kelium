    ws = wb.create_sheet("Сводка", 0)
    ws.append(["Тип карт", "Карт в наборе", "Копий всего"])
    for i in (1, 2, 3):
        c = ws.cell(row=1, column=i)
        c.font = ШАПКА_ТЕКСТ
        c.fill = ШАПКА_ФОН
