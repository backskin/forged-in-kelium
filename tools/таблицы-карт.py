# -*- coding: utf-8 -*-
"""ВСЕ КАРТЫ ИГРЫ В ОДНОЙ КНИГЕ EXCEL — по листу на тип карт.

Заказ дизайнера 25.08.2026: работать с картами удобнее в таблицах, а не в
документах. Отсюда требования, которые тут и выполнены:

* КАЖДЫЙ ТИП КАРТ — СВОЙ ЛИСТ. Задания, начальные задания, супер-задания,
  арсенал, начальный арсенал, супер-арсенал, контейнеры, рынок.
* УТИЛЬ — ОТДЕЛЬНЫМИ ЛИСТАМИ, свой для заданий и свой для арсенала: утиль
  правится отдельно от основного эффекта и сравнивать его удобно между собой,
  а не через всю строку карты.
* КОЛОНКА «КОПИЙ» у арсенала и контейнеров — сколько копий ОСНОВНОГО ЭФФЕКТА
  лежит в колоде. У заданий её нет: задания задуманы все разными.
* СВОДКА с общим числом карт — формулами, а не числом: правишь листы, сумма
  пересчитывается сама.

Источник — снимок каталога ИЗ КОДА (kelium.ВыгрузкаКаталога): у карт, живущих в
коде, файл набора это зеркало, а печатный текст берётся с самой карты.

Запуск:
    java kelium.ВыгрузкаКаталога <тип> таб "снимок"     (по разу на тип)
    python tools/таблицы-карт.py таб
"""
import io
import sys

import yaml
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

СНИМОК = sys.argv[1] if len(sys.argv) > 1 else "таб"
ЦЕЛЬ = sys.argv[2] if len(sys.argv) > 2 else "docs/КАРТЫ — все таблицы.xlsx"

ШРИФТ = "Arial"
ШАПКА_ФОН = PatternFill("solid", fgColor="1F3864")
ШАПКА_ТЕКСТ = Font(name=ШРИФТ, size=10, bold=True, color="FFFFFF")
ТЕКСТ = Font(name=ШРИФТ, size=10)
ЖИРНЫЙ = Font(name=ШРИФТ, size=10, bold=True)
ЗАПОЛНИТЬ = PatternFill("solid", fgColor="FFF2CC")   # колонки под ручную правку
РАМКА = Border(*[Side(style="thin", color="D0D0D0")] * 4)

ПРИРОДА = {
    "state": "состояние",
    "incident": "происшествие",
    "sacrifice": "жертва",
}
РОДА = {"infantry": "пехота", "vehicle": "техника",
        "tower": "вышка", "aircraft": "авиация"}
ЯЧЕЙКИ = {"kelium": "келемий", "ammo": "боеприпас", "trophy": "трофей",
          "coin": "монета", "trophy": "трофей"}
СИМВОЛЫ = {"circle": "круг", "square": "квадрат", "triangle": "треугольник",
           "rhomb": "ромб", "diamond": "ромб", "hourglass": "песочные часы"}
РЕДКОСТЬ = {"common": "обычный", "good": "хороший", "rare": "редкий"}
НАГРАДЫ = {
    "coin": "монеты", "ammo": "боеприпасы", "trophy": "трофеи",
    "kelium": "келемий", "objective_card": "карты задания",
    "arsenal": "карта арсенала",
    "arsenal_from_display": "карта арсенала НА ВЫБОР из открытых",
    "module": "жетон модуля", "storage_token": "жетон хранилища",
    "vp": "победные очки",
}


def набор(тип):
    путь = f"data/cards/{тип}.{СНИМОК}.yaml"
    return yaml.safe_load(io.open(путь, encoding="utf-8"))[тип]


def награда(узел):
    if not узел:
        return ""
    части = []
    for ключ, значение in узел.items():
        имя = НАГРАДЫ.get(ключ, ключ)
        if ключ == "module":
            части.append("жетон модуля "
                         + ("атаки" if значение == "attack" else "сборки"))
        elif значение == 1:
            части.append(имя)
        else:
            части.append(f"{значение} {имя}")
    return ", ".join(части)


def условие(карта, ключ):
    узел = карта.get(ключ)
    if not isinstance(узел, dict):
        return ""
    return str(узел.get("условие", узел))


def верх(карта):
    в = карта.get("top") or {}
    return str(в.get("label", ""))


def низ(карта):
    н = карта.get("bottom") or {}
    return str(н.get("label", ""))


def ячейки(карта):
    return ", ".join(f"{я.get('amount', 1)} {ЯЧЕЙКИ.get(я.get('kind'), я.get('kind'))}"
                     for я in (карта.get("cells") or []))


def лист(wb, имя, заголовки, строки, ширины, заполняемые=()):
    """Один лист: шапка, строки, ширины колонок, жёлтые колонки под правку."""
    ws = wb.create_sheet(имя)
    ws.append(заголовки)
    for i, з in enumerate(заголовки, start=1):
        c = ws.cell(row=1, column=i)
        c.font = ШАПКА_ТЕКСТ
        c.fill = ШАПКА_ФОН
        c.alignment = Alignment(vertical="center", wrap_text=True)
    for строка in строки:
        ws.append(строка)
    for r in range(2, ws.max_row + 1):
        for i in range(1, len(заголовки) + 1):
            c = ws.cell(row=r, column=i)
            c.font = ЖИРНЫЙ if i == 1 else ТЕКСТ
            c.alignment = Alignment(vertical="top", wrap_text=True)
            c.border = РАМКА
            if заголовки[i - 1] in заполняемые:
                c.fill = ЗАПОЛНИТЬ
    for i, ш in enumerate(ширины, start=1):
        ws.column_dimensions[get_column_letter(i)].width = ш
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(заголовки))}{ws.max_row}"
    return ws


def main():
    задания = набор("objectives")
    арсенал = набор("arsenal")
    суперзадания = набор("super_objectives")
    суперарсенал = набор("super_arsenal")
    контейнеры = набор("containers")
    рынок = набор("market")

    обычные_з = [c for c in задания if c.get("kind") != "starting"]
    начальные_з = [c for c in задания if c.get("kind") == "starting"]
    обычный_а = [c for c in арсенал if c.get("kind") != "starting"]
    начальный_а = [c for c in арсенал if c.get("kind") == "starting"]

    wb = Workbook()
    wb.remove(wb.active)

    # ------------------------------ ЗАДАНИЯ ------------------------------
    лист(wb, "Задания",
         ["№", "Название", "Природа", "Условие", "Усиление",
          "Награда", "Усиленная награда", "Утиль", "Описание"],
         [[c["id"], c.get("name", ""),
           ПРИРОДА.get(str(c.get("type")), str(c.get("type"))),
           условие(c, "requirement"), условие(c, "enhanced"),
           награда(c.get("base_reward")), награда(c.get("special_reward")),
           верх(c), c.get("описание", "")] for c in обычные_з],
         [7, 22, 15, 46, 34, 24, 30, 30, 70])

    лист(wb, "Начальные задания",
         ["№", "Название", "Природа", "Условие", "Награда", "Утиль", "Описание"],
         [[c["id"], c.get("name", ""),
           ПРИРОДА.get(str(c.get("type")), str(c.get("type"))),
           условие(c, "requirement"), награда(c.get("base_reward")),
           верх(c), c.get("описание", "")] for c in начальные_з],
         [7, 22, 15, 46, 24, 30, 70])

    лист(wb, "Супер-задания",
         ["№", "Название", "Подзаголовок", "Супероружие", "Символ",
          "Четыре ячейки", "ПО за вскрытие", "Печатный текст", "Описание"],
         [[c["id"], c.get("name", ""), c.get("subtitle", ""),
           РОДА.get(c.get("weapon_unit"), c.get("weapon_unit", "")),
           СИМВОЛЫ.get(c.get("requires_symbol"), c.get("requires_symbol", "")),
           ячейки(c), c.get("vp_on_reveal", 5),
           c.get("текст_карты", ""), c.get("описание", "")] for c in суперзадания],
         [10, 16, 24, 14, 16, 30, 12, 70, 60])

    # ------------------------------ АРСЕНАЛ ------------------------------
    лист(wb, "Арсенал",
         ["№", "Название", "Копий", "Вид низа", "Основной эффект (низ)",
          "Утиль (верх)", "Описание"],
         [[c["id"], c.get("name", ""), 1,
           "СПЕЦ" if (c.get("bottom") or {}).get("kind") == "SPEC" else "постоянный",
           низ(c), верх(c), c.get("описание", "")] for c in обычный_а],
         [7, 24, 8, 13, 60, 44, 70],
         заполняемые=("Копий",))

    лист(wb, "Начальный арсенал",
         ["№", "Название", "Копий", "Вид низа", "Основной эффект (низ)",
          "Утиль (верх)", "Описание"],
         [[c["id"], c.get("name", ""), 1,
           "СПЕЦ" if (c.get("bottom") or {}).get("kind") == "SPEC" else "постоянный",
           низ(c), верх(c), c.get("описание", "")] for c in начальный_а],
         [7, 24, 8, 13, 60, 44, 70],
         заполняемые=("Копий",))

    лист(wb, "Супер-арсенал",
         ["№", "Название", "Вид", "Род войск", "Прочность", "ПО на карте",
          "Что делает", "Печатный текст", "Описание"],
         [[c["id"], c.get("name", ""),
           "супер-войско" if c.get("kind") == "troop" else "способность",
           РОДА.get(c.get("unit"), c.get("unit", "")),
           f"+{c['hp_bonus']}" if c.get("hp_bonus") else "",
           (c.get("vp_on_card") or 0) + (c.get("vp_flat") or 0),
           c.get("label", ""), c.get("текст_карты", ""), c.get("описание", "")]
          for c in суперарсенал],
         [8, 24, 16, 13, 11, 12, 56, 60, 60])

    # ---------------------------- КОНТЕЙНЕРЫ -----------------------------
    лист(wb, "Контейнеры",
         ["№", "Название", "Копий", "Редкость", "Эффект", "Описание"],
         [[c["id"], c.get("name", ""), 1,
           РЕДКОСТЬ.get(c.get("tier"), c.get("tier", "")),
           str((c.get("a") or {}).get("label", "")), c.get("описание", "")]
          for c in контейнеры],
         [7, 26, 8, 13, 40, 70],
         заполняемые=("Копий",))

    # ------------------------------- РЫНОК -------------------------------
    лист(wb, "Рынок",
         ["№", "Название", "Левое предложение", "Что даёт слева",
          "Правое предложение", "Что даёт справа", "Описание"],
         [[c["id"], c.get("name", ""),
           (c.get("left") or {}).get("name", ""),
           (c.get("left") or {}).get("label", ""),
           (c.get("right") or {}).get("name", ""),
           (c.get("right") or {}).get("label", ""),
           c.get("описание", "")] for c in рынок],
         [20, 22, 20, 40, 20, 40, 70])

    # ------------------------------- УТИЛЬ -------------------------------
    # ОТДЕЛЬНЫМИ ЛИСТАМИ: утиль правится сам по себе, и сравнивать его надо
    # между собой — а в строке карты он теряется среди условий и наград.
    лист(wb, "Утиль заданий",
         ["№", "Карта", "Утиль-эффект", "Код эффекта", "Параметры"],
         [[c["id"], c.get("name", ""), верх(c),
           str((c.get("top") or {}).get("effect", "")),
           str((c.get("top") or {}).get("params", ""))] for c in задания],
         [7, 24, 46, 22, 34])

    лист(wb, "Утиль арсенала",
         ["№", "Карта", "Вид карты", "Утиль-эффект", "Код эффекта", "Параметры"],
         [[c["id"], c.get("name", ""),
           "начальная" if c.get("kind") == "starting" else "обычная",
           верх(c), str((c.get("top") or {}).get("effect", "")),
           str((c.get("top") or {}).get("params", ""))] for c in арсенал],
         [7, 24, 13, 46, 22, 34])

    # ------------------------------ СВОДКА -------------------------------
    # ФОРМУЛАМИ, А НЕ ЧИСЛАМИ: правишь листы — сумма пересчитывается сама.
    ws = wb.create_sheet("Сводка", 0)
    ws.append(["Тип карт", "Карт в наборе", "Копий всего"])
    for i in (1, 2, 3):
        c = ws.cell(row=1, column=i)
        c.font = ШАПКА_ТЕКСТ
        c.fill = ШАПКА_ФОН
    строки = [
        ("Задания", "Задания", None),
        ("Начальные задания", "Начальные задания", None),
        ("Супер-задания", "Супер-задания", None),
        ("Арсенал", "Арсенал", "C"),
        ("Начальный арсенал", "Начальный арсенал", "C"),
        ("Супер-арсенал", "Супер-арсенал", None),
        ("Контейнеры", "Контейнеры", "C"),
        ("Рынок", "Рынок", None),
    ]
    r = 2
    for подпись, имялиста, копии in строки:
        ws.cell(row=r, column=1, value=подпись).font = ТЕКСТ
        ws.cell(row=r, column=2,
                value=f"=COUNTA('{имялиста}'!A2:A1000)").font = ТЕКСТ
        ws.cell(row=r, column=3,
                value=(f"=SUM('{имялиста}'!{копии}2:{копии}1000)" if копии
                       else f"=B{r}")).font = ТЕКСТ
        r += 1
    ws.cell(row=r, column=1, value="ВСЕГО").font = ЖИРНЫЙ
    ws.cell(row=r, column=2, value=f"=SUM(B2:B{r - 1})").font = ЖИРНЫЙ
    ws.cell(row=r, column=3, value=f"=SUM(C2:C{r - 1})").font = ЖИРНЫЙ
    ws.cell(row=r + 2, column=1,
            value="«Копий» — сколько копий ОСНОВНОГО эффекта в колоде; жёлтые "
                  "колонки заполняются вручную. У заданий копий нет: они все "
                  "разные.").font = ТЕКСТ
    ws.cell(row=r + 3, column=1,
            value="Источник: снимок каталога из кода (kelium.ВыгрузкаКаталога), "
                  "снимок «" + СНИМОК + "».").font = ТЕКСТ
    ws.column_dimensions["A"].width = 26
    ws.column_dimensions["B"].width = 16
    ws.column_dimensions["C"].width = 14

    wb.save(ЦЕЛЬ)
    print("готово:", ЦЕЛЬ)
    for имя in wb.sheetnames:
        print("  лист:", имя)


if __name__ == "__main__":
    main()
