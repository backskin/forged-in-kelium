КРАСНЫЙ = (173, 0, 0)


def строки_текста(d, текст, f, ширина):
    out, cur = [], ''
    for w in текст.split():
        проба = (cur + ' ' + w).strip()
        if cur and d.textlength(проба, font=f) > ширина:
            out.append(cur)
            cur = w
        else:
            cur = проба
    if cur:
        out.append(cur)
    return out


def красные_строки(im, строки, y0, шаг, р):
    """Строки условия: красный текст на белых полупрозрачных плашках, по правому краю."""
    d = ImageDraw.Draw(im)
    f = шрифт('TekturNarrow-Regular.ttf', р * K)
    слой = Image.new('RGBA', im.size, (0, 0, 0, 0))
    ds = ImageDraw.Draw(слой)
    правый = 627 * K
    for i, t in enumerate(строки):
        w = d.textlength(t, font=f)
        y = (y0 + i * шаг) * K
        ds.rectangle((правый - w - 10 * K, y - 22 * K, правый + 10 * K, y + 22 * K),
                     fill=(255, 255, 255, 185))
    im.alpha_composite(слой)
    d = ImageDraw.Draw(im)
    for i, t in enumerate(строки):
        d.text((правый, (y0 + i * шаг) * K), t, font=f, fill=КРАСНЫЙ, anchor='rm')


