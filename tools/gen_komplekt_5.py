ТЕКСТ_А = (0, 65, 77)
ИМЯ_А = (66, 131, 150)
НОМЕР_А = (90, 130, 161)
ВЕРХ_А = (135, 75, 74)
ЗНАЧКИ = {'spec': 25, 'kel': 5, 'gear': 8, 'coin': 1, 'cell': 28}


def части(текст):
    """«**жирное**» и «{иконка}» → список (вид, значение)."""
    out = []
    for кусок in re.split(r'(\*\*[^*]+\*\*|\{[a-z]+\})', текст):
        if not кусок:
            continue
        if кусок.startswith('**'):
            for w in кусок.strip('*').split():
                out.append(('ж', w))
        elif кусок.startswith('{'):
            out.append(('и', кусок[1:-1]))
        else:
            for w in кусок.split():
                out.append(('т', w))
    return out


def арсенал_текст(im, текст, р, y0, левый=150, правый=722, низ=470):
    d = ImageDraw.Draw(im)
    while True:
        fо = шрифт('TekturNarrow-Regular.ttf', р * K)
        fж = шрифт('TekturNarrow-Bold.ttf', р * K)
        ик = int(р * 1.25 * K)
        пробел = d.textlength(' ', font=fо)
        строки, cur, ш = [], [], 0
        for вид, з in части(текст):
            w = ик if вид == 'и' else d.textlength(з, font=fж if вид == 'ж' else fо)
            if cur and ш + пробел + w > (правый - левый) * K:
                строки.append((cur, ш))
                cur, ш = [], 0
            # знак препинания прилипает к предыдущему слову
            прилип = вид != 'и' and з[:1] in ',.;:!?»)'
            if cur and not прилип:
                ш += пробел
            cur.append((вид, з, w, прилип))
            ш += w
        if cur:
            строки.append((cur, ш))
        шаг = int(р * 1.5)
        if y0 + len(строки) * шаг <= низ or р <= 24:
            break
        р -= 2
    y = y0
    for стр, ш in строки:
        x = правый * K - ш
        первый = True
        for вид, з, w, прилип in стр:
            if not первый and not прилип:
                x += пробел
            первый = False
            if вид == 'и':
                ic = вписать(икона(ЗНАЧКИ[з]), ик, ик)
                im.alpha_composite(ic, (int(x), int(y * K - ic.height / 2)))
            else:
                d.text((x, y * K), з, font=fж if вид == 'ж' else fо, fill=ТЕКСТ_А,
                       anchor='lm', stroke_width=2 * K, stroke_fill=БЕЛЫЙ)
            x += w
        y += шаг


def арсенал_новый_низ(файл, имя, текст, номер, звезда, р=36):
    """Верхняя полоса — с печатной карты, остальное — пустой шаблон ∞ дизайнера."""
    печ = крупно(os.path.join(АРСЕНАЛ_ЭКСП, 'арсенал-%d.png' % файл))
    im = крупно(os.path.join(АРСЕНАЛ_ШАБЛ, 'арсенал-1.png'))
    верх = 122 * K
    полоса = печ.crop((0, 0, печ.width, верх))
    # мягкий шов: нижние 16 px полосы растворяются в шаблон
    маска = Image.new('L', полоса.size, 255)
    dm = ImageDraw.Draw(маска)
    for i in range(16 * K):
        dm.line((0, верх - 1 - i, полоса.width, верх - 1 - i), fill=int(255 * i / (16 * K)))
    im.paste(полоса, (0, 0), маска)
    d = ImageDraw.Draw(im)
    f_имя = шрифт('Tektur-Bold.ttf', 40 * K)
    while d.textlength(имя, font=f_имя) > 560 * K:
        f_имя = шрифт('Tektur-Bold.ttf', f_имя.size - 2)
    d.text((718 * K, 167 * K), имя, font=f_имя, fill=БЕЛЫЙ, anchor='rm',
           stroke_width=4 * K, stroke_fill=ИМЯ_А)
    арсенал_текст(im, текст, р, 238)
    if звезда:
        z = вписать(икона(21), 80 * K, 80 * K)
        im.alpha_composite(z, (22 * K, 405 * K))
    d.text((748 * K, 465 * K), str(номер), font=шрифт('Tektur-Bold.ttf', 26 * K),
           fill=НОМЕР_А, anchor='rm')
    return мелко(im)


def арсенал_новый_верх(файл, строки_верха):
    """Меняет только надпись верха: стирает её куском шаблона, пишет новую."""
    im = крупно(os.path.join(АРСЕНАЛ_ЭКСП, 'арсенал-%d.png' % файл))
    ш = крупно(os.path.join(АРСЕНАЛ_ШАБЛ, 'арсенал-1.png'))
    b = tuple(v * K for v in (245, 18, 600, 118))
    кусок = ш.crop(b)
    # края заплатки растворяются: шов на полупрозрачной шапке не виден
    маска = Image.new('L', кусок.size, 0)
    ImageDraw.Draw(маска).rounded_rectangle((0, 0, кусок.width - 1, кусок.height - 1),
                                            radius=18 * K, fill=255)
    from PIL import ImageFilter
    маска = маска.filter(ImageFilter.GaussianBlur(9 * K))
    im.paste(кусок, b[:2], маска)
    d = ImageDraw.Draw(im)
    f = шрифт('Tektur-Bold.ttf', 38 * K)
    # как на печати этой карты: белые буквы с бордовой обводкой
    for i, t in enumerate(строки_верха):
        d.text((420 * K, (45 + i * 48) * K), t, font=f, fill=БЕЛЫЙ, anchor='mm',
               stroke_width=4 * K, stroke_fill=ВЕРХ_А)
    return мелко(im)


