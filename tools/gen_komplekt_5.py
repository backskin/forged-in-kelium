def ветка_построить(развилка, сторона):
    """Иконка развилки, в правом нижнем углу — кран: «построй …»."""
    холст = Image.new('RGBA', (сторона, сторона), (0, 0, 0, 0))
    осн = вписать(икона(РАЗВИЛКА[развилка]), int(сторона * 0.74), int(сторона * 0.74))
    холст.alpha_composite(осн, (int(сторона * 0.04), int(сторона * 0.06)))
    кран = вписать(икона(31), int(сторона * 0.60), int(сторона * 0.60))
    холст.alpha_composite(кран, (сторона - кран.width, сторона - кран.height))
    return холст


