ТОНКАЯ = Side(style='thin', color='FFB0B0B0')
РАМКА = Border(left=ТОНКАЯ, right=ТОНКАЯ, top=ТОНКАЯ, bottom=ТОНКАЯ)


def main():
    # Сверка с диктовкой: числа мест должны сойтись до карты.
    from collections import Counter
    низов = Counter(b for _, _, b, _ in КОЛОДА)
    верхов = Counter(t for _, t, _, _ in КОЛОДА)
    ждём_низов = {'B2': 2, 'B7': 2, 'B9': 2, 'B10': 2, 'B12': 2, 'B14': 2,
                  'B17': 2, 'B19': 2, 'B20': 2, 'B21': 2}
    ждём_верхов = {'T2': 3, 'T1': 1, 'T6': 1, 'T14': 1}
    for код, (_, _) in НИЗЫ.items():
        надо = ждём_низов.get(код, 1)
        if низов[код] != надо:
            raise SystemExit(f'низ {код}: {низов[код]} карт вместо {надо}')
    for код in ВЕРХА:
        надо = ждём_верхов.get(код, 2)
        if верхов[код] != надо:
            raise SystemExit(f'верх {код}: {верхов[код]} карт вместо {надо}')
    if len(КОЛОДА) != 32:
        raise SystemExit(f'карт {len(КОЛОДА)}, а надо 32')

    wb = Workbook()
    ws = wb.active
    ws.title = 'Арсенал 5.0.0'

    заголовки = ['№', 'НАЗВАНИЕ КАРТЫ', 'код верха', 'ВЕРХ (утиль) — разовое действие',
                 'тип низа', 'НИЗ (установка) — постоянное свойство', 'зачем такая пара']
    ширины = [5, 26, 17, 46, 15, 62, 62]
    ws.append(заголовки)
    for i, (з, ш) in enumerate(zip(заголовки, ширины), start=1):
        c = ws.cell(row=1, column=i)
        c.font = Font(bold=True, color='FFFFFFFF')
        c.fill = PatternFill('solid', fgColor='FF2F5D50')
        c.alignment = Alignment(vertical='center', wrap_text=True)
        c.border = РАМКА
        ws.column_dimensions[get_column_letter(i)].width = ш
    ws.row_dimensions[1].height = 32

    for n, (имя, t, b, зачем) in enumerate(КОЛОДА, start=1):
        код_верха, действие = ВЕРХА[t]
        тип, установка = НИЗЫ[b]
        ws.append([n, имя, код_верха, действие, тип, установка, зачем])
        for i in range(1, len(заголовки) + 1):
            c = ws.cell(row=n + 1, column=i)
            c.alignment = Alignment(vertical='top', wrap_text=True)
            c.border = РАМКА
            if n % 2 == 0:
                c.fill = PatternFill('solid', fgColor='FFF2F6F4')
        ws.cell(row=n + 1, column=2).font = Font(bold=True)

    ws.freeze_panes = 'A2'
    ws.auto_filter.ref = f'A1:G{len(КОЛОДА) + 1}'

    # Второй лист — сколько какой половины в колоде, чтобы сверять глазами.
    ws2 = wb.create_sheet('Сколько чего')
    ws2.append(['ВЕРХ: код', 'действие', 'карт'])
    for t, (код, действие) in ВЕРХА.items():
        ws2.append([код, действие, верхов[t]])
    ws2.append([])
    ws2.append(['НИЗ: тип', 'установка', 'карт'])
    for b, (тип, установка) in НИЗЫ.items():
        ws2.append([тип, установка, низов[b]])
    for i, ш in enumerate([18, 62, 8], start=1):
        ws2.column_dimensions[get_column_letter(i)].width = ш
    for row in ws2.iter_rows():
        for c in row:
            c.alignment = Alignment(vertical='top', wrap_text=True)
    for r in (1, len(ВЕРХА) + 3):
        for c in ws2[r]:
            c.font = Font(bold=True)

    wb.save(ЦЕЛЬ)
    print(f'готово: {ЦЕЛЬ}, карт {len(КОЛОДА)}')


if __name__ == '__main__':
    main()
