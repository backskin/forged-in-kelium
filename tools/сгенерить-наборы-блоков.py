# -*- coding: utf-8 -*-
"""ГЕНЕРАТОР НАБОРОВ БЛОКОВ — все сочетания контейнеров и жёлтых ячеек.

ЗАЧЕМ. В каталоге блоков дизайнер выбирает набор двумя параметрами: сколько
гексов блока несут печатный контейнер и сколько — жёлтую ячейку энергии. Наборов
в данных было пять, а сочетаний этих параметров двенадцать: семь пар не
существовали, и каталог на них отвечал «нет набора с таким сочетанием». Правило
дизайнера 31.08.2026: несуществующие сочетания надо не скрывать, а СГЕНЕРИТЬ.

ЧТО МЕНЯЕТСЯ, А ЧТО НЕТ. Геометрия сторон — физический картон: двадцать сторон
(пять малых блоков по 5 гексов и пять больших по 6, каждый двусторонний), и она
во всех наборах ОДНА И ТА ЖЕ (проверено: отпечатки (q,r) совпадают у всех пяти
версий). Различается только РАЗМЕТКА: на каких гексах контейнер и жёлтая ячейка
и в какой ячейке гекса они стоят. Поэтому генератор берёт геометрию из
существующего набора и раскладывает по ней разметку.

ПЯТЬ ПРАВИЛ РАЗМЕТКИ — не выдуманы, а сняты с существующих наборов замером:
  1. на гексе с контейнером И жёлтой ячейкой их индексы РАЗНЫЕ (250 случаев в
     данных, ни одного совпадения);
  2. индексы контейнеров внутри одной стороны не повторяются;
  3. индексы жёлтых ячеек внутри одной стороны не повторяются;
  4. ровно ОДИН контейнер на стороне стоит в центральной ячейке (индекс 6),
     остальные — в боковых 0..5; жёлтая ячейка в центре не бывает никогда;
  5. сторона Б никогда не повторяет рисунок стороны А того же блока.
Плюс требование дизайнера к прежним наборам: перекос по сторонам не выше 1 —
здесь это ровное распределение индексов 0..5 по всем сторонам.

Запуск:  python tools/сгенерить-наборы-блоков.py [--перезаписать]
Без ключа существующие файлы не трогаются: генерируются только отсутствующие
сочетания.
"""
import io
import random
import sys
from collections import Counter

import yaml

ГЕОМЕТРИЯ_ИЗ = 'data/blocks/blocks.1.4.0.yaml'
ПАПКА = 'data/blocks'
ЦЕНТР = 6                      # индекс центральной ячейки гекса
БОКОВЫЕ = list(range(6))       # 0..5 — боковые ячейки

# Сколько гексов несут контейнер на МАЛОМ блоке (на большом всегда +1).
# Значения взяты из существующих наборов: 5 (все), 4 и 3.
КОНТЕЙНЕРЫ = [5, 4, 3]
# Сколько гексов несут жёлтую ячейку. None — жёлтых ячеек нет вовсе.
ЭНЕРГИЯ = [None, 5, 4, 3]


def геометрия():
    """Двадцать сторон с их гексами: [(id блока, kind, сторона, [(q,r)...])]."""
    d = yaml.safe_load(io.open(ГЕОМЕТРИЯ_ИЗ, encoding='utf-8').read())
    стороны = []
    for b in d['blocks']:
        for сторона in ('A', 'B'):
            гексы = (b.get('faces') or {}).get(сторона)
            if not isinstance(гексы, list):
                continue
            стороны.append((b['id'], b['kind'], сторона,
                            [(h['q'], h['r']) for h in гексы]))
    return стороны


def существующие():
    """Какие сочетания уже лежат в данных: {(контейнеров, энергии): id}."""
    import glob
    найдено = {}
    for f in sorted(glob.glob(ПАПКА + '/blocks.*.yaml')):
        d = yaml.safe_load(io.open(f, encoding='utf-8').read())
        vid = (d.get('meta') or {}).get('id', f)
        малые = [b for b in d['blocks'] if b.get('kind') == 'small']
        if not малые:
            continue
        лицо = (малые[0].get('faces') or {}).get('A') or []
        к = sum(1 for h in лицо if (h.get('cell') if h.get('cell') is not None else -1) >= 0)
        э = sum(1 for h in лицо if (h.get('energy') if h.get('energy') is not None else -1) >= 0)
        найдено[(к, э if э > 0 else None)] = vid
    return найдено


def выбрать_ровно(счётчик, сколько, из_чего, запрещено=()):
    """Взять `сколько` наименее использованных значений — так растёт ровность."""
    можно = [v for v in из_чего if v not in запрещено]
    можно.sort(key=lambda v: (счётчик[v], v))
    return можно[:сколько]


def разметить_сторону(гексы, кол_контейнеров, кол_энергии, счК, счЭ, rnd):
    """Одна сторона: кому контейнер, кому жёлтая ячейка и с какими индексами."""
    порядок = list(range(len(гексы)))
    rnd.shuffle(порядок)
    сКонтейнером = порядок[:кол_контейнеров]

    # Индексы контейнеров: ровно один центральный, остальные боковые и разные.
    центральный = rnd.choice(сКонтейнером)
    боковые = выбрать_ровно(счК, кол_контейнеров - 1, БОКОВЫЕ)
    rnd.shuffle(боковые)
    индексК = {}
    for i in сКонтейнером:
        if i == центральный:
            индексК[i] = ЦЕНТР
        else:
            индексК[i] = боковые.pop()

    индексЭ = {}
    if кол_энергии:
        # Жёлтые ячейки предпочитают гексы с контейнером — так набор читается
        # как «эти гексы рабочие», а не как две независимые россыпи.
        сЭнергией = list(сКонтейнером)
        rnd.shuffle(сЭнергией)
        сЭнергией = сЭнергией[:кол_энергии]
        если_мало = [i for i in порядок if i not in сЭнергией]
        while len(сЭнергией) < кол_энергии and если_мало:
            сЭнергией.append(если_мало.pop(0))
        занято = set()
        for i in сЭнергией:
            нельзя = занято | ({индексК[i]} if i in индексК else set())
            свободные = выбрать_ровно(счЭ, 1, БОКОВЫЕ, запрещено=нельзя)
            if not свободные:
                return None                     # тупик — пусть решает пересдача
            индексЭ[i] = свободные[0]
            занято.add(свободные[0])

    for i in индексК.values():
        if i != ЦЕНТР:
            счК[i] += 1
    for i in индексЭ.values():
        счЭ[i] += 1

    записи = []
    for n, (q, r) in enumerate(гексы):
        рек = {'q': q, 'r': r, 'cell': индексК.get(n, -1)}
        if кол_энергии:
            рек['energy'] = индексЭ.get(n, -1)
        записи.append(рек)
    return записи


def набор(стороны, кол_контейнеров_малый, кол_энергии_малый, зерно, id_набора):
    """Собрать весь набор из двадцати сторон; при тупике — пересдать с новым зерном."""
    for попытка in range(400):
        rnd = random.Random(зерно + попытка)
        счК, счЭ = Counter(), Counter()
        блоки = {}
        порядок_блоков = []
        сорвалось = False
        for bid, kind, сторона, гексы in стороны:
            малый = kind == 'small'
            кк = кол_контейнеров_малый if малый else кол_контейнеров_малый + 1
            кэ = None if кол_энергии_малый is None else (
                кол_энергии_малый if малый else кол_энергии_малый + 1)
            разметка = разметить_сторону(гексы, кк, кэ, счК, счЭ, rnd)
            if разметка is None:
                сорвалось = True
                break
            if bid not in блоки:
                блоки[bid] = {'id': bid, 'kind': kind, 'faces': {}}
                порядок_блоков.append(bid)
            блоки[bid]['faces'][сторона] = разметка
        if сорвалось:
            continue
        # Правило 5: сторона Б не повторяет сторону А.
        if any(b['faces'].get('A') == b['faces'].get('B') for b in блоки.values()):
            continue
        # Ровность: перекос по боковым индексам не выше 1.
        if счК and max(счК.values()) - min(счК[i] for i in БОКОВЫЕ) > 1:
            continue
        if счЭ and max(счЭ.values()) - min(счЭ[i] for i in БОКОВЫЕ) > 1:
            continue
        подпись = ('без жёлтых ячеек' if кол_энергии_малый is None
                   else f'{кол_энергии_малый}/5 и {кол_энергии_малый + 1}/6')
        meta = {
            'id': id_набора,
            'type': 'blocks',
            'seed': зерно + попытка,
            'описание': f'контейнеры {кол_контейнеров_малый}/5 и '
                        f'{кол_контейнеров_малый + 1}/6, энергия {подпись}',
            'сгенерировано': 'tools/сгенерить-наборы-блоков.py',
        }
        if кол_энергии_малый is not None:
            meta['partial_energy'] = True
        return {'meta': meta,
                'blocks': [блоки[bid] for bid in порядок_блоков]}
    return None


def main():
    перезаписать = '--перезаписать' in sys.argv
    стороны = геометрия()
    было = существующие()
    print('сторон в геометрии:', len(стороны))
    print('сочетаний уже есть:', len(было))

    свободный = 0
    сделано = []
    for к in КОНТЕЙНЕРЫ:
        for э in ЭНЕРГИЯ:
            if (к, э) in было and not перезаписать:
                continue
            id_набора = f'2.{свободный}.0'
            свободный += 1
            n = набор(стороны, к, э, 20260831, id_набора)
            if n is None:
                print(f'  НЕ СОБРАЛОСЬ: контейнеры {к}, энергия {э}')
                continue
            путь = f'{ПАПКА}/blocks.{id_набора}.yaml'
            шапка = (
                '# CONTENT: blocks  version ' + id_набора + '\n'
                '# СГЕНЕРИРОВАНО tools/сгенерить-наборы-блоков.py по правилу\n'
                '# дизайнера 31.08.2026: несуществующие сочетания контейнеров и\n'
                '# жёлтых ячеек не скрывать, а придумать. Геометрия сторон взята\n'
                '# из набора 1.4.0 и не менялась - это физический картон.\n'
                '# ' + n['meta']['описание'] + '\n')
            io.open(путь, 'w', encoding='utf-8').write(
                шапка + yaml.safe_dump(n, allow_unicode=True, sort_keys=False, width=100))
            сделано.append((id_набора, n['meta']['описание']))

    print('сгенерировано наборов:', len(сделано))
    for i, о in сделано:
        print(f'  {i}: {о}')


if __name__ == '__main__':
    main()
