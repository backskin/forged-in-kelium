# -*- coding: utf-8 -*-
"""ГЕНЕРАТОР НАБОРОВ БЛОКОВ — по три варианта разметки на каждое сочетание.

ЗАЧЕМ. В каталоге блоков дизайнер выбирает набор двумя параметрами: сколько
гексов блока несут печатный контейнер и сколько — жёлтую ячейку энергии. Пар
таких параметров двенадцать, и на каждую нужен не один набор, а ТРИ разных
раскладки, чтобы было из чего выбирать при печати (заказ 02.09.2026). Итого
36 наборов: id вида 3.<сочетание>.<вариант>, вариант — последняя цифра.

ВАРИАНТ 1 — ОСОБЫЙ. Отдельное требование дизайнера: в нём блоки должны попарно
отличаться друг от друга как можно сильнее. Поэтому первый вариант собирается
не случайно, а жадно: каждая следующая сторона выбирается из четырёх десятков
законных кандидатов — та, что дальше всех отстоит от уже разложенных сторон
своего размера. Расстояние между сторонами — по скольким гексам не совпали
пары «ячейка контейнера, ячейка энергии». В шапку набора пишется замер:
наименьшее и среднее попарное расстояние (см. поле «разброс»).
Варианты 2 и 3 — обычная случайная раскладка, только проверенная на то, что не
повторяет ни первый вариант, ни друг друга.

ЧТО МЕНЯЕТСЯ, А ЧТО НЕТ. Геометрия сторон — физический картон: двадцать сторон
(пять малых блоков по 5 гексов и пять больших по 6, каждый двусторонний), и она
во всех наборах ОДНА И ТА ЖЕ (проверено: отпечатки (q,r) совпадают у всех пяти
авторских версий). Различается только РАЗМЕТКА: на каких гексах контейнер и
жёлтая ячейка и в какой ячейке гекса они стоят. Авторские наборы 1.0.0–1.4.0
генератор не трогает.

ПЯТЬ ПРАВИЛ РАЗМЕТКИ — не выдуманы, а сняты с существующих наборов замером:
  1. на гексе с контейнером И жёлтой ячейкой их индексы РАЗНЫЕ (250 случаев в
     данных, ни одного совпадения);
  2. индексы контейнеров внутри одной стороны не повторяются;
  3. индексы жёлтых ячеек внутри одной стороны не повторяются;
  4. ровно ОДИН контейнер на стороне стоит в центральной ячейке (индекс 6),
     остальные — в боковых 0..5; жёлтая ячейка в центре не бывает никогда;
  5. сторона Б никогда не повторяет рисунок стороны А того же блока.
Плюс требование дизайнера к прежним наборам: перекос по сторонам не выше 1 —
здесь это ровное распределение индексов 0..5 по всем сторонам.

Запуск:  python tools/сгенерить-наборы-блоков.py [--перезаписать]
Без ключа уже лежащие файлы 3.*.* не трогаются.
"""
import glob
import io
import itertools
import os
import random
import sys
from collections import Counter

import yaml

ГЕОМЕТРИЯ_ИЗ = 'data/blocks/blocks.1.4.0.yaml'
ПАПКА = 'data/blocks'
ЦЕНТР = 6                      # индекс центральной ячейки гекса
БОКОВЫЕ = list(range(6))       # 0..5 — боковые ячейки
ВАРИАНТОВ = 3                  # сколько раскладок на каждое сочетание

# Сколько гексов несут контейнер на МАЛОМ блоке (на большом всегда +1).
# Значения взяты из существующих наборов: 5 (все), 4 и 3.
КОНТЕЙНЕРЫ = [5, 4, 3]
# Сколько гексов несут жёлтую ячейку. None — жёлтых ячеек нет вовсе.
ЭНЕРГИЯ = [None, 5, 4, 3]

ЗЕРНО = 20260902
КАНДИДАТОВ = 40                # сколько раскладок стороны перебрать в варианте 1


def геометрия():
    """Двадцать сторон с их гексами: [(id блока, kind, сторона, [(q,r)...])]."""
    d = yaml.safe_load(io.open(ГЕОМЕТРИЯ_ИЗ, encoding='utf-8').read())
    стороны = []
    for b in d['blocks']:
        for сторона in ('A', 'B'):
            гексы = (b.get('faces') or {}).get(сторона)
            if not isinstance(гексы, list):
                continue
            стороны.append((b['id'], b['kind'], сторона,
                            [(h['q'], h['r']) for h in гексы]))
    return стороны


def выбрать_ровно(счётчик, сколько, из_чего, запрещено=(), rnd=None):
    """Взять `сколько` наименее использованных значений — так растёт ровность.

    rnd подмешивается в сортировку: при равном счёте выбор случайный, иначе все
    кандидаты стороны выходили бы одинаковыми и перебор в варианте 1 был бы
    бессмысленным.
    """
    можно = [v for v in из_чего if v not in запрещено]
    ключ = ((lambda v: (счётчик[v], rnd.random())) if rnd is not None
            else (lambda v: (счётчик[v], v)))
    можно.sort(key=ключ)
    return можно[:сколько]


def разметить_сторону(гексы, кол_контейнеров, кол_энергии, счК, счЭ, rnd):
    """Одна сторона: кому контейнер, кому жёлтая ячейка и с какими индексами.

    Счётчики НЕ трогаются — что израсходовано, возвращается отдельно, чтобы
    можно было перебрать несколько кандидатов и списать только принятого.
    """
    порядок = list(range(len(гексы)))
    rnd.shuffle(порядок)
    сКонтейнером = порядок[:кол_контейнеров]

    # Индексы контейнеров: ровно один центральный, остальные боковые и разные.
    центральный = rnd.choice(сКонтейнером)
    боковые = выбрать_ровно(счК, кол_контейнеров - 1, БОКОВЫЕ, rnd=rnd)
    rnd.shuffle(боковые)
    индексК = {}
    for i in сКонтейнером:
        if i == центральный:
            индексК[i] = ЦЕНТР
        else:
            индексК[i] = боковые.pop()

    индексЭ = {}
    if кол_энергии:
        # Жёлтые ячейки предпочитают гексы с контейнером — так набор читается
        # как «эти гексы рабочие», а не как две независимые россыпи.
        сЭнергией = list(сКонтейнером)
        rnd.shuffle(сЭнергией)
        сЭнергией = сЭнергией[:кол_энергии]
        если_мало = [i for i in порядок if i not in сЭнергией]
        while len(сЭнергией) < кол_энергии and если_мало:
            сЭнергией.append(если_мало.pop(0))
        занято = set()
        for i in сЭнергией:
            нельзя = занято | ({индексК[i]} if i in индексК else set())
            свободные = выбрать_ровно(счЭ, 1, БОКОВЫЕ, запрещено=нельзя, rnd=rnd)
            if not свободные:
                return None                     # тупик — пусть решает пересдача
            индексЭ[i] = свободные[0]
            занято.add(свободные[0])

    записи = []
    for n, (q, r) in enumerate(гексы):
        рек = {'q': q, 'r': r, 'cell': индексК.get(n, -1)}
        if кол_энергии:
            рек['energy'] = индексЭ.get(n, -1)
        записи.append(рек)
    расходК = [i for i in индексК.values() if i != ЦЕНТР]
    расходЭ = list(индексЭ.values())
    return записи, расходК, расходЭ


def отпечаток(разметка):
    """Рисунок стороны без координат — по нему и считается непохожесть."""
    return tuple((h['cell'], h.get('energy', -1)) for h in разметка)


def расстояние(a, b):
    """По скольким гексам две стороны не совпали."""
    return sum(1 for x, y in zip(a, b) if x != y)


def разброс(отпечатки):
    """(наименьшее, среднее) попарное расстояние внутри группы сторон."""
    пары = list(itertools.combinations(отпечатки, 2))
    if not пары:
        return 0, 0.0
    d = [расстояние(a, b) for a, b in пары]
    return min(d), sum(d) / len(d)


def набор(стороны, кол_контейнеров_малый, кол_энергии_малый, зерно, id_набора,
          пореже=False, чужие=()):
    """Собрать весь набор из двадцати сторон.

    пореже=True — вариант 1: каждая сторона выбирается из КАНДИДАТОВ раскладок
    так, чтобы она была как можно дальше от уже разложенных сторон своего
    размера. чужие — отпечатки целых наборов, повторять которые нельзя.
    """
    for попытка in range(400):
        rnd = random.Random(зерно + попытка * 7919)
        счК, счЭ = Counter(), Counter()
        блоки = {}
        порядок_блоков = []
        разложено = {'small': [], 'big': []}
        сорвалось = False
        for bid, kind, сторона, гексы in стороны:
            малый = kind == 'small'
            кк = кол_контейнеров_малый if малый else кол_контейнеров_малый + 1
            кэ = None if кол_энергии_малый is None else (
                кол_энергии_малый if малый else кол_энергии_малый + 1)

            сколько = КАНДИДАТОВ if пореже else 1
            лучший = None
            for _ in range(сколько):
                кандидат = разметить_сторону(гексы, кк, кэ, счК, счЭ, rnd)
                if кандидат is None:
                    continue
                разметка, расходК, расходЭ = кандидат
                if not пореже:
                    лучший = кандидат
                    break
                свой = отпечаток(разметка)
                уже = разложено[kind]
                близость = min((расстояние(свой, о) for о in уже), default=99)
                сумма = sum(расстояние(свой, о) for о in уже)
                # Ровность важнее непохожести: перекос индексов ломает печать,
                # а похожие блоки — только скучны. Поэтому она первым ключом.
                п = Counter(счК)
                п.update(расходК)
                перекос = (max(п.values()) - min(п[i] for i in БОКОВЫЕ)) if п else 0
                оценка = (-перекос, близость, сумма)
                if лучший is None or оценка > лучший[0]:
                    лучший = (оценка, кандидат)
            if лучший is None:
                сорвалось = True
                break
            разметка, расходК, расходЭ = лучший[1] if пореже else лучший
            счК.update(расходК)
            счЭ.update(расходЭ)
            разложено[kind].append(отпечаток(разметка))
            if bid not in блоки:
                блоки[bid] = {'id': bid, 'kind': kind, 'faces': {}}
                порядок_блоков.append(bid)
            блоки[bid]['faces'][сторона] = разметка
        if сорвалось:
            continue
        # Правило 5: сторона Б не повторяет сторону А.
        if any(b['faces'].get('A') == b['faces'].get('B') for b in блоки.values()):
            continue
        # Ровность: перекос по боковым индексам не выше 1.
        if счК and max(счК.values()) - min(счК[i] for i in БОКОВЫЕ) > 1:
            continue
        if счЭ and max(счЭ.values()) - min(счЭ[i] for i in БОКОВЫЕ) > 1:
            continue
        весь = tuple(sorted(разложено['small'])) + tuple(sorted(разложено['big']))
        if весь in чужие:
            continue                      # такой вариант уже есть в сочетании

        мал = разброс(разложено['small'])
        бол = разброс(разложено['big'])
        подпись = ('без жёлтых ячеек' if кол_энергии_малый is None
                   else f'{кол_энергии_малый}/5 и {кол_энергии_малый + 1}/6')
        meta = {
            'id': id_набора,
            'type': 'blocks',
            'seed': зерно + попытка * 7919,
            'вариант': int(id_набора.rsplit('.', 1)[1]),
            'описание': f'контейнеры {кол_контейнеров_малый}/5 и '
                        f'{кол_контейнеров_малый + 1}/6, энергия {подпись}',
            'разброс': f'малые: наименьшее {мал[0]}, среднее {мал[1]:.2f}; '
                       f'большие: наименьшее {бол[0]}, среднее {бол[1]:.2f}',
            'сгенерировано': 'tools/сгенерить-наборы-блоков.py',
        }
        if кол_энергии_малый is not None:
            meta['partial_energy'] = True
        return ({'meta': meta,
                 'blocks': [блоки[bid] for bid in порядок_блоков]}, весь, мал, бол)
    return None


def main():
    перезаписать = '--перезаписать' in sys.argv
    стороны = геометрия()
    print('сторон в геометрии:', len(стороны))

    сделано = []
    сочетание = 0
    for к in КОНТЕЙНЕРЫ:
        for э in ЭНЕРГИЯ:
            чужие = set()
            for вариант in range(1, ВАРИАНТОВ + 1):
                id_набора = f'3.{сочетание}.{вариант}'
                путь = f'{ПАПКА}/blocks.{id_набора}.yaml'
                if os.path.exists(путь) and not перезаписать:
                    continue
                собрано = набор(стороны, к, э, ЗЕРНО + вариант * 101, id_набора,
                                пореже=(вариант == 1), чужие=чужие)
                if собрано is None:
                    print(f'  НЕ СОБРАЛОСЬ: контейнеры {к}, энергия {э}, '
                          f'вариант {вариант}')
                    continue
                n, весь, мал, бол = собрано
                чужие.add(весь)
                пояснение = ('вариант 1 - блоки разведены друг от друга как '
                             'можно дальше' if вариант == 1
                             else f'вариант {вариант} - случайная раскладка')
                шапка = (
                    '# CONTENT: blocks  version ' + id_набора + '\n'
                    '# СГЕНЕРИРОВАНО tools/сгенерить-наборы-блоков.py.\n'
                    '# На каждое сочетание контейнеров и жёлтых ячеек - три\n'
                    '# раскладки (заказ дизайнера 02.09.2026); ' + пояснение + '.\n'
                    '# Геометрия сторон взята из авторского набора 1.4.0 и не\n'
                    '# менялась - это физический картон.\n'
                    '# ' + n['meta']['описание'] + '\n'
                    '# разброс: ' + n['meta']['разброс'] + '\n')
                io.open(путь, 'w', encoding='utf-8').write(
                    шапка + yaml.safe_dump(n, allow_unicode=True,
                                           sort_keys=False, width=100))
                сделано.append((id_набора, n['meta']['описание'], мал, бол))
            сочетание += 1

    print('сгенерировано наборов:', len(сделано))
    for i, о, мал, бол in сделано:
        print(f'  {i}: {о} | мин. расстояние малые {мал[0]} большие {бол[0]}')


if __name__ == '__main__':
    main()
