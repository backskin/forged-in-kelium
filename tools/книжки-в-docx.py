class Книжка:

    def __init__(self):
        self.doc = Document()
        self.колонок = 1
        # КОМПАКТНЫЙ НАБОР — для оборота обложки. Памятка это справочная
        # страница, её читают взглядом по месту, а не подряд; она обязана
        # уместиться на ОДНУ сторону, иначе перестаёт быть памяткой. Свой,
        # более мелкий кегль ей положен ровно поэтому.
        self.масштаб = 1.0
        # Сколько пустых страниц вставить перед оборотом обложки (см. добить).
        self.добивка_страниц = 0
        настроить_раздел(self.doc.sections[0], 1)
        # Колонцифру ставит ПЕРВАЯ ЧАСТЬ, а не обложка: номер страницы поверх
        # арта в обрез выглядит браком печати.
        self.колонцифра_поставлена = False
        стиль = self.doc.styles['Normal']
        стиль.font.name = ОСНОВНОЙ
        стиль.font.size = Pt(10.5)
        стиль.font.color.rgb = ЧЕРНИЛА
        стиль.element.rPr.rFonts.set(qn('w:cs'), ОСНОВНОЙ)
        фон_страницы(self.doc, ФОН_СТРАНИЦЫ)
        русский_язык(стиль)
        переносы(self.doc)

    # --- разделы ---------------------------------------------------------
    def раздел(self, колонок, с_новой_страницы=False):
        вид = WD_SECTION.NEW_PAGE if с_новой_страницы else WD_SECTION.CONTINUOUS
        настроить_раздел(self.doc.add_section(вид), колонок)
        self.колонок = колонок

    def в_две_колонки(self):
        if self.колонок != 2:
            self.раздел(2)

    # --- абзацы ----------------------------------------------------------
    def абзац(self, стиль=None, before=0, after=3, интерлиньяж=1.15):
        p = self.doc.add_paragraph(style=стиль)
        pf = p.paragraph_format
        pf.space_before = Pt(before * self.масштаб)
        pf.space_after = Pt(after * self.масштаб)
        pf.line_spacing = интерлиньяж
        pf.widow_control = True
        return p

    def набрать(self, p, текст, шрифт=ОСНОВНОЙ, кегль=10, цвет=ЧЕРНИЛА,
                жирный_весь=False):
        for кусок, жир, кур in куски_с_разметкой(текст):
            r = p.add_run(кусок)
            r.font.name = шрифт
            r.font.size = Pt(кегль * self.масштаб)
            r.font.color.rgb = цвет
            r.bold = жир or жирный_весь
            r.italic = кур
            r._element.rPr.rFonts.set(qn('w:cs'), шрифт)
        return p

    # --- блоки -----------------------------------------------------------
    def добить(self):
        """СТРАНИЦ ДОЛЖНО БЫТЬ КРАТНО ЧЕТЫРЁМ — правило вёрстки.

        Книжка на скрепке складывается из листов, сложенных пополам: страниц
        всегда 4, 8, 12… Типография иначе её не примет. Сколько добить, считает
        tools/собрать-книги.ps1 по готовому PDF — заранее это не известно.
        """
        for _ in range(self.добивка_страниц):
            self.раздел(1, с_новой_страницы=True)
            self.абзац(before=0, after=0).add_run('')
        self.добивка_страниц = 0

    def часть(self, текст):
        """Название части — баннером во всю ширину, с новой страницы."""
        # ПАМЯТКА ОСТАЁТСЯ ПОСЛЕДНЕЙ СТРАНИЦЕЙ КНИГИ. Пустые листы добивки
        # вставляются ПЕРЕД ней: она печатается на обороте обложки, и лист
        # после неё сделал бы оборотом пустоту.
        памятка = текст.upper().startswith('ПАМЯТКА')
        if памятка:
            self.добить()
        # Памятка набирается мельче остальной книги — см. self.масштаб.
        self.масштаб = 0.64 if памятка else 1.0
        # ВЫРОВНЯТЬ КОЛОНКИ ПРЕДЫДУЩЕЙ ЧАСТИ. Word разливает текст по колонкам
        # только до разрыва раздела «на текущей странице»; перед разрывом «с
        # новой страницы» он этого не делает, и короткая часть повисает одной
        # длинной левой колонкой при пустой правой. Пустой непрерывный раздел
        # ровно здесь и заставляет его разложить текст на две равные колонки.
        if self.колонок == 2:
            self.раздел(2)
        self.раздел(1, с_новой_страницы=True)
        if not self.колонцифра_поставлена:
            подвал = self.doc.sections[-1]
            подвал.footer.is_linked_to_previous = False
            номера_страниц(подвал)
            self.колонцифра_поставлена = True
        p = self.абзац(before=0, after=10)
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        уровень_структуры(p, 0)
        грань(p._p.get_or_add_pPr(), 'bottom', ШАПКА_ФОН, размер=12)
        self.набрать(p, текст, шрифт=АКЦЕНТНЫЙ, кегль=17, цвет=СИНИЙ,
                     жирный_весь=True)
        self.раздел(2)

    def заголовок(self, уровень, текст):
        кегль = {2: 11.5, 3: 10, 4: 9.5}[уровень]
        p = self.абзац(before=9 if уровень == 2 else 7, after=3)
        # Заголовок в конце страницы, а текст под ним на следующей — брак.
        p.paragraph_format.keep_with_next = True
        уровень_структуры(p, уровень - 1)
        # ДВА АКЦЕНТА, А НЕ ОДИН: части и разделы — охрой обложки, действия
        # внутри них — зеленью келемия. Так на развороте видно, где кончается
        # раздел и начинается очередное действие, без лишних линеек.
        self.набрать(p, текст, шрифт=АКЦЕНТНЫЙ, кегль=кегль,
                     цвет=СИНИЙ if уровень == 2 else КЕЛЕМИЙ, жирный_весь=True)

    def текст(self, строка):
        self.набрать(self.абзац(), строка)

    def пункт(self, строка, номерной=False, номер=1):
        p = self.абзац(after=2)
        pf = p.paragraph_format
        pf.left_indent = Mm(4.5)
        pf.first_line_indent = Mm(-4.5)
        метка = f'{номер}. ' if номерной else '— '
        r = p.add_run(метка)
        r.font.name = ОСНОВНОЙ
        r.font.size = Pt(10.5)
        r.font.color.rgb = КЕЛЕМИЙ
        r.bold = True
        self.набрать(p, строка)

    def выноска(self, абзацы):
        for k, строка in enumerate(абзацы):
            p = self.абзац(before=4 if k == 0 else 0,
                           after=4 if k == len(абзацы) - 1 else 2)
            pPr = p._p.get_or_add_pPr()
            тень(pPr, ВЫНОСКА_ФОН)
            грань(pPr, 'left', ВЫНОСКА_КАНТ, размер=18)
            pf = p.paragraph_format
            pf.left_indent = Mm(3)
            pf.right_indent = Mm(1.5)
            self.набрать(p, строка, кегль=9)

    def иконки(self, строчки):
        """Место под иконку, имя, значение. Первая колонка — пустая клетка."""
        всего = int(ШИРИНА_КОЛОНКИ.twips)
        коробка = int(Mm(9).twips)
        имя = int(Mm(27).twips)
        ширины = [коробка, имя, всего - коробка - имя]
        t = self.doc.add_table(rows=0, cols=3)
        t.alignment = WD_TABLE_ALIGNMENT.LEFT
        t.autofit = False
        оформить_сетку(t, РАМКА)
        фиксированная_раскладка(t)
        for ci, ш in enumerate(ширины):
            t.columns[ci].width = Twips(ш)
        ряды = []
        for ключ, название, что in строчки:
            row = t.add_row()
            не_рвать(row)
            ряды.append(row)
            for ci in range(3):
                cell = row.cells[ci]
                cell.width = Twips(ширины[ci])
                cell._tc.get_or_add_tcPr().append(поля_ячейки())
                p = cell.paragraphs[0]
                p.paragraph_format.space_before = Pt(2.5)
                p.paragraph_format.space_after = Pt(2.5)
                p.paragraph_format.line_spacing = 1.04
                if ci == 0:
                    # МЕСТО ПОД ИКОНКУ: пустая клетка с заливкой. Ключ иконки
                    # не печатается — он нужен художнику в исходнике, а не
                    # игроку на странице.
                    тень(cell._tc.get_or_add_tcPr(), ИКОНКА_ФОН)
                    p.add_run('')
                elif ci == 1:
                    self.набрать(p, название, шрифт=ТАБЛИЧНЫЙ, кегль=7.5,
                                 жирный_весь=True)
                else:
                    self.набрать(p, что, шрифт=ТАБЛИЧНЫЙ, кегль=7.5, цвет=СЕРЫЙ)
        if len(ряды) <= НЕРАЗРЫВНАЯ_ДО:
            for row in ряды[:-1]:
                держать_вместе(row)
        хвост = self.абзац(before=0, after=6)
        хвост.add_run('')

    def сетка(self, клетки):
        """ЧЕТЫРЕ РАСКЛАДКИ НА СТРАНИЦУ, 2×2.

        По одной раскладке на страницу выходило одиннадцать страниц с большим
        пустым низом. Вчетверо мельче поле читается по-прежнему: на картинке
        важно расположение зарождений и стартов, а не подписи координат.
        """
        if self.колонок != 1:
            self.раздел(1)
        колонок = 2
        зазор = Mm(5)
        клетка_ш = Mm((ШИРИНА_ТЕКСТА.mm - зазор.mm) / колонок)
        t = self.doc.add_table(rows=0, cols=колонок)
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        t.autofit = False
        фиксированная_раскладка(t)
        for ci in range(колонок):
            t.columns[ci].width = Twips(int(клетка_ш.twips))
        for ряд in range(0, len(клетки), колонок):
            row = t.add_row()
            не_рвать(row)
            for ci in range(колонок):
                cell = row.cells[ci]
                cell.width = Twips(int(клетка_ш.twips))
                p = cell.paragraphs[0]
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                p.paragraph_format.space_before = Pt(0)
                p.paragraph_format.space_after = Pt(1)
                if ряд + ci >= len(клетки):
                    continue
                путь, подпись = клетки[ряд + ci]
                if not os.path.exists(путь):
                    self.набрать(p, '[нет картинки: %s]' % путь, кегль=7.5)
                    continue
                ш, в = размер_картинки(путь)
                k = min((клетка_ш.mm - 3) / ш, КЛЕТКА_СЕТКИ_В.mm / в)
                p.add_run().add_picture(путь, width=Mm(ш * k), height=Mm(в * k))
                c = cell.add_paragraph()
                c.alignment = WD_ALIGN_PARAGRAPH.CENTER
                c.paragraph_format.space_before = Pt(0)
                c.paragraph_format.space_after = Pt(2)
                self.набрать(c, подпись, шрифт=АКЦЕНТНЫЙ, кегль=8,
                             цвет=СИНИЙ, жирный_весь=True)

    def картинка(self, путь, подпись, высота=None):
        """Картинка во всю ширину: в колонку 88 мм раскладка не читается."""
        if not os.path.exists(путь):
            self.текст('[нет картинки: %s]' % путь)
            return
        if self.колонок != 1:
            self.раздел(1)
        ш, в = размер_картинки(путь)
        # Вписать в поле страницы целиком, с местом под подпись.
        предел_в = Mm(высота) if высота else ПРЕДЕЛ_КАРТИНКИ_В
        k = min(ПРЕДЕЛ_КАРТИНКИ_Ш.mm / ш, предел_в.mm / в)
        p = self.абзац(before=2, after=2)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(путь, width=Mm(ш * k), height=Mm(в * k))
        if подпись:
            c = self.абзац(before=0, after=8)
            c.alignment = WD_ALIGN_PARAGRAPH.CENTER
            self.набрать(c, подпись, шрифт=АКЦЕНТНЫЙ, кегль=8, цвет=СЕРЫЙ)
        self.раздел(2)

    def пример(self, абзацы):
        """ПРИМЕР — разыгранный кусок партии.

        Все руководства по книгам правил требуют разобранного хода: правило
        читают, а понимают на примере. Оформление тёплое и с кантом — так
        видно, что это НЕ правило, а его иллюстрация, и при перечитывании
        примеры можно пропускать глазами.
        """
        for k, строка in enumerate(абзацы):
            p = self.абзац(before=5 if k == 0 else 0,
                           after=5 if k == len(абзацы) - 1 else 2)
            pPr = p._p.get_or_add_pPr()
            тень(pPr, ПРИМЕР_ФОН)
            грань(pPr, 'left', ПРИМЕР_КАНТ, размер=18)
            pf = p.paragraph_format
            pf.left_indent = Mm(3)
            pf.right_indent = Mm(1.5)
            if k == 0:
                r = p.add_run('ПРИМЕР.  ')
                r.font.name = АКЦЕНТНЫЙ
                r.font.size = Pt(7.5 * self.масштаб)
                r.font.color.rgb = RGBColor(0x8A, 0x63, 0x14)
                r.bold = True
            self.набрать(p, строка, кегль=9)

    def таблица(self, строки):
        колонок = max(len(r) for r in строки)
        строки = [r + [''] * (колонок - len(r)) for r in строки]
        широкая = колонок >= ШИРОКАЯ_ОТ
        if широкая:
            self.раздел(1)
        всего = ШИРИНА_ТЕКСТА if широкая else ШИРИНА_КОЛОНКИ

        # ШИРИНА КОЛОНКИ — по содержимому, но НЕ УЖЕ САМОГО ДЛИННОГО СЛОВА в
        # ней. Без этого пола колонка «Вид» получает место по средней длине
        # строки и режет слова посередине: «происшеств/ие», «состо/яние».
        # Сначала каждой колонке выдаётся её пол, остаток делится по весам.
        веса, полы = [], []
        for c in range(колонок):
            длины = [len(чистый(r[c])) for r in строки]
            веса.append(sum(длины) / len(длины) * 0.6 + max(длины) * 0.4)
            слово = max((len(w) for r in строки for w in чистый(r[c]).split()),
                        default=4)
            полы.append(int(слово * ЗНАК_ТВИПОВ) + ПОЛЯ_ЯЧЕЙКИ_ТВИПОВ)
        всего_твипов = int(всего.twips)
        if sum(полы) > всего_твипов:
            # Пол шире страницы — ужимаем пропорционально, тут уже без вариантов.
            k = всего_твипов / sum(полы)
            полы = [int(п * k) for п in полы]
            ширины = полы
        else:
            остаток = всего_твипов - sum(полы)
            сумма = sum(веса) or 1
            ширины = [полы[c] + int(остаток * веса[c] / сумма)
                      for c in range(колонок)]
        ширины[-1] += всего_твипов - sum(ширины)

        t = self.doc.add_table(rows=0, cols=колонок)
        t.alignment = WD_TABLE_ALIGNMENT.LEFT
        t.autofit = False
        оформить_сетку(t, РАМКА)
        # ШИРИНЫ ЗАДАЮТСЯ ДВАЖДЫ — на колонках и на КАЖДОЙ ячейке, и только
        # объектом длины: голое число python-docx понимает как EMU, а не твипы,
        # и колонки схлопываются в нитку.
        фиксированная_раскладка(t)
        for ci, ш in enumerate(ширины):
            t.columns[ci].width = Twips(ш)
        ряды = []
        for ri, строка in enumerate(строки):
            row = t.add_row()
            не_рвать(row)
            for ci, ячейка in enumerate(строка):
                cell = row.cells[ci]
                cell.width = Twips(ширины[ci])
                cell._tc.get_or_add_tcPr().append(поля_ячейки())
                p = cell.paragraphs[0]
                pf = p.paragraph_format
                pf.space_before = Pt(1.5)
                pf.space_after = Pt(1.5)
                pf.line_spacing = 1.04
                if ri == 0:
                    тень(cell._tc.get_or_add_tcPr(), ШАПКА_ФОН)
                    self.набрать(p, ячейка, шрифт=УЗКИЙ, кегль=7.5,
                                 цвет=RGBColor(0xFF, 0xFF, 0xFF),
                                 жирный_весь=True)
                else:
                    self.набрать(p, ячейка, шрифт=ТАБЛИЧНЫЙ, кегль=7.5)
            if ri == 0:
                повторять_шапку(row)
            ряды.append(row)
        # ЦЕЛИКОМ НА ОДНУ СТРАНИЦУ, пока это физически возможно.
        if len(ряды) <= НЕРАЗРЫВНАЯ_ДО:
            for row in ряды[:-1]:
                держать_вместе(row)
        # Таблицы вплотную к тексту читаются как его часть — отбиваем.
        хвост = self.абзац(before=0, after=6)
        хвост.add_run('')
        if широкая:
            self.раздел(2)


def поля_ячейки():
    mar = OxmlElement('w:tcMar')
    for сторона, значение in (('top', 40), ('bottom', 40),
                              ('left', 70), ('right', 70)):
        e = OxmlElement('w:' + сторона)
        e.set(qn('w:w'), str(значение))
        e.set(qn('w:type'), 'dxa')
        mar.append(e)
    return mar


def размер_картинки(путь):
    """Ширина и высота файла в миллиметрах при 96 точках на дюйм."""
    with Image.open(путь) as im:
        ш, в = im.size
    return ш * 25.4 / 96.0, в * 25.4 / 96.0


def фон_страницы(doc, цвет):
    """ЗАЛИТЬ СТРАНИЦУ ПЕСОЧНЫМ.

    Две части: сама краска (w:background у документа) и разрешение её
    ПОКАЗЫВАТЬ И ПЕЧАТАТЬ (w:displayBackgroundShape в настройках). Без второго
    Word держит цвет в файле, но рисует белый лист — и в PDF уходит белый.
    """
    корень = doc.element
    bg = OxmlElement('w:background')
    bg.set(qn('w:color'), цвет)
    корень.insert(0, bg)
    e = OxmlElement('w:displayBackgroundShape')
    doc.settings.element.append(e)


def русский_язык(стиль):
    """Язык текста — русский: без него Word переносит слова по чужим правилам."""
    lang = OxmlElement('w:lang')
    lang.set(qn('w:val'), 'ru-RU')
    стиль.element.rPr.append(lang)


def переносы(doc):
    """АВТОПЕРЕНОС. В колонке 88 мм русское слово занимает четверть строки, и
    без переносов правый край рвётся на полстроки, а длинные слова в таблицах
    ломаются посередине."""
    settings = doc.settings.element
    for имя, значение in (('autoHyphenation', '1'),
                          ('doNotHyphenateCaps', '1'),
                          ('hyphenationZone', '284')):   # 5 мм
        e = OxmlElement('w:' + имя)
        e.set(qn('w:val'), значение)
        settings.append(e)


def фиксированная_раскладка(table):
    """Word не пересчитывает колонки под содержимое — ширины наши."""
    tblPr = table._tbl.tblPr
    layout = OxmlElement('w:tblLayout')
    layout.set(qn('w:type'), 'fixed')
    tblPr.append(layout)


def повторять_шапку(row):
    """Шапка таблицы повторяется на каждой странице, где таблица продолжается."""
    trPr = row._tr.get_or_add_trPr()
    e = OxmlElement('w:tblHeader')
    trPr.append(e)


def держать_вместе(row, держать=True):
    """Строка «не отрывается от следующей» — так таблица едет целиком.

    Разорванная надвое таблица теряет смысл: на второй странице остаются
    голые числа без того, к чему они относятся.
    """
    for cell in row.cells:
        for p in cell.paragraphs:
            p.paragraph_format.keep_with_next = держать


def не_рвать(row):
    """Строка таблицы целиком остаётся в одной колонке.

    Без этого длинная строка разваливается по границе колонки: в левой
    остаётся «СПЕЦ-», в правой — «ное действие», и таблица читается как
    опечатка.
    """
    trPr = row._tr.get_or_add_trPr()
    trPr.append(OxmlElement('w:cantSplit'))


def оформить_сетку(table, цвет):
    tblPr = table._tbl.tblPr
    borders = OxmlElement('w:tblBorders')
    for сторона in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        e = OxmlElement('w:' + сторона)
        e.set(qn('w:val'), 'single')
        e.set(qn('w:sz'), '4')
        e.set(qn('w:space'), '0')
        e.set(qn('w:color'), цвет)
        borders.append(e)
    tblPr.append(borders)


