def номера_частей(книга):
    """Номера страниц частей из прошлой выгрузки (см. tools/собрать-книги.ps1)."""
    путь = 'tools/страницы.json'
    if not os.path.exists(путь):
        return {}
    import json
    данные = json.load(io.open(путь, encoding='utf-8-sig'))
    return данные.get(книга, {})


def содержание(кн, части, номера):
    """СОДЕРЖАНИЕ сразу за обложкой.

    Книгу правил читают дважды: подряд перед первой партией и по месту посреди
    неё. Второе без оглавления не работает — правило приходится искать
    перелистыванием.

    НЕ ПОЛЕМ WORD, А ТЕКСТОМ. Поле TOC обновляется при каждой выгрузке, и на
    документе с шестью десятками разделов выгрузка в PDF не заканчивается
    вовсе. Номера страниц берутся из PDF прошлого прохода и печатаются как
    обычный текст — Word при экспорте ничего не пересчитывает.
    """
    кн.раздел(1, с_новой_страницы=True)
    p = кн.абзац(before=0, after=10)
    грань(p._p.get_or_add_pPr(), 'bottom', ШАПКА_ФОН, размер=12)
    кн.набрать(p, 'СОДЕРЖАНИЕ', шрифт=АКЦЕНТНЫЙ, кегль=17, цвет=СИНИЙ,
               жирный_весь=True)
    кн.раздел(2)
    for заголовок in части:
        стр = кн.абзац(before=0, after=3)
        pf = стр.paragraph_format
        pf.left_indent = Mm(7)
        pf.first_line_indent = Mm(-7)
        кн.набрать(стр, заголовок, шрифт=ПОДПИСНОЙ, кегль=9)
        номер = номера.get(заголовок)
        if номер:
            точки = стр.add_run('  ' + '·' * 3 + '  ')
            точки.font.name = ОСНОВНОЙ
            точки.font.size = Pt(9)
            точки.font.color.rgb = СЕРЫЙ
            r = стр.add_run(str(номер))
            r.font.name = ПОДПИСНОЙ
            r.font.size = Pt(9)
            r.font.color.rgb = СИНИЙ
            r.bold = True


def обложка(кн, книга, версия):
    """Обложка — КАРТИНКА В ОБРЕЗ, во весь лист.

    Поля у этого раздела обнуляются, колонцифры на нём нет: обложка печатается
    навылет, и белая рамка вокруг арта её бы убила. Если файла обложки нет,
    собирается запасная типографская — книга остаётся собираемой.
    """
    путь = книга.get('обложка')
    if путь and os.path.exists(путь):
        section = кн.doc.sections[0]
        section.left_margin = section.right_margin = Mm(0)
        section.top_margin = section.bottom_margin = Mm(0)
        p = кн.абзац(before=0, after=0, интерлиньяж=1)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(путь, width=СТОРОНА, height=СТОРОНА)
        return
    верх, низ = книга['титул']
    # Кегль титула — от длины строки: «СПРАВОЧНИК» и «КРИСТАЛЛЫ РАЗДОРА» в одну
    # мерку не лезут, а переносить титул нельзя.
    кегль = 35 if max(len(верх), len(низ)) <= 11 else 23
    p = кн.абзац(before=170, after=0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    кн.набрать(p, верх, шрифт=ОБЛОЖЕЧНЫЙ, кегль=кегль, цвет=СИНИЙ,
               жирный_весь=True)
    p = кн.абзац(before=0, after=14)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    кн.набрать(p, низ, шрифт=ОБЛОЖЕЧНЫЙ, кегль=кегль, цвет=СИНИЙ,
               жирный_весь=True)
    p = кн.абзац(before=0, after=0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    грань(p._p.get_or_add_pPr(), 'top', ШАПКА_ФОН, размер=12)
    кн.набрать(p, книга['подзаголовок'], шрифт=ПОДПИСНОЙ, кегль=11,
               цвет=ЧЕРНИЛА)
    p = кн.абзац(before=2, after=0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    кн.набрать(p, книга['строка'], шрифт=ПОДПИСНОЙ, кегль=11, цвет=СЕРЫЙ)
    p = кн.абзац(before=150, after=0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    кн.набрать(p, версия, шрифт=ПОДПИСНОЙ, кегль=9, цвет=СЕРЫЙ)


def собрать(книга, версия):
    текст = io.open(книга['источник'], encoding='utf-8').read()
    блоки = разобрать(текст)

    # Названия частей — для оглавления. Первый заголовок первого уровня это
    # титул книги, он на обложке и в содержание не идёт.
    части = [б[2] for б in блоки if б[0] == 'heading' and б[1] == 1][1:]

    кн = Книжка()
    кн.добивка_страниц = int(книга.get('добить', 0))
    обложка(кн, книга, версия)
    содержание(кн, части, номера_частей(книга['цель']))

    номер_пункта = 0
    предыдущий = None
    # ПЕРВЫЙ заголовок первого уровня — название книги, его рисует обложка.
    # Всё, что стоит до ВТОРОГО, тоже на обложке: подзаголовок и вводная
    # выноска. Определяем это порядком, а не словами в заголовке: у двух книг
    # титулы разные, а правило одно.
    титул_пройден = False
    начали = False
    for номер, блок in enumerate(блоки):
        вид = блок[0]
        следующий = блоки[номер + 1][0] if номер + 1 < len(блоки) else None
        if вид == 'heading':
            уровень, строка = блок[1], блок[2]
            if уровень == 1:
                if not титул_пройден:
                    титул_пройден = True
                    continue
                начали = True
                кн.часть(строка)
            elif начали:
                # ЗАГОЛОВОК ПЕРЕД КАРТИНКОЙ начинает НОВУЮ СТРАНИЦУ и идёт во
                # всю ширину. Раскладка занимает почти всю страницу целиком, и
                # ужать её нельзя — поле перестанет читаться. Значит заголовку
                # рядом с ней место только сверху, на своей странице; иначе он
                # висит внизу предыдущей, оторванный от своей картинки.
                if следующий in ('image', 'grid'):
                    кн.раздел(1, с_новой_страницы=True)
                else:
                    кн.в_две_колонки()
                кн.заголовок(уровень, строка)
            else:
                continue
            предыдущий = 'heading'
            номер_пункта = 0
            continue
        if not начали:
            continue
        if вид not in ('image', 'grid'):
            кн.в_две_колонки()
        if вид == 'para':
            кн.текст(блок[1])
            номер_пункта = 0
        elif вид == 'bullet':
            кн.пункт(блок[1])
            номер_пункта = 0
        elif вид == 'ordered':
            номер_пункта = номер_пункта + 1 if предыдущий == 'ordered' else 1
            кн.пункт(блок[1], номерной=True, номер=номер_пункта)
        elif вид == 'quote':
            кн.выноска(блок[1])
            номер_пункта = 0
        elif вид == 'table':
            кн.таблица(блок[1])
            номер_пункта = 0
        elif вид == 'example':
            кн.пример(блок[1])
            номер_пункта = 0
        elif вид == 'icons':
            кн.иконки(блок[1])
            номер_пункта = 0
        elif вид == 'image':
            кн.картинка(блок[1], блок[2], блок[3])
            номер_пункта = 0
        elif вид == 'grid':
            кн.сетка(блок[1])
            номер_пункта = 0
        предыдущий = вид

    # Добивка вставляется ПЕРЕД оборотом обложки (см. Книжка.добить), а если
    # оборота у книги нет — здесь, в самом конце.
    кн.добить()

    кн.doc.save(книга['цель'])
    print('готово:', книга['цель'])
    print('  блоков:', len(блоки), ' разделов:', len(кн.doc.sections))


def добивка():
    """Сколько пустых страниц добавить каждой книге (см. собрать-книги.ps1)."""
    путь = 'tools/добивка.json'
    if not os.path.exists(путь):
        return {}
    import json
    # utf-8-SIG, а не utf-8: файл пишет PowerShell, а он ставит BOM даже там,
    # где просят utf8, и json.load на нём падает.
    return json.load(io.open(путь, encoding='utf-8-sig'))


def main():
    имена = sys.argv[1:] or list(КНИГИ)
    сколько = добивка()
    for имя, книга in КНИГИ.items():
        книга['добить'] = int(сколько.get(имя, 0))
    # Версия одна на обе книги: она у правил, справочник идёт к ним.
    правила = io.open(КНИГИ['рулбук']['источник'], encoding='utf-8').read()
    m = re.search(r'\*\*Версия правил ([0-9.]+)\.\*\*', правила)
    версия = 'Версия правил ' + m.group(1) if m else 'версия правил ?'
    for имя in имена:
        if имя not in КНИГИ:
            raise SystemExit('нет такой книги: %s (есть: %s)'
                             % (имя, ', '.join(КНИГИ)))
        собрать(КНИГИ[имя], версия)


if __name__ == '__main__':
    main()
