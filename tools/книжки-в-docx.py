def разобрать(текст):
    """Markdown -> список блоков. Ровно те виды, что есть в рулбуке."""
    блоки = []
    строки = текст.split('\n')
    i = 0
    while i < len(строки):
        s = строки[i].rstrip()
        if s.startswith('<!--') or s.strip() == '---':
            i += 1
            continue
        m = re.match(r'^(#{1,4})\s+(.*)$', s)
        if m:
            блоки.append(('heading', len(m.group(1)), m.group(2).strip()))
            i += 1
            continue
        if s.strip() == ':иконки:':
            i += 1
            строчки = []
            while i < len(строки) and строки[i].strip() != ':конец:':
                части = [c.strip() for c in строки[i].split('|')]
                if len(части) >= 3:
                    строчки.append(части[:3])
                i += 1
            i += 1
            if строчки:
                блоки.append(('icons', строчки))
            continue
        if s.strip() == ':пример:':
            i += 1
            абзацы = []
            while i < len(строки) and строки[i].strip() != ':конец:':
                if строки[i].strip():
                    абзацы.append(строки[i].strip())
                i += 1
            i += 1
            if абзацы:
                блоки.append(('example', абзацы))
            continue
        if s.strip() == ':сетка:':
            i += 1
            клетки = []
            while i < len(строки) and строки[i].strip() != ':конец:':
                части = [c.strip() for c in строки[i].split('|')]
                if len(части) >= 2:
                    клетки.append((части[0], части[1]))
                i += 1
            i += 1
            if клетки:
                блоки.append(('grid', клетки))
            continue
        # Высота картинки задаётся в фигурных скобках: ![](путь){30} — 30 мм.
        m = re.match(r'^!\[(.*?)\]\((.+?)\)(?:\{(\d+)\})?\s*$', s)
        if m:
            блоки.append(('image', m.group(2).strip(), m.group(1).strip(),
                          int(m.group(3)) if m.group(3) else None))
            i += 1
            continue
        if s.startswith('|'):
            таблица = []
            while i < len(строки) and строки[i].lstrip().startswith('|'):
                ячейки = [c.strip() for c in строки[i].strip().strip('|').split('|')]
                if not all(re.fullmatch(r':?-{2,}:?', c) for c in ячейки):
                    таблица.append(ячейки)
                i += 1
            if таблица:
                блоки.append(('table', таблица))
            continue
        if s.startswith('>'):
            куски = []
            while i < len(строки) and строки[i].lstrip().startswith('>'):
                куски.append(re.sub(r'^\s*>\s?', '', строки[i]).rstrip())
                i += 1
            # Пустая строка внутри выноски делит её на абзацы.
            абзацы, тек = [], []
            for к in куски:
                if к.strip():
                    тек.append(к)
                elif тек:
                    абзацы.append(' '.join(тек))
                    тек = []
            if тек:
                абзацы.append(' '.join(тек))
            блоки.append(('quote', абзацы))
            continue
        m = re.match(r'^(\s*)([-*]|\d+\.)\s+(.*)$', s)
        if m:
            вид = 'bullet' if m.group(2) in '-*' else 'ordered'
            куски = [m.group(3)]
            i += 1
            # Продолжения пункта — строки с отступом.
            while i < len(строки) and re.match(r'^\s+\S', строки[i]) \
                    and not строки[i].lstrip().startswith(('|', '>', '#')) \
                    and not re.match(r'^\s*([-*]|\d+\.)\s', строки[i]):
                куски.append(строки[i].strip())
                i += 1
            блоки.append((вид, ' '.join(куски)))
            continue
        if not s.strip():
            i += 1
            continue
        куски = []
        while i < len(строки) and строки[i].strip() \
                and not строки[i].lstrip().startswith(('|', '>', '#')) \
                and not re.match(r'^\s*([-*]|\d+\.)\s', строки[i]) \
                and строки[i].strip() != '---':
            куски.append(строки[i].strip())
            i += 1
        блоки.append(('para', ' '.join(куски)))
    return блоки


def куски_с_разметкой(текст):
    """Разложить строку на (текст, жирный, курсив) по **…** и *…*."""
    out = []
    for часть in re.split(r'(\*\*[^*]+\*\*|(?<!\*)\*[^*]+\*(?!\*)|`[^`]+`)', текст):
        if not часть:
            continue
        if часть.startswith('**') and часть.endswith('**'):
            out.append((часть[2:-2], True, False))
        elif часть.startswith('`') and часть.endswith('`'):
            out.append((часть[1:-1], False, True))
        elif часть.startswith('*') and часть.endswith('*'):
            out.append((часть[1:-1], False, True))
        else:
            out.append((часть, False, False))
    return out


