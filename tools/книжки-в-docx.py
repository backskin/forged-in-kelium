"""КНИЖКИ В DOCX — квадратные книжки с текстом в две колонки.

Собирает ОБЕ книги игры одним и тем же способом: книгу правил и справочник.
Вёрстка у них общая — иначе на столе они выглядели бы как из разных наборов.

Заказ дизайнера: правила отдельным документом Word, страница квадратная,
текст на странице в два столбца.

Как устроено:

* СТРАНИЦА КВАДРАТНАЯ, 210×210 мм. Обычный печатный формат квадратной
  настолочной книжки: помещается в коробку рядом с полем и не требует
  нестандартной резки.
* ТЕКСТ В ДВЕ КОЛОНКИ. Колонка выходит около 88 мм — это 45-50 знаков в
  строке, то есть ровно та ширина, на которой глаз не теряет строку.
* ЗАГОЛОВОК ЧАСТИ — ВО ВСЮ ШИРИНУ. Часть начинается с новой страницы, её
  название идёт баннером через оба столбца, и только под ним текст снова
  разбивается надвое. Иначе название части тонет в левой колонке.
* ШИРОКИЕ ТАБЛИЦЫ (от четырёх колонок) РАЗВОРАЧИВАЮТСЯ НА ВСЮ ШИРИНУ. В
  столбец 88 мм приложение с шестью колонками не влезает вовсе: строки
  ломаются по одному слову. Узкие таблицы (две-три колонки) остаются в потоке.
  Технически это разрывы раздела «на текущей странице» — тот же приём, каким
  верстают журналы.

Кроме обычной размётки Markdown понимает ещё две вещи:

* `![подпись](путь.png)` — картинка. Всегда во всю ширину страницы, вписанная
  в поле так, чтобы поместиться на страницу целиком.
* блок `:иконки:` … `:конец:` со строками вида `ключ | Имя | что значит` —
  таблица, в первой колонке которой пустое МЕСТО ПОД ИКОНКУ. Рисунков иконок
  пока нет; место под них печатается, чтобы был виден и объём работы, и то,
  что ни одна не забыта.

Источник — сами книги, размётка Markdown. Правится Markdown, документ
пересобирается; руками docx не трогать.

Запуск: python tools/книжки-в-docx.py            (обе книги)
        python tools/книжки-в-docx.py справочник (одну)
"""
