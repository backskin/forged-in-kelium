def тень(элемент, цвет):
    """Заливка абзаца или ячейки."""
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), цвет)
    элемент.append(shd)


def уровень_структуры(p, уровень):
    """Пометить абзац уровнем структуры — по ним Word собирает оглавление.

    Заголовки у нас свои, а не встроенные стили Word, и без этой пометки поле
    оглавления не находит ни одной строки.
    """
    pPr = p._p.get_or_add_pPr()
    e = OxmlElement('w:outlineLvl')
    e.set(qn('w:val'), str(уровень))
    pPr.append(e)


def грань(pPr, сторона, цвет, размер=6):
    bdr = pPr.find(qn('w:pBdr'))
    if bdr is None:
        bdr = OxmlElement('w:pBdr')
        pPr.append(bdr)
    e = OxmlElement('w:' + сторона)
    e.set(qn('w:val'), 'single')
    e.set(qn('w:sz'), str(размер))
    e.set(qn('w:space'), '6')
    e.set(qn('w:color'), цвет)
    bdr.append(e)


def настроить_раздел(section, колонок):
    """Квадратная страница, поля и число колонок — на каждый раздел свои."""
    section.page_width = СТОРОНА
    section.page_height = СТОРОНА
    section.left_margin = section.right_margin = ПОЛЕ_БОК
    section.top_margin = section.bottom_margin = ПОЛЕ_ВЕРХ
    section.header_distance = Mm(9)
    section.footer_distance = Mm(9)
    sectPr = section._sectPr
    for старый in sectPr.findall(qn('w:cols')):
        sectPr.remove(старый)
    cols = OxmlElement('w:cols')
    cols.set(qn('w:num'), str(колонок))
    cols.set(qn('w:space'), str(int(ПРОМЕЖУТОК.twips)))
    cols.set(qn('w:equalWidth'), '1')
    # Порядок детей sectPr схемой не проверяется жёстко, но Word ждёт cols
    # после полей — кладём в конец, как это делает он сам.
    sectPr.append(cols)
    return section


def номера_страниц(section):
    """Колонцифра по центру подвала. Остальные разделы наследуют её сами."""
    p = section.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run()
    r.font.name = АКЦЕНТНЫЙ
    r.font.size = Pt(8)
    r.font.color.rgb = СЕРЫЙ
    fld = OxmlElement('w:fldSimple')
    fld.set(qn('w:instr'), 'PAGE')
    r._r.addnext(fld)


