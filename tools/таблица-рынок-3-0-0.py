ТОНКАЯ = Side(style='thin', color='FFB0B0B0')
РАМКА = Border(left=ТОНКАЯ, right=ТОНКАЯ, top=ТОНКАЯ, bottom=ТОНКАЯ)
ФИНИШНЫЙ = 'FFFDF3E0'
ОБЫЧНЫЙ = 'FFEFF3FB'


def main():
    финишных = sum(1 for r in К if r[1])
    if финишных != 3:
        raise SystemExit(f'карт с флажком финиша {финишных}, а надо 3')
    if len(К) != 9:
        raise SystemExit(f'карт {len(К)}, а надо 9')

    wb = Workbook()
    ws = wb.active
    ws.title = 'Рынок 3.0.0'
    заголовки = ['№', 'КАРТА', 'финиш', 'нехватка', 'ЛЕВОЕ предложение',
                 'ПРАВОЕ предложение', 'кто за что дерётся', 'разбор']
    ширины = [4, 22, 8, 16, 46, 46, 34, 68]
    ws.append(заголовки)
    for i, (з, ш) in enumerate(zip(заголовки, ширины), start=1):
        c = ws.cell(row=1, column=i)
        c.font = Font(bold=True, color='FFFFFFFF')
        c.fill = PatternFill('solid', fgColor='FF2F4F6D')
        c.alignment = Alignment(vertical='center', wrap_text=True)
        c.border = РАМКА
        ws.column_dimensions[get_column_letter(i)].width = ш
    ws.row_dimensions[1].height = 34

    for n, (имя, флаг, нехватка, лево, право, кто, разбор) in enumerate(К, start=1):
        ws.append([n, имя, флаг, нехватка, лево, право, кто, разбор])
        фон = ФИНИШНЫЙ if флаг else ОБЫЧНЫЙ
        for i in range(1, len(заголовки) + 1):
            c = ws.cell(row=n + 1, column=i)
            c.alignment = Alignment(vertical='top', wrap_text=True)
            c.border = РАМКА
            c.fill = PatternFill('solid', fgColor=фон)
        ws.cell(row=n + 1, column=2).font = Font(bold=True)
        ws.cell(row=n + 1, column=3).font = Font(bold=True, color='FFB06000')

    # Подготовка колоды — прямо под таблицей, чтобы правило не потерялось.
    низ = len(К) + 3
    ws.cell(row=низ, column=2, value='ПОДГОТОВКА КОЛОДЫ').font = Font(bold=True)
    ws.cell(row=низ + 1, column=2,
            value='Одна из трёх карт с флажком ФИНИШ кладётся вниз колоды '
                  'взакрытую. Поверх — пять из шести непомеченных, вразнобой. '
                  'Колода из шести карт: одна вскрывается в Обновление каждого '
                  'раунда, значит партия идёт не больше шести раундов. Предел '
                  'раундов равен числу карт рынка — это уже записано в своде, '
                  'нового правила здесь нет.')
    ws.cell(row=низ + 1, column=2).alignment = Alignment(wrap_text=True, vertical='top')
    ws.merge_cells(start_row=низ + 1, start_column=2, end_row=низ + 1, end_column=8)
    ws.row_dimensions[низ + 1].height = 60

    ws.freeze_panes = 'A2'
    ws.auto_filter.ref = f'A1:H{len(К) + 1}'
    wb.save(ЦЕЛЬ)
    print(f'готово: {ЦЕЛЬ}, карт {len(К)}, из них с флажком финиша {финишных}')


if __name__ == '__main__':
    main()
