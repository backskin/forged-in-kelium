# -*- coding: utf-8 -*-
"""ТАБЛИЦА ЗАДАНИЙ, СВЕРЕННАЯ САМА С СОБОЙ.

В таблице дизайнера последняя колонка — «Описание», связный текст карты. Она
пишется отдельно от колонок условия и наград, поэтому легко отстаёт: правишь
условие в одной клетке, а описание рядом остаётся от прежней версии.

Здесь описание сверяется с тем, что стоит в остальных колонках той же строки:

  * числа наград, названные в описании, — с колонками наград;
  * условие и усиление — по первым значащим словам.

Это НЕ сверка с игрой (для неё есть `сверка-заданий-18-09.py`), а проверка
таблицы на внутреннюю связность: пока строка спорит сама с собой, заносить
её в колоду не с чего — непонятно, какая из двух половин верна.

Запуск: python tools/сверка-таблицы-саму-с-собой.py
"""

import csv
import io
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ТАБЛИЦА = os.path.join(КОРЕНЬ, "data", "cards", "эталон",
                       "задания-40-таблица-дизайнера-18.09.2026.csv")

НАГРАДЫ = [
    ("монеты", r"(\d+)\s+монет"),
    ("боеприпасы", r"(\d+)\s+боеприпас"),
    ("карты задания", r"(\d+)\s+карт[аы]?\s+задани"),
    ("трофеи", r"(\d+)\s+трофе"),
]


def число(s):
    s = (s or "").strip().replace(",", ".")
    try:
        return int(float(s))
    except ValueError:
        return 0


def ключ(текст, слов=6):
    t = (текст or "").lower().replace("ё", "е")
    t = re.sub(r"[^a-zа-я0-9]+", " ", t)
    return " ".join(t.split()[:слов])


def main():
    with io.open(ТАБЛИЦА, encoding="utf-8-sig", newline="") as f:
        строки = list(csv.DictReader(f))

    спорных = 0
    for с in строки:
        опис = с.get("Описание") or ""
        # описание до тире — это пересказ условия; после «условие усилено» — усиления
        беды = []

        # 1. Числа базовой награды. Берём только то, что описание называет
        # ДО слов про усиление: дальше речь о другой награде.
        голова = re.split(r"услови[ея] усилен|усилено", опис)[0]
        for кол, шаблон in НАГРАДЫ:
            в_описании = [int(m) for m in re.findall(шаблон, голова)]
            в_колонке = число(с.get(кол))
            if в_описании and в_описании[0] != в_колонке:
                беды.append("%s: в колонке %d, в описании %d"
                            % (кол, в_колонке, в_описании[0]))
            elif not в_описании and в_колонке:
                беды.append("%s: в колонке %d, в описании не названы"
                            % (кол, в_колонке))

        # 2. Условие: описание начинается его пересказом.
        усл = ключ(с.get("Условие"))
        if усл and ключ(голова, 60).find(усл[:24]) < 0:
            беды.append("условие и описание говорят о разном")

        # 3. Усиление: есть в колонке — должно быть и в описании, и наоборот.
        есть_кол = bool((с.get("Усиление") or "").strip())
        есть_опис = bool(re.search(r"услови[ея] усилен|усилено", опис))
        if есть_кол != есть_опис:
            беды.append("усиление: в колонке %s, в описании %s"
                        % ("есть" if есть_кол else "нет",
                           "есть" if есть_опис else "нет"))

        if беды:
            спорных += 1
            print("\n№%s %s — %s" % (с["№"], с["Семейство"],
                                     (с.get("Условие") or "").strip()[:70]))
            for б in беды:
                print("   ", б)

    print("\nстрок, спорящих сами с собой: %d из %d" % (спорных, len(строки)))
    return 1 if спорных else 0


if __name__ == "__main__":
    sys.exit(main())
