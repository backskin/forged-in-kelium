# -*- coding: utf-8 -*-
"""РАСКЛАДКА ЛИЦ КАРТ ПРИКАЗОВ, КОНТЕЙНЕРОВ, РЫНКА, РУБАШЕК И ПАМЯТОК.

Задания и арсенал раскладывает tools/gen_card_art.py — здесь их нет.

Игра ищет картинки по именам (kelium.report.Textures):
  card/orders/<id карты>.png         лицо приказа (id из orders.4.0.0)
  card/orders/security_<цвет>.png    «Затаиться» в цвете колоды
  card/orders/back_<цвет>.png, back  рубашки приказов
  card/container/<id>.png            лицо контейнера (id из containers.6.0.0)
  card/market/<id>.png               лицо карты рынка (id из market.3.0.0)
  card/deck_<колода>.png             рубашки колод
  card/aid_*.png                     памятки игрока
Цвет «красный» в именах рисунков приказов исторически зовётся scarlet;
BoardSheet/OrderCardsPanel спрашивают и red, и scarlet.

ЧТО ПРОЧИТАНО ПО КАРТИНКАМ (экспорт 24–25.09.2026, листы-коллажи):

ПРИКАЗЫ — «карты-приказов-симметрия-1..25» (а не «new»: по new набор
orders.4.0.0 и собирался, но в «симметрии» спец-плашки стоят латинским
квадратом, ровно как записано в orders.4.0.0):
  1–4 синие, 5–8 красные, 9–12 зелёные, 13–16 жёлтые; в каждой четвёрке
  верхний приказ Разместить, Приобрести, Контролировать, Исследовать, нижний —
  следующий по кругу. Спец-плашки сверены со всеми 16 записями orders.4.0.0
  (синие: +2 монеты, боеприпас, манёвр, задание; красные: манёвр, +2, боеприпас,
  задание; зелёные: задание, манёвр, +2, боеприпас; жёлтые: боеприпас, задание,
  манёвр, +2) — расхождений нет.
  17–20 «Затаиться» синяя, красная, зелёная, жёлтая; 21–24 рубашки тех же
  цветов; 25 — общая рубашка (командир), она же deck_orders.
  Прежние лица набора 3.0.0 (blue_acq… yellow_oper) не трогаются: по ним
  читаются записи старых партий.

КОНТЕЙНЕРЫ — «контейнеры-new-1..15», 15-я рубашка. Буква лица в левом верхнем
углу, число копий — в правом. Сверка с containers.6.0.0 (печать → данные):
  1 A две монеты ×3        ≠ c01 A 1 монета ×3            — НЕ КЛАДЁТСЯ
  2 B два боеприпаса ×3    ≠ c02 B 1 боеприпас ×3         — НЕ КЛАДЁТСЯ
  3 D монета и задание ×3  ≠ c03 D 1 карта задания ×3     — НЕ КЛАДЁТСЯ
  4 C келемий ×3           = c04
  5 E трофей ×3            = c05
  6 F монета и боеприпас ×3 = c06
  7 G задание и боеприпас ×3 = c07 (в данных буква H)
  8 H задание и келемий ×2   = c08 (в данных буква G)
  9 I два задания ×2       = c09
  10 J три монеты ×2       ≠ c10 J 2 монеты ×2            — НЕ КЛАДЁТСЯ
  11 K три боеприпаса ×2   ≠ c11 K 2 боеприпаса ×2        — НЕ КЛАДЁТСЯ
  12 L карта арсенала ×2   = c12 (в данных 1 копия)
  13 M жетон техники ×2    = c13 (в данных 1 копия)
  14 N жетон пехоты ×2     = c14 (в данных 1 копия)
  Лицо кладётся, только если НАПЕЧАТАННОЕ ДЕЙСТВИЕ совпало с данными: иначе
  игрок видел бы на карте не то, что она даёт. Непохожие остаются рисованными.

РЫНОК — «Карты рынка-1..11»: 1 — рубашка, 2–11 — карты с номерами 01–10.
Печать — другой набор, не market.3.0.0: на 01 «наём 2 разных войск на 1 гекс
| 5 монет», на 02 «5 монет | 2 арсенала», на 03 «2 арсенала | Манёвр» … а
m3_01 — «5 монет | Снаряжение даром», m3_02 — «3 боеприпаса | Бой даром».
Ни одна из десяти карт с каталогом не совпала, поэтому лица рынка НЕ
кладутся (только рубашка). Таблица печати — РЫНОК_ПЕЧАТЬ ниже.

РУБАШКИ — «экспорт-рубашки»: арсенал, начальный арсенал, супер-арсенал,
задания, начальные задания, супер-задания, рынок, контейнеры — по одной на
колоду, подписи на самих картинках.

ПАМЯТКИ — «Памятка игрока new-1..4»: 1 «Раунд игры» (фазы), 2 «Розыгрыш карт
приказов / Конец игры», 3 «Памятка действий» (стройка, энергия, снаряжение,
добыча), 4 «Памятка действий» (манёвр, бой, рынок, наука). Игра показывает
aid_round (1) и aid_actions (3); 2 и 4 кладутся рядом как aid_orders и
aid_actions_2.

Листы TTS (*-лицо.png, *-рубашка.png, колода-*.png, *.tsdb) — не карты,
пропускаются.

Запуск:  python tools/gen_card_faces.py [--проверить]
"""
import os
import sys

from PIL import Image

КОРЕНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
КАРТЫ = os.path.join(КОРЕНЬ, "data", "textures", "card")
ДИСК = os.path.join(os.path.expanduser("~"), "Yandex.Disk", "Forged in Kelium")
ПРИКАЗЫ = os.path.join(ДИСК, "Компоненты игрока", "экспорт-карты-приказов")
ПАМЯТКИ = os.path.join(ДИСК, "Компоненты игрока", "экспорт-памятки")
КОНТЕЙНЕРЫ = os.path.join(ДИСК, "Общие компоненты", "экспорт-контейнеры")
РЫНОК = os.path.join(ДИСК, "Общие компоненты", "экспорт-колода-рынка")
РУБАШКИ = os.path.join(ДИСК, "Общие компоненты", "экспорт-рубашки")

ЦВЕТА = [("blue", "blue"), ("red", "scarlet"), ("green", "green"), ("yellow", "yellow")]
ВЕРХ = ["place", "acquire", "control", "explore"]

# номер контейнера в экспорте → id в containers.6.0.0; None — печать разошлась
КОНТЕЙНЕР = {1: None, 2: None, 3: None, 4: "c04", 5: "c05", 6: "c06", 7: "c07",
             8: "c08", 9: "c09", 10: None, 11: None, 12: "c12", 13: "c13", 14: "c14"}

# что напечатано на картах рынка 01–10 (левое | правое предложение)
РЫНОК_ПЕЧАТЬ = {
    1: "наём 2 разных войск на 1 гекс | 5 монет",
    2: "5 монет | 2 арсенала",
    3: "2 арсенала | Манёвр",
    4: "Манёвр | Питание",
    5: "Питание | 3 боеприпаса",
    6: "3 боеприпаса | посмотри 4 задания, оставь 2",
    7: "посмотри 4 задания, оставь 2 | Бой",
    8: "Бой | наём 2 разных войск на 1 гекс",
    9: "5 монет | Питание",
    10: "3 боеприпаса | 2 арсенала",
}


def раскладка():
    out = []
    for i, (цвет, _) in enumerate(ЦВЕТА):
        for j, верх in enumerate(ВЕРХ):
            out.append((os.path.join(ПРИКАЗЫ, "карты-приказов-симметрия-%d.png" % (1 + 4 * i + j)),
                        os.path.join("orders", "%s_%s.png" % (цвет, верх))))
    for i, (_, рисунок) in enumerate(ЦВЕТА):
        out.append((os.path.join(ПРИКАЗЫ, "карты-приказов-симметрия-%d.png" % (17 + i)),
                    os.path.join("orders", "security_%s.png" % рисунок)))
        out.append((os.path.join(ПРИКАЗЫ, "карты-приказов-симметрия-%d.png" % (21 + i)),
                    os.path.join("orders", "back_%s.png" % рисунок)))
    общая = os.path.join(ПРИКАЗЫ, "карты-приказов-симметрия-25.png")
    out += [(общая, os.path.join("orders", "back.png")), (общая, "deck_orders.png")]
    for n, id_ in КОНТЕЙНЕР.items():
        if id_:
            out.append((os.path.join(КОНТЕЙНЕРЫ, "контейнеры-new-%d.png" % n),
                        os.path.join("container", id_ + ".png")))
    for файл, имя in (("арсенал.png", "deck_arsenal"), ("арсенал-начальный.png", "deck_arsenal_start"),
                      ("арсенал-супер.png", "deck_super_arsenal"), ("задания.png", "deck_objectives"),
                      ("Задания начальные.png", "deck_objectives_start"),
                      ("задания супер.png", "deck_super_objectives"),
                      ("Карты рынка.png", "deck_market"), ("контейнеры.png", "deck_containers")):
        out.append((os.path.join(РУБАШКИ, файл), имя + ".png"))
    for n, имя in ((1, "aid_round"), (2, "aid_orders"), (3, "aid_actions"), (4, "aid_actions_2")):
        out.append((os.path.join(ПАМЯТКИ, "Памятка игрока new-%d.png" % n), имя + ".png"))
    return out


def главная():
    проверить = "--проверить" in sys.argv
    for откуда, куда in раскладка():
        новый = Image.open(откуда)
        путь = os.path.join(КАРТЫ, куда)
        был = Image.open(путь).size if os.path.exists(путь) else None
        знак = "" if был in (None, новый.size) else "  (был %dx%d)" % был
        print("%-30s <- %-36s %dx%d%s%s" % (куда, os.path.basename(откуда), *новый.size, знак,
                                           "" if был else "  НОВЫЙ"))
        if not проверить:
            os.makedirs(os.path.dirname(путь), exist_ok=True)
            новый.save(путь, optimize=True)
    for n, id_ in КОНТЕЙНЕР.items():
        if not id_:
            print("контейнер new-%d: печать разошлась с containers.6.0.0 — лицо не кладётся" % n)
    for n, текст in РЫНОК_ПЕЧАТЬ.items():
        print("рынок %02d (%s): нет в market.3.0.0 — лицо не кладётся" % (n, текст))
    return 0


if __name__ == "__main__":
    sys.exit(главная())
