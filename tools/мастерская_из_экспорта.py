def арсенал(тип, список, рисунков):
    out = []
    for i, (имя, спец, слева, верх, справа, низ, звезда, доп) in enumerate(список):
        c = {'тип': тип, 'иконки': ВЕРСИЯ, 'рисунок': i % рисунков + 1, 'спец': спец,
             'верх': верх, 'верх_по_центру': False, 'верх_слева': слева, 'верх_справа': справа,
             'имя': имя, 'низ': низ, 'ряд': '', 'звезда': звезда, 'контейнер': False}
        c.update(доп)
        out.append(c)
    return out


