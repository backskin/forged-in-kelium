def main():
    текст = io.open(ЦЕЛЬ, encoding='utf-8').read()
    d = yaml.safe_load(текст)
    карты = d['super_objectives']
    нет = [c['id'] for c in карты if c['id'] not in ОПИСАНИЯ]
    if нет:
        raise SystemExit(f'нет описаний для: {нет}')
    for c in карты:
        c['описание'] = ОПИСАНИЯ[c['id']]

    шапка = текст.split('meta:')[0]
    io.open(ЦЕЛЬ, 'w', encoding='utf-8').write(
        шапка + yaml.safe_dump({'meta': d['meta'], 'super_objectives': карты},
                               allow_unicode=True, sort_keys=False, width=100))
    print(f'готово: {ЦЕЛЬ}, описаний {len(карты)}')


if __name__ == '__main__':
    main()
