def файл(версия):
    return '%s/blocks.%s.yaml' % (ПАПКА, версия)


def записать(стороны, поРазмеру, версия, зерно, энергии, контейнеров, эталон, замеры):
    d = yaml.safe_load(io.open(ГЕОМЕТРИЯ_ИЗ, encoding='utf-8').read())
    счётчик = {'small': 0, 'big': 0}
    разметка = {}
    for i, (bid, размер, имя, гексы) in enumerate(стороны):
        разметка[(bid, имя)] = (гексы, поРазмеру[размер][счётчик[размер]])
        счётчик[размер] += 1

    блоки = []
    for b in d['blocks']:
        новый = {'id': b['id'], 'kind': b['kind'], 'faces': {}}
        for имя in ('A', 'B'):
            если = разметка.get((b['id'], имя))
            if если is None:
                continue
            гексы, f = если
            новый['faces'][имя] = [
                {'q': q, 'r': r, 'cell': f.конт[p], 'energy': f.энер[p]}
                for p, (q, r) in enumerate(гексы)]
        блоки.append(новый)

    шапка = (
        '# CONTENT: blocks  version %s\n'
        '# %s\n'
        '# Собран tools/наборы-блоков-5.py, зерно %d.\n'
        '#\n'
        '# РАВНОМЕРНОЕ РАСПРЕДЕЛЕНИЕ — то, ради чего семейство 5.* и сделано.\n'
        '# Каждый боковой сектор занят энергией примерно поровну, и контейнером\n'
        '# тоже; то же самое отдельно на КАЖДОМ по счёту гексе стороны; и «только\n'
        '# контейнер», «только энергия», «и то и то» разложены по местам поровну.\n'
        '# Замеренные размахи — в meta.равномерность ниже.\n'
        '#\n'
        '# Пустых гексов нет ни одного. Энергия %d из 5 (малый) и %d из 6 (большой);\n'
        '# контейнеры %d из 5 и %d из 6, один из них — в ячейке авиации (сектор %d).\n'
        '# Расположение энергии и контейнеров у любой пары сторон одного размера\n'
        '# совпадает не больше чем на одном гексе.\n'
        '#\n'
        '# Геометрия сторон взята из авторского набора 1.4.0 и не менялась —\n'
        '# это физический картон.\n'
        % (версия,
           'ЭТАЛОННЫЙ НАБОР — сочетание, которое дизайнер держит основным.'
           if эталон else 'Сочетание из сетки 5.* — правила и цели те же.',
           зерно, энергии['small'], энергии['big'],
           контейнеров['small'], контейнеров['big'], НЕБО))

    мета = {
        'id': версия,
        'type': 'blocks',
        'seed': зерно,
        'описание': ('энергия %d/5 и %d/6, контейнеры %d/5 и %d/6, '
                     'один в ячейке авиации'
                     % (энергии['small'], энергии['big'],
                        контейнеров['small'], контейнеров['big'])),
        'пустых_гексов': 0,
        'предел_совпадений_на_пару': ПРЕДЕЛ_СОВПАДЕНИЙ,
        'равномерность': замеры,
        'сгенерировано': 'tools/наборы-блоков-5.py',
    }
    if эталон:
        мета['эталон'] = True
    текст = yaml.dump({'meta': мета, 'blocks': блоки},
                      allow_unicode=True, sort_keys=False, width=100)
    io.open(файл(версия), 'w', encoding='utf-8', newline='').write(шапка + текст)


