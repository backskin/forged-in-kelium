def размахи(набор, n):
    """Размах каждой гистограммы: наибольшее минус наименьшее."""
    def размах(счёт, ключи):
        значения = [счёт.get(k, 0) for k in ключи]
        return max(значения) - min(значения)

    сектЭ = Counter()
    сектК = Counter()
    небо = Counter()
    видМесто = [Counter() for _ in range(n)]
    поМестуЭ = []
    поМестуК = []
    for f in набор:
        небо[f.небо] += 1
        for p in range(n):
            видМесто[p][f.вид(p)] += 1
            if f.энер[p] != ПУСТО:
                сектЭ[f.энер[p]] += 1
            if f.конт[p] not in (ПУСТО, НЕБО):
                сектК[f.конт[p]] += 1
    for p in range(n):
        сЭ = Counter(f.энер[p] for f in набор if f.энер[p] != ПУСТО)
        сК = Counter(f.конт[p] for f in набор if f.конт[p] not in (ПУСТО, НЕБО))
        поМестуЭ.append(размах(сЭ, БОКОВЫЕ))
        поМестуК.append(размах(сК, БОКОВЫЕ))
    видРазмах = {}
    имена = {0: 'только контейнер', 1: 'только энергия', 2: 'оба'}
    for вид in (0, 1, 2):
        счёт = Counter({p: видМесто[p].get(вид, 0) for p in range(n)})
        видРазмах[имена[вид]] = размах(счёт, list(range(n)))
    return {
        'секторы энергии, размах': размах(сектЭ, БОКОВЫЕ),
        'секторы контейнеров, размах': размах(сектК, БОКОВЫЕ),
        'секторы по месту гекса, наибольший размах':
            'энергия %d, контейнеры %d' % (max(поМестуЭ), max(поМестуК)),
        'что на гексе, размах по местам':
            ', '.join('%s %d' % (k, v) for k, v in видРазмах.items()),
        'ячейка авиации по местам, размах': размах(небо, list(range(n))),
    }


