def геометрия():
    """Двадцать сторон: (id блока, размер, сторона, [(q, r), ...])."""
    d = yaml.safe_load(io.open(ГЕОМЕТРИЯ_ИЗ, encoding='utf-8').read())
    стороны = []
    for b in d['blocks']:
        for имя in ('A', 'B'):
            гексы = (b.get('faces') or {}).get(имя)
            if not isinstance(гексы, list):
                continue
            стороны.append((b['id'], b['kind'], имя,
                            [(h['q'], h['r']) for h in гексы]))
    return стороны


