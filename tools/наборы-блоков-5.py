def откл(счёт, ключи, всего):
    """Сумма квадратов отклонений от идеала."""
    if всего == 0:
        return 0.0
    идеал = всего / len(ключи)
    return sum((счёт.get(k, 0) - идеал) ** 2 for k in ключи)


def штраф(набор, n):
    """Насколько распределение далеко от равномерного. Меньше — лучше."""
    сектВсегоЭ = Counter()
    сектВсегоК = Counter()
    сектМестоЭ = [Counter() for _ in range(n)]
    сектМестоК = [Counter() for _ in range(n)]
    видМесто = [Counter() for _ in range(n)]
    небоМесто = Counter()
    всегоЭ = 0
    всегоК = 0
    всегоЭм = [0] * n
    всегoКм = [0] * n

    for f in набор:
        небоМесто[f.небо] += 1
        for p in range(n):
            видМесто[p][f.вид(p)] += 1
            s = f.энер[p]
            if s != ПУСТО:
                сектВсегоЭ[s] += 1
                сектМестоЭ[p][s] += 1
                всегоЭ += 1
                всегоЭм[p] += 1
            c = f.конт[p]
            if c != ПУСТО and c != НЕБО:
                сектВсегоК[c] += 1
                сектМестоК[p][c] += 1
                всегоК += 1
                всегoКм[p] += 1

    ц = 0.0
    ц += ВЕС_СЕКТОРЫ_ВСЕГО * (откл(сектВсегоЭ, БОКОВЫЕ, всегоЭ)
                              + откл(сектВсегоК, БОКОВЫЕ, всегоК))
    for p in range(n):
        ц += ВЕС_СЕКТОРЫ_ПО_МЕСТУ * (откл(сектМестоЭ[p], БОКОВЫЕ, всегоЭм[p])
                                     + откл(сектМестоК[p], БОКОВЫЕ, всегoКм[p]))
    # «что на гексе»: три вида, каждый со своим итогом по всему набору
    for вид in (0, 1, 2):
        всего = sum(видМесто[p].get(вид, 0) for p in range(n))
        счёт = Counter({p: видМесто[p].get(вид, 0) for p in range(n)})
        ц += ВЕС_ЧТО_НА_ГЕКСЕ * откл(счёт, list(range(n)), всего)
    ц += ВЕС_НЕБО_ПО_МЕСТУ * откл(небоМесто, list(range(n)), len(набор))
    return ц


