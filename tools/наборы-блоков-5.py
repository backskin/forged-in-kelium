class Сторона:
    """
    Разметка одной стороны блока.

    N — места БЕЗ энергии (каждое обязано нести контейнер);
    A — места С контейнером (N входит в A целиком);
    небо — то место из A, чей контейнер стоит в ячейке авиации;
    конт/энер — сектор по каждому месту либо ПУСТО.
    """

    __slots__ = ('n', 'N', 'A', 'небо', 'конт', 'энер')

    def __init__(self, n, N, A):
        self.n = n
        self.N = frozenset(N)
        self.A = frozenset(A)
        self.небо = None
        self.конт = [ПУСТО] * n
        self.энер = [ПУСТО] * n

    def копия(self):
        c = Сторона(self.n, self.N, self.A)
        c.небо = self.небо
        c.конт = list(self.конт)
        c.энер = list(self.энер)
        return c

    def случайныеСекторы(self, rnd):
        """Разложить секторы заново по уже выбранным местам. False — не вышло."""
        self.небо = rnd.choice(sorted(self.A))
        наземные = [p for p in sorted(self.A) if p != self.небо]
        сЭнергией = [p for p in range(self.n) if p not in self.N]
        self.конт = [ПУСТО] * self.n
        self.энер = [ПУСТО] * self.n
        self.конт[self.небо] = НЕБО
        for p, s in zip(наземные, rnd.sample(БОКОВЫЕ, len(наземные))):
            self.конт[p] = s
        for p, s in zip(сЭнергией, rnd.sample(БОКОВЫЕ, len(сЭнергией))):
            self.энер[p] = s
        return self.законна()

    def законна(self):
        """Жёсткие правила ОДНОЙ стороны."""
        кон = [s for s in self.конт if s != ПУСТО and s != НЕБО]
        эн = [s for s in self.энер if s != ПУСТО]
        if len(set(кон)) != len(кон) or len(set(эн)) != len(эн):
            return False
        if sum(1 for s in self.конт if s == НЕБО) != 1:
            return False
        for p in range(self.n):
            if self.конт[p] == ПУСТО and self.энер[p] == ПУСТО:
                return False
            if self.конт[p] != ПУСТО and self.конт[p] == self.энер[p]:
                return False
            if self.энер[p] == НЕБО:
                return False
        return True

    def вид(self, p):
        """Что на месте p: 0 — только контейнер, 1 — только энергия, 2 — оба."""
        if self.энер[p] == ПУСТО:
            return 0
        if self.конт[p] == ПУСТО:
            return 1
        return 2


def парыМест(n, энергий, контейнеров):
    """Все законные пары (места без энергии, места с контейнером)."""
    безЭнергии = n - энергий
    добрать = контейнеров - безЭнергии
    if добрать < 0:
        return []
    out = []
    for N in itertools.combinations(range(n), безЭнергии):
        прочие = [h for h in range(n) if h not in N]
        for доп in itertools.combinations(прочие, добрать):
            out.append((frozenset(N), frozenset(N) | frozenset(доп)))
    return out


def нужныРазныеМеста(n, сколько):
    """
    Обязаны ли наборы мест различаться.

    Места «у обеих метки нет» дают совпадения сами: одинаковые наборы дают их
    сразу n - сколько. При n - сколько >= 2 предел нарушен при любых секторах.
    """
    return n - сколько >= 2


