def один(стороны, номер, контМалый, энерМалый, перезаписать):
    версия = '5.%d.0' % номер
    эталон = номер == 0
    if os.path.exists(файл(версия)) and not перезаписать:
        return '%s — уже лежит, не тронут%s' % (версия, ' (ЭТАЛОН)' if эталон else '')
    энергии = {'small': энерМалый, 'big': энерМалый + 1}
    контейнеров = {'small': контМалый, 'big': контМалый + 1}
    for размер in ('small', 'big'):
        безЭнергии = ГЕКСОВ[размер] - энергии[размер]
        if контейнеров[размер] < безЭнергии:
            return ('%s — НЕЗАКОННО: на %s блоке %d гексов без энергии, '
                    'а контейнеров %d'
                    % (версия, размер, безЭнергии, контейнеров[размер]))

    база = ЗЕРНО + номер * 1000000
    поРазмеру = {}
    замеры = {}
    for размер in ('big', 'small'):
        сколько = sum(1 for x in стороны if x[1] == размер)
        найдено = половина(размер, сколько, база + (0 if размер == 'big' else 7717),
                           энергии[размер], контейнеров[размер])
        if найдено is None:
            return '%s — НЕ СОШЛОСЬ: законной раскладки не нашлось' % версия
        поРазмеру[размер] = найдено
        замеры['малые' if размер == 'small' else 'большие'] = \
            размахи(найдено, ГЕКСОВ[размер])
    записать(стороны, поРазмеру, версия, база, энергии, контейнеров, эталон, замеры)
    сводка = []
    for группа, что in замеры.items():
        сводка.append('%s: секторы Э%d К%d, по месту %s, что на гексе (%s)'
                      % (группа, что['секторы энергии, размах'],
                         что['секторы контейнеров, размах'],
                         что['секторы по месту гекса, наибольший размах'],
                         что['что на гексе, размах по местам']))
    return '%s — готово. ' % версия + ' | '.join(сводка)


