def начальный(n, сколько, пары, энергий, контейнеров, rnd):
    """Любая законная раскладка половины — с неё начинается отжиг."""
    разныеК = нужныРазныеМеста(n, контейнеров)
    разныеЭ = нужныРазныеМеста(n, энергий)
    for _ in range(СТАРТОВ):
        набор = []
        занятыеA = set()
        занятыеN = set()
        # НАБОР МЕСТ БЕРЁТСЯ ИЗ ПУЛА, А НЕ ОДНИМ ПРОХОДОМ ПО СПИСКУ. Когда метки
        # стоят на ВСЕХ гексах, законный набор мест ровно один — прежняя
        # редакция успевала взять одну сторону из десяти и сдавалась. Повторять
        # набор мест в таком случае ЗАКОННО: мест «у обеих метки нет» не
        # существует, и совпадения дают только секторы.
        for _ in range(сколько * 400):
            if len(набор) >= сколько:
                break
            свободные = [(N, A) for N, A in пары
                         if not (разныеК and A in занятыеA)
                         and not (разныеЭ and N in занятыеN)]
            if not свободные:
                break
            N, A = rnd.choice(свободные)
            f = Сторона(n, N, A)
            if f.случайныеСекторы(rnd) and влезает(f, набор):
                набор.append(f)
                занятыеA.add(A)
                занятыеN.add(N)
        if len(набор) >= сколько:
            return набор[:сколько]
    return None


def перекосСекторов(набор, n, поле):
    """Счёт боковых секторов по всему набору для одного вида метки."""
    счёт = Counter()
    for f in набор:
        линия = f.конт if поле == 0 else f.энер
        for p in range(n):
            if линия[p] != ПУСТО and линия[p] != НЕБО:
                счёт[линия[p]] += 1
    return счёт


def подтянуть(набор, n, rnd):
    """
    НАПРАВЛЕННЫЙ ХОД: снять метку с переизбыточного сектора и поставить в
    недостающий.

    Слепые правки до ровного распределения доходят долго: чтобы сдвинуть
    гистограмму, случайной замене надо угадать И место, И нужный сектор. Здесь
    сектор выбирается по замеру — самый частый меняется на самый редкий, — и
    поиск идёт к цели, а не гуляет вокруг.
    """
    поле = 0 if rnd.random() < 0.5 else 1
    счёт = перекосСекторов(набор, n, поле)
    порядок = sorted(БОКОВЫЕ, key=lambda x: счёт.get(x, 0))
    редкий = порядок[0]
    частый = порядок[-1]
    if счёт.get(частый, 0) - счёт.get(редкий, 0) <= 1:
        return None
    кандидаты = []
    for i, f in enumerate(набор):
        линия = f.конт if поле == 0 else f.энер
        for p in range(n):
            if линия[p] == частый and редкий not in линия:
                кандидаты.append((i, p))
    if not кандидаты:
        return None
    i, p = rnd.choice(кандидаты)
    новая = набор[i].копия()
    линия = новая.конт if поле == 0 else новая.энер
    линия[p] = редкий
    if not новая.законна():
        return None
    return i, новая


def правка(набор, n, пары, энергий, контейнеров, rnd):
    """
    Одна мелкая правка. Возвращает (индекс, новая сторона) или None.

    Три вида правок, и все мелкие нарочно: крупные ломают пару-правило и почти
    всегда отвергаются, а мелкие двигают распределение шаг за шагом.
    """
    # ЧЕТВЕРТЬ ХОДОВ — НАПРАВЛЕННЫЕ: они и вытягивают гистограммы в ровные.
    if rnd.random() < 0.25:
        п = подтянуть(набор, n, rnd)
        if п is not None:
            i, новая = п
            прочие = [f for j, f in enumerate(набор) if j != i]
            if влезает(новая, прочие):
                return i, новая
        return None

    i = rnd.randrange(len(набор))
    было = набор[i]
    что = rnd.random()
    новая = было.копия()
    if что < 0.34:
        # МЕЛКИЙ ХОД: одному месту сменить сектор на свободный. Крупные правки
        # почти всегда отвергаются парным правилом, и поиск на них стоит; мелкие
        # двигают распределение по одному шагу и проходят гораздо чаще.
        поле = новая.энер if rnd.random() < 0.5 else новая.конт
        места = [p for p in range(n)
                 if поле[p] != ПУСТО and поле[p] != НЕБО]
        if not места:
            return None
        p = rnd.choice(места)
        занятые = {поле[q] for q in range(n) if q != p and поле[q] != ПУСТО}
        свободные = [x for x in БОКОВЫЕ if x not in занятые]
        if not свободные:
            return None
        поле[p] = rnd.choice(свободные)
        if not новая.законна():
            return None
    elif что < 0.55:
        # МЕЛКИЙ ХОД: поменять секторы двух мест одного вида местами. Так
        # распределение по МЕСТУ гекса двигается, не меняя общего по секторам.
        поле = новая.энер if rnd.random() < 0.5 else новая.конт
        места = [p for p in range(n)
                 if поле[p] != ПУСТО and поле[p] != НЕБО]
        if len(места) < 2:
            return None
        p, q = rnd.sample(места, 2)
        поле[p], поле[q] = поле[q], поле[p]
        if not новая.законна():
            return None
    elif что < 0.70:
        # крупный ход: переставить секторы целиком, места оставить
        if not новая.случайныеСекторы(rnd):
            return None
    elif что < 0.85:
        # пересадить небесный контейнер на другое своё место
        варианты = [p for p in sorted(новая.A) if p != новая.небо]
        if not варианты:
            return None
        куда = rnd.choice(варианты)
        свободные = [s for s in БОКОВЫЕ
                     if s not in [новая.конт[p] for p in range(n) if p != куда]
                     and s != новая.энер[новая.небо]]
        if not свободные:
            return None
        новая.конт[новая.небо] = rnd.choice(свободные)
        новая.конт[куда] = НЕБО
        новая.небо = куда
        if not новая.законна():
            return None
    else:
        # сменить набор мест на другой, свободный
        разныеК = нужныРазныеМеста(n, контейнеров)
        разныеЭ = нужныРазныеМеста(n, энергий)
        занятыеA = {f.A for j, f in enumerate(набор) if j != i}
        занятыеN = {f.N for j, f in enumerate(набор) if j != i}
        свободные = [(N, A) for N, A in пары
                     if not (разныеК and A in занятыеA)
                     and not (разныеЭ and N in занятыеN)]
        if not свободные:
            return None
        N, A = rnd.choice(свободные)
        новая = Сторона(n, N, A)
        if not новая.случайныеСекторы(rnd):
            return None
    прочие = [f for j, f in enumerate(набор) if j != i]
    if not влезает(новая, прочие):
        return None
    return i, новая


def половина(размер, сколько, зерно, энергий, контейнеров):
    """Найти самую равномерную законную разметку сторон одного размера."""
    n = ГЕКСОВ[размер]
    пары = парыМест(n, энергий, контейнеров)
    if not пары:
        return None
    лучший = None
    лучшийШтраф = None
    for заход in range(ЗАХОДОВ):
        rnd = random.Random(зерно + заход * 9176)
        набор = начальный(n, сколько, пары, энергий, контейнеров, rnd)
        if набор is None:
            continue
        текущий = штраф(набор, n)
        t0 = max(1.0, текущий / 12.0)
        for шаг in range(ШАГОВ):
            п = правка(набор, n, пары, энергий, контейнеров, rnd)
            if п is None:
                continue
            i, новая = п
            старая = набор[i]
            набор[i] = новая
            стало = штраф(набор, n)
            дельта = стало - текущий
            t = t0 * (1.0 - шаг / ШАГОВ) + 1e-9
            if дельта <= 0 or rnd.random() < math.exp(-дельта / t):
                текущий = стало
            else:
                набор[i] = старая
            if текущий == 0:
                break
        if лучшийШтраф is None or текущий < лучшийШтраф:
            лучшийШтраф = текущий
            лучший = [f.копия() for f in набор]
            if лучшийШтраф == 0:
                break
    return лучший


