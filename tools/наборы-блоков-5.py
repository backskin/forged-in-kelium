def совпало(a, b, поле):
    ma = a.конт if поле == 0 else a.энер
    mb = b.конт if поле == 0 else b.энер
    return sum(1 for x, y in zip(ma, mb) if x == y)


def параЗаконна(a, b):
    return (совпало(a, b, 0) <= ПРЕДЕЛ_СОВПАДЕНИЙ
            and совпало(a, b, 1) <= ПРЕДЕЛ_СОВПАДЕНИЙ)


def влезает(сторона, прочие):
    return all(параЗаконна(сторона, x) for x in прочие)


