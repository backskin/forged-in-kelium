def число(s):
    s = (s or "").strip().replace(",", ".")
    try:
        return int(float(s))
    except ValueError:
        return 0


def чистая(s):
    """Строка таблицы без переносов и лишних пробелов."""
    return " ".join((s or "").split())


def награда(строка, колонки):
    из = {}
    for кол, поле in колонки.items():
        n = число(строка.get(кол))
        if not n:
            continue
        if поле == "module_attack":
            из["module"] = "attack"
        elif поле == "module_assembly":
            из["module"] = "assembly"
        elif поле == "tech_step":
            из["tech_step"] = True
        else:
            из[поле] = n
    return из


def словами(блок):
    """{'coin': 2, 'ammo': 1} -> «2 монеты и 1 боеприпас»."""
    куски = []
    for поле, формы in СЛОВА.items():
        n = блок.get(поле)
        if not n:
            continue
        хвост = n % 10
        сотня = n % 100
        if хвост == 1 and сотня != 11:
            слово = формы[0]
        elif хвост in (2, 3, 4) and сотня not in (12, 13, 14):
            слово = формы[1]
        else:
            слово = формы[2]
        куски.append("%d %s" % (n, слово))
    if блок.get("arsenal"):
        куски.append("карта арсенала")
    if блок.get("module") == "attack":
        куски.append("жетон модуля атаки")
    if блок.get("module") == "assembly":
        куски.append("жетон модуля сборки")
    if блок.get("tech_step"):
        куски.append("ступень трека технологий")
    if not куски:
        return ""
    if len(куски) == 1:
        return куски[0]
    return ", ".join(куски[:-1]) + " и " + куски[-1]


def словами_база(строка):
    """Базовая награда словами: она теперь всегда действие (или позолота)."""
    п = чистая(строка.get("Награда: действие"))
    if п == "ПОЗОЛОЧЕНИЕ МОДУЛЯ":
        return "позолота одного своего модуля"
    return "бесплатное действие %s" % п.capitalize()


def описание(строка, база, усил):
    усл = чистая(строка["Условие"]).rstrip(".")
    текст = "%s — награда %s." % (усл, словами_база(строка))
    ус = чистая(строка["Усиление"]).rstrip(".")
    if ус:
        текст += " %s%s — условие усилено: %s." % (
            ус[0].upper(), ус[1:], словами(усил) or "ничего")
    return текст


def main():
    with io.open(ТАБЛИЦА, encoding="utf-8-sig", newline="") as f:
        таблица = list(csv.DictReader(f))
    путь_старой = os.path.join(КОРЕНЬ, "data", "cards",
                               "objectives.%s.yaml" % СТАРАЯ)
    сырое = io.open(путь_старой, encoding="utf-8").read()
    данные = yaml.safe_load(сырое)
    карты = данные["objectives"]
    по_ид = {c["id"]: c for c in карты}

    по_семьям_т, по_семьям_к = {}, {}
    for стр in таблица:
        по_семьям_т.setdefault(чистая(стр["Семейство"]), []).append(стр)
    for сем in СЕМЕЙСТВА:
        m = re.search(r"^#\s*%s:\s*(.+)$" % re.escape(сем), сырое, re.M)
        по_семьям_к[сем] = m.group(1).split() if m else []

    правок, неизвестные = 0, set()
    for сем in СЕМЕЙСТВА:
        строки, иды = по_семьям_т.get(сем, []), по_семьям_к.get(сем, [])
        assert len(строки) == len(иды), (сем, len(строки), len(иды))
        for стр, cid in zip(строки, иды):
            c = по_ид[cid]
            утиль = чистая(стр["Утиль"])
            утиль = ЗАМЕНЫ_УТИЛЯ.get(утиль, утиль)
            if утиль not in УТИЛЬ:
                неизвестные.add(утиль)
                continue
            эффект, params = УТИЛЬ[утиль]
            c["requirement"] = {"условие": чистая(стр["Условие"])}
            ус = чистая(стр["Усиление"])
            if ус:
                c["enhanced"] = {"условие": ус}
            else:
                c.pop("enhanced", None)
            печатная = чистая(стр.get("Награда: действие"))
            assert печатная in НАГРАДА_ДЕЙСТВИЕМ, (стр["№"], печатная)
            база = dict(НАГРАДА_ДЕЙСТВИЕМ[печатная])
            усил = награда(стр, УСИЛ)
            c["base_reward"] = база
            if усил:
                c["special_reward"] = усил
            else:
                c.pop("special_reward", None)
            top = {"label": утиль, "effect": эффект}
            if params:
                top["params"] = dict(params)
            c["top"] = top
            c["описание"] = описание(стр, база, усил)
            правок += 1

    if неизвестные:
        print("НЕИЗВЕСТНЫЙ УТИЛЬ (карты не тронуты):")
        for у in sorted(неизвестные):
            print("  *", у)
        return 1

    данные["meta"]["id"] = НОВАЯ
    данные["meta"]["выгружено"] = (
        "задания %s: РЕВИЗИЯ 18.09.2026 — базовая награда стала ДЕЙСТВИЕМ "
        "(8 наград по 5 карт), ресурс остался только в усиленной. Условия, "
        "усиления, утиль и обе награды. «Движение 2 войсками» заменено полным "
        "Манёвром, «атака одним войском» — полноценным Боем (решение того же "
        "дня после онлайн-теста). Описания собраны заново из колонок." % НОВАЯ)

    шапка = сырое.split("meta:")[0].replace(
        "CONTENT: objectives  version %s" % СТАРАЯ,
        "CONTENT: objectives  version %s" % НОВАЯ)
    путь_новой = os.path.join(КОРЕНЬ, "data", "cards",
                              "objectives.%s.yaml" % НОВАЯ)
    with io.open(путь_новой, "w", encoding="utf-8", newline="\n") as f:
        f.write(шапка)
        yaml.safe_dump(данные, f, allow_unicode=True, sort_keys=False,
                       width=100, default_flow_style=False)
    print("занесено карт: %d -> %s" % (правок, os.path.basename(путь_новой)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
