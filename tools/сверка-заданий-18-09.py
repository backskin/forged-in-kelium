# -*- coding: utf-8 -*-
"""СВЕРКА КОЛОДЫ ЗАДАНИЙ С ТАБЛИЦЕЙ ДИЗАЙНЕРА ОТ 18.09.2026.

Таблица лежит в `data/cards/эталон/задания-40-таблица-дизайнера-18.09.2026.csv`
и является ЭТАЛОНОМ: где данные игры с ней расходятся, неправа игра.

Формат новый. В прежней таблице (13.09, .tsv) награда была записана строкой —
«2 монет, 1 БПР, МОДУЛЬ АТАКИ», — и её приходилось разбирать текстом. Теперь
на каждый вид награды своя колонка с числом, отдельно базовая и усиленная.
Поэтому и сверщик отдельный: старый этот файл просто не прочтёт.

СВЯЗКА СТРОКИ И КАРТЫ — по семейству и порядку внутри него. По формулировкам
пары искать нельзя: они как раз и расходятся, это и есть предмет сверки.

Запуск: python tools/сверка-заданий-18-09.py
Код возврата 1, если есть расхождения, — годится как сторож.
"""

import csv
import io
import os
import re
import sys

import yaml

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ТАБЛИЦА = os.path.join(КОРЕНЬ, "data", "cards", "эталон",
                       "задания-40-таблица-дизайнера-18.09.2026.csv")

# БАЗОВАЯ НАГРАДА — ДЕЙСТВИЕ (ревизия 18.09.2026): ресурсных колонок у базы
# больше нет, всё печатное имя лежит в одной клетке. Ресурс остался в усилении.
НАГРАДА_ДЕЙСТВИЕМ = {
    "СТРОЙКА": "build",
    "СНАРЯЖЕНИЕ": "assembly",
    "ДОБЫЧА": "mining",
    "МАНЁВР": "movement",
    "БОЙ": "combat",
    "РЫНОК": "market",
    "НАУКА": "science",
    "ПОЗОЛОЧЕНИЕ МОДУЛЯ": "gild",
}
УСИЛЕНИЕ = {
    "усил.: монеты": "coin",
    "усил.: боеприпасы": "ammo",
    "усил.: карты задания": "objective_card",
    "усил.: трофеи": "trophy",
    "усил.: карта арсенала": "arsenal",
    "усил.: модуль сборки": "module:assembly",
    "усил.: модуль атаки": "module:attack",
    "звезда на треке технологий (положить кубик и получить в конце игры ПО)":
        "tech_step",
}

# ДВА УТИЛЯ ЗАМЕНЕНЫ ПОСЛЕ ТОГО, КАК ТАБЛИЦА БЫЛА НАПИСАНА (дизайнер,
# 18.09.2026, по итогам онлайн-теста): половинчатые действия в утиле не
# работали, и «движение двумя войсками» стало полным Манёвром, а «атака
# одним войском» — полноценным Боем. Расхождением это не считается.
ЗАМЕНЫ_УТИЛЯ = {
    "ДВИЖЕНИЕ 2 войсками": "ПОЛНЫЙ МАНЁВР",
    "АТАКА ОДНИМ ВОЙСКОМ": "ПОЛНОЦЕННЫЙ БОЙ",
}

# Семейства в том порядке, в каком колода собрана (шапка objectives.yaml).
СЕМЕЙСТВА = ["Выработка", "Засада", "Обеспечение", "Развёртывание",
             "Расплата", "Устранение", "Экспансия"]


def свод():
    """Действующий свод и версия колоды заданий в нём — а не наугад."""
    путь = os.path.join(КОРЕНЬ, "engine", "src", "main", "java", "kelium",
                        "dataio", "GameConfig.java")
    ид = re.search(r'"kelium\.ruleset",\s*"([^"]+)"',
                   io.open(путь, encoding="utf-8").read()).group(1)
    правила = io.open(os.path.join(КОРЕНЬ, "data", "rulesets", ид + ".yaml"),
                      encoding="utf-8").read()
    версия = re.search(r"^\s*objectives:\s*([0-9.]+)", правила, re.M).group(1)
    return ид, версия


def ключ(текст):
    """Текст без того, чем письмо отличается от смысла: регистр, ё, знаки."""
    t = (текст or "").lower().replace("ё", "е")
    t = re.sub(r"[^a-zа-я0-9]+", " ", t)
    return " ".join(t.split())


def число(s):
    s = (s or "").strip().replace(",", ".")
    if not s:
        return 0
    try:
        return int(float(s))
    except ValueError:
        return 0


def награда_таблицы(строка, колонки):
    из = {}
    for кол, поле in колонки.items():
        n = число(строка.get(кол))
        if n:
            из[поле] = n
    return из


def награда_карты(блок):
    """Награда из данных игры в том же словаре, что и у таблицы."""
    из = {}
    if not блок:
        return из
    for k, v in блок.items():
        if k == "module":
            из["module:" + str(v)] = 1
        elif k == "tech_step":
            из["tech_step"] = 1 if v is True else число(str(v))
        elif isinstance(v, bool):
            из[k] = 1 if v else 0
        elif isinstance(v, (int, float)):
            из[k] = int(v)
        else:
            из[k] = 1
    return {k: v for k, v in из.items() if v}


def main():
    ид, версия = свод()
    колода = os.path.join(КОРЕНЬ, "data", "cards", "objectives.%s.yaml" % версия)
    данные = yaml.safe_load(io.open(колода, encoding="utf-8"))["objectives"]
    with io.open(ТАБЛИЦА, encoding="utf-8-sig", newline="") as f:
        таблица = list(csv.DictReader(f))

    print("свод %s, колода заданий %s (%d карт), таблица %d строк"
          % (ид, версия, len(данные), len(таблица)))

    # Порядок карт в файле колоды — это и есть порядок семейств из её шапки;
    # разбираем обе стороны по семействам и идём парами.
    по_семьям_т = {}
    for стр in таблица:
        по_семьям_т.setdefault(стр["Семейство"].strip(), []).append(стр)
    шапка = io.open(колода, encoding="utf-8").read()
    по_семьям_к = {}
    for сем in СЕМЕЙСТВА:
        m = re.search(r"^#\s*%s:\s*(.+)$" % re.escape(сем), шапка, re.M)
        по_семьям_к[сем] = m.group(1).split() if m else []
    карта_по_ид = {c["id"]: c for c in данные}

    беды = 0
    for сем in СЕМЕЙСТВА:
        строки = по_семьям_т.get(сем, [])
        иды = по_семьям_к.get(сем, [])
        if len(строки) != len(иды):
            print("\n%s: в таблице %d карт, в колоде %d — пары не сходятся"
                  % (сем, len(строки), len(иды)))
            беды += 1
            continue
        for стр, cid in zip(строки, иды):
            c = карта_по_ид.get(cid)
            if c is None:
                print("\n%s №%s: карты %s нет в колоде" % (сем, стр["№"], cid))
                беды += 1
                continue
            расхождения = []
            пары = [
                ("требование", стр["Условие"],
                 (c.get("requirement") or {}).get("условие")),
                ("усиление", стр["Усиление"],
                 (c.get("enhanced") or {}).get("условие")),
                ("утиль",
                 ЗАМЕНЫ_УТИЛЯ.get(" ".join((стр["Утиль"] or "").split()),
                                  стр["Утиль"]),
                 (c.get("top") or {}).get("label")),
            ]
            for имя, было, стало in пары:
                if ключ(было) != ключ(стало):
                    расхождения.append("  %-10s таблица: %s\n  %-10s колода:  %s"
                                       % (имя, (было or "—").strip(), "", стало))
            печатная = " ".join((стр.get("Награда: действие") or "").split())
            вТаблице = НАГРАДА_ДЕЙСТВИЕМ.get(печатная)
            блок = c.get("base_reward") or {}
            вКолоде = блок.get("action") or ("gild" if блок.get("gild") else None)
            if вТаблице != вКолоде:
                расхождения.append(
                    "  %-10s таблица: %s\n  %-10s колода:  %s"
                    % ("награда", печатная or "—", "", вКолоде or "—"))
            for имя, тк, тб in (("усил.награда", награда_таблицы(стр, УСИЛЕНИЕ),
                                 награда_карты(c.get("special_reward"))),):
                if тк != тб:
                    расхождения.append("  %-10s таблица: %s\n  %-10s колода:  %s"
                                       % (имя, тк or "—", "", тб or "—"))
            if расхождения:
                беды += 1
                print("\n%s №%s -> %s «%s»"
                      % (сем, стр["№"], cid, c.get("name", "")))
                for р in расхождения:
                    print(р)

    print("\nкарт с расхождениями: %d из %d" % (беды, len(таблица)))
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())
