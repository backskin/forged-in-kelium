# -*- coding: utf-8 -*-
"""ДОКУМЕНТ ПО СУПЕР-ЗАДАНИЯМ НОВОГО ОБРАЗЦА — семейство «одна карта втайне».

Покрывает две редакции, у которых общая раздача (каждому игроку одна карта в
подготовку, рубашки одинаковые) и разная механика половин:

  5.0 — «суперутиль или накопитель»: поля stockpile и burn. ОТМЕНЕНА
        дизайнером 31.08.2026, оставлена ради сыгранных замеров.
  6.0 — «множитель в финале плюс жёсткое требование»: поля multiplier,
        requirement и reward. ДЕЙСТВУЮЩАЯ.

Старый образец (четыре ячейки, вскрытие, счётчик запуска, жетон супероружия)
живёт в отдельном инструменте tools/документ-супер-заданий.py — у него другая
форма карты, и склеивать их в один шаблон значило бы печатать полуправду.

Колонка «замечания» пустая нарочно: требования низа 6.0 — черновик под ревью.

Запуск: python tools/документ-супер-задания-новые.py [версия]
"""
import io
import sys

import yaml
from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.shared import Cm, Pt, RGBColor

ВЕРСИЯ = sys.argv[1] if len(sys.argv) > 1 else "6.0.0"
ИСТОЧНИК = f"data/cards/super_objectives.{ВЕРСИЯ}.yaml"
ЦЕЛЬ = f"docs/КАРТЫ СУПЕР ЗАДАНИЙ {ВЕРСИЯ}.docx"


def сер(п, текст, кегль=9):
    run = п.add_run(текст)
    run.font.size = Pt(кегль)
    run.font.color.rgb = RGBColor(0x60, 0x60, 0x60)
    return run


def образец(карты):
    """Какая редакция перед нами — по полям первой карты."""
    return "6.0" if "multiplier" in карты[0] else "5.0"


def main():
    набор = yaml.safe_load(io.open(ИСТОЧНИК, encoding="utf-8"))
    карты = набор["super_objectives"]
    вид = образец(карты)

    doc = Document()
    if вид == "6.0":
        doc.add_heading(f"Супер-задания {ВЕРСИЯ} — множитель в финале "
                        f"и жёсткое требование", 0)
        п = doc.add_paragraph()
        сер(п, "Каждому игроку в подготовку втайне раздаётся ОДНА карта. Она "
               "НЕ сжигается и не удаляется и остаётся перед игроком до конца "
               "партии. ВЕРХ карты — множитель победных очков, считается В "
               "ФИНАЛЕ игры (значок финала, а не «всегда»). НИЗ — жёсткое "
               "требование и очень хорошая награда за него; награда берётся "
               "один раз и множитель верха не отменяет. Требования низа — "
               "черновик, колонка «замечания» под ваши пометки.", 10)
        колонки = ["№", "карта", "ВЕРХ: множитель в финале",
                   "НИЗ: жёсткое требование", "НИЗ: награда", "замечания"]
        ширины = [Cm(0.9), Cm(2.9), Cm(4.6), Cm(4.4), Cm(4.6), Cm(2.0)]
        поля = ("multiplier", "requirement", "reward")
    else:
        doc.add_heading(f"Супер-задания {ВЕРСИЯ} — «суперутиль или накопитель»", 0)
        п = doc.add_paragraph()
        сер(п, "Отменённая редакция, оставлена ради сыгранных замеров. Каждому "
               "игроку втайне одна карта; сыграть можно только одну половину: "
               "суперутиль сжигается СПЕЦ-действием, накопитель платит очками "
               "в конце, если карта дожила нетронутой.", 10)
        колонки = ["№", "карта", "НАКОПИТЕЛЬ (очки в конце)",
                   "СУПЕРУТИЛЬ (разовый эффект)", "замечания"]
        ширины = [Cm(0.9), Cm(3.2), Cm(5.8), Cm(5.8), Cm(2.6)]
        поля = ("stockpile", "burn")

    doc.add_heading("Все карты одной таблицей", 1)
    т = doc.add_table(rows=1, cols=len(колонки))
    т.style = "Table Grid"
    т.alignment = WD_TABLE_ALIGNMENT.CENTER
    шапка = т.rows[0].cells
    for i, з in enumerate(колонки):
        шапка[i].paragraphs[0].add_run(з).bold = True
    for n, к in enumerate(карты, 1):
        ряд = т.add_row().cells
        ряд[0].text = str(n)
        ряд[1].text = str(к.get("name", к["id"]))
        for i, поле in enumerate(поля):
            ряд[2 + i].text = str(к.get(поле, ""))
        ряд[-1].text = ""
    for ряд in т.rows:
        for i, кл in enumerate(ряд.cells):
            кл.width = ширины[i]
            for пар in кл.paragraphs:
                for run in пар.runs:
                    run.font.size = Pt(9)

    doc.add_page_break()
    doc.add_heading("По одной карте", 1)
    подписи = ({"multiplier": "ВЕРХ — МНОЖИТЕЛЬ В ФИНАЛЕ: ",
                "requirement": "НИЗ — ЖЁСТКОЕ ТРЕБОВАНИЕ: ",
                "reward": "НИЗ — НАГРАДА: "}
               if вид == "6.0" else
               {"stockpile": "НАКОПИТЕЛЬ: ", "burn": "СУПЕРУТИЛЬ: "})
    for n, к in enumerate(карты, 1):
        doc.add_heading(f"{n}. «{к.get('name', к['id'])}»  ({к['id']})", 2)
        for поле in поля:
            п = doc.add_paragraph()
            п.add_run(подписи[поле]).bold = True
            п.add_run(str(к.get(поле, "")))

    doc.save(ЦЕЛЬ)
    print(f"готово: {ЦЕЛЬ} карт: {len(карты)}, образец {вид}")


if __name__ == "__main__":
    main()
