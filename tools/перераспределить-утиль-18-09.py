# -*- coding: utf-8 -*-
"""ПЕРЕРАСПРЕДЕЛИТЬ УТИЛЬ В ТАБЛИЦЕ ЗАДАНИЙ (заказ дизайнера 18.09.2026).

Дословно: «поменять распределение утилей сверху: там слишком много сейчас
реакций на бой, а нужны ПРОВОКАЦИИ боя — спавны войск, их движение и розыгрыш
боя».

Что было в таблице от 18.09.2026: 13 карт из 40 несли реакции на чужой бой
(заградительный огонь, ответный огонь, отход, рикошет, эвакуация, бой перед
чужим боем) и только 10 — действия. Реакция не начинает войну: она ждёт, пока
войну начнёт кто-то другой. Тридцать три процента колоды, которые нельзя
разыграть по своей воле, и есть та самая нехватка столкновений.

Стало:
    ПОЛНОЦЕННЫЙ БОЙ                 8     провокации: 23 карты из 40
    ПОЛНЫЙ МАНЁВР                   8
    РАЗВЁРТЫВАНИЕ (1 войско)        7
    СМЕНА ЭНЕРГИИ ИЛИ МОДУЛЕЙ       7     «чаще смена энергии и смена модуля»
    реакции                         4     по одной каждого вида — как редкость
    РЕМОНТ ГЕКСА                    2
    ОБМЕН В НАУКЕ ИЛИ НА РЫНКЕ      2
    ЗАКРОМА (+1 боеприпас)          2

Утиль раздаётся ПО СЕМЕЙСТВАМ, а не вперемешку: семейство — это то, чем карта
занята по смыслу, и утиль обязан ему отвечать. Устранение и Засада воюют,
Развёртывание и Обеспечение выставляют войска, Расплата отвечает ударом на
удар — там и осталась половина всех реакций.

Запуск: python tools/перераспределить-утиль-18-09.py
Меняет ТОЛЬКО колонку «Утиль» таблицы-эталона. Колоду после этого пересобирает
`tools/занести-задания-18-09.py`, а сходство проверяет `tools/сверка-заданий-18-09.py`.
"""

import csv
import io
import os
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ТАБЛИЦА = os.path.join(КОРЕНЬ, "data", "cards", "эталон",
                       "задания-40-таблица-дизайнера-18.09.2026.csv")

БОЙ = "ПОЛНОЦЕННЫЙ БОЙ"
МАНЁВР = "ПОЛНЫЙ МАНЁВР"
СПАВН = "РАЗВЁРТЫВАНИЕ: поставь 1 войско из запаса"
ЭНЕРГИЯ = "СМЕНА ЭНЕРГИИ ИЛИ СМЕНА МОДУЛЕЙ"
РЕМОНТ = "РЕМОНТ ГЕКСА"
ОБМЕН = "1 ОБМЕН В НАУКЕ (не трек) ИЛИ 1 ОБМЕН НА РЫНКЕ (не карта)"
ЗАКРОМА = "ЗАКРОМА: +1 БОЕПРИПАС В ПРИКАЗ НАСТУПЛЕНИЕ"
ОТВЕТНЫЙ = "ОТВЕТНЫЙ ОГОНЬ: твоё уничтоженное войско наносит 1 урон убийце"
ЗАГРАДИТЕЛЬНЫЙ = "ЗАГРАДИТЕЛЬНЫЙ ОГОНЬ: твоё уничтоженное здание наносит 1 урон убийце"
РИКОШЕТ = "РИКОШЕТ: атака по твоему жетону переходит на любой другой жетон в том же гексе"
ЭВАКУАЦИЯ = "ЭВАКУАЦИЯ ТРОФЕЕВ: твой уничтоженный жетон уходит в твой запас"

# Номер карты в таблице -> новый утиль. Номера идут подряд внутри семейства,
# поэтому раздача читается семейство за семейством.
РАЗДАЧА = {
    # Выработка (5) — хозяйство: энергия, обмен, запасы, одно развёртывание
    1: ЭНЕРГИЯ, 2: ЭНЕРГИЯ, 3: ЗАКРОМА, 4: СПАВН, 5: ОБМЕН,
    # Засада (5) — бой из укрытия; здесь же две из четырёх реакций
    6: БОЙ, 7: БОЙ, 8: РИКОШЕТ, 9: ОТВЕТНЫЙ, 10: МАНЁВР,
    # Обеспечение (4) — снабжение и выставление войск
    11: ЗАКРОМА, 12: СПАВН, 13: СПАВН, 14: ЭНЕРГИЯ,
    # Развёртывание (7) — имя семейства и есть его утиль
    15: СПАВН, 16: СПАВН, 17: СПАВН, 18: МАНЁВР, 19: МАНЁВР,
    20: ЭНЕРГИЯ, 21: ЭНЕРГИЯ,
    # Расплата (4) — ответ ударом на удар: вторая половина реакций
    22: ЗАГРАДИТЕЛЬНЫЙ, 23: ЭВАКУАЦИЯ, 24: БОЙ, 25: ЭНЕРГИЯ,
    # Устранение (10) — самое воинственное семейство
    26: БОЙ, 27: БОЙ, 28: БОЙ, 29: БОЙ, 30: МАНЁВР, 31: МАНЁВР,
    32: МАНЁВР, 33: СПАВН, 34: РЕМОНТ, 35: ОБМЕН,
    # Экспансия (5) — расширение: движение вперёд
    36: МАНЁВР, 37: МАНЁВР, 38: БОЙ, 39: ЭНЕРГИЯ, 40: РЕМОНТ,
}


def main():
    with io.open(ТАБЛИЦА, encoding="utf-8-sig", newline="") as f:
        читатель = csv.DictReader(f)
        колонки = читатель.fieldnames
        строки = list(читатель)

    было = {}
    for с in строки:
        n = int(с["№"])
        было[" ".join((с["Утиль"] or "").split())] = было.get(
            " ".join((с["Утиль"] or "").split()), 0) + 1
        с["Утиль"] = РАЗДАЧА[n]

    with io.open(ТАБЛИЦА, "w", encoding="utf-8-sig", newline="") as f:
        писец = csv.DictWriter(f, fieldnames=колонки)
        писец.writeheader()
        писец.writerows(строки)

    стало = {}
    for с in строки:
        стало[с["Утиль"]] = стало.get(с["Утиль"], 0) + 1
    print("новое распределение утиля:")
    for у, n in sorted(стало.items(), key=lambda p: -p[1]):
        print("  %2d  %s" % (n, у))
    провокации = стало.get(БОЙ, 0) + стало.get(МАНЁВР, 0) + стало.get(СПАВН, 0)
    реакции = sum(n for у, n in стало.items()
                  if у in (ОТВЕТНЫЙ, ЗАГРАДИТЕЛЬНЫЙ, РИКОШЕТ, ЭВАКУАЦИЯ))
    print("\nпровокаций боя %d из %d, реакций %d" % (провокации, len(строки), реакции))
    return 0


if __name__ == "__main__":
    sys.exit(main())
