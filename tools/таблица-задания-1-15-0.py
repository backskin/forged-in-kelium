# ---------------------------------------------------------------------------
#  ЦЕНА КАРТЫ — это оценка НАГРАДЫ за выполнение, а не сложности задания.
#
#  Коэффициенты выведены сверкой всех сорока карт 04.09.2026: с этими числами
#  сходятся 40 из 40. Дизайнер по памяти называл боеприпас 1.2 и трофей 2.0 —
#  с ними расходятся тринадцать карт, ровно на 0.05 за боеприпас и 0.1 за
#  трофей, так что в таблице использованы числа ниже.
#
#  ОГОВОРКА ПРО ТРОФЕЙ: во всей колоде трофей стоит в награде ровно один раз
#  (карта 11, «2 трофея» = 4.2). Одна точка не даёт отличить 2.1 от 2.0 с
#  ошибкой в этой карте. Если дизайнер подтвердит 2.0 — поправить здесь и там.
#
#  Усиленная награда (арсенал, трофеи, модули) в цену НЕ входит вовсе.
#  Карт арсенала в базовой награде нет ни одной, поэтому коэффициента для них
#  тут и не появилось.
#
#  Цель по средней цене колоды — 3.5.
# ---------------------------------------------------------------------------
ЦЕНА_ТРОФЕЯ = 2.1
ЦЕНА_МОНЕТЫ = 1.0
ЦЕНА_БОЕПРИПАСА = 1.25
ЦЕНА_ЗАДАНИЯ = 1.6
СРЕДНЯЯ_ЦЕЛЬ = 3.5
ДОПУСК_СРЕДНЕЙ = 0.15


def проверить_цены():
    """Пересчитать цену каждой карты из её награды и сверить с записанной."""
    беда = []
    сумма = 0.0
    for н, карта in enumerate(К, 1):
        т, мон, бпр, зад = карта[4]
        расчёт = round(ЦЕНА_ТРОФЕЯ * т + ЦЕНА_МОНЕТЫ * мон
                       + ЦЕНА_БОЕПРИПАСА * бпр + ЦЕНА_ЗАДАНИЯ * зад, 4)
        сумма += карта[5]
        if abs(расчёт - карта[5]) > 1e-9:
            беда.append(f'  карта {н}: записано {карта[5]}, по награде {расчёт}')
    if беда:
        raise SystemExit('цена разошлась с наградой:\n' + '\n'.join(беда))
    средняя = сумма / len(К)
    if abs(средняя - СРЕДНЯЯ_ЦЕЛЬ) > ДОПУСК_СРЕДНЕЙ:
        raise SystemExit(f'средняя цена колоды {средняя:.3f}, '
                         f'цель {СРЕДНЯЯ_ЦЕЛЬ} ± {ДОПУСК_СРЕДНЕЙ}')
    print(f'  цены сошлись у всех {len(К)}; средняя {средняя:.3f} '
          f'при цели {СРЕДНЯЯ_ЦЕЛЬ}')


