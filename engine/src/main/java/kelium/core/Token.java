package kelium.core;

/**
 * Общий интерфейс жетона (юнит или здание) — нужен для смешанного хранения в
 * трофейном пространстве и общей обработки в бою/науке/возврате.
 */
public sealed interface Token permits UnitToken, BuildingToken {

    /** Индекс места-владельца жетона. */
    int owner();

    /**
     * Уникальный номер экземпляра жетона. Нужен всем, кто связывает жетон с
     * ячейкой гекса ({@code Hex.sideOwner}) или переносит его между списками
     * (трофейное пространство, копия состояния для просчёта вперёд).
     */
    int uid();

    /** Трофейная ценность жетона (на его трофейной стороне). */
    int trophyValue();

    /** Кто держит жетон на трофейном поле (null — жетон в игре у владельца). */
    Integer capturedBy();

    /** Задать держателя трофея. */
    void setCapturedBy(Integer seat);

    /** Где стоит жетон (id гекса), либо null в резерве. */
    String hexId();

    /** Переставить жетон на гекс (или в резерв при null). */
    void setHexId(String hexId);

    /** Сбросить весь накопленный урон (возврат уничтоженного жетона). */
    void resetDamage();

    /** Этап Обновления: снять ОДИН кубик урона (урон копится по раундам). */
    void healOneDamage();

    /**
     * КАТЕГОРИЯ ЦЕЛИ этого жетона в бою: по ней таблица атак планшета решает,
     * кто кого может бить. Вышка бьётся как здание — это правило, и живёт оно
     * ровно здесь, а не в трёх копиях по боту и резолверу.
     */
    Target category();
}
