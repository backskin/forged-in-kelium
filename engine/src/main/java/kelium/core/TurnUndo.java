package kelium.core;

/**
 * ПАМЯТКА ХОДА для отката (концепт «Командный пункт», §5).
 *
 * <p>{@link GameState#restoreFrom} возвращает НА МЕСТО всё, что лежит в самом
 * состоянии, — но знание «что уже сыграно в ЭТОМ ходу» живёт в контексте хода
 * движка ({@code kelium.engine.TurnContext}), который ядру не виден. Без него
 * откат возвращал ресурсы, а движок продолжал считать отменённое действие
 * сыгранным — игрок молча ТЕРЯЛ слот действия (найдено при проектировании
 * этапа 5, 24.08.2026).
 *
 * <p>Интерфейс объявлен в ядре, реализуется контекстом хода в движке;
 * {@code GameState.turnUndo} привязывается движком на время хода — так же, как
 * {@code combat} и {@code agents}.
 */
public interface TurnUndo {

    /** Снять памятку изменяемого состояния хода (что сыграно, счётчики). */
    Object saveTurn();

    /** Вернуть состояние хода к ранее снятой памятке. */
    void restoreTurn(Object memento);
}
