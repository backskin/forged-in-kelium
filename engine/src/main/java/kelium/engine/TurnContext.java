package kelium.engine;

import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Учёт в пределах одного хода игрока внутри круга.
 *
 * <p>Хранит номер места (seat), использование SPEC-действий и лимит, счётчики
 * операций для наценок, множество уже сыгранных действий приказа и флаг
 * использования бесплатного хода ЦУ.
 */
public final class TurnContext {

    public final int seat;
    public int specUsed = 0;
    public int specLimit = 1;
    // счётчики операций по имени действия -> сколько раз выполнена «операция»
    public final Map<String, Integer> opCounts = new HashMap<>();
    // действия приказа, уже сыгранные в этот ход (каждое по разу). LinkedHashSet,
    // а не HashSet, — порядок нужен проигрывателю: карта БЕЗОПАСНОСТЬ (джокер)
    // показывает, какие именно два действия из восьми выбрал игрок, и делает
    // это в том порядке, в каком их разыграли.
    public final Set<String> actionsPlayed = new LinkedHashSet<>();
    // использован ли бесплатный ход ЦУ?
    public boolean cuFreeMoveUsed = false;

    public TurnContext(int seat, int specLimit) {
        this.seat = seat;
        this.specLimit = specLimit;
    }

    /**
     * СНЯТ ЛИ ЛИМИТ СПЕЦ-ДЕЙСТВИЙ до конца хода (эффект карты «разыграй любое
     * число спец-действий»). Ход синхронизирует флаг с журналом перед каждым
     * предложением СПЕЦ.
     */
    public boolean specUnlimited = false;

    /** Осталось ли ещё разрешённое SPEC-действие в этот ход. */
    public boolean canSpec() {
        return specUnlimited || specUsed < specLimit;
    }

    /** Отметить использование одного SPEC-действия; ошибка при превышении лимита. */
    public void useSpec() {
        if (!canSpec()) {
            throw new IllegalStateException("превышен лимит SPEC-действий");
        }
        specUsed++;
    }

    /**
     * Наценка за СЛЕДУЮЩУЮ операцию {@code action} по расписанию вида [0,1,2,3];
     * при выходе за пределы берётся последний элемент.
     */
    public int nextOpSurcharge(String action, List<Integer> schedule) {
        int i = opCounts.getOrDefault(action, 0);
        return schedule.get(Math.min(i, schedule.size() - 1));
    }

    /** Учесть проведённую операцию действия {@code action} (для роста наценки). */
    public void recordOp(String action) {
        opCounts.merge(action, 1, Integer::sum);
    }

    // ======================================================================
    //  ЧТО ЕЩЁ МОЖНО СЫГРАТЬ В ЭТОМ ХОДУ
    // ======================================================================
    //  Нужно индикаторам заданий ({@link ObjectiveHints}): план из двух действий
    //  бесполезен, если действие осталось одно, а план через Бой бесполезен, если
    //  вскрыт приказ Разработка. Ход заполняет эти поля перед розыгрышем
    //  действий; до того они пусты, и планировщик считает, что доступно всё.

    /** Действия вскрытого приказа этого хода (в порядке из карты). */
    public final Set<String> orderActions = new LinkedHashSet<>();
    /** Сколько ОСНОВНЫХ действий разрешено этим приказом. */
    public int allowedActions = 0;

    /** Названия действий, которые в этом ходу ещё не сыграны. */
    public Set<String> remainingActionNames() {
        Set<String> out = new LinkedHashSet<>(orderActions);
        out.removeAll(actionsPlayed);
        return out;
    }

    /** Сколько основных действий ещё осталось сыграть. */
    public int remainingActions() {
        return Math.max(0, allowedActions - actionsPlayed.size());
    }

    /**
     * ПОТОЛОК ОБЪЕКТОВ В ОДНОМ БЕСПЛАТНОМ ДЕЙСТВИИ (ревью дизайнера 17.08.2026).
     *
     * <p>Бесплатная Сборка «всеми зданиями сразу» и бесплатная Стройка «сколько
     * влезет» были сильнее выполненного задания — карту выгоднее было сжечь, чем
     * выполнить, и колода сама себя обесценивала. Теперь карта пишет предел:
     * «Сборка не более чем двумя зданиями», «одна строительная операция».
     *
     * <p>Ноль или отсутствие ключа — предела нет (обычное действие своего хода).
     */
    public final Map<String, Integer> objectLimits = new HashMap<>();

    /** Предел объектов для действия; {@link Integer#MAX_VALUE}, если не задан. */
    public int objectLimit(String action) {
        Integer v = objectLimits.get(action);
        return v == null || v <= 0 ? Integer.MAX_VALUE : v;
    }

    /**
     * ЭНЕРГИЯ НЕ ТРЕБУЕТСЯ: все здания считаются запитанными до конца этого
     * действия.
     *
     * <p>Карта рынка «Военный подряд», предложение «Мобилизация». Ведомство
     * поднимает производство приказом, а не подключением: платить энергией не
     * надо ничем и ни за что.
     *
     * <p>Это не «выдать кубики», а именно снять требование: кубиков в игре
     * дефицит, и выдача трёх штук осталась бы на поле после действия.
     */
    public boolean allPowered = false;

    /**
     * НАДБАВКИ СНЯТЫ для перечисленных счётчиков операций.
     *
     * <p>Ключи те же, по которым ведётся {@link #opCounts}: {@code build_place},
     * {@code energy_swap}, {@code combat}. Карта рынка «Инженерная контора»
     * снимает надбавку за второе и последующее размещение («Подряд на стройку»)
     * и делает Смену энергии полностью бесплатной («Перекоммутация»).
     *
     * <p>Счётчик операций при этом ведётся по-прежнему — снята только цена.
     */
    public final Set<String> noSurcharge = new LinkedHashSet<>();

    // ======================================================================
    //  НАДБАВКИ УТИЛЯ К ОДНОМУ ДЕЙСТВИЮ (заказ дизайнера 21.08.2026)
    // ======================================================================
    //  Утиль карты арсенала теперь умеет не только «дай ресурс» и «выполни
    //  действие», но и «выполни действие ВОТ ТАК». Все такие надбавки живут
    //  здесь, в контексте одного действия, и вместе с ним заканчиваются:
    //  постоянного правила они не меняют и в следующий ход не переходят.
    //
    //  ПОЧЕМУ НЕ ЧЕРЕЗ РЕЕСТР СПОСОБНОСТЕЙ. Реестр отвечает на вопросы правил
    //  СОСТОЯНИЕМ игрока («пока карта установлена»), и его спрашивают в том
    //  числе вхолостую — боты просчитывают ходы вперёд. Одноразовая надбавка от
    //  такого вопроса сгорела бы, не будучи использованной. Контекст же живёт
    //  ровно одно разрешение действия и никем не переспрашивается.

    /** Скидка в монетах на КАЖДУЮ постройку в этом действии Стройки. */
    public int buildDiscountCoins = 0;

    /** Постройки в этом действии бесплатны совсем (цена не платится). */
    public boolean buildFree = false;

    /** Сколько своих зданий можно перенести в этом действии БЕСПЛАТНО. */
    public int freeBuildingMoves = 0;

    /** В этом действии Стройки доступны ТОЛЬКО переносы, без новых построек. */
    public boolean buildMovesOnly = false;

    /** Сколько жетонов войск двигаются в этом действии без платы за ход. */
    public int freeExtraMoves = 0;

    /** Рынок: можно взять ОБА предложения карты, а не одно. */
    public boolean marketBothOffers = false;

    /** Сборка: столько зданий выдают за раз И войско, И боеприпас. */
    public int assemblyDualOutput = 0;

    /**
     * Добыча: столько НЕЗАПИТАННЫХ добытчиков работают в это действие даром.
     *
     * <p>Именно незапитанных: запитанные работают и так, все до последнего, —
     * значит «ещё один добытчик» может означать только того, кому не хватило
     * кубика.
     */
    public int freeMinerMoves = 0;

    /** Наука: разрешён обмен обломков на монеты по печатному курсу утиля. */
    public boolean scienceDebrisToCoin = false;
}
