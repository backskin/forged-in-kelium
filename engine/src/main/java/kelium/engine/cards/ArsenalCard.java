package kelium.engine.cards;

/**
 * КАРТА АРСЕНАЛА — верх (утиль) и низ (постоянная способность или СПЕЦ).
 *
 * <p>Карта арсенала играется одним из двух способов, и оба взаимоисключающие:
 *
 * <ul>
 *   <li><b>утиль</b> — карту сжигают ради разового эффекта сверху;</li>
 *   <li><b>установка</b> — карту кладут открытой перед собой, и работает низ:
 *       либо ПОСТОЯННАЯ способность (меняет правило, пока карта лежит), либо
 *       СПЕЦ-действие (тратит единственное СПЕЦ за ход).</li>
 * </ul>
 *
 * <p>Постоянные способности реализуются не здесь, а точками правил
 * ({@code kelium.engine.ability.Hook}): движок сам спрашивает «какая сейчас
 * скорость техники», и установленная карта отвечает. Здесь карта только
 * объявляет, какую способность она включает, — связь остаётся одна и видимая.
 */
public interface ArsenalCard extends Card {

    @Override
    default Family family() {
        return Family.АРСЕНАЛ;
    }

    /** Стартовая карта раздаётся на подготовке и в общую колоду не идёт. */
    default boolean starting() {
        return "starting".equals(String.valueOf(data().getOrDefault("kind", "regular")));
    }

    /**
     * Сжечь карту ради верхнего эффекта. {@code false} — сейчас нельзя.
     */
    boolean burn(CardContext ctx);

    /**
     * Идентификатор постоянной способности, которую включает низ карты, или
     * {@code null}, если низ — СПЕЦ-действие без пассивной части.
     */
    default String passiveId() {
        return null;
    }

    /**
     * Можно ли прямо сейчас применить СПЕЦ-действие установленной карты.
     * Карты без СПЕЦ отвечают {@code false} и ничего не переопределяют.
     */
    default boolean canUseSpec(CardContext ctx) {
        return false;
    }

    /** Применить СПЕЦ-действие. Вызывается, только если {@link #canUseSpec}. */
    default boolean useSpec(CardContext ctx) {
        return false;
    }

    /**
     * НАСКОЛЬКО КАРТА ПОЛЕЗНА ИМЕННО СЕЙЧАС — от 0.0 до 1.0.
     *
     * <p>Нужно боту, чтобы выбирать между «сжечь ради монет» и «поставить ради
     * способности». Раньше этот выбор делался по одному общему весу, из-за чего
     * карты арсенала ставились реже одной за партию: сжечь давало понятную
     * прибавку сейчас, а установка — непонятную потом.
     *
     * @param install спрашивают про установку ({@code true}) или про утиль
     */
    default double usefulness(CardContext ctx, boolean install) {
        return 0.5;
    }
}
