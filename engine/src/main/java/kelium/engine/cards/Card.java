package kelium.engine.cards;

/**
 * КАРТА — объект, а не строка в YAML.
 *
 * <p>Базовый договор для всех семейств: задания, арсенал, рынок, контейнеры,
 * супер задания. Каждая карта знает свой идентификатор (он же связывает её с
 * записью в данных), своё имя для человека и умеет рассказать о себе так, чтобы
 * это можно было показать в справочнике и понять боту.
 *
 * <p>ПОЧЕМУ ДАННЫЕ ОСТАЮТСЯ. Числа (сколько монет, сколько очков, какой порог)
 * по-прежнему живут в YAML: их правит дизайнер, и пересборка ради смены цифры
 * недопустима. В коде живёт ПОВЕДЕНИЕ — что карта проверяет и что делает. Числа
 * карта берёт из своей записи в данных через {@link #data()}.
 */
public interface Card {

    /** Идентификатор из данных: {@code as1}, {@code o17}, {@code c14}. */
    String id();

    /** Имя для человека — то, что напечатано на карте. */
    String name();

    /** Семейство карты. */
    Family family();

    /** Запись карты в данных: числа, награды, тексты. Никогда не {@code null}. */
    java.util.Map<String, Object> data();

    /** Подключить данные карты после загрузки набора. Вызывает только реестр. */
    void bind(java.util.Map<String, Object> data);

    /**
     * КАРТА ОПИСЫВАЕТ СЕБЯ САМА — источником правды служит класс, а не файл.
     *
     * <p>Заказ дизайнера 17.08.2026: «отойти от предикатов и yaml и перейти
     * полностью на код с документацией; данные о картах будут выгружаться по
     * принципу документации кода». У такой карты имя, пороги, награда, печатный
     * текст и поведение объявлены в классе, а {@link #data()} их ВЫГРУЖАЕТ. Реестр
     * при загрузке набора не подключает к ней запись из файла, а НАКРЫВАЕТ запись
     * выгрузкой — поэтому расхождение между кодом и каталогом становится
     * невозможным по устройству, а не по чьей-то внимательности.
     *
     * <p>Карты, ещё не переехавшие в код, отвечают {@code false} и продолжают
     * читать числа из записи, как раньше: переезд идёт по семействам, и оба
     * способа обязаны работать рядом, пока он не закончен.
     */
    default boolean describesItself() {
        return false;
    }

    /**
     * Короткое описание того, что карта делает, — одной фразой и по-русски.
     * Идёт в справочник приложения и в подсказку боту.
     */
    String describe();

    /** Семейства карт. */
    enum Family {
        /** Карта задания: условие плюс награда, либо сжигается ради верха. */
        ЗАДАНИЕ,
        /** Карта арсенала: верх — утиль, низ — постоянная способность или СПЕЦ. */
        АРСЕНАЛ,
        /** Карта рынка: два предложения, действуют раунд. */
        РЫНОК,
        /** Карта контейнера: разовая находка. */
        КОНТЕЙНЕР,
        /** Супер задание: две ступени, мгновенная победа за вторую. */
        СУПЕР_ЗАДАНИЕ
    }
}
