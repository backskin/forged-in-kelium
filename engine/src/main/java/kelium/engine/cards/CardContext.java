package kelium.engine.cards;

import java.util.List;
import java.util.Map;

import kelium.core.GameState;
import kelium.core.PlayerState;
import kelium.core.Resource;
import kelium.core.Token;
import kelium.core.UnitToken;

/**
 * ЧТО КАРТА МОЖЕТ СПРОСИТЬ У ИГРЫ И ЧТО МОЖЕТ С НЕЙ СДЕЛАТЬ.
 *
 * <p>Договор, который движок предоставляет карте. Всё, что карта делает с
 * партией, проходит через него — прямых правок состояния из кода карты быть не
 * должно, иначе снова расползётся то, ради чего затевался модуль карт: правила
 * начнут жить в двух местах.
 *
 * <p>Правило разделения. Здесь только ОБЩИЕ услуги, нужные многим картам:
 * ресурсы, урон, перемещение, выбор игрока, вопросы про поле. Всё, что нужно
 * ровно одной карте, реализуется В САМОЙ КАРТЕ поверх этих услуг, а не
 * добавляется сюда — иначе договор разрастётся до размеров движка.
 *
 * <p>Кто реализует: {@code kelium.engine.EngineCardContext} (внутри движка).
 * Кто пользуется: модуль {@code cards}.
 */
public interface CardContext {

    // ==================================================================
    //  ЧИТАТЬ: карта смотрит на партию
    // ==================================================================

    /** Полное состояние партии — для условий, которые смотрят на всё поле. */
    GameState state();

    /** Чьей картой играют. */
    int seat();

    /** Планшет и запасы того, чьей картой играют. */
    default PlayerState me() {
        return state().player(seat());
    }

    /** Номер текущего раунда. */
    default int round() {
        return state().round;
    }

    /**
     * Сколько раундов ОСТАЛОСЬ до конца партии по самой близкой из причин.
     *
     * <p>Нужно картам и оценке ботов: «уничтожить чужой добытчик» стоит
     * по-разному в третьем раунде и в последнем. Возвращается оценка, а не
     * гарантия — партию может оборвать мгновенная победа.
     */
    int roundsLeft();

    /** Сколько ресурса на руках у игрока. */
    default int have(Resource r) {
        return me().resources.get(r);
    }

    /** Все живые жетоны игрока на поле (войска и здания). */
    List<Token> myTokensOnField();

    /** Живые жетоны противников на поле. */
    List<Token> enemyTokensOnField();

    /**
     * Гексы, до которых жетон может достать АТАКОЙ в этот момент, с учётом
     * стенок, дальности и способностей. Пустой список — бить некого.
     */
    List<String> attackReach(UnitToken unit);

    // ==================================================================
    //  МЕНЯТЬ: карта действует
    // ==================================================================

    /** Выдать ресурсы (склад ограничивает, лишнее теряется — как в правилах). */
    void gain(Resource r, int amount);

    /** Забрать ресурсы; вернёт сколько удалось забрать. */
    int pay(Resource r, int amount);

    /** Снять {@code n} кубиков урона с жетона (не больше, чем на нём есть). */
    void heal(Token token, int n);

    /** Положить {@code n} кубиков урона; уничтожение и трофеи — как в бою. */
    void damage(Token token, int n);

    /** Передвинуть войско на гекс; проверки проходимости — внутри движка. */
    boolean move(UnitToken unit, String hexId);

    /** Дать игроку бесплатное действие указанного типа прямо сейчас. */
    void freeAction(String action);

    /** Выдать победные очки напрямую (источник указывается для разбора партии). */
    void grantVp(int vp, String source);

    // ==================================================================
    //  СПРАШИВАТЬ: там, где выбирает игрок, а не карта
    // ==================================================================

    /**
     * Спросить у того, кто играет (бот или человек), какой из вариантов взять.
     *
     * @param kind  повод выбора — по нему бот отличает «кого лечить» от «куда идти»
     * @param options варианты; пустой список означает, что выбора нет
     * @return выбранный вариант или {@code null}, если вариантов не было
     */
    <T> T ask(String kind, List<T> options);

    /** Записать в журнал партии, что карта сделала — для разбора и отчётов. */
    void log(String event, Map<String, Object> details);
}
