package kelium.engine.cards;

/**
 * КАРТА КОНТЕЙНЕРА — разовая находка с одним или двумя напечатанными
 * эффектами (сторона {@code a}, необязательная сторона {@code b}).
 *
 * <p>Движок читает эффекты контейнера из {@link #data()} напрямую (та же
 * запись {@code effect}/{@code params}/{@code label}, что и у утиля карты
 * арсенала или задания) — здесь нет отдельного метода «применить», потому что
 * применение уже устроено как общая услуга движка ({@code Effects.apply}),
 * проверенная и без единой мёртвой ссылки. Карта лишь описывает себя.
 */
public interface ContainerCard extends Card {

    @Override
    default Family family() {
        return Family.КОНТЕЙНЕР;
    }
}
