package kelium.engine.cards;

/**
 * КАРТА ЗАДАНИЯ — условие, усиленное условие и два способа сыграть.
 *
 * <p>Раньше карта задания была размазана по трём местам: условие жило в
 * {@code Predicates} строковым ключом, награда — в {@code Objectives}, верхний
 * эффект — в {@code Effects}. Карты как целого не существовало нигде, и потому:
 *
 * <ul>
 *   <li>проверить карту целиком было нечем — тест мог проверить только предикат;</li>
 *   <li>бот не понимал, ЧТО карта требует: он видел награду, но не видел пути к
 *       ней, поэтому из шести полученных заданий выполнял одно, а пять жёг;</li>
 *   <li>условие, которого не было в реестре предикатов, молча не выполнялось
 *       никогда — карта лежала мёртвой и выглядела рабочей.</li>
 * </ul>
 *
 * <p>Теперь всё это — один класс на карту.
 */
public interface ObjectiveCard extends Card {

    @Override
    default Family family() {
        return Family.ЗАДАНИЕ;
    }

    /**
     * Выполнено ли ОБЫЧНОЕ требование карты прямо сейчас.
     *
     * <p>Смотреть можно на что угодно в {@link CardContext#state()} — в этом и
     * смысл: карта сама знает, что считать.
     */
    boolean satisfied(CardContext ctx);

    /**
     * Выполнено ли УСИЛЕННОЕ требование. По умолчанию усиленного нет.
     *
     * <p>Замер 15.08.2026: усиленную ветку берут в 0.2–0.6 раза за партию, то
     * есть почти никогда. Отдельный метод нужен, чтобы это можно было мерить по
     * каждой карте, а не «в среднем по колоде».
     */
    default boolean satisfiedEnhanced(CardContext ctx) {
        return false;
    }

    /**
     * НАСКОЛЬКО БЛИЗКО выполнение — от 0.0 (даже не начинал) до 1.0 (готово).
     *
     * <p>Это главная новая вещь для ботов. Раньше карта отвечала только «да/нет»,
     * и бот не мог отличить задание, до которого один шаг, от невыполнимого —
     * оба выглядели как «нет». Отсюда и привычка жечь карты вместо выполнения.
     *
     * <p>По умолчанию — грубая оценка по {@link #satisfied}: выполнено или нет.
     * Каждая карта, у которой есть счётный прогресс, должна переопределить.
     */
    default double progress(CardContext ctx) {
        return satisfied(ctx) ? 1.0 : 0.0;
    }

    /**
     * Выдать награду за выполнение. Числа берутся из данных карты, поэтому
     * большинству карт этот метод переопределять не нужно — награду раздаёт
     * общий код по записи {@code reward} / {@code reward_enhanced}.
     *
     * @param enhanced выполнено ли усиленное требование
     */
    default void reward(CardContext ctx, boolean enhanced) {
        CardRewards.grantFromData(ctx, this, enhanced);
    }

    /**
     * ЧЕГО НЕ ХВАТАЕТ ДО ВЫПОЛНЕНИЯ — человеческой строкой.
     *
     * <p>Объявлено здесь, а не только в модуле карт, потому что читает это
     * ДВИЖОК: {@link kelium.engine.ObjectiveHints} собирает индикаторы по руке и
     * должен уметь спросить об этом карту, условие которой живёт в коде
     * ({@code checked_by: card}), не завися от модуля карт.
     */
    default String needed(CardContext ctx) {
        return "";
    }

    /**
     * ВЕРХНИЙ ЭФФЕКТ — то, ради чего карту сжигают, не выполняя.
     *
     * <p>Возвращает {@code false}, если сжечь сейчас нельзя (например, нет цели).
     */
    boolean burn(CardContext ctx);
}
