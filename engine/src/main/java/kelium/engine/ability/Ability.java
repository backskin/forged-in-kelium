package kelium.engine.ability;

import java.util.Set;

import kelium.core.Agent;
import kelium.core.GameState;

/**
 * СПОСОБНОСТЬ — то, что карта арсенала (или супер-арсенала) добавляет к правилам.
 *
 * <p>Способность ОБЪЯВЛЯЕТ себя, а не вписывается в движок: где вмешивается
 * ({@link #hooks()}), когда срабатывает ({@link #trigger()}), что делает
 * ({@link #modify} или {@link #apply}) и — отдельно — что она даёт БОТУ
 * ({@link #hint()}). Благодаря последнему боту не нужно рукописное число «сколько
 * эта карта стоит»: он читает самоописание и сверяет его со своим планом.
 */
public interface Ability {

    /** Когда способность работает. */
    enum Trigger {
        /** Постоянно, пока карта установлена: правит значения правил. */
        PASSIVE,
        /** По СПЕЦ-действию игрока (одно за ход). */
        SPEC,
        /** Реакция на событие движка (убийство, контратака, Обновление). */
        ON_EVENT
    }

    /** Идентификатор — тот же, что в данных карты (поле {@code passive}). */
    String id();

    Trigger trigger();

    /** Точки правил, в которые способность вмешивается. Пусто быть не может. */
    Set<Hook> hooks();

    /**
     * ПОСТОЯННОЕ вмешательство: правит значение правила в точке. Вызывается
     * движком через {@link RuleQuery}; способность сама смотрит, её ли это случай
     * (нужный тип здания, есть ли авиация на гексе и т. п.).
     */
    default void modify(RuleQuery q) {
    }

    /**
     * СПЕЦ-действие или реакция: делает ход. Возвращает true, если способность
     * реально сработала (иначе движок считает, что игрок ничего не потратил).
     */
    default boolean apply(GameState state, int seat, Agent agent) {
        return false;
    }

    /** Самоописание для бота: какое узкое место снимает и на каком горизонте. */
    Hint hint();
}
