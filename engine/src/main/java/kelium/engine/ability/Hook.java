package kelium.engine.ability;

/**
 * ТОЧКИ ПРАВИЛ — те и только те места, где движок готов слушать способности карт
 * (проект «Арсенал как система способностей», 13.08.2026).
 *
 * <p>Зачем закрытый перечень. Прежде пассивка была строкой, которую движок искал
 * руками в месте срабатывания: {@code if (hasPassive(seat, "…"))}. Ревизия
 * 13.08.2026 нашла шесть пассивок из 29, которые «есть», но не работают — вызов
 * просто забыли, и заметить это было нечем. Теперь у каждой способности есть
 * ОБЪЯВЛЕННАЯ точка, движок в этой точке ОБЯЗАН спросить реестр, а тест обходит
 * все зарегистрированные способности и валится, если чью-то точку никто не
 * спрашивает ({@link Abilities#unaskedHooks()}).
 *
 * <p>Правило: никаких проверок способностей вне реестра. Если способности негде
 * вмешаться — добавляется НОВАЯ точка, осознанно, а не россыпь условий по коду.
 */
public enum Hook {

    // ---- Сборка ----
    ASSEMBLY_ENERGY_NEEDED("сколько энергии требует здание для Сборки"),
    ASSEMBLY_UNITS_OUT("сколько войск выходит за одну Сборку"),
    ASSEMBLY_AMMO_OUT("сколько боеприпасов выходит за одну Сборку"),
    ASSEMBLY_PAY_ENERGY_WITH_COIN("можно ли докупить недостающую энергию монетой"),

    // ---- Стройка ----
    BUILD_ZONE("какие гексы доступны для стройки"),
    BUILD_PRICE("цена постройки здания"),
    BUILD_FREE_MOVE_BUILDING("бесплатный перенос своего здания"),
    BUILD_UNIT_WITH_BUILDING("войско сразу на построенное здание"),

    // ---- Движение ----
    UNIT_SPEED("скорость рода войск"),
    MOVEMENT_FREE_EXTRA("сколько лишних шагов бесплатны"),
    MOVEMENT_JUMP_OVER("через какие гексы можно перепрыгнуть"),

    // ---- Бой ----
    ATTACK_AMMO_COST("цена атаки в боеприпасах"),
    ATTACK_RANGE("дальность выбора цели"),
    ATTACK_TARGETS("по кому можно бить"),
    ATTACK_PROTECT_HEX("защита своих жетонов на гексе"),
    COMBAT_SECOND_BATTLE_SURCHARGE("надбавка за второй и следующий бой"),
    COMBAT_RETALIATION("порядок и право контратаки"),

    // ---- Жетоны ----
    TOKEN_HP("здоровье жетона"),
    TOKEN_RETURN_TO_RESERVE("возврат жетона в запас"),

    // ---- Энергия ----
    ENERGY_SOURCES("какие источники дают кубики энергии"),
    ENERGY_SWAP_COST("цена перемещения энергии"),
    ENERGY_INCOME("доход от энергии в Обновление"),

    // ---- Приказы ----
    ORDER_BLOCK_BYPASS("обход блокировки приказа совпадением"),
    ORDER_BOTTOM_ACTIONS("сколько действий даёт нижний приказ"),
    ORDER_SPEC_COUNT("сколько СПЕЦ-действий за ход"),

    // ---- Хранилище ----
    STORAGE_CELLS("сколько ячеек на складе"),
    STORAGE_HOLDS_DEBRIS("можно ли держать на складе кубики обломков"),

    // ---- Экономика ----
    MARKET_RATES("курсы обменов рынка"),
    SCIENCE_PAY_WITH("чем платить за шаги науки"),
    REFRESH_INCOME("что приходит в Обновление"),

    // ---- Очки ----
    SCORING_VP_SOURCE("новый источник победных очков"),
    SCORING_VP_MODIFIER("правка существующего источника очков"),

    // ---- Поле ----
    FIELD_ADD_SPAWN_TILE("добавить тайл зарождения на поле"),
    FIELD_FORBID_HEX("сделать гекс недоступным");

    private final String what;

    Hook(String what) {
        this.what = what;
    }

    /** Человеческое описание точки — для отчётов и сообщений об ошибках. */
    public String what() {
        return what;
    }
}
