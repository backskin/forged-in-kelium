package kelium.engine.ability;

import java.util.List;

import kelium.core.Choice;
import kelium.core.GameState;

/**
 * НОВЫЕ ВОЗМОЖНОСТИ В МЕНЮ РЕШЕНИЙ — вторая опора системы способностей
 * (замечание дизайнера 13.08.2026: карта арсенала должна уметь давать НОВЫЕ
 * действия и спец-действия, а не только править числа).
 *
 * <p>Движок в каждой точке решения спрашивает не только правила, но и
 * способности: «что ты хочешь ДОБАВИТЬ в список вариантов?». Так появляются:
 *
 * <ul>
 *   <li>новое СПЕЦ-действие («забери карту приказа из сброса и сбрось закрытую»);</li>
 *   <li>новое основное действие («уничтожь чужое здание своим войском»);</li>
 *   <li>новые варианты внутри существующего решения (цель на расстоянии 2,
 *       перепрыгнуть гекс с тайлом, построить на соседнем гексе без примыкания).</li>
 * </ul>
 *
 * <p>Ключевая мысль: возможность не «зашита в движок с условием на карту», а
 * ПРИХОДИТ ОТ КАРТЫ. Движок только спрашивает и исполняет выбранное.
 */
public interface OptionSource {

    /** Где именно спрашивают варианты. */
    enum Slot {
        /** Меню основных действий хода. */
        ACTION,
        /** Меню СПЕЦ-действий. */
        SPEC,
        /** Куда может пойти войско (движение). */
        MOVE_DESTINATION,
        /** Откуда можно бить (гекс-источник боя). */
        COMBAT_SOURCE,
        /** По какому гексу можно бить. */
        COMBAT_TARGET,
        /** Где можно строить. */
        BUILD_HEX,
        /** Что можно сделать с картами приказов (взять из сброса, обменять). */
        ORDER_CARDS,
        /** Что можно сделать с энергией. */
        ENERGY,
        /** Свободные решения вне хода (реакции с выбором). */
        FREE
    }

    /**
     * Варианты, которые эта способность добавляет в решение. Пустой список —
     * сейчас нечего добавить (условие не выполнено).
     *
     * <p>Каждый вариант обязан несли {@code kind}, начинающийся с
     * {@code ability:<id>}: по нему движок поймёт, кому отдать исполнение, и
     * запишет в метрики, что сработала именно эта карта.
     */
    List<Choice> options(GameState state, int seat, Slot slot);

    /**
     * Исполнить выбранный вариант. Возвращает true, если способность реально
     * что-то сделала (движок тогда спишет СПЕЦ/действие).
     */
    boolean perform(GameState state, int seat, Choice chosen, kelium.core.Agent agent);
}
