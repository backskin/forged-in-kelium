package kelium.engine.ability;

import java.util.Map;
import java.util.Set;

import kelium.core.Agent;
import kelium.core.GameState;

/**
 * РЕАКЦИИ НА СОБЫТИЯ — третья опора системы способностей (замечание дизайнера
 * 13.08.2026: карта должна уметь срабатывать «во время события, иногда даже не в
 * свой ход»).
 *
 * <p>Способность подписывается на события движка и получает окно, чтобы что-то
 * сделать: получить ресурс, вернуть жетон, снять урон, забрать карту. Владельцем
 * реакции может быть НЕ активный игрок — именно так работают «если тебя
 * контратаковали», «когда чужое войско входит на твой гекс», «в Обновление
 * получи доход».
 */
public interface Reaction {

    /**
     * Типы событий движка, на которые подписана способность. Имена — те же, что
     * в потоке событий: {@code combat_hit}, {@code refresh}, {@code container},
     * {@code objective}, {@code turn_orders}, {@code spawn_flip} и т. д. Это
     * позволяет вешать реакции на ЛЮБОЕ уже существующее событие, не заводя под
     * каждую карту особый крючок в движке.
     */
    Set<String> events();

    /**
     * Сработать на событие. {@code owner} — место игрока, которому принадлежит
     * карта (может отличаться от {@code event.seat}: реакция бывает и в чужой ход).
     *
     * @return true, если реакция что-то изменила (пойдёт в метрики)
     */
    boolean on(GameState state, int owner, Map<String, Object> event, Agent agent);
}
