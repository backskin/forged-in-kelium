package kelium.engine.step;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

import kelium.core.GameState;

/**
 * ПОЗИЦИЯ В ПОШАГОВОМ API (23.09.2026): снимок стола в начале круга плюс номера
 * вариантов всех решений, принятых с тех пор (всеми игроками, по порядку).
 *
 * <p>Зачем так, а не «состояние посреди хода». Движок задаёт вопросы игрокам
 * изнутри действий — посреди Стройки, посреди Боя, — и остановить его там
 * нельзя. Но он строго детерминирован: один и тот же снимок и одни и те же
 * решения дают одну и ту же партию. Значит, позиция — это «откуда» и «какими
 * решениями», а сама обстановка восстанавливается повтором ({@link Шаг#достать}).
 *
 * <p>Позиция неизменяема: {@link #применить} возвращает новую.
 */
public final class Позиция {

    /** Точная копия стола в начале круга; сама не меняется никогда. */
    final GameState снимок;
    /** Номера выбранных вариантов после снимка. */
    final List<Integer> ходы;

    Позиция(GameState снимок, List<Integer> ходы) {
        this.снимок = снимок;
        this.ходы = Collections.unmodifiableList(new ArrayList<>(ходы));
    }

    /** Позиция после ещё одного решения: выбран вариант номер {@code вариант}. */
    public Позиция применить(int вариант) {
        List<Integer> н = new ArrayList<>(ходы);
        н.add(вариант);
        return new Позиция(снимок, н);
    }

    /** Сколько решений принято после начала круга. */
    public int глубина() {
        return ходы.size();
    }

    /** Раунд и круг снимка — для подписей и отладки. */
    public String откуда() {
        return "раунд " + снимок.round + ", круг " + снимок.circle;
    }
}
