# -*- coding: utf-8 -*-
"""Разрезать «набор-1-без-фона.png» (Leonardo, Remove Background) на отдельные
предметы: каждый — своя прямоугольная область, края уже чистые."""
from PIL import Image

im = Image.open("набор-1-без-фона.png").convert("RGBA")
РАМКИ = {
    "мешочек-красный": (150, 220, 500, 660),
    "мешочек-синий": (480, 220, 820, 660),
    "кубики-келемий": (840, 460, 1080, 640),
    "кубики-боеприпасы": (1130, 460, 1370, 650),
    "кубики-трофеи": (190, 690, 450, 890),
    "кубики-энергия": (510, 690, 760, 900),
    "монеты": (860, 720, 1100, 880),
    "фишка-первого": (1170, 640, 1340, 880),
}
for имя, рамка in РАМКИ.items():
    кус = im.crop(рамка)
    кус = кус.crop(кус.getchannel("A").point(lambda v: 255 if v > 6 else 0).getbbox())
    кус.save(имя + ".png")
    print(имя, кус.size)
