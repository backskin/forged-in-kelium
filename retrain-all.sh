#!/bin/sh
# ПОЛНЫЙ ЦИКЛ ОБУЧЕНИЯ И ЗАМЕРА (переписан 12.08.2026 вместе с новой системой ботов).
#
# Порядок здесь НЕ случайный — это последовательность «обучить → измерить →
# понять», и каждый шаг опирается на предыдущий:
#
#   1. САМОИГРА всех характеров друг против друга. У каждой линии свой зал славы
#      (замороженные прошлые чемпионы), поэтому популяция не может ходить по кругу
#      «камень-ножницы-бумага». Чемпион линии обновляется ТОЛЬКО если стал сильнее
#      на отложенных партиях — тех, которых отбор не видел.
#   2. ЛИГА с рейтингом Эло. Единственная общая линейка: от случайного бота до
#      просчитывающего, все на одной шкале. Без неё «стало лучше» недоказуемо.
#   3. АТЛАС СТРАТЕГИЙ (MAP-Elites). Не один чемпион, а сетка чемпионов по стилям
#      игры: какие стратегии в игре рабочие и равны ли они. Это балансовый ответ.
#   4. ЧТО ПРИНОСИТ ПОБЕДУ. Модель учится предсказывать исход по расстановке;
#      её коэффициенты читаются словами — за что в этой игре платят очками.
#
# Прежняя версия скрипта гоняла EvoTrainer по 15 линиям подряд и НИЧЕГО не
# измеряла: на выходе были геномы, про которые нельзя было сказать, стали они
# сильнее или слабее.
set -e

# Три модуля вместо одного (разделено 14.08.2026): fat-jar теперь собирает
# модуль gui (он зависит от bots, тот — от engine, шейд бандлит всё вместе).
JAR=gui/target/kelium-runner.jar
if [ ! -f "$JAR" ]; then
  echo "Нет $JAR — собери: mvn -o package -DskipTests"
  exit 1
fi

STAMP=$(date +%Y-%m-%d)
LOG="reports/balance/обучение-$STAMP.log"
mkdir -p reports/balance
: > "$LOG"

# Сколько партий отдать каждому характеру в самоигре. 20000 — примерно час.
PER_CHARACTER=${PER_CHARACTER:-20000}
# ЗНАКОМСТВО С КАРТАМИ (заказ дизайнера 14.08.2026, curriculum-обучение):
# партий на характер ПЕРЕД обычной самоигрой, где карты арсенала/заданий
# сыплются бесплатно (вероятность 0.6, убывает до нуля к концу этой партии
# бюджета) — боты должны много раз увидеть карты и решить, что с ними
# делать, прежде чем веса их оценки станут значить хоть что-то. 0 = пропустить.
CARD_GAMES=${CARD_GAMES:-5000}
# Объём лиги (кругов). За круг каждый участник играет на каждом месте за каждым столом.
LEAGUE_ROUNDS=${LEAGUE_ROUNDS:-24}
# Сколько стратегий перебрать для атласа.
ATLAS_CANDIDATES=${ATLAS_CANDIDATES:-500}
# Сколько самоигр собрать для модели «что приносит победу».
INSIGHT_GAMES=${INSIGHT_GAMES:-400}

run() {
  echo "" | tee -a "$LOG"
  echo "=== $1 ===" | tee -a "$LOG"
  shift
  java -cp "$JAR" "$@" 2>&1 | grep -v '^\[SETUP\]' | tee -a "$LOG"
}

# ВАЖНО: перед обучением убеждаемся, что память ботов не перенаправлена в
# папку-архив. Один раз она была направлена в archive-pre-selfplay, и обучение
# молча читало старые геномы и писало новые в бэкап.
run "ГДЕ ЛЕЖИТ ПАМЯТЬ БОТОВ" kelium.dataio.Locations

run "1. САМОИГРА ВСЕХ ХАРАКТЕРОВ (по $PER_CHARACTER партий на характер, + $CARD_GAMES знакомства с картами)" \
  kelium.agents.SelfPlayTrainer "$PER_CHARACTER" 16 12 "$((PER_CHARACTER / 10))" "" "$CARD_GAMES"

for players in 4 3; do
  run "2. ЛИГА ($players игрока, $LEAGUE_ROUNDS кругов)" \
    kelium.agents.Arena "$players" "$LEAGUE_ROUNDS" \
    "random,heuristic:economist,default,balanced,hawk,dove,opportunist,explorer,chaos,search:balanced,deep:balanced"
done

run "3. АТЛАС СТРАТЕГИЙ (4 игрока, $ATLAS_CANDIDATES кандидатов)" \
  kelium.agents.MapElites 4 "$ATLAS_CANDIDATES" 4 12

run "4. ЧТО ПРИНОСИТ ПОБЕДУ (4 игрока, $INSIGHT_GAMES самоигр)" \
  kelium.agents.ValueTrainer 4 "$INSIGHT_GAMES" 300 24

echo "" | tee -a "$LOG"
echo "ГОТОВО. Отчёты:" | tee -a "$LOG"
echo "  reports/balance/лига-4p.md              — кто сильнее, единая шкала Эло" | tee -a "$LOG"
echo "  reports/balance/атлас-стратегий-4p.md   — какие стили игры рабочие" | tee -a "$LOG"
echo "  reports/balance/что-приносит-победу-4p.md — за что игра платит очками" | tee -a "$LOG"
echo "  reports/balance/самоигра.log            — ход обучения характеров" | tee -a "$LOG"
